#!/usr/bin/env python3
"""Толчок в ветку, отличную от текущей, отвергается ДО вызова git.

Держит правила каталога 012 и 189: первое — что в чужую ветку не пушат, второе
— что ветка носит имя ЗАДАЧИ и живёт с ней; сторож сверяет имя из команды с
текущей головой, и обе половины держатся одной проверкой.

Правило 012 держалось ничем с ответом «предмет вне досягаемости: чья ветка,
знает человек». Ответ описывал не тот предмет. Признак «чужая ветка» машине
и правда недоступен — а признак, которым пользуется сосед, доступен вполне:
**имя ветки в команде не совпадает с текущей головой**. Промах пальцем,
скопированная из передачи строка, старое имя из прошлой смены — все три дают
одно и то же наблюдаемое: содержимое уезжает не туда, куда смотрит окно.

ПОЧЕМУ ХУК, А НЕ ГЕЙТ. Конвейер видит артефакт, а не действие: к моменту его
запуска толчок уже состоялся, ветка уже сдвинута, а `git push` в общую ветку
из окна и вовсе запрещён отдельно (131). Отвергать надо до вызова git —
единственное место, где это возможно, стоит перед инструментом. Приём взят у
грейдера (`.claude/hooks/pre_tool_use.py`), файл — нет: у него запрет шире и
собран под его конвейер (правило 162).

ЧТО РАЗРЕШЕНО. Толчок без имени ветки (`git push`), толчок текущей ветки под
любым её собственным именем, `HEAD:<ветка>` — там имя цели задаётся явно и
осознанно, и запрет на общую ветку живёт не здесь. Всё остальное с явным
именем ветки отвергается.

ТЕЛО ДОКУМЕНТА НА ВХОДЕ — ДАННЫЕ, А НЕ КОМАНДЫ. `cat > файл <<'EOF' … EOF`
пишет файл, и строка `git push` внутри него — текст, а не действие. Сторож
смотрит на действие: это уже было сказано в его наборе про запись чужим
инструментом, но запись через оболочку тем же случаем не покрывалась, и
сторож отверг запись файла с примером для человека.

Вход: JSON события PreToolUse на stdin. Выход: 0 — пропустить, 2 — отвергнуть
с причиной в stderr.
"""

from __future__ import annotations

import json
import re
import shlex
import subprocess
import sys
from pathlib import Path

#: Ключи, за которыми идёт значение, а не имя ветки.
WITH_VALUE = {"--repo", "-o", "--push-option", "--exec", "--receive-pack"}
#: Ключи `git push`, при которых команда НИЧЕГО не отправляет: она удаляет
#: ссылки. Охват у них командный, а не поссылочный, — в отличие от формы
#: `:ветка`, которая удаляет одну ссылку и уживается с толчком в той же строке.
DELETES_ALL = {"--delete", "-d"}
#: Глобальные ключи самого git, за которыми идёт значение: `git -C путь push`.
#: Отделять их приходится, потому что подкоманда — первое слово БЕЗ ключа.
GLOBAL_WITH_VALUE = {"-C", "-c", "--git-dir", "--work-tree", "--namespace",
                     "--exec-path", "--super-prefix"}


def подкоманда(words: list[str]) -> tuple[str, list[str]] | None:
    """Подкоманда git и её аргументы. None — это не вызов git.

    ПОДКОМАНДА — ПЕРВОЕ СЛОВО БЕЗ КЛЮЧА, А НЕ ПРОСТО СЛОВО РЯДОМ. Здесь стояло
    «`push` среди первых трёх слов», и `git stash push <пути>` — обычное
    сохранение работы — читалось как толчок в ветку с именем первого файла.
    Замер 8 сентября: сторож отверг `git stash push scripts/check_bindings.py
    scripts/check_derived.py` со словами «толчок в scripts/check_derived.py».
    Ложный отказ на верной работе — то, чего 051 запрещает прямо: красное,
    которое нельзя снять своей работой, приучают обходить.

    И ЭТО БЫЛ ЕЩЁ РАЗЪЕЗД ВНУТРИ ОДНОГО ХУКА. Соседняя `толкает()` требовала
    `push` СРАЗУ после `git` и на том же `git stash push` отвечала «нет». Две
    функции одного сторожа отвечали на один вопрос по-разному, и разошлись бы
    дальше молча (022). Теперь разбор один, и обе спрашивают его.
    """
    if not words or words[0].rsplit("/", 1)[-1] != "git":
        return None
    i = 1
    while i < len(words):
        слово = words[i]
        if слово in GLOBAL_WITH_VALUE:
            i += 2                      # ключ и его значение
            continue
        if слово.startswith("-"):
            i += 1
            continue
        return слово, words[i + 1:]
    return None


#: Ссылка вида `HEAD:main` или `refs/heads/x:y` — цель названа явно.
REFSPEC = re.compile(r"^[^:]+:[^:]+$")
#: Перенаправление вывода: `>`, `2>&1`, `<file`. В имени ветки этих знаков
#: не бывает, а в команде окна они бывают почти всегда.
REDIRECT = re.compile(r"[<>]")


def current_branch() -> str | None:
    done = subprocess.run(["git", "rev-parse", "--abbrev-ref", "HEAD"],
                          capture_output=True, text=True)
    return done.stdout.strip() or None if done.returncode == 0 else None


#: Начало документа на входе: `<<EOF`, `<<-'EOF'`, `<< "EOF"`. Тело такого
#: документа — ДАННЫЕ, а не команды: им пишут файлы.
HEREDOC_RE = re.compile(r"<<-?\s*(['\"]?)(\w+)\1")


def without_heredocs(command: str) -> str:
    """Команда без тел документов на входе.

    ЗАМЕР, ИЗ КОТОРОГО ЭТО ВЫРОСЛО. Окно писало файл прогона через `cat > … <<
    'YML'`, и внутри файла стоял ПРИМЕР для человека: «переименуйте ветку —
    git push -u origin agent/$BRANCH». Сторож разобрал строку примера как
    команду и отверг запись файла. Собственный набор сторожа этот случай уже
    называл — «строка в файле не команда», — но проверял его только на записи
    ЧУЖИМ инструментом, а не на записи через оболочку.

    Тот же приём, что у самого сторожа с перенаправлением: то, что после
    признака перестаёт быть командой, дальше не разбирается.
    """
    lines = command.splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        out.append(lines[i])
        m = HEREDOC_RE.search(lines[i])
        if m:
            конец = m.group(2)
            i += 1
            while i < len(lines) and lines[i].strip() != конец:
                i += 1                  # тело документа — данные, пропускаем
        i += 1
    return "\n".join(out)


#: Команды, которые МЕНЯЮТ текущую ветку. Сторож обязан их учитывать: он
#: спрашивает ветку у git ДО того, как команда выполнится, и `git checkout X &&
#: git push origin X` выглядел бы толчком в чужую. Замер: за одну смену это
#: отвергло верный толчок трижды подряд.
SWITCH = {"checkout", "switch"}
#: Ключи `checkout`/`switch`, за которыми идёт имя новой ветки.
SWITCH_WITH_NAME = {"-b", "-B", "-c", "-C"}
#: Что git ветками не называет: `check-ref-format` запрещает компонент `.` и
#: `..`, а путём они приходят регулярно.
НЕ_ИМЯ_ВЕТКИ = {".", ".."}


def switched_to(words: list[str]) -> str | None:
    """Ветка, на которую переходит эта команда, ЕСЛИ она переходит.

    `checkout` решает две задачи разом, и различает их `--`: всё за ним —
    ПУТИ, а не ссылки. `git checkout -- файл` и `git checkout main -- файл`
    восстанавливают содержимое и никуда не переходят; прежний разбор возвращал
    оттуда `файл` и `main` как имя ветки, после чего верный толчок в свою
    ветку объявлялся чужим (инцидент 8 сентября,
    `git checkout -- export/rules.json && git push -u origin своя`).

    Различать `git checkout имя` без `--` сторож не берётся: `export/rules.json`
    и `agent/тема` неразличимы текстом, и решает это сам git, глядя в дерево.
    Достоверна здесь только форма с `--`, ею и ограничен ответ (051).

    ОСВОБОЖДЕНИЕ ОТНОСИТСЯ К `checkout` И НЕ ОТНОСИТСЯ К `switch` — соседняя
    подкоманда решает тот же признак иначе. У `switch` форм с путями нет
    вовсе, и `--` там обычный терминатор ключей: `git switch -- ветка`
    ПЕРЕКЛЮЧАЕТ HEAD. Проверено запуском на git 2.43.0, а не чтением
    руководства: «Switched to branch», голова переехала. Сложив обе
    подкоманды в одно освобождение, сторож отверг бы толчок в ветку, на
    которую окно только что перешло, — тот же ложный отказ, против которого
    правка и делается (195).
    """
    вызов = подкоманда(words)
    if вызов is None or вызов[0] not in SWITCH:
        return None
    подкоманда_имя, tail = вызов
    if подкоманда_имя == "checkout" and "--" in tail:
        return None
    for i, w in enumerate(tail):
        if w in SWITCH_WITH_NAME and i + 1 < len(tail):
            return tail[i + 1]
        if not w.startswith("-") and not REDIRECT.search(w):
            # `.` и `..` git именем ветки не принимает вовсе, а как путь они
            # приходят постоянно: `git checkout .` — восстановление.
            return None if w in НЕ_ИМЯ_ВЕТКИ else w
    return None


def targets(command: str, current: str | None = None) -> list[str]:
    """Имена веток, названные в командах `git push`, — те, что ЧУЖИЕ.

    Ветка считается по ходу строки: `git switch X && git push origin X` — это
    толчок в свою, а не в чужую, и отвергать его значит краснеть на верной
    работе (051).

    Имя, собранное подстановкой (`$b`, `${имя}`), сторож не разворачивает и не
    угадывает: он пропускает такой толчок. Его предмет — НАЗВАННАЯ чужая
    ветка; «неизвестно» и «чужая» — разные ответы, и путать их значит
    запрещать недостоверное (051).

    УДАЛЕНИЕ ССЫЛКИ ПРЕДМЕТОМ НЕ ЯВЛЯЕТСЯ. Посылка сторожа — «содержимое
    уехало бы не туда, куда смотрит окно»; у удаления содержимого нет вовсе,
    и посылка к нему не относится. Две формы различаются охватом, и различие
    здесь не косметическое: `--delete`/`-d` относится ко ВСЕЙ команде, а
    `:ветка` — к одной ссылке, и `git push origin main :старая` в той же
    строке и удаляет, и толкает.
    """
    out: list[str] = []
    # Перевод строки разделяет команды не хуже `&&`, и в записи файла
    # через оболочку он единственный разделитель.
    for part in re.split(r"&&|\|\||;|\||\n", without_heredocs(command)):
        try:
            words = shlex.split(part)
        except ValueError:              # незакрытая кавычка — не наше дело
            continue
        переход = switched_to(words)
        if переход is not None:
            current = переход
            continue
        вызов = подкоманда(words)
        if вызов is None or вызов[0] != "push":
            continue
        tail = вызов[1]
        positional: list[str] = []
        skip = False
        удаляет_всё = False
        for word in tail:
            # Перенаправление и всё, что за ним, — не ссылки, а имена файлов.
            # Замер на первой же пробе: `2>&1` уехало в список веток, и хук
            # назвал предметом отказа то, чего в команде не было (158).
            if REDIRECT.search(word):
                break
            if skip:
                skip = False
                continue
            if word in WITH_VALUE:
                skip = True
                continue
            # Проверяется ПОСЛЕ WITH_VALUE: `git push -o --delete` — значение
            # ключа, а не ключ, и порядок здесь несущий, а не стилистический.
            if word in DELETES_ALL:
                удаляет_всё = True
                continue
            if word.startswith("-"):
                continue
            positional.append(word)
        if удаляет_всё:
            continue                    # содержимого в команде нет
        # Первый позиционный — удалённый репозиторий, дальше ссылки.
        for ref in positional[1:]:
            if ref.startswith(":"):
                continue                # `:ветка` — удаление одной ссылки
            if REFSPEC.match(ref):
                continue                # `HEAD:ветка` — цель названа явно
            имя = ref.removeprefix("refs/heads/")
            # Подстановка оболочки: значения сторож не знает и не выдумывает.
            if "$" in имя or "`" in имя:
                continue
            if current is not None and имя != current:
                out.append(имя)
    return out


def толкает(command: str) -> bool:
    """Команда действительно вызывает git-толчок, а не упоминает эти слова.

    Тела heredoc уже вырезаны соседней функцией — там текст, а не команды.
    Здесь остаётся вторая форма того же: слово внутри строки-аргумента.
    """
    for part in re.split(r"&&|\|\||;|\||\n", without_heredocs(command)):
        try:
            слова = shlex.split(part)
        except ValueError:
            continue
        вызов = подкоманда(слова)
        if вызов is not None and вызов[0] == "push":
            return True
    return False


def первый_коммит_ветки(корень: Path) -> str | None:
    """Тело коммита, из которого конвейер возьмёт тело изменения.

    ПОЧЕМУ ИМЕННО ПЕРВЫЙ. `agent-pr` открывает изменение и ставит ему тело ОДИН
    раз — из первого коммита поверх общей ветки. Правка коммита после толчка
    тела на площадке уже не меняет: там останется то, что уехало первым.

    КОММИТ СПРАШИВАЕТСЯ У ТОГО ЖЕ ВЫБОРА, ЧТО И У КОНВЕЙЕРА. Здесь стоял свой
    разбор `origin/main..HEAD`, и он повторял дефект конвейера один в один: на
    ветке поверх соседней первым в диапазоне идёт ЧУЖОЙ коммит, и хук проверял
    бы чужое тело, а уехало бы своё. Два ответа на один вопрос разошлись бы —
    и разошлись бы молча (022).
    """
    выбор = корень / "scripts" / "pr_source_commit.py"
    if not выбор.exists():
        return None                     # чужое дерево — не наш предмет
    названо = subprocess.run(
        [sys.executable, str(выбор), "--root", str(корень), "--base", "origin/main"],
        capture_output=True, text=True, encoding="utf-8")
    if названо.returncode != 0:
        return None                     # коммитов нет либо выбор не отработал
    sha = названо.stdout.strip()
    if not sha:
        return None
    тело = subprocess.run(["git", "-C", str(корень), "log", "-1", "--format=%B", sha],
                          capture_output=True, text=True, encoding="utf-8")
    return тело.stdout if тело.returncode == 0 else None


def тело_не_проходит(корень: Path) -> str | None:
    """Причина, по которой конвейер отвергнет тело изменения. None — пройдёт.

    ПОЧЕМУ ХУК, А НЕ ГЕЙТ, И ЭТО ТА ЖЕ ПРИЧИНА, ЧТО У СОСЕДА ВЫШЕ. Гейт тела
    живёт на изменении и потому видит АРТЕФАКТ: к его запуску тело уже уехало,
    а поправить коммит недостаточно — `agent-pr` ставит тело один раз при
    открытии, и на площадке останется старое. Дальше нужен человек: правка тела
    через API и ручной перезапуск проверки.

    ЗАМЕР 7 сентября: ТРИ красных подряд по этой причине — изменения #372, #373
    и #376, все с «в теле нет строки связи с задачей» либо «часть без остатка»,
    при том что в коммите строка была либо дописывалась следом. Каждое стоило
    правки через API и перезапуска.

    ПОЧЕМУ ПРОГОН ПЕРЕД ТОЛЧКОМ ЭТОГО НЕ ЛОВИЛ. Он читает тело первого коммита
    ветки, а зовут его ПЕРЕД коммитом — на тот момент тела ещё нет, и шаг
    честно отвечает третьим исходом. Механизм существовал и срабатывал мимо:
    ровно то, о чём 018 — у проверки есть окружение, где она осмысленна.
    Здесь оно единственное: между коммитом и толчком.
    """
    скрипт = корень / "scripts" / "pr_body.py"
    if not скрипт.exists():
        return None                     # чужое дерево — не наш предмет
    тело = первый_коммит_ветки(корень)
    if тело is None:
        return None
    done = subprocess.run([sys.executable, str(скрипт), "--check", "--body-file", "-"],
                          input=тело, capture_output=True, text=True, encoding="utf-8")
    if done.returncode == 0:
        return None
    if done.returncode == 2:
        return None                     # проверка не отработала — не мешаем (039)
    return (done.stdout + done.stderr).strip()


def main() -> int:
    try:
        event = json.load(sys.stdin)
    except (ValueError, OSError):
        return 0                        # не разобрали событие — не мешаем
    if event.get("tool_name") != "Bash":
        return 0
    command = (event.get("tool_input") or {}).get("command") or ""
    branch = current_branch()
    if branch is None or branch == "HEAD":
        return 0                        # отделённая голова — сравнивать не с чем
    чужие = targets(command, branch)
    if чужие:
        print(f"толчок в {', '.join(чужие)}, а окно стоит на {branch}. "
              "Содержимое уехало бы не туда, куда смотрит окно (правило 012). "
              f"Если ветка верна — перейдите в неё: git switch {чужие[0]}",
              file=sys.stderr)
        return 2

    # ВТОРОЙ ПРЕДМЕТ ТОГО ЖЕ ХУКА: тело, из которого конвейер соберёт изменение.
    # ТОЛЧОК УЗНАЁТСЯ РАЗБОРОМ, А НЕ ВХОЖДЕНИЕМ СЛОВА, и это поймано пробой на
    # самом хуке: первая редакция спрашивала «есть ли слово push среди слов» и
    # отвергла команду, где эти два слова стояли ВНУТРИ строки-аргумента —
    # текстом для другой программы, а не действием. Тот же довод, что у соседа
    # выше про heredoc: сторож смотрит на действие. Ложный отказ здесь дороже
    # пропуска — он останавливает работу, которая ничего не нарушает (051).
    if not толкает(command):
        return 0
    беда = тело_не_проходит(Path.cwd())
    if беда:
        print("тело первого коммита ветки не пройдёт гейт изменения:\n"
              f"{беда}\n"
              "Конвейер ставит тело изменения ОДИН раз при открытии — поправить "
              "коммит после толчка уже недостаточно, придётся править тело через "
              "API и перезапускать проверку руками. Поправьте здесь: "
              "git commit --amend", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
