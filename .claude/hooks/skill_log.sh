#!/bin/sh
# Обёртка журнала навыков: зовёт skill_log.py интерпретатором планки (#866).
#
# Журнал — канал без права голоса: ни отказ записи, ни отсутствие
# интерпретатора не мешают вызову навыка (084): хук выходит с кодом 0, а не
# закрывает работу, как страж толчка, — тот сторожит действие, этот записывает.
dir=$(dirname "$0")
. "$dir/floor.sh"
floor=$(planka_floor "${CLAUDE_PROJECT_DIR:-.}/pyproject.toml")
py=""
[ -n "$floor" ] && py=$(command -v "python$floor" 2>/dev/null)
# Без планки — системный python3: разбор журнала держит грамматику 3.11, и
# молча пустой журнал хуже записи младшим интерпретатором (находка обзора #868).
[ -z "$py" ] && py=$(command -v python3 2>/dev/null)
if [ -n "$py" ]; then
  exec "$py" "$dir/skill_log.py" "$@"
fi
echo "журнал навыков: ни python${floor:-?}, ни python3 нет — вызов не записан" >&2
exit 0
