#!/bin/sh
# Обёртка журнала навыков: зовёт skill_log.py интерпретатором планки (#866).
#
# Журнал — канал без права голоса: ни отказ записи, ни отсутствие
# интерпретатора не мешают вызову навыка (084). Поэтому без планки хук молча
# выходит с кодом 0, а не закрывает работу, как страж толчка: тот сторожит
# действие, этот только записывает.
dir=$(dirname "$0")
. "$dir/floor.sh"
floor=$(planka_floor "${CLAUDE_PROJECT_DIR:-.}/pyproject.toml")
py=""
[ -n "$floor" ] && py=$(command -v "python$floor" 2>/dev/null)
if [ -n "$py" ]; then
  exec "$py" "$dir/skill_log.py" "$@"
fi
echo "журнал навыков: интерпретатора python${floor:-?} нет — вызов не записан" >&2
exit 0
