#!/bin/sh
# Обёртка журнала навыков: зовёт skill_log.py интерпретатором планки (#866).
#
# ТОЛЬКО ПЛАНКОЙ, И ЭТО ПРАВИЛО 217, А НЕ ВКУС. Хук окна исполняется в окружении
# процесса окна, где голый `python3` — системный, а не планки. Здесь стоял
# запасной `python3` (#869, #875) — ровно инцидент 217, возвращённый починкой
# находки по 211; заметил владелец. Интерпретатор планки ставит хук старта
# окна, и его отсутствие — поломка окна, а не повод исполнить код другим.
#
# Журнал — канал без права голоса (084): без планки хук не закрывает работу, как
# страж толчка, а называет поломку в stderr и выходит с кодом 0.
dir=$(dirname "$0")
. "$dir/floor.sh"
floor=$(planka_floor "${CLAUDE_PROJECT_DIR:-.}/pyproject.toml")
py=""
[ -n "$floor" ] && py=$(command -v "python$floor" 2>/dev/null)
if [ -n "$py" ]; then
  exec "$py" "$dir/skill_log.py" "$@"
fi
echo "журнал навыков: интерпретатора планки python${floor:-?} нет — хук старта его не поставил, вызов не записан. Перезапустите окно (217)." >&2
exit 0
