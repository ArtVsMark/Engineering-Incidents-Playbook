#!/bin/bash
# Старт облачной сессии: Python 3.14 на месте, окружение проверки — на планке.
#
# ТОЛЬКО В ОБЛАКЕ. На машине владельца окружение его, и ставить туда
# интерпретатор без спроса хук не вправе: признак облака — CLAUDE_CODE_REMOTE.
#
# ЗАЧЕМ СТАВИТЬ ИНТЕРПРЕТАТОР. Ставится версия ПЛАНКИ, а не прошитая: сейчас
# это 3.14 (решение владельца 1 октября), а образ облачного окна несёт только
# 3.10–3.13, и встроенный uv 0.8.17 знает лишь 3.14.0rc2. Сайт установщика uv
# (astral.sh) закрыт сетевой политикой, PyPI — открыт, поэтому uv ставится из
# PyPI. Замер 1 октября: uv 0.12.21 ставит 3.14.7 за ~2 с.
#
# ВЕРСИЯ uv ЗАКРЕПЛЕНА. Хук исполняет поставленное с правом записи в
# /usr/local/bin при каждом старте окна; незакреплённая версия значила бы, что
# код, который здесь исполняется, меняется без единой правки дерева.
#
# ЗАЧЕМ .venv НА ПЛАНКЕ. Системный python3 образа — 3.11, ниже планки, и
# прогон перед толчком с него отказывает (check_python_version.py). Окружение
# собирается на версии из requires-python — той же, на которой гоняет
# конвейер, — поэтому «чисто локально» снимается с его поверхности (037).
# Сдвинется планка — хук сам соберёт окружение на новой версии.
#
# СБОЙ СЕТИ НЕ РОНЯЕТ СТАРТ. Хук ходит в PyPI и за интерпретатором, а
# «стартовый хук на сетевом вызове превращает открытие окна в лотерею» — так
# это записано у хука грейдера, который поэтому в сеть не ходит вовсе. Здесь
# сеть нужна, поэтому иначе: всякий отказ — предупреждение с названным шагом и
# выход 0. Окно открывается всегда; не готово только то, что названо.
set -uo pipefail

#: Версия uv, которой ставится интерпретатор. Двигается правкой этой строки.
UV_VERSION="0.12.21"
#: Куда ставится uv и куда кладётся ссылка на интерпретатор. Переопределяются
#: только набором — чтобы ветку установки исполнить, а не прочесть.
UV_HOME="${SESSION_START_UV_HOME:-/opt/uv}"
BIN_DIR="${SESSION_START_BIN_DIR:-/usr/local/bin}"

warn() {
  echo "старт окна: $1 — окно работает без этого; прогон перед толчком запускайте интерпретатором не ниже планки вручную" >&2
}

if [ "${CLAUDE_CODE_REMOTE:-}" != "true" ]; then
  exit 0
fi
# Переменные площадки читаются с умолчанием: при `set -u` их отсутствие
# уронило бы хук ненулевым кодом мимо обещания «выход 0 всегда».
project="${CLAUDE_PROJECT_DIR:-}"
env_file="${CLAUDE_ENV_FILE:-}"

# Планку читает floor.sh — без Python: интерпретатора планки на машине ещё нет,
# а системный python3 окна (3.11) читать код каталога в стиле планки не умеет.
# Почему это не второй разбор по смыслу — сказано в floor.sh (214).
. "$(dirname "$0")/floor.sh"

# СТРОКА СТАТУСА — ОДНА, В STDOUT, ПРИ ЛЮБОМ ИСХОДЕ В ОБЛАКЕ. stdout хука
# старта площадка кладёт в контекст окна, stderr — нет: предупреждения хука
# видит человек, а окно — нет. Вне облака хук молчит целиком: окружение там
# владельца, и судить его хук не берётся. Строка называет итог по трём звеньям
# переезда (217): `python3` окна, .venv и страж толчка. Спрашивается состояние
# на выходе, а не пройденные шаги, поэтому ловушка ставится ДО первого раннего
# выхода, и «зелёная» строка не шире проверки: .venv считается на планке,
# только если он на её версии, с зависимостями, обновлёнными в этот старт, и
# выставлен в PATH окна через файл окружения площадки (находки обзора #675).
pyver() {
  "$1" -c 'import sys; print("%d.%d.%d" % sys.version_info[:3])' 2>/dev/null
}
#: Звенья, которые знает только сам хук: состояние машины их не выдаёт.
in_project=""
deps_stale=""
status_line() {
  local f full py3 venv out=""
  if [ -z "$in_project" ]; then
    echo "окно НЕ на планке: нет каталога проекта (CLAUDE_PROJECT_DIR) — Python окна не проверен"
    return
  fi
  f=$(planka_floor pyproject.toml)
  if [ -z "$f" ]; then
    echo "окно НЕ на планке: в pyproject.toml нет requires-python"
    return
  fi
  full=""
  command -v "python$f" >/dev/null 2>&1 && full=$(pyver "python$f")
  py3=$(pyver python3)
  venv=$(pyver .venv/bin/python)
  # Страж толчка зовётся тем же python$f (push_guard.sh): нет его — толчок
  # закрыт, и это называется отдельно от отсутствия интерпретатора.
  [ -n "$full" ] || out="$out; python$f не поставлен, страж толчка закрыт"
  [ "${py3%.*}" = "$f" ] || out="$out; python3 — ${py3:-нет}"
  if [ "${venv%.*}" != "$f" ]; then
    out="$out; .venv — ${venv:-нет}"
  elif [ ! -e .venv/.deps-installed ]; then
    out="$out; .venv без тестовых зависимостей"
  else
    [ -z "$deps_stale" ] || out="$out; тестовые зависимости .venv не обновлены"
    # PATH окна виден только через файл окружения: процесс окна читает его
    # после хука, и спросить свой PATH хук не может.
    # Сверяется ТА ЖЕ строка, что пишет хук, целиком (-x): подстрока пути
    # совпала бы с комментарием, чужим export или `.venv/bin2`, а провал
    # самой записи остался бы зелёным (находка обзора #676).
    grep -qxF "$path_line" "${env_file:-/dev/null}" 2>/dev/null \
      || out="$out; .venv не выставлен в PATH окна"
  fi
  if [ -z "$out" ]; then
    echo "окно на $full: python3, .venv и страж толчка — на планке"
  else
    echo "окно НЕ на планке $f: ${out#; }"
  fi
}
# Строка PATH для файла окружения — одна на запись и на сверку статуса.
# Она ИДЕМПОТЕНТНА: файл окружения перечитывается не один раз за жизнь окна,
# и безусловный `export PATH=…:$PATH` копил одинаковые звенья — замер 02.10:
# .venv/bin в PATH десять раз подряд.
path_line="case \":\$PATH:\" in *\":$project/.venv/bin:\"*) ;; *) export PATH=\"$project/.venv/bin:\$PATH\" ;; esac"
trap status_line EXIT

if [ -z "$project" ] || ! cd "$project"; then
  warn "нет каталога проекта (CLAUDE_PROJECT_DIR)"
  exit 0
fi
in_project=1

floor=$(planka_floor pyproject.toml)
if [ -z "$floor" ]; then
  warn "в pyproject.toml нет requires-python — планки, на которой собирать окружение, нет"
  exit 0
fi

if ! command -v "python$floor" >/dev/null 2>&1; then
  { python3.12 -m venv "$UV_HOME" \
      && "$UV_HOME/bin/pip" install -q "uv==$UV_VERSION" \
      && "$UV_HOME/bin/uv" python install "$floor" \
      && ln -sf "$("$UV_HOME/bin/uv" python find "$floor")" "$BIN_DIR/python$floor"; } \
    || { warn "Python $floor не поставлен"; exit 0; }
fi

# `python3` ОКНА — ВЕРСИЯ ПЛАНКИ, а не только `python$floor` рядом. Хуки
# площадки исполняются в окружении самого процесса окна, куда PATH из
# CLAUDE_ENV_FILE не доходит, и голый `python3` там — тот, что пришёл с
# образом. Замер 02.10: /usr/local/bin/python3 → /usr/bin/python3.11 при уже
# поставленном python3.14 рядом — переезд был формальным и здесь.
if [ "$(python3 -c 'import sys; print("%d.%d" % sys.version_info[:2])' 2>/dev/null)" != "$floor" ]; then
  ln -sf "$(command -v "python$floor")" "$BIN_DIR/python3" \
    || warn "python3 окна не переключён на $floor"
fi

if [ ! -x .venv/bin/python ] || [ "$(.venv/bin/python -c 'import sys; print("%d.%d" % sys.version_info[:2])')" != "$floor" ]; then
  rm -rf .venv
  "python$floor" -m venv .venv || { warn "окружение на $floor не собрано"; exit 0; }
  touch .venv/.built-by-hook
fi
# Два разных сбоя pip. Различает их МЕТКА в самом .venv, которую кладёт
# только успешная установка: признак живёт в дереве и переживает перезапуск
# окна, а пересборка .venv стирает его вместе с окружением. Метка есть —
# зависимости когда-то стояли, окно окружение не теряет: PATH выставляется с
# предупреждением. Метки нет — зависимостей не было никогда, и пустой .venv
# в PATH окну не нужен. Исключение — .venv, собранный ПРЕЖНИМ хуком, который
# меток не клал вовсе: нет ни метки зависимостей, ни метки сборки
# (.built-by-hook), а `pip freeze` не пуст. Такой метится задним числом, а не
# теряет PATH на первом же сбое сети (находка обзора #664). Метка сборки —
# ЗАЩИТНАЯ, наблюдённого случая за ней нет: pip сначала разрешает и качает
# всё, а ставит потом, так что сбой сети оставляет freeze пустым. Непустым
# его на своём .venv делает только сбой в САМОЙ фазе установки (кончилось
# место, процесс убит) — и тогда исключение «прежний .venv» досталось бы
# окружению без целых зависимостей (находка обзора #665). Цена метки — один
# пустой файл, а без неё условие опиралось бы на то, как pip упорядочивает
# свои фазы.
deps_mark=.venv/.deps-installed
if .venv/bin/pip install -q -r requirements-test.txt; then
  touch "$deps_mark"
elif [ -e "$deps_mark" ] || { [ ! -e .venv/.built-by-hook ] && [ -n "$(.venv/bin/pip freeze 2>/dev/null)" ]; }; then
  touch "$deps_mark"
  deps_stale=1
  warn "тестовые зависимости не обновлены — окружение на $floor оставлено как было"
else
  warn "окружение на $floor собрано, но тестовые зависимости не поставлены ни разу — в PATH не выставлено"
  exit 0
fi

if [ -z "$env_file" ]; then
  warn "площадка не дала CLAUDE_ENV_FILE — .venv собран, но в PATH окна не выставлен"
  exit 0
fi
grep -qxF "$path_line" "$env_file" 2>/dev/null || echo "$path_line" >> "$env_file"
exit 0
