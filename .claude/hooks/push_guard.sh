#!/bin/sh
# Обёртка стража толчка: зовёт push_guard.py ИНТЕРПРЕТАТОРОМ ПЛАНКИ.
#
# ПОЧЕМУ НЕ `python3` НАПРЯМУЮ. Хук исполняется в окружении самого процесса
# окна, а не в PATH, который хук старта выставил командам (CLAUDE_ENV_FILE
# действует только на них). Голый `python3` там — системный 3.11, и страж в
# стиле 3.14 падал бы на нём SyntaxError'ом. Ненулевой код, кроме 2, площадка
# считает НЕблокирующей ошибкой: толчок прошёл бы без проверки, молча.
#
# НЕТ ИНТЕРПРЕТАТОРА ПЛАНКИ — ТОЛЧОК ЗАКРЫТ, ОСТАЛЬНОЕ ОТКРЫТО. Хук стоит на
# каждой команде оболочки; закрыть всё значило бы обездвижить окно из-за
# сбоя сети при старте. Закрывается только то, что страж и сторожит.
dir=$(dirname "$0")
. "$dir/floor.sh"
floor=$(planka_floor "${CLAUDE_PROJECT_DIR:-.}/pyproject.toml")
py=""
[ -n "$floor" ] && py=$(command -v "python$floor" 2>/dev/null)
if [ -n "$py" ]; then
  exec "$py" "$dir/push_guard.py"
fi
# ЗАПАСНОЙ РАЗБОР ГРУБЕЕ СТРАЖА, И ГРАНИЦА ЕГО СДВИНУТА В СТОРОНУ ЗАКРЫТИЯ.
# Литерал «git push» пропускал `git -C путь push`, `git p''ush`, `git\tpush`, и
# такие толчки уходили непроверенными (находка обзора #672). Здесь из входа
# берётся ТОЛЬКО поле `command` — не весь JSON, где `cwd` и пути могут нести
# слово `git` (находка обзора #710), — с него снимаются кавычки и обратные
# косые, и закрывается команда, где `push` стоит после `git`. Лишне закрытое
# (`git stash push`, `git log | grep push`) стоит одной команды в окне,
# которое и так сломано. ГРАНИЦА: косвенный толчок — `c=push; git $c`,
# подстановка, алиас — не видит ни этот разбор, ни сам страж.
#
# Поле достаётся awk, а не python: python здесь как раз и нет. КЛЮЧ ИЩЕТСЯ
# КАК КЛЮЧ — `"command"`, за которым двоеточие: первое вхождение СЛОВА могло
# быть значением (`"description":"command"`), и разбор отдавал пустую команду,
# то есть открывал толчок (находка обзора #712). Разбор, не нашедший ключа,
# отдаёт ВЕСЬ вход: неуверенность решается прежним грубым правилом, то есть
# закрытием, а не открытием. ЦЕНА ЭТОГО — НАЗВАННАЯ ГРАНИЦА, А НЕ ДЫРА: без
# ключа-строки (`"command": null`, массив, иная форма входа) слово `git` из
# `cwd` или пути снова может лишне закрыть постороннюю команду со словом
# `push` — класс #710 возвращается, но только в сторону закрытия. У Bash-хука
# площадки ключ-строка есть всегда, поэтому дальше эта ветка не уточняется:
# третья находка по одному месту (обзор #714) закрыта решением владельца
# 08.10 записать границу, а не латать форму (210).
# Строка JSON читается посимвольно, с `\"` внутри;
# `\uXXXX` не раскрывается — для слов `git` и `push` (ASCII) это не нужно.
input=$(cat | awk '
  { buf = buf $0 "\n" }
  END {
    if (!match(buf, /"command"[ \t\n]*:[ \t\n]*"/)) {
      gsub(/["\047\\]/, "", buf)
      print buf
      exit
    }
    rest = substr(buf, RSTART + RLENGTH)
    out = ""
    for (k = 1; k <= length(rest); k++) {
      c = substr(rest, k, 1)
      if (c == "\\") { k++; continue }
      if (c == "\"") break
      out = out c
    }
    gsub(/\047/, "", out)
    print out
  }')
case "$input" in
  *git*push*)
    echo "страж толчка не запущен: интерпретатора планки python${floor:-?} нет в окне — хук старта его не поставил. Толчок закрыт до починки: без стража он ушёл бы непроверенным. Перезапустите окно или поставьте python${floor:-?} вручную." >&2
    exit 2 ;;
esac
exit 0
