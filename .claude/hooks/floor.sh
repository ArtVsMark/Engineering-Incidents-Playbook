# Планка requires-python, прочитанная БЕЗ Python. Подключается через `.`.
#
# ПОЧЕМУ ВТОРОЙ РАЗБОР, ХОТЯ ЕСТЬ check_python_version.floor (214). Хукам он
# нужен ДО того, как на машине есть интерпретатор планки: хук старта по нему
# решает, какую версию ставить, а обёртка стража — каким интерпретатором его
# звать. Читать его пришлось бы системным python3 окна (3.11), и тогда
# check_python_version.py навсегда остался бы в грамматике 3.11 — ровно
# формальный переезд, который здесь и убран. Разбор один и тот же по смыслу
# держит тест: tests/test_session_start_hook.py сверяет этот sed с
# check_python_version.floor на настоящем манифесте и на подделках.
planka_floor() {
  sed -nE 's/^[[:space:]]*requires-python[[:space:]]*=[[:space:]]*"[^"0-9]*([0-9]+)\.([0-9]+).*/\1.\2/p' \
    "${1:-pyproject.toml}" 2>/dev/null | head -n 1
}
