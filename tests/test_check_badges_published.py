"""Ссылка на ветку значков: находится несобранное, пропускается собранное.

Разбор адреса и обе его формы проверены самопроверкой скрипта; здесь предмет
другой — доезжает ли решение до кода возврата, различает ли гейт три исхода и
берёт ли он своё имя у `origin`, когда его не назвали ключом (039, 140, 005).
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import check_badges_published as cbp
from conftest import write

СВОЁ = "Хозяин/Каталог"
НА_ВЕТКЕ = ".github/badges/version.json"
НЕТ_НА_ВЕТКЕ = ".github/badges/tests.json"


def адрес(путь: str, репозиторий: str = СВОЁ) -> str:
    return f"https://{cbp.HOST}/{репозиторий}/{cbp.BRANCH}/{путь}"


def ветка(корень: Path, *пути: str) -> Path:
    """Снимок ветки: каталог, содержимое которого её и составляет."""
    for п in пути:
        write(корень / п, "{}")
    return корень


def прогон(документы: Path, снимок: Path, *ключи: str) -> int:
    return cbp.main(["--published", str(снимок), "--docs", str(документы),
                     *ключи])


def test_ссылка_на_несобранное_есть_находка(repo: Path) -> None:
    write(repo / "дерево" / "README.md", адрес(НЕТ_НА_ВЕТКЕ))
    снимок = ветка(repo / "ветка", НА_ВЕТКЕ)
    assert прогон(repo / "дерево", снимок, "--slug", СВОЁ) == 1


def test_ссылка_на_лежащее_на_ветке_чиста(repo: Path) -> None:
    write(repo / "дерево" / "README.md", адрес(НА_ВЕТКЕ))
    снимок = ветка(repo / "ветка", НА_ВЕТКЕ)
    assert прогон(repo / "дерево", снимок, "--slug", СВОЁ) == 0


def test_адрес_внутри_url_кодированного_параметра_читается(repo: Path) -> None:
    """Восемь ссылок из двадцати одной живут так, и сырым поиском их нет."""
    сырой = адрес(НЕТ_НА_ВЕТКЕ)
    закодированный = сырой.replace(":", "%3A").replace("/", "%2F")
    документ = f"https://img.shields.io/endpoint?url={закодированный}&style=flat"
    write(repo / "дерево" / "README.md", документ)
    # Смысл случая: без декодирования этой ссылки в документе НЕТ.
    assert сырой not in документ
    снимок = ветка(repo / "ветка", НА_ВЕТКЕ)
    assert прогон(repo / "дерево", снимок, "--slug", СВОЁ) == 1


def test_ветка_чужого_репозитория_не_наш_предмет(repo: Path) -> None:
    """Её рисуем не мы: находки нет, но и предмета нет — это третий исход."""
    write(repo / "дерево" / "README.md", адрес(НЕТ_НА_ВЕТКЕ, "Сосед/Проект"))
    снимок = ветка(repo / "ветка", НА_ВЕТКЕ)
    assert прогон(repo / "дерево", снимок, "--slug", СВОЁ) == 2


def test_ни_одной_ссылки_это_отказ_разбора(repo: Path) -> None:
    """Витрина без них не работает: зелёное здесь скрыло бы протухший разбор."""
    write(repo / "дерево" / "README.md", "текст без единого адреса")
    снимок = ветка(repo / "ветка", НА_ВЕТКЕ)
    assert прогон(repo / "дерево", снимок, "--slug", СВОЁ) == 2


def test_нет_снимка_ветки_сверять_не_с_чем(repo: Path) -> None:
    write(repo / "дерево" / "README.md", адрес(НА_ВЕТКЕ))
    assert прогон(repo / "дерево", repo / "нет-такого", "--slug", СВОЁ) == 2


def test_пустой_снимок_ветки_это_отказ(repo: Path) -> None:
    write(repo / "дерево" / "README.md", адрес(НА_ВЕТКЕ))
    (repo / "пусто").mkdir()
    assert прогон(repo / "дерево", repo / "пусто", "--slug", СВОЁ) == 2


def test_двоичный_файл_пропускается_а_не_роняет(repo: Path) -> None:
    write(repo / "дерево" / "README.md", адрес(НА_ВЕТКЕ))
    (repo / "дерево" / "значок.png").write_bytes(b"\x89PNG\r\n\x1a\n\xff\xfe")
    снимок = ветка(repo / "ветка", НА_ВЕТКЕ)
    assert прогон(repo / "дерево", снимок, "--slug", СВОЁ) == 0


def test_своё_имя_берётся_у_origin_а_не_вписано(repo: Path) -> None:
    """Ключа `--slug` нет: имя обязано прийти из адреса origin (005)."""
    дерево = repo / "дерево"
    дерево.mkdir()
    subprocess.run(["git", "-C", str(дерево), "init", "-q"], check=True)
    subprocess.run(["git", "-C", str(дерево), "remote", "add", "origin",
                    f"https://github.com/{СВОЁ}.git"], check=True)
    write(дерево / "README.md", адрес(НЕТ_НА_ВЕТКЕ))
    снимок = ветка(repo / "ветка", НА_ВЕТКЕ)
    assert прогон(дерево, снимок) == 1


def test_без_origin_проверка_не_отрабатывает(repo: Path) -> None:
    """Чья ветка в ссылке — неизвестно, и это отказ, а не чистый прогон (075)."""
    write(repo / "дерево" / "README.md", адрес(НА_ВЕТКЕ))
    снимок = ветка(repo / "ветка", НА_ВЕТКЕ)
    assert прогон(repo / "дерево", снимок) == 2
