"""Гейт соседей сверяет ответ по всей цепочке замещения (обзор #899)."""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))

import check_duplicates as cd  # noqa: E402

ВЕРДИКТ = (
    "Предмет другой: соседи говорят про подпись записи, эта запись — "
    "про порядок очереди, и общего у них только слова."
)


def запись(номер: str, суть: str, замена: str = "") -> str:
    """Подделка правила в форме каталога; `замена` — номер в «Заменено»."""
    пометка = f"**Заменено.** {замена}\n\n" if замена else ""
    return (
        f"# Подделка {номер}\n\n**Правило.** {суть}.\n\n{пометка}"
        f"## Инцидент\n\nМеханизм сломался так, что {суть}.\n\n"
        f"## Применимость\n\n**Работает** там, где {суть}.\n\n"
        "## След\n\nArtVsMark/Engineering-Incidents-Playbook#1\n"
    )


def дерево(tmp_path: Path, рассмотрено_новым: list[str]) -> Path:
    """003 заменено 150, 150 заменено 160: цепочка из двух замен."""
    папка = tmp_path / "rules" / "ru"
    папка.mkdir(parents=True)
    правила = {
        "001": ("учётные данные подменяются на записи, и автором становится приложение", ""),
        "002": ("подпись записи это свойство окна, и узнаётся она пробой", ""),
        "003": ("учётные данные подменяются на записи окна, и автором становится бот", "150"),
        "145": ("учётные данные подменяются, и автором становится приложение", ""),
        "150": ("журнал выпуска собирается фрагментами без общего файла", "160"),
        "160": ("журнал выпуска собирается фрагментами по одному на изменение", ""),
    }
    for номер, (суть, замена) in правила.items():
        (папка / f"{номер}-r.md").write_text(запись(номер, суть, замена), encoding="utf-8")
    (tmp_path / ".rules").mkdir()
    ответы = {
        "145": {"considered": рассмотрено_новым, "verdict": ВЕРДИКТ},
        "160": {"considered": ["001", "002", "003", "145", "150"], "verdict": ВЕРДИКТ},
    }
    (tmp_path / ".rules" / "neighbours.json").write_text(
        json.dumps({"baseline": 144, "answers": ответы}, ensure_ascii=False), encoding="utf-8"
    )
    return tmp_path


def test_замещённая_в_верхушку_не_встаёт_встаёт_её_преемник(tmp_path, capsys):
    """Замещённое правилом не является: в соседях его нет, есть его преемник (17.10)."""
    корень = дерево(tmp_path, ["001", "002"])
    assert cd.mode_check(корень) == 1
    err = capsys.readouterr().err
    assert "верхние соседи не рассмотрены — 160" in err
    assert "003 (" not in err and "150 (" not in err


def test_ответ_о_замещённой_закрывает_её_последнего_преемника(tmp_path):
    """Ответ, данный до слияния, назвал 003 — сосед 160 закрыт по цепочке 003 → 150 → 160."""
    корень = дерево(tmp_path, ["001", "002", "003"])
    assert cd.mode_check(корень) == 0


def test_замещённые_не_входят_в_счёт_и_самую_близкую_пару(tmp_path, capsys):
    """«Самая близкая пара» не бывает парой «запись ↔ её сводная», счёт — по действующим."""
    корень = дерево(tmp_path, ["001", "002", "160"])
    assert cd.mode_check(корень) == 0
    out = capsys.readouterr().out
    assert "правил 4 (ещё 2 заменены)" in out
    пара = out.split("самая близкая пара корпуса:")[1].split("(")[0]
    assert "003" not in пара and "150" not in пара
