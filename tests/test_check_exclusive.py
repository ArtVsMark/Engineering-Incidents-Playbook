"""Исключительные утверждения сверяются друг с другом: гейт проверяется тем, что
обязан отвергнуть, и тем, что обязан пропустить.

ГЛАВНОЕ ЗДЕСЬ НЕ СЛУЧАИ, А ЗАМЕР НА ЖИВОМ ИНЦИДЕНТЕ, и он записан в докстроке
скрипта: способ прогнан по CLAUDE.md грейдера (1245 строк, 39 исключительных
утверждений, 741 пара), и настоящая противоречащая пара встала ВТОРЫМ местом.
Без этого механизм был бы гипотезой о том, что близость предмета ловит
противоречие (037).

Гейт не судит: порога у меры нет, и «противоречие» он не объявляет никогда — он
требует ОТВЕТА по верхним парам. Поэтому случаи спрашивают наличие ответа, а не
вердикт.

Источник подделки (правило 170): подделываются свои же документы — тексты
сочинены здесь нарочно; настоящая сторона у гейта это дерево каталога, и на нём
он гоняется конвейером.
"""

from __future__ import annotations

import json

import check_exclusive as ce


ДЛИННОЕ = ("Состояние находки живёт только в самой задаче: реестр в документе "
           "аудита заполняется один раз, при архивации, потому что два "
           "источника означают один устаревший.")
ВТОРОЕ = ("Закрыл находку — впиши её в реестр тем же заходом: состояние находки "
          "читают только оттуда, и пропущенная строка означает, что документ "
          "числит закрытое открытым.")


def дерево(tmp_path, файлы: dict[str, str], ответы: dict | None = None):
    (tmp_path / ".rules").mkdir(exist_ok=True)
    for имя, текст in файлы.items():
        (tmp_path / имя).write_text(текст, encoding="utf-8")
    if ответы is not None:
        (tmp_path / ".rules" / "exclusives.json").write_text(
            json.dumps({"answers": ответы}, ensure_ascii=False), encoding="utf-8")
    return tmp_path


# ── что попадает в предмет ─────────────────────────────────────────────────

def test_isklyuchitelnoe_utverzhdenie_nahoditsya(tmp_path):
    корень = дерево(tmp_path, {"AGENTS.md": ДЛИННОЕ})
    утв = ce.утверждения(корень)
    assert len(утв) == 1
    assert утв[0][0].startswith("AGENTS.md#") and утв[0][1].startswith("AGENTS.md:")


def test_bez_markera_ne_predmet(tmp_path):
    """Без «только» два утверждения совместимы — исключительность и есть то,
    что превращает два верных ответа в один неверный."""
    корень = дерево(tmp_path, {"AGENTS.md": ДЛИННОЕ.replace("только ", "")})
    assert ce.утверждения(корень) == []


def test_korotkoe_ne_predmet(tmp_path):
    """«Только» в заголовке или подписи предметом не является, а шумит."""
    корень = дерево(tmp_path, {"AGENTS.md": "## Только для окна"})
    assert ce.утверждения(корень) == []


def test_stroka_tablitsy_ne_abzats(tmp_path):
    """ГРАНИЦА, НАЙДЕННАЯ ЗАМЕРОМ: первая редакция брала абзац целиком, и три
    верхние пары из пяти оказались таблица-против-таблицы — близость давала
    РАЗМЕТКА, а не предмет. Ячейка к тому же описывает предмет своей строки и
    документ не связывает."""
    таблица = ("| Что | Как |\n| --- | --- |\n"
               "| гейт | смотрит только на объявленные пути и ничего сверх "
               "того, потому что иначе краснеет на верном |\n")
    корень = дерево(tmp_path, {"AGENTS.md": таблица})
    assert ce.утверждения(корень) == []


def test_dokument_vne_spiska_ne_smotritsya(tmp_path):
    """Свод правил под гейт не подпадает: там исключительность и есть предмет
    записи, и краснеть на ней значило бы краснеть на работе (051)."""
    (tmp_path / "rules").mkdir()
    (tmp_path / "rules" / "001-x.md").write_text(ДЛИННОЕ, encoding="utf-8")
    assert ce.утверждения(tmp_path) == []


# ── ключ пары ──────────────────────────────────────────────────────────────

def test_klyuch_ne_zavisit_ot_poryadka():
    assert ce.ключ("a.md#1", "b.md#2") == ce.ключ("b.md#2", "a.md#1")


def test_imya_ustoychivo_k_pravke_sosseda():
    """ГЛАВНЫЙ УРОК ЭТОГО ГЕЙТА, найденный живым отказом: имя пары не должно
    зависеть от НОМЕРА СТРОКИ. Первая редакция звала пару «файл:строка», и
    первая же правка выше по документу сдвинула номера — пять записанных
    вердиктов разом перестали находиться (125)."""
    было = ce.имя_пары("AGENTS.md", ДЛИННОЕ)
    стало = ce.имя_пары("AGENTS.md", ДЛИННОЕ)
    assert было == стало
    assert ce.имя_пары("AGENTS.md", ДЛИННОЕ + " и ещё") != было


# ── что гейт обязан отвергнуть ─────────────────────────────────────────────

def test_para_bez_otveta_otkaz(tmp_path):
    корень = дерево(tmp_path, {"AGENTS.md": ДЛИННОЕ, "START.md": ВТОРОЕ}, {})
    assert ce.main(["--root", str(корень), "--check"]) == 1


def test_net_otveta_faylom_eto_tretiy_ishod(tmp_path):
    корень = дерево(tmp_path, {"AGENTS.md": ДЛИННОЕ, "START.md": ВТОРОЕ})
    assert ce.main(["--root", str(корень), "--check"]) == 2


def test_net_utverzhdeniy_eto_tretiy_ishod(tmp_path):
    """Гейт, не нашедший предмета, обязан упасть, а не зазеленеть (075)."""
    корень = дерево(tmp_path, {"AGENTS.md": "обычный текст без исключений"}, {})
    assert ce.main(["--root", str(корень), "--check"]) == 2


# ── что гейт обязан пропустить ─────────────────────────────────────────────

def test_s_otvetom_chisto(tmp_path):
    корень = дерево(tmp_path, {"AGENTS.md": ДЛИННОЕ, "START.md": ВТОРОЕ})
    утв = ce.утверждения(корень)
    к = ce.ключ(утв[0][0], утв[1][0])
    (корень / ".rules" / "exclusives.json").write_text(
        json.dumps({"answers": {к: {"verdict": "разные предметы", "why": "..."}}},
                   ensure_ascii=False), encoding="utf-8")
    assert ce.main(["--root", str(корень), "--check"]) == 0


def test_near_pokazyvaet_i_ne_sudit(tmp_path, capsys):
    """`--near` НИКОГДА не отвечает отказом: он показывает, а решает человек —
    порога у меры нет, и самая близкая пара обычно законна."""
    корень = дерево(tmp_path, {"AGENTS.md": ДЛИННОЕ, "START.md": ВТОРОЕ})
    assert ce.main(["--root", str(корень), "--near"]) == 0
    assert "↔" in capsys.readouterr().out
