"""Набор подделок проверяется тем же приёмом, что применяет сам.

У этого скрипта отрицательного предмета не было ни в каком виде: он прогоняет
подделки ЧУЖИХ гейтов, а собственная его поломка не ловилась ничем. Найдено
подъёмом метрики «без отвергаемого предмета» до отказа — до этого числа
печатались и ни к чему не вели.

ЧТО ИМЕННО ЗДЕСЬ ЛОВИТСЯ. Три поломки, и все три тихие:

  · вердикт вынесен посреди перебора — случаи за ним бегут в пустоту, а прогон
    отвечает «расхождений нет» (правило 159, приехало от витрины 31 августа);
  · третий исход слит со вторым — «набор не отработал» записывается в находки,
    и чинить начинают не то (039);
  · находка не названа — красное без предмета чинить нечем (158).

Сеть и площадка не трогаются: главный ход зовётся с подменёнными наборами,
потому что предмет здесь — СВОДКА по наборам, а не их содержимое.
"""

from __future__ import annotations

import check_gates as cg


def набор(находки: list[str], сломан: int = 0):
    """Поддельный набор: отдаёт заданные находки и заданный третий исход."""
    return lambda: (находки, сломан)


def подменить(monkeypatch, наборы: list) -> None:
    """Главный ход зовёт свои наборы через один кортеж — его и подменяем."""
    monkeypatch.setattr(cg, "suite_attribution", наборы[0])
    for имя in ("suite_audit", "suite_shape", "suite_index",
                "suite_first_parents", "suite_charter", "suite_near",
                "suite_require_coauthor", "suite_near_subject",
                "suite_proposals"):
        monkeypatch.setattr(cg, имя, наборы[1] if len(наборы) > 1 else набор([]))


def test_chistyy_progon_eto_nol(monkeypatch):
    подменить(monkeypatch, [набор([])])

    assert cg.main() == 0


def test_nahodka_v_pervom_nabore_eto_odin(monkeypatch):
    подменить(monkeypatch, [набор(["гейт пропустил подделку"])])

    assert cg.main() == 1


def test_nahodka_v_POSLEDNEM_nabore_tozhe_odin(monkeypatch):
    """ГЛАВНЫЙ СЛУЧАЙ (159). Вердикт по накопителю обязан выноситься после
    последнего набора: ранний выход превратил бы всё, что идёт следом, в
    печать — случаи бегут, находки дописываются в список, который уже прочитан,
    и прогон отвечает «расхождений нет»."""
    подменить(monkeypatch, [набор([]), набор(["последний набор нашёл поломку"])])

    assert cg.main() == 1


def test_nabor_ne_otrabotal_eto_dva_a_ne_nahodka(monkeypatch):
    """Третий исход прекращает перебор и не смешивается со вторым: «не
    отработал» чинит тот, кто запускает, а находку — автор (039)."""
    подменить(monkeypatch, [набор([], сломан=2)])

    assert cg.main() == 2


def test_nahodka_nazvana_v_vyvode(monkeypatch, capsys):
    """Красное без предмета чинить нечем: находка обязана попасть в вывод (158)."""
    подменить(monkeypatch, [набор(["конкретная поломка гейта"])])
    cg.main()

    assert "конкретная поломка гейта" in capsys.readouterr().err


def test_chistyy_progon_nazyvaet_chislo_sluchaev(monkeypatch, capsys):
    """«Расхождений нет» без числа случаев неотличимо от «наборов не было»."""
    подменить(monkeypatch, [набор([])])
    cg.main()

    out = capsys.readouterr().out
    assert "случаев" in out and "расхождений нет" in out
