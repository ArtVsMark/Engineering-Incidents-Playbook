#!/usr/bin/env python3
"""Сужение признака спрашивает о соседях — там, где сужение видно машинно.

Машинная половина правила 195. Перечень соседей формализовать нельзя: «что ещё
решает этот признак» — суждение, и требовать перечень формально значило бы
получить формальный перечень, то есть зелёный гейт ровно там, где правило
нарушено (146). Но ЧАСТЬ предмета следует из диффа без всякого суждения, и она
здесь.

ЧТО СЧИТАЕТСЯ СУЖЕНИЕМ. Множество символов, которые принимал символьный класс
регулярного выражения, ЛИБО множество элементов литерального `{...}`
уменьшилось: что-то, решавшееся так, теперь решается иначе. Сравниваются не
строки, а множества, и не по кускам, а по изменению ЦЕЛИКОМ — перенос того же
множества в другой файл сокращается сам, и ложного отказа не даёт.

ПОЧЕМУ «УБЫЛО», А НЕ «СТАЛО ПОДМНОЖЕСТВОМ». Инцидент, ради которого гейт
заведён, подмножеством не является: `[ \\t>#-*]` стало
`(?:[ \\t>#-]|\\*(?=\\s))`, то есть звёздочка ушла из класса и вернулась
альтернативой рядом. Признак «добавленное ⊂ убранного» этого не видит вовсе.
Видит другой: диапазон `#-*` покрывал `$%&'()*`, а новый класс — нет. Убыло
семь символов, и этого довода достаточно.

ЧТО ГЕЙТ ТРЕБУЕТ. Не перечня соседей, а ОДНОЙ СТРОКИ во фрагменте журнала:

    Соседи: <у кого спросили и что вышло>

Форма та же, что у вердикта о правиле, который держит `collect_changelog.py`:
машина держит не суждение, а то, что вопрос ЗАДАН (182).

ЧЕГО ЭТА ПОЛОВИНА НЕ ЛОВИТ — И ЭТО ГРАНИЦА, А НЕ НЕДОРАБОТКА. Зелёное здесь не
значит «соседей нет»:

  • ДОБАВЛЕНИЕ элемента к неполному перечислению. Третий случай инцидента 195
    (`rejected` добавлен, `unreviewed` не тронут) не ловится вовсе: там ничего
    не сужалось. Убыль — не весь предмет правила, а его машинная часть;
  • кортежи и списки: `("a", "b")` от вызова функции текстом не отличить, и
    попытка дала бы ложный отказ на каждом вызове с двумя строками (051);
  • ВНЕШНИЙ уровень вложенного литерала: у `{"a": {"b": 1}}` читается `"b": 1`
    и не читается `"a"`. Внутренний при этом читается полноценно, и убыль
    ключа из него — находка;
  • удаление ветви `elif`: перенос ветви внутри файла неотличим от её
    удаления, и гейт краснел бы на первом же рефакторинге. Названо здесь
    вслух, чтобы не читалось как забытое.

Исходы:
  0 — сужений нет, либо о соседях сказано;
  1 — признак сужен, а строки о соседях нет;
  2 — проверка не отработала: диапазон не читается либо нет каталога
      фрагментов (039, 075).

Реализует правила каталога:
  195 — починка называет соседние случаи: гейт держит машинную половину;
  182 — «машинно нельзя» разбирается надвое, и держится ЗАДАННЫЙ вопрос;
  051 — запрещается достоверное: сравнение по изменению целиком, а не по
        кускам, чтобы перенос не читался как сужение;
  039 — три исхода, и третий не молчит;
  158 — третий исход называет предмет: что именно не прочиталось;
  140 — набор бьёт в оба конца: сужение находится, расширение и перенос — нет.

Запуск:
  python scripts/check_narrowing.py --range origin/main...HEAD
  python scripts/check_narrowing.py --selftest
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FRAGMENTS = ROOT / "changelog.d"

#: Строка, которой автор говорит, что о соседях спросил. Держится ВОПРОС, а не
#: ответ: судить об ответе машина не может, а требовать его форму — значит
#: получить форму (182).
СОСЕДИ = re.compile(r"^\s*Соседи:\s*(\S.*)$", re.M)

#: Строковый литерал: только в нём символьный класс отличим от взятия по
#: индексу. `items[0]` иначе читался бы классом из одного символа.
СТРОКА = re.compile(r"""[rbfu]{0,2}("(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*')""")

#: Символьный класс внутри строки. Отрицающий `[^…]` считается наравне:
#: убыль символа из него — то же изменение решения.
КЛАСС = re.compile(r"\[\^?((?:[^\]\\]|\\.)*)\]")

#: Литеральное множество или словарь. Скобок внутри нет, и это значит, что у
#: вложенного читается ВНУТРЕННИЙ уровень, а внешний — нет: у `{"a": {"b": 1}}`
#: виден `"b": 1` и не виден `"a"`. Проверено прогоном, а не предположено:
#: первая редакция объявляла вложенное «не перечислением» и была опровергнута
#: своим же случаем — ключ из вложенного словаря убывает так же, как элемент
#: из множества, и молчать об этом не за что.
МНОЖЕСТВО = re.compile(r"\{([^{}]*)\}")


def символы(класс: str) -> set[str]:
    """Символы, которые принимает класс. Диапазоны раскрываются.

    Раскрываются потому, что инцидент 195 именно в диапазоне и жил: `#-*`
    покрывал семь знаков, и без раскрытия убыль была бы не видна.
    """
    вышло: set[str] = set()
    куски: list[str] = []
    i = 0
    while i < len(класс):
        if класс[i] == "\\" and i + 1 < len(класс):
            куски.append(класс[i:i + 2])
            i += 2
            continue
        куски.append(класс[i])
        i += 1
    j = 0
    while j < len(куски):
        # Диапазон — только между двумя знаками: `-` с краю литерален.
        if (0 < j < len(куски) - 1 and куски[j] == "-"
                and len(куски[j - 1]) == 1 and len(куски[j + 1]) == 1
                and ord(куски[j - 1]) <= ord(куски[j + 1])):
            начало, конец = ord(куски[j - 1]), ord(куски[j + 1])
            вышло |= {chr(c) for c in range(начало, конец + 1)}
            j += 2
            continue
        вышло.add(куски[j])
        j += 1
    return вышло


def элементы(тело: str) -> set[str]:
    """Элементы литерального множества, как они написаны."""
    return {ч.strip() for ч in тело.split(",") if ч.strip()}


def атомы(строки: list[str]) -> tuple[set[str], set[str]]:
    """Символы классов и элементы множеств, встреченные в этих строках."""
    знаки: set[str] = set()
    члены: set[str] = set()
    for строка in строки:
        for литерал in СТРОКА.findall(строка):
            for класс in КЛАСС.findall(литерал):
                знаки |= символы(класс)
        for тело in МНОЖЕСТВО.findall(строка):
            if '"' in тело or "'" in тело:
                члены |= элементы(тело)
    return знаки, члены


def сужения(diff: str) -> list[str]:
    """Что убыло из признаков этого изменения. Пусто — сужений нет.

    СЧИТАЕТСЯ ПО ИЗМЕНЕНИЮ ЦЕЛИКОМ, А НЕ ПО КУСКУ. Перенос того же множества в
    другой файл — убыль в одном месте и прибыль в другом; по куску это читалось
    бы сужением, по изменению сокращается само (051).
    """
    убрано = [s[1:] for s in diff.splitlines()
              if s.startswith("-") and not s.startswith("---")]
    добавлено = [s[1:] for s in diff.splitlines()
                 if s.startswith("+") and not s.startswith("+++")]
    было_знаков, было_членов = атомы(убрано)
    стало_знаков, стало_членов = атомы(добавлено)
    вышло: list[str] = []
    ушли_знаки = было_знаков - стало_знаков
    if ушли_знаки:
        показ = " ".join(sorted(repr(з) for з in ушли_знаки)[:12])
        вышло.append(f"символьный класс перестал принимать: {показ}")
    ушли_члены = было_членов - стало_членов
    if ушли_члены:
        вышло.append("из множества убрано: " + ", ".join(sorted(ушли_члены)[:12]))
    return вышло


def тронутые_фрагменты(диапазон: str) -> tuple[list[Path] | None, str]:
    """Фрагменты журнала, тронутые этим изменением, — там и ищется ответ."""
    done = subprocess.run(
        ["git", "diff", "--name-only", "-z", "--diff-filter=AM",
         диапазон, "--", "changelog.d"],
        cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
    if done.returncode != 0:
        return None, (done.stderr or "").strip()
    return [ROOT / имя for имя in done.stdout.split("\0") if имя], ""


def diff_of(диапазон: str) -> tuple[str | None, str]:
    """Дифф изменения. Без контекста: контекст дал бы чужие строки за свои."""
    done = subprocess.run(
        ["git", "diff", "-U0", диапазон, "--", "*.py"],
        cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
    if done.returncode != 0:
        return None, (done.stderr or "").strip()
    return done.stdout, ""


def selftest() -> int:
    """Гейт прогоняется тем, что обязан найти И что обязан пропустить (140)."""
    ДИФФ = lambda было, стало: "\n".join(
        [f"-{s}" for s in было] + [f"+{s}" for s in стало])
    случаи = [
        # ── обязан НАЙТИ ──────────────────────────────────────────────────
        ("инцидент 195: звёздочка ушла из класса в альтернативу",
         ДИФФ([r'ПРЕФИКС = re.compile(r"^[ \t>#-*]*")'],
              [r'ПРЕФИКС = re.compile(r"^(?:[ \t>#-]|\*(?=\s))*")']), True),
        ("класс сузился прямо",
         ДИФФ([r'X = re.compile(r"[abc]")'], [r'X = re.compile(r"[ab]")']), True),
        ("из множества убран элемент",
         ДИФФ(['WITH_VALUE = {"--repo", "-o", "--exec"}'],
              ['WITH_VALUE = {"--repo", "-o"}']), True),
        ("диапазон раскрыт: убыль внутри него видна",
         ДИФФ([r'X = re.compile(r"[a-e]")'], [r'X = re.compile(r"[a-c]")']), True),
        # ── обязан ПРОПУСТИТЬ ─────────────────────────────────────────────
        ("расширение класса",
         ДИФФ([r'X = re.compile(r"[ab]")'], [r'X = re.compile(r"[abc]")']), False),
        ("добавление элемента в множество",
         ДИФФ(['S = {"a", "b"}'], ['S = {"a", "b", "c"}']), False),
        ("переименование при том же классе",
         ДИФФ([r'СТАРОЕ = re.compile(r"[abc]")'],
              [r'НОВОЕ = re.compile(r"[abc]")']), False),
        ("перенос множества: убыло в одном месте, прибыло в другом",
         ДИФФ(['S = {"a", "b"}'], ['# сюда', 'S = {"a", "b"}']), False),
        ("правка, не трогающая признаков вовсе",
         ДИФФ(["x = 1"], ["x = 2"]), False),
        ("взятие по индексу классом не считается",
         ДИФФ(["y = items[0]"], ["y = items[1]"]), False),
        ("вложенный словарь потерял ключ — это тоже убыль",
         ДИФФ(['S = {"a": {"b": 1}}'], ['S = {"a": {}}']), True),
    ]
    сломано: list[str] = []
    for имя, diff, ждём in случаи:
        вышло = сужения(diff)
        if bool(вышло) != ждём:
            сломано.append(f"{имя}: вышло {вышло or 'пусто'}")
        print(f"  {'сужение' if вышло else 'чисто  ':<8} — {имя}")

    # СТРОКА ОТВЕТА ЧИТАЕТСЯ, А НЕ ПОДРАЗУМЕВАЕТСЯ.
    for текст, ждём in [("Соседи: спросили, других форм нет", True),
                        ("> правило 195 — про соседей", False),
                        ("соседи где-то рядом", False),
                        ("  Соседи: и вот что вышло", True),
                        ("Соседи:", False)]:
        if bool(СОСЕДИ.search(текст)) != ждём:
            сломано.append(f"строка ответа: «{текст}» разобрана неверно")
    print("  ответ    — строка «Соседи:» отличается от прозы о соседях")

    if сломано:
        print("\nсамопроверка провалена:", file=sys.stderr)
        for s in сломано:
            print(f"  {s}", file=sys.stderr)
        return 1
    print("самопроверка пройдена: сужение находится, расширение и перенос — нет")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--range", dest="диапазон", default="origin/main...HEAD",
                    help="диапазон изменения")
    ap.add_argument("--selftest", action="store_true",
                    help="прогнать разбор на обеих сторонах границы")
    args = ap.parse_args(argv)

    if args.selftest:
        return selftest()

    # ── исход 2 ────────────────────────────────────────────────────────────
    if not FRAGMENTS.is_dir():
        print(f"проверка не отработала: нет каталога фрагментов {FRAGMENTS} — "
              "спрашивать ответ негде", file=sys.stderr)
        return 2
    diff, почему = diff_of(args.диапазон)
    if diff is None:
        print(f"проверка не отработала: дифф диапазона {args.диапазон!r} не "
              f"прочитан — {почему or 'git молчит'}", file=sys.stderr)
        return 2
    фрагменты, почему = тронутые_фрагменты(args.диапазон)
    if фрагменты is None:
        print(f"проверка не отработала: список фрагментов диапазона "
              f"{args.диапазон!r} не прочитан — {почему or 'git молчит'}",
              file=sys.stderr)
        return 2

    найдено = сужения(diff)
    if not найдено:
        print("сужений признаков в изменении нет — спрашивать не о чем")
        return 0

    сказано = [п for п in фрагменты
               if п.exists() and СОСЕДИ.search(п.read_text(encoding="utf-8"))]
    if сказано:
        print("признак сужен, и о соседях сказано: "
              + ", ".join(п.name for п in сказано))
        return 0

    # ── исход 1 ────────────────────────────────────────────────────────────
    print("признак сужен, а о соседях не сказано:", file=sys.stderr)
    for строка in найдено:
        print(f"  • {строка}", file=sys.stderr)
    print("\n  Что решалось этим признаком ещё? Работавшее могло сломаться, "
          "а сломанное — остаться сломанным (правило 195).", file=sys.stderr)
    print("  Ответ — строкой во фрагменте журнала:", file=sys.stderr)
    print("      Соседи: <у кого спросили и что вышло>", file=sys.stderr)
    print("  «Соседей нет» — законный ответ, но произнесённый.", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
