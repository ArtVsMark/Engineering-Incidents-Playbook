#!/usr/bin/env python3
"""Темп прогона по расписанию выведен из бюджета, а роль его объявлена.

Два правила, один предмет, и потому один гейт (022): и то и другое спрашивается
у одной записи — `.rules/schedules.json`, — и разводить их по двум скриптам
значило бы держать разбор cron в двух местах.

ПРАВИЛО 033 — интервал выводится АРИФМЕТИЧЕСКИ из бюджета, а не выбирается
словами. Прежний ответ каталога звучал так: «интервал прогонов выбран словами
(„не в 0 и не в 30, чтобы не совпадать с пиком“), а не выведен из бюджета».
Слова верные, но проверить их нечем, и добавленное завтра третье расписание в
тот же час никто не заметит. Здесь считается: сколько вызовов наружу прогон
делает в ХУДШИЙ час и укладывается ли сумма по всем расписаниям этого часа в
объявленную долю часового лимита.

ПОЧЕМУ ХУДШИЙ ЧАС, А НЕ СУТКИ. Квота часовая и скользящая: суточная сумма может
быть скромной, а прогон всё равно упрётся в стену, если весь расход приходится
на одну минуту. Суточное усреднение — ровно та арифметика, которая зеленеет
перед отказом.

ПОЧЕМУ СУММА, А НЕ КАЖДЫЙ ПО ОТДЕЛЬНОСТИ. Квота ОБЩАЯ (правило 058): расход
нескольких прогонов в одном часу складывается, и два расписания, каждое из
которых укладывается, вместе могут не уложиться.

ПРАВИЛО 169 — расписание площадки говорит «когда-нибудь», а не «раз в N минут».
Отсюда две проверки. Роль объявлена: `main` или `safety-net`. У страховки
обязателен ЗАМЕР срабатываний — пока его нет, основной путь строят так, будто
страховки не существует. И страховка со сроком короче интервала расписания
отвергается сразу: она неверна по построению, а не «рискованна».

ЧЕГО ГЕЙТ НЕ ДЕЛАЕТ. Не выводит цену прогона из его файла: шаг зовёт скрипт,
скрипт зовёт другой, часть вызовов условна — приблизительный ответ, выданный за
точный, хуже объявленного (037). Цена ОБЪЯВЛЯЕТСЯ, а гейт держит арифметику и
совпадение расписания с файлом.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.

Реализует правила каталога:
  033 — темп повторяющейся работы выводится из бюджета арифметически;
  169 — расписание — пожелание, а не частота; у страховки обязан быть замер;
  058 — квота общая: расход прогонов одного часа складывается;
  050 — доля лимита двигается только вниз (проверяется чтением, не машиной);
  039 — три исхода: чисто · есть находки · проверка не отработала;
  075 — ноль расписаний это отказ, а не чистый прогон;
  158 — третий исход называет предмет отказа, а не только причину;
  165 — печатается ОХВАТ: арифметика показывается и когда она сошлась.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ОТВЕТ = Path(".rules") / "schedules.json"
ПРОГОНЫ = Path(".github") / "workflows"

#: Строка расписания в файле прогона: `- cron: "23 6 * * *"`.
CRON_RE = re.compile(r"^\s*-\s*cron:\s*[\"']([^\"']+)[\"']", re.M)

РОЛИ = ("main", "safety-net")


def раскрыть(поле: str, низ: int, верх: int) -> set[int]:
    """Значения одного поля cron. Пустое множество — поле не разобрано.

    Разбор свой, а не библиотекой: конвейер каталога обходится стандартной
    библиотекой, и гейт, требующий установки, перестал бы запускаться там, где
    его запускают чаще всего, — на рабочем столе. Тот же довод у sections()
    в check_workflows.py.
    """
    значения: set[int] = set()
    for кусок in поле.split(","):
        шаг = 1
        if "/" in кусок:
            кусок, _, s = кусок.partition("/")
            if not s.isdigit() or int(s) == 0:
                return set()
            шаг = int(s)
        if кусок == "*":
            начало, конец = низ, верх
        elif "-" in кусок:
            a, _, b = кусок.partition("-")
            if not (a.isdigit() and b.isdigit()):
                return set()
            начало, конец = int(a), int(b)
        elif кусок.isdigit():
            начало = конец = int(кусок)
        else:
            return set()
        if not (низ <= начало <= конец <= верх):
            return set()
        значения |= set(range(начало, конец + 1, шаг))
    return значения


def часы_и_минуты(cron: str) -> tuple[set[int], set[int]] | None:
    """Часы и минуты расписания; None — строка не разобрана."""
    поля = cron.split()
    if len(поля) != 5:
        return None
    минуты = раскрыть(поля[0], 0, 59)
    часы = раскрыть(поля[1], 0, 23)
    if not минуты or not часы:
        return None
    return часы, минуты


def интервал_минут(cron: str) -> int | None:
    """Наименьший промежуток между запусками в минутах; None — не разобрано.

    Считается по ХУДШЕМУ случаю в сутках: страховка обязана успевать всегда, а
    не в среднем.
    """
    разбор = часы_и_минуты(cron)
    if разбор is None:
        return None
    часы, минуты = разбор
    моменты = sorted(ч * 60 + м for ч in часы for м in минуты)
    if len(моменты) == 1:
        return 24 * 60
    промежутки = [b - a for a, b in zip(моменты, моменты[1:])]
    промежутки.append(моменты[0] + 24 * 60 - моменты[-1])
    return min(промежутки)


def запусков_в_час(cron: str, час: int) -> int:
    """Сколько раз прогон стартует внутри этого часа."""
    разбор = часы_и_минуты(cron)
    if разбор is None:
        return 0
    часы, минуты = разбор
    return len(минуты) if час in часы else 0


def расписания_в_файле(текст: str) -> list[str]:
    """Строки cron из файла прогона."""
    return CRON_RE.findall(текст)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)
    ответ_путь = args.root / ОТВЕТ
    прогоны_путь = args.root / ПРОГОНЫ

    # ── исход 2 ────────────────────────────────────────────────────────────
    if not ответ_путь.exists():
        print(f"проверка не отработала: нет {ОТВЕТ} — цену расписаний "
              "объявляет он, и выводить её из файлов прогонов нельзя",
              file=sys.stderr)
        return 2
    try:
        ответ = json.loads(ответ_путь.read_text(encoding="utf-8"))
    except ValueError as e:
        print(f"проверка не отработала: {ОТВЕТ} не разобрать — {e}",
              file=sys.stderr)
        return 2
    файлы = sorted(прогоны_путь.glob("*.yml"))
    if not файлы:
        print(f"проверка не отработала: в {ПРОГОНЫ} нет ни одного файла — "
              "проверять нечего, и зеленеть на этом нельзя", file=sys.stderr)
        return 2

    в_дереве: dict[str, list[str]] = {}
    for f in файлы:
        строки = расписания_в_файле(f.read_text(encoding="utf-8"))
        if строки:
            в_дереве[f.name] = строки
    if not в_дереве:
        print(f"проверка не отработала: в {ПРОГОНЫ} нет ни одного расписания — "
              "предмета нет, и зеленеть на этом нельзя (075)", file=sys.stderr)
        return 2

    объявлено = ответ.get("runs") or {}
    лимит = (ответ.get("limits") or {}).get("gh_api_per_hour")
    доля = ответ.get("share")
    if not isinstance(лимит, int) or not isinstance(доля, (int, float)):
        print(f"проверка не отработала: в {ОТВЕТ} нет числового лимита либо "
              "доли — считать не из чего", file=sys.stderr)
        return 2

    # ── исход 1 ────────────────────────────────────────────────────────────
    находки: list[str] = []

    # ОБЕ СТОРОНЫ, А НЕ ОДНА: незаявленное расписание — дыра, заявленное без
    # файла — протухшая запись, и вторая молчит громче первой (146).
    for имя in sorted(set(в_дереве) - set(объявлено)):
        находки.append(f"{ПРОГОНЫ}/{имя}: расписание есть, а цены и роли в "
                       f"{ОТВЕТ} не объявлено — темп выбран словами (033)")
    for имя in sorted(set(объявлено) - set(в_дереве)):
        находки.append(f"{ОТВЕТ}: объявлен {имя}, а расписания в "
                       f"{ПРОГОНЫ}/{имя} нет — запись протухла")

    расход: dict[int, list[tuple[str, int]]] = {}
    for имя, запись in sorted(объявлено.items()):
        if имя not in в_дереве:
            continue
        cron = запись.get("cron")
        if cron not in в_дереве[имя]:
            находки.append(
                f"{ОТВЕТ}: у {имя} объявлено «{cron}», а в файле "
                f"{в_дереве[имя]} — объявление разошлось с фактом (049)")
            continue
        разбор = часы_и_минуты(cron)
        if разбор is None:
            находки.append(f"{ОТВЕТ}: расписание {имя} «{cron}» не разобрано — "
                           "пять полей, значения в границах")
            continue
        роль = запись.get("role")
        if роль not in РОЛИ:
            находки.append(f"{ОТВЕТ}: у {имя} роль «{роль}», а бывает "
                           f"{' или '.join(РОЛИ)} (169)")
        elif роль == "safety-net":
            # ГЛАВНАЯ ПОЛОВИНА 169, И ОНА ЗАПРЕТ, А НЕ ПРЕДУПРЕЖДЕНИЕ.
            if "measured" not in запись:
                находки.append(
                    f"{ОТВЕТ}: {имя} объявлен страховкой без замера "
                    "срабатываний. Пока замера нет, основной путь строят так, "
                    "будто страховки не существует (169)")
            срок = запись.get("deadline_minutes")
            промежуток = интервал_минут(cron)
            if isinstance(срок, int) and промежуток and срок < промежуток:
                находки.append(
                    f"{ОТВЕТ}: {имя} страхует срок {срок} мин расписанием с "
                    f"промежутком {промежуток} мин. Планировщик говорит "
                    "«когда-нибудь», а не «раз в N минут» — такая страховка "
                    "неверна по построению (169)")
        цена = запись.get("gh_calls_per_run")
        if not isinstance(цена, int) or цена < 0:
            находки.append(f"{ОТВЕТ}: у {имя} нет числа gh_calls_per_run — "
                           "бюджет считать не из чего (033)")
            continue
        for час in range(24):
            n = запусков_в_час(cron, час)
            if n:
                расход.setdefault(час, []).append((имя, цена * n))

    потолок = лимит * доля
    пики: list[str] = []
    for час in sorted(расход):
        сумма = sum(c for _, c in расход[час])
        кто = " + ".join(f"{и} {c}" for и, c in расход[час])
        пики.append(f"    {час:02d}:xx — {кто} = {сумма} из {потолок:.0f}")
        if сумма > потолок:
            находки.append(
                f"час {час:02d}:xx — расписания просят {сумма} вызовов при "
                f"разрешённых {потолок:.0f} ({лимит} × {доля}). Квота общая: "
                "расход прогонов одного часа складывается (058, 033)")

    if находки:
        print("темп прогонов по расписанию разошёлся с бюджетом:",
              file=sys.stderr)
        for n in находки:
            print(f"  • {n}", file=sys.stderr)
        print(f"\n  Арифметика по часам:", file=sys.stderr)
        for p in пики:
            print(p, file=sys.stderr)
        return 1

    print(f"темп выведен из бюджета: расписаний {len(в_дереве)}, "
          f"часовой лимит {лимит}, доля каталога {доля}")
    for p in пики:
        print(p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
