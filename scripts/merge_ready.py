#!/usr/bin/env python3
"""Готово ли изменение к слиянию: красное основание и список проверок.

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ СКРИПТ, А НЕ УСЛОВИЕ В ОБОЛОЧКЕ. У условия в `run:` нет
отвергаемого предмета: подсунуть ему подделанный список проверок нечем, и
проверить его можно только живым слиянием — то есть никак (правила 140, 145).

ЧТО ЗДЕСЬ ДЕРЖИТСЯ. Правило 010 дословно: «условие „нет красных и нет
ожидающих“ истинно на ПУСТОМ множестве». Сторож слияния проверял только
отсутствие красных, и изменение без единого прогона проходило как чистое.

Пустой список — не редкость и не сбой: изменение с конфликтом НЕ ПОЛУЧАЕТ
прогонов вовсе, потому что площадка не может собрать ссылку слияния и события
`pull_request` не рождается. В этом состоянии проверок нет штатно, и оно с
«всё зелено» неотличимо ровно так, как предупреждает 010.

ОБЯЗАТЕЛЬНАЯ ПРОВЕРКА СПРАШИВАЕТСЯ ПОИМЁННО. «Что-то зелёное есть» — не то же
самое, что «прошла та самая»: посторонняя работа зеленеет сама по себе, и её
достаточно, чтобы условие стало истинным. Разрешительный список вместо
запретительного, ровно 068.

КРАСНАЯ ОБЩАЯ ВЕТКА ЗАМОРАЖИВАЕТ ОЧЕРЕДЬ, и это проверяется ПЕРВЫМ. Правило
053 требует именно порядка: красное основание — условие входа в очередь, а не
одна из сортировок. Пока основание сломано, зелёная проверка не означает
работоспособность — она означает, что сломанное не стало хуже.

ИНЦИДЕНТ, ИЗ КОТОРОГО ЭТО ВЫРОСЛО. 2 сентября 2026 общая ветка покраснела в
08:55, и в неё за полчаса уехали два изменения — оба с полностью зелёными
проверками на сломанном основании. Ответ каталога по 053 при этом называл
механизмом `main-red.yml`, а тот только заводит задачу: он никого не
останавливает. Заявленный гейт держал не то утверждение, ради которого
построен (146), и обнаружил это человек, а не прогон.

ЧТО РАЗМОРАЖИВАЕТ. Метка на изменении, по умолчанию `blocker`. Приём взят у
грейдера целиком — у него та же метка и та же роль, — а файл нет: там очередь
считается своим скриптом по своей шкале приоритетов (правило 162). Одна метка
вместо вычисления «а это ли починка»: чинящее красноту из состояния площадки не
выводится, и 053 говорит об этом прямо.

Запуск:
  gh api …/check-runs | python scripts/merge_ready.py --required catalogue \
      --base-runs base.json --labels "$LABELS"
Коды:    0 сливать можно · 1 сливать нельзя · 2 проверка не отработала

Реализует правила каталога:
  010 — пустой список проверок трактуется как «не стартовало», а не «всё хорошо»;
  053 — красная общая ветка замораживает очередь, и размораживает её метка на
        изменении, а не догадка механизма о том, что именно чинит красноту;
  162 — приём заморозки взят у соседа, а не изобретён: у него та же метка;
  022 — «какие работы красны» спрашивается у main_red.red_names, а не считается
        здесь заново: вторая свёртка той же территории разошлась бы молча;
  168 — обязательная проверка спрашивается ПОИМЁННО и ровно одна: «что-то
        зелёное» ею не является, а пропущенная работа засчиталась бы
        пройденной.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# Свёртка «какие работы на ветке красны» живёт у дежурного и берётся у него:
# она уже отвечает на этот вопрос ПО ПОСЛЕДНЕМУ прогону каждой работы, а не по
# записям истории событий (правило 009). Второй такой же счёт здесь разошёлся
# бы с первым при первой правке (022).
import main_red

#: Исходы, которые считаются незелёными. Список её, площадки, а не наш.
BAD = ("failure", "timed_out", "cancelled", "action_required", "stale")
#: Исходы, означающие «ещё идёт». Ожидание — не отказ, но и не разрешение.
PENDING = (None, "", "queued", "in_progress", "waiting", "pending", "requested")


#: Метка, размораживающая очередь. Слово взято у соседа намеренно: человек,
#: переходящий между проектами, не переучивается, а метка значит то же самое.
THAW = "blocker"


def frozen(base_runs: list[dict], labels: list[str], thaw: str,
           excluded: frozenset[str] = frozenset()) -> tuple[str, str]:
    """Причина заморозки и состояние основания, годное для печати.

    Проверяется ПЕРВЫМ и отдельно от проверок самого изменения: это условие
    входа в очередь, а не одна из сортировок (053). Зелёная проверка на
    сломанном основании говорит лишь, что сломанное не стало хуже.

    Разморозка меткой НЕ ДЕЛАЕТ ОСНОВАНИЕ ЗЕЛЁНЫМ, и отчёт обязан это
    говорить: «прошло, потому что метка» и «прошло, потому что чисто» —
    разные ответы, и подменять первый вторым значит врать отчётом (158).
    """
    red = main_red.red_names(base_runs, excluded)
    if not red:
        # «Зелёное» и «нечем судить» — разные ответы, и второй обязан быть
        # виден (039, 075). Работа, у которой все прогоны отменены, ничего не
        # подтверждает; очередь она не морозит — отмена не вердикт, — но и
        # молчать о ней значит выдавать незнание за чистоту.
        немые = main_red.unresolved_names(base_runs, excluded)
        if немые:
            return "", ("основание зелёное; без вердикта: " + ", ".join(немые)
                        + " — все прогоны этих работ отменены, и подтверждают они ничего")
        return "", "основание зелёное"
    названы = ", ".join(red)
    if thaw in labels:
        return "", f"основание красное ({названы}), разморожено меткой «{thaw}»"
    return ("общая ветка красная: " + названы
            + f". Очередь заморожена — двигается только изменение с меткой "
            f"«{thaw}», то есть та самая починка. Остальные проверки прошли бы "
            "на сломанном основании и ничего не значат (правило 053)"), ""


def awaited(runs: list[dict], names: list[str]) -> tuple[bool, str]:
    """Дождались ли ВЕРДИКТА необязательных каналов. Второе — причина.

    ВЕРДИКТ — ЭТО «СОСТОЯЛСЯ», А НЕ «ЗЕЛЁНЫЙ», и в этом вся суть. Канал
    необязательный: его находки советуют, а его отказ не запрещает (084).
    Держит слияние только ОТСУТСТВИЕ ответа — то есть прогон, который ещё идёт.

    ТРИ СОСТОЯНИЯ, И ОНИ РАЗНЫЕ (039, 027):
      • прогона нет вовсе — ждать нечего: канал не работает (нет ключа, форк),
        и ожидание было бы вечным. Слияние идёт;
      • прогон завершён любым исходом, включая отказ по исчерпанной квоте, —
        вердикт есть. Слияние идёт;
      • прогон идёт — вердикта нет. Слияние ждёт.

    ЗАМЕР, ИЗ КОТОРОГО ЭТО ВЫРОСЛО (8 сентября): из 29 слитых изменений с
    прогоном ревью вердикт успел к слиянию у 10. Дежурный ждал всех проверок и
    так, но СЛИВАЛА площадка по взведённому автомержу, а он ждёт только
    обязательные. Девятнадцать раз работа канала пропала целиком.
    """
    if not names:
        return True, "необязательных каналов не ждём"
    ждём: list[str] = []
    ответили: list[str] = []
    for имя in names:
        свои = [r for r in runs if r.get("name") == имя]
        if not свои:
            ответили.append(f"{имя}: не запускался")
            continue
        идут = [r for r in свои if r.get("status") != "completed"
                or r.get("conclusion") in PENDING]
        if идут:
            ждём.append(имя)
        else:
            исходы = sorted({(r.get("conclusion") or "?") for r in свои})
            ответили.append(f"{имя}: {', '.join(исходы)}")
    if ждём:
        return False, ("вердикта ещё нет: " + ", ".join(ждём)
                       + ". Канал необязательный — держит не его краснота, а "
                       "молчание (084)")
    return True, "вердикты необязательных каналов: " + "; ".join(ответили)


def verdict(runs: list[dict], required: list[str],
            optional: list[str] | None = None) -> tuple[bool, str]:
    """Можно ли сливать. Вторая строка — причина, годная для печати.

    НЕОБЯЗАТЕЛЬНЫЕ КАНАЛЫ ИСКЛЮЧАЮТСЯ ОТСЮДА, И ЭТО ПОЧИНКА, А НЕ ОГОВОРКА.
    Правило 084 говорит прямо: канал, не объявленный основной работой, не
    должен ни задерживать слияние, ни ронять его. Прежде здесь считались ВСЕ
    проверки подряд — значит красное ревью держало бы слияние, а идущее
    держало бы его до конца прогона. На замере это не проявилось только
    потому, что за 33 прогона ревью не покраснело ни разу: гейт был зелёным по
    отсутствию предмета, а не по верности (146).

    Ответ о них даёт awaited() выше, и он другой: держит не краснота, а
    молчание.
    """
    optional = optional or []
    if optional:
        runs = [r for r in runs if r.get("name") not in optional]
    if not runs:
        return False, ("проверок нет НИ ОДНОЙ — это «не стартовало», а не «всё "
                       "хорошо» (правило 010). Частая причина: у изменения "
                       "конфликт, и площадка не собрала ссылку слияния")
    bad = sorted({r.get("name", "?") for r in runs
                  if (r.get("conclusion") or "") in BAD})
    if bad:
        return False, "незелёные проверки: " + ", ".join(bad)
    waiting = sorted({r.get("name", "?") for r in runs
                      if r.get("status") != "completed"
                      or r.get("conclusion") in PENDING})
    if waiting:
        return False, "проверки ещё идут: " + ", ".join(waiting)
    green = {r.get("name") for r in runs if r.get("conclusion") == "success"}
    missing = [n for n in required if n not in green]
    if missing:
        return False, ("обязательные проверки не зелены на этой голове: "
                       + ", ".join(missing) + ". Зелены: "
                       + (", ".join(sorted(n for n in green if n)) or "—"))
    return True, f"проверок {len(runs)}, все зелёные, обязательные на месте"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--required", default="", metavar="ИМЕНА",
                    help="имена обязательных проверок через запятую")
    ap.add_argument("--base-runs", metavar="ФАЙЛ", type=Path,
                    help="прогоны общей ветки: gh run list --branch main "
                         "--json name,status,conclusion,createdAt. Без ключа "
                         "заморозка НЕ проверяется — и это видно в отчёте")
    ap.add_argument("--base-exclude", default="", metavar="ИМЕНА",
                    help="работы общей ветки, чьё красное не морозит очередь; "
                         "список принадлежит потребителю, а не инструменту")
    ap.add_argument("--labels", default="", metavar="МЕТКИ",
                    help="метки изменения через запятую")
    ap.add_argument("--thaw-label", default=THAW, metavar="МЕТКА",
                    help=f"метка, размораживающая очередь (по умолчанию {THAW})")
    ap.add_argument("--await", dest="await_", default="", metavar="ИМЕНА",
                    help="необязательные каналы, чьего ВЕРДИКТА ждём перед "
                         "слиянием: держит не краснота, а молчание. Прогон, "
                         "который не запускался, ожиданием не считается")
    ap.add_argument("--freeze-only", action="store_true",
                    help="спросить только про основание и не читать проверок "
                         "изменения: заморозка — условие ВХОДА в очередь, и "
                         "спрашивается до того, как у изменения появятся свои "
                         "проверки (053)")
    args = ap.parse_args(argv)
    required = [n.strip() for n in args.required.split(",") if n.strip()]
    ждать = [n.strip() for n in args.await_.split(",") if n.strip()]
    labels = [n.strip() for n in args.labels.split(",") if n.strip()]
    excluded = frozenset(n.strip() for n in args.base_exclude.split(",") if n.strip())

    # ── заморозка спрашивается ПЕРВОЙ (053) ────────────────────────────────
    заморожено = ""
    основание = "основание не спрошено"
    if args.base_runs is not None:
        try:
            base = json.loads(args.base_runs.read_text(encoding="utf-8"))
        except (OSError, ValueError) as e:
            print(f"проверка не отработала: прогоны общей ветки не прочитаны "
                  f"— {args.base_runs}: {e}", file=sys.stderr)
            return 2
        if not isinstance(base, list):
            print(f"проверка не отработала: в {args.base_runs} нет списка "
                  "прогонов общей ветки", file=sys.stderr)
            return 2
        заморожено, основание = frozen(base, labels, args.thaw_label, excluded)
        if заморожено:
            print(f"сливать нельзя: {заморожено}", file=sys.stderr)
            return 1
    elif args.freeze_only:
        print("проверка не отработала: --freeze-only без --base-runs — "
              "спрашивать про основание нечем", file=sys.stderr)
        return 2

    if args.freeze_only:
        print(f"очередь не заморожена: {основание}")
        return 0

    # ── исход 2 ────────────────────────────────────────────────────────────
    raw = sys.stdin.read()
    if not raw.strip():
        print("проверка не отработала: на stdin пусто — список проверок "
              "подаётся туда (`gh api ... | merge_ready.py`)", file=sys.stderr)
        return 2
    try:
        doc = json.loads(raw)
    except ValueError as e:
        print(f"проверка не отработала: список проверок не разобран — {e}",
              file=sys.stderr)
        return 2
    runs = doc.get("check_runs") if isinstance(doc, dict) else doc
    if not isinstance(runs, list):
        print("проверка не отработала: в JSON со stdin нет ключа "
              "`check_runs` и сам он не список", file=sys.stderr)
        return 2

    # ВЕРДИКТ НЕОБЯЗАТЕЛЬНЫХ СПРАШИВАЕТСЯ ПЕРВЫМ, И ЭТО НЕ ПОРЯДОК РАДИ
    # ПОРЯДКА. Отказ обязательной проверки — причина не сливать НИКОГДА;
    # молчание необязательной — причина не сливать СЕЙЧАС. Печатать первую как
    # вторую значило бы врать отчётом (158): «ждём ревью» на красном catalogue.
    дождались, почему_ждём = awaited(runs, ждать)
    ok, why = verdict(runs, required, ждать)
    if ok and not дождались:
        print(f"сливать рано: {почему_ждём}", file=sys.stderr)
        return 1
    if ok:
        print(f"сливать можно: {основание}, {why}; {почему_ждём}")
        return 0
    # ── исход 1 ────────────────────────────────────────────────────────────
    print(f"сливать нельзя: {why}", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
