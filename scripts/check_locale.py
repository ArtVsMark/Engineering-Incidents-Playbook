#!/usr/bin/env python3
"""Английское дерево — перевод, а не копия русского: сверяется языком.

Правило 077 держалось ничем с оговоркой «подстрочник от перевода отличает
только чтение». Оговорка верна и остаётся в силе — но она закрывала собой
случай грубее и дешевле: запись, положенную в `rules/en/` **по-русски**.
Структурный паритет её не ловит: разделы на месте, имена файлов совпадают,
`build_rules_index.py --check` зелёный. Ловит только язык.

ПОРОГИ НЕ ВЫДУМАНЫ, А ЗАМЕРЕНЫ. На корпусе из 162 пар доля кириллицы в
`rules/en/` — от 0.000 до 0.022 (медиана 0.000), в `rules/ru/` — от 0.814 до
0.946. Нарушение даёт значение у другого края, а не рядом с порогом, поэтому
пороги стоят с запасом в разы: 0.15 сверху для английского дерева и 0.50 снизу
для русского. Приём взят у витрины (`check_page.py`, доля кириллицы с порогом
50%) — приём, а не файл: у неё предмет страница профиля, здесь пара записей
(правило 162).

ЧЕГО ЗДЕСЬ НЕТ. Оценки качества перевода. Подстрочник, калька и потерянный
смысл — предмет чтения на обоих языках, и это граница самого 077. Гейт
отвечает на один вопрос: переведено ли вообще.

ДВУЯЗЫЧНЫЕ ДОКУМЕНТЫ СЮДА НЕ ВХОДЯТ. `export/README.md` (0.505),
`CONNECT.md` (0.601) и `TOP-10.md` (0.401) держат оба языка в одном файле, и
любой порог для них означал бы запрет на двуязычие.

Реализует правила каталога:
  077 — совпадение ключей ещё не перевод: проверяется язык, а не структура;
  137 — сторож смотрит на сырое значение: доля считается по буквам файла;
  051 — запрещают достоверное: непереведённая запись — факт, а не подозрение;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  075 — пустое дерево это отказ, а не чистый прогон;
  158 — третий исход называет предмет.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: Потолок для английского дерева и пол для русского. Замер названы в шапке:
#: между худшим настоящим значением и порогом — разы, а не проценты.
EN_CEIL = 0.15
RU_FLOOR = 0.50
#: Английские документы вне дерева правил: у них тот же вопрос и тот же ответ.
EN_DOCS = ("README.en.md",)


def share(text: str) -> float:
    """Доля кириллицы среди букв. Пунктуация и код в знаменатель не идут."""
    letters = [c for c in text if c.isalpha()]
    if not letters:
        return 0.0
    return sum(1 for c in letters
               if "а" <= c.lower() <= "я" or c.lower() == "ё") / len(letters)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT,
                        help="корень каталога; по умолчанию сам этот репозиторий")
    args = parser.parse_args(argv)
    root: Path = args.root

    ru = sorted((root / "rules" / "ru").glob("*.md"))
    en = sorted((root / "rules" / "en").glob("*.md"))
    en += [root / name for name in EN_DOCS if (root / name).exists()]

    # ── исход 2 ────────────────────────────────────────────────────────────
    if not ru or not en:
        print("проверка не отработала: нет пары языковых деревьев — "
              f"{root / 'rules' / 'ru'} и {root / 'rules' / 'en'}. Сверять "
              "язык не с чем", file=sys.stderr)
        return 2

    # ── исход 1 ────────────────────────────────────────────────────────────
    problems: list[str] = []
    for path in en:
        got = share(path.read_text(encoding="utf-8"))
        if got > EN_CEIL:
            problems.append(
                f"{path.relative_to(root)}: кириллицы {got:.0%} при потолке "
                f"{EN_CEIL:.0%} — запись положена в английское дерево "
                "непереведённой. Структура этого не видит: разделы на месте")
    for path in ru:
        got = share(path.read_text(encoding="utf-8"))
        if got < RU_FLOOR:
            problems.append(
                f"{path.relative_to(root)}: кириллицы {got:.0%} при поле "
                f"{RU_FLOOR:.0%} — в русском дереве лежит английский текст")

    if problems:
        print("языковые деревья разошлись с языком:", file=sys.stderr)
        for p in problems:
            print(f"  • {p}", file=sys.stderr)
        return 1

    худший_en = max(share(p.read_text(encoding="utf-8")) for p in en)
    худший_ru = min(share(p.read_text(encoding="utf-8")) for p in ru)
    print(f"языки на месте: пар {len(ru)}, кириллицы в английском дереве не "
          f"больше {худший_en:.0%}, в русском не меньше {худший_ru:.0%}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
