#!/usr/bin/env python3
"""Что стало с задачей ПОСЛЕ слияния: проверяется, а не предполагается.

Правило 173 требует от изменения одного из трёх ответов и добавляет вторую
половину, без которой первая держится обещанием: закрытая задача обязана быть
закрытой, частичная — открытой и с непустым остатком.

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ПРОГОН, А НЕ ГЕЙТ ИЗМЕНЕНИЯ. `pr_body.py` проверяет
ФОРМУ ответа до слияния — там предмета «что стало с задачей» ещё нет. Врёт
строка `Closes` именно после: площадка закрыла не то, не закрыла ничего, или
задача осталась стоять с описанием работы, которой больше нет. Проверка,
стоящая до события, проверяет намерение (139).

ИНЦИДЕНТ. Задача #186 простояла шесть дней, называя две находки, которые к тому
времени были починены. Заметил человек. До этого замер по двенадцати слияниям
показал ноль связей — ту половину закрыл `pr_body.py`, эту не закрывало ничто.

АДРЕСАТ — САМА ЗАДАЧА, а не журнал прогона: там её видит тот, кто её ведёт
(142). Комментарий идемпотентен по скрытому маркеру: заголовок правят руками, и
тогда прогон писал бы второй комментарий вместо обновления.

ЧЕГО ЭТОТ ПРОГОН НЕ ДЕЛАЕТ. Не закрывает задач и не ставит галочек. «Сделано, а
задача открыта» — наблюдение; закрытие говорит человек, потому что он говорит
им «я посмотрел».

Исходы:
  0 — задачи в согласии с изменением;
  1 — есть расхождения, И ОНИ ЗАПИСАНЫ В САМИХ ЗАДАЧАХ;
  2 — проверка не отработала: площадка не ответила, ответ не разобран ЛИБО
      замечание не доставлено. Последнее — тоже отказ механизма, а не находка:
      исход 1 утверждает «в задаче написано», и если не написано, вызывающий
      узнаёт неправду (039, 075).

Реализует правила каталога:
  173 — состояние задачи после слияния проверяется, а не предполагается;
  142 — у находки есть адресат, и это сама задача;
  022 — что считать связью, спрашивается у pr_body, а не определяется заново;
  039 — три исхода: чисто · есть находки · проверка не отработала.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import ghcli
import pr_body

ROOT = Path(__file__).resolve().parent.parent

gh = ghcli.run

#: Непроставленная галочка. Остаток, названный прозой, состоянием не является
#: (028): по нему приходится вычислять, что осталось, чтением.
OPEN_BOX_RE = re.compile(r"^[ \t>*-]*\[ \]", re.M)

MARKER = "<!-- task-state: по этой строке замечание находится снова -->"


def tasks(body: str) -> tuple[list[str], list[str]]:
    """Задачи, названные телом: закрываемые целиком и делаемые частично.

    Что считать связью, решает pr_body — там это уже записано, и второе
    определение разошлось бы с первым молча (022).
    """
    closes = [m.group(2) for m in pr_body.CLOSING_RE.finditer(body)]
    parts = [m.group(1) for m in pr_body.PART_RE.finditer(body)]
    return closes, parts


def verdict(number: str, kind: str, state: str, issue_body: str) -> str:
    """Расхождение между обещанием изменения и состоянием задачи. «» — согласие."""
    state = (state or "").upper()
    if kind == "closes":
        if state != "CLOSED":
            return (f"#{number}: изменение обещало закрыть задачу, а она "
                    "открыта. Площадка закрывает по слову в ТЕЛЕ — проверьте, "
                    "что слово доехало до слитого коммита (064)")
        return ""
    if state == "CLOSED":
        return (f"#{number}: изменение объявило себя ЧАСТЬЮ, а задача закрыта. "
                "Остаток исчез вместе с ней, и найти его можно только по "
                "памяти того, кто сливал (173)")
    if not OPEN_BOX_RE.search(issue_body or ""):
        return (f"#{number}: задача открыта как частичная, но остатка в ней "
                "нет — ни одной непроставленной галочки. По прозе состояние "
                "приходится вычислять чтением (028)")
    return ""


def issue(number: str) -> tuple[dict | None, str]:
    """Состояние задачи по REST. Вторая строка — причина отказа."""
    # ПО REST, А НЕ ЧЕРЕЗ GraphQL: у второго своя узкая квота, и её исчерпание
    # 2 сентября остановило конвейер целиком при зелёном коде.
    #
    # И ЭТО НАДО БЫЛО НЕ ОБЪЯВИТЬ, А СДЕЛАТЬ. Стояло `gh issue view --json`, а
    # эта форма у gh идёт РОВНО ЧЕРЕЗ GraphQL — то есть комментарий обещал
    # обратное тому, что делал вызов. Заявление о механизме есть утверждение о
    # механизме, и оно сверяется (044). `gh api` с путём — единственная форма,
    # про которую сказанное здесь верно; `{owner}` и `{repo}` подставляет сам
    # gh из текущего репозитория.
    code, out = gh("api", f"repos/{{owner}}/{{repo}}/issues/{number}",
                   "--jq", "{number, state, body}")
    if code != 0:
        return None, out
    try:
        return json.loads(out or "{}"), ""
    except ValueError as e:
        return None, f"ответ не разобран: {e}"


def pulls_for(sha: str) -> tuple[list[dict] | None, str]:
    """Изменения, содержащие коммит, по REST. Вторая строка — причина отказа."""
    # ПО REST И ПУТЁМ, А НЕ ПОДКОМАНДОЙ — по той же причине, что и в issue():
    # `gh pr list --search` уходит в GraphQL, у которого своя узкая квота (001).
    code, out = gh("api", f"repos/{{owner}}/{{repo}}/commits/{sha}/pulls",
                   "--jq", "[.[] | {number, body, merged_at, merge_commit_sha}]")
    if code != 0:
        return None, out
    try:
        значение = json.loads(out or "[]")
    except ValueError as e:
        return None, f"ответ не разобран: {e}"
    return (значение if isinstance(значение, list) else []), ""


def тот_же(a: str | None, b: str | None) -> bool:
    """Один ли это коммит. Короткий отпечаток и полный — одно и то же имя."""
    a, b = (a or "").lower(), (b or "").lower()
    return bool(a and b) and (a.startswith(b) or b.startswith(a))


def promise_of(pulls: list[dict], sha: str,
               fallback: str) -> tuple[str, str]:
    """Тело, в котором живёт обещание изменения, и откуда оно взято.

    ОБЕЩАНИЕ ЖИВЁТ В ТЕЛЕ ИЗМЕНЕНИЯ, А НЕ В ТЕЛЕ СЛИЯНИЯ, И ЭТО ЗАМЕР. Прогон
    брал `git log -1` с головы общей ветки — а тело squash-коммита `automerge`
    собирает ЗАНОВО, из одних трейлеров, и передаёт площадке явным
    `commit_message`. Строка `Closes`/`Part of` туда не попадает никогда:
    8 сентября её несли 1 первопредок из 60, и тот слит другим путём. Значит
    ответом был вечный «изменение задач не называет — проверять нечего», то
    есть исход 0 на непроверенном предмете (146, 075).

    ЦЕНА ИЗМЕРЕНА ЗАДАЧЕЙ #355. Она ждёт ответа на вопрос «есть ли у
    MERGE_QUEUE_TOKEN право читать задачи» и говорит прямо: «проба ставится
    только изменением, тело которого несёт Closes или Part of». Такое изменение
    было — `03c2ee7`, и в теле его изменения #352 стоит `Part of #351`. До
    головы общей ветки эта строка не доехала, и проба не ставилась ни разу.

    ЧТО СПРАШИВАЕТСЯ У ПЛОЩАДКИ. Изменение, СЛИТОЕ этим коммитом: сначала то,
    чей `merge_commit_sha` и есть наш коммит, затем любое слитое. Неслитое
    изменение, в котором коммит просто присутствует, обещанием не считается —
    оно ничего не обещало про ЭТО слияние, и брать его тело значило бы гадать.

    Пусто — законный ответ, а не отказ: в общую ветку можно толкнуть и без
    изменения. Тогда берётся тело коммита, и об этом говорится вслух: молчание
    о подмене источника неотличимо от проверенного (039, 158).
    """
    слитые = [p for p in pulls if p.get("merged_at")]
    свои = [p for p in слитые if тот_же(p.get("merge_commit_sha"), sha)]
    for кто, откуда in ((свои, "слито этим коммитом"), (слитые, "слито")):
        if кто:
            п = кто[0]
            return (п.get("body") or ""), f"тело изменения #{п['number']} ({откуда})"
    return fallback, ("тело коммита — изменения, слитого им, у площадки нет; "
                      "так выглядит толчок в общую ветку напрямую")


def selftest() -> int:
    """Разбор и вердикт прогоняются тем, что обязаны отвергнуть И пропустить."""
    случаи = [
        ("закрыта — согласие", "42", "closes", "CLOSED", "", ""),
        ("обещала закрыть, а открыта", "42", "closes", "OPEN", "", "открыта"),
        ("часть, задача открыта с остатком", "7", "part", "OPEN",
         "- [ ] второй потребитель", ""),
        ("часть, а задача закрыта", "7", "part", "CLOSED", "- [ ] хвост", "закрыта"),
        ("часть без остатка", "7", "part", "OPEN", "просто проза", "остатка"),
        ("часть, галочка уже проставлена — остатка нет", "7", "part", "OPEN",
         "- [x] всё", "остатка"),
    ]
    сломано: list[str] = []
    for имя, номер, вид, состояние, тело, ждём in случаи:
        got = verdict(номер, вид, состояние, тело)
        ok = (ждём in got) if ждём else (got == "")
        if not ok:
            сломано.append(f"{имя}: вышло «{got or 'согласие'}»")
        print(f"  {'находка' if got else 'согласие':<9} — {имя}")

    closes, parts = tasks("Closes #12\n\nPart of #34\n\nОстаётся: хвост\n")
    if closes != ["12"] or parts != ["34"]:
        сломано.append(f"разбор тела: closes={closes}, parts={parts}")
    if tasks("упоминание #99 в прозе")[0]:
        сломано.append("упоминание в прозе принято за связь")
    print(f"  разбор    — closes={closes}, part={parts}")

    # ВЫБОР ИСТОЧНИКА ОБЕЩАНИЯ — ДВУСТОРОННИЙ (140). Из одних «обязан взять у
    # изменения» не виден ложный подхват: неслитое изменение, в котором коммит
    # просто лежит, обещания про ЭТО слияние не давало.
    SHA = "03c2ee7c1111111111111111111111111111aaaa"
    PR = lambda n, b, m="2026-09-04T14:08:29Z", c=SHA: {
        "number": n, "body": b, "merged_at": m, "merge_commit_sha": c}
    источники = [
        ("слито этим коммитом — берём его тело",
         [PR(352, "Part of #351")], "Part of #351", "#352"),
        ("коротким отпечатком — тот же коммит",
         [PR(352, "Part of #351", c="03c2ee7")], "Part of #351", "#352"),
        ("несколько изменений — своё вперёд чужого",
         [PR(9, "Closes #1", c="beefbeef"), PR(352, "Part of #351")],
         "Part of #351", "#352"),
        ("изменения нет вовсе — тело коммита, и это сказано",
         [], "ТЕЛО-КОММИТА", "тело коммита"),
        ("изменение есть, но НЕ слито — обещания не давало",
         [PR(500, "Closes #77", m=None, c=None)], "ТЕЛО-КОММИТА", "тело коммита"),
        ("слитое изменение без связи — пусто, но НЕ подмена на коммит",
         [PR(403, "Без задачи, потому что …")], "Без задачи", "#403"),
    ]
    for имя, вход, ждём_тело, ждём_источник in источники:
        тело, источник = promise_of(вход, SHA, "ТЕЛО-КОММИТА")
        if ждём_тело not in тело or ждём_источник not in источник:
            сломано.append(f"{имя}: вышло «{тело[:30]}» из «{источник}»")
        print(f"  источник  — {имя}")

    if сломано:
        print("\nсамопроверка провалена:", file=sys.stderr)
        for s in сломано:
            print(f"  {s}", file=sys.stderr)
        return 1
    print("самопроверка пройдена: вердикт различает согласие и расхождение")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--body-file", type=Path, help="файл с телом слитого изменения")
    ap.add_argument("--sha", help="коммит общей ветки: по нему у площадки "
                                  "спрашивается СЛИТОЕ им изменение, чьё тело "
                                  "и несёт обещание. Без ключа читается "
                                  "--body-file, и это тело коммита")
    ap.add_argument("--selftest", action="store_true", help="прогнать разбор и вердикт")
    ap.add_argument("--comment", action="store_true",
                    help="написать замечание в саму задачу (142)")
    args = ap.parse_args(argv)

    if args.selftest:
        return selftest()

    # ── исход 2 ────────────────────────────────────────────────────────────
    if args.body_file is None or not args.body_file.exists():
        print(f"проверка не отработала: --body-file не передан либо не "
              f"существует ({args.body_file})", file=sys.stderr)
        return 2
    body = args.body_file.read_text(encoding="utf-8")
    if args.sha:
        pulls, err = pulls_for(args.sha)
        if pulls is None:
            print(f"проверка не отработала: изменение, слитое коммитом "
                  f"{args.sha[:8]}, у площадки не спрошено — {err}",
                  file=sys.stderr)
            return 2
        body, откуда = promise_of(pulls, args.sha, body)
        # ИСТОЧНИК НАЗЫВАЕТСЯ ВСЛУХ. «Проверять нечего» имеет два прочтения —
        # «обещания не давали» и «прочитали не то», — и без этой строки они
        # неразличимы. Ровно так дефект и прожил незамеченным (158).
        print(f"обещание взято там, где записано: {откуда}")
    closes, parts = tasks(body)
    if not closes and not parts:
        print("изменение задач не называет — проверять нечего")
        return 0

    находки: list[str] = []
    #: Находки, которые не доехали до адресата. Молчание здесь означало бы, что
    #: механизм отчитался о доставке, которой не было (075).
    недоставлено: list[str] = []
    for номер, вид in [(n, "closes") for n in closes] + [(n, "part") for n in parts]:
        данные, err = issue(номер)
        if данные is None:
            print(f"проверка не отработала: задача #{номер} не прочитана — {err}",
                  file=sys.stderr)
            return 2
        плохо = verdict(номер, вид, данные.get("state", ""), данные.get("body", ""))
        if not плохо:
            continue
        находки.append(плохо)
        if args.comment:
            # ДОСТАВКА ПРОВЕРЯЕТСЯ, А НЕ ПРЕДПОЛАГАЕТСЯ. Код возврата здесь
            # игнорировался, и прогон печатал «замечание оставлено в самой
            # задаче», когда никакого замечания не появлялось: у находки
            # объявлен адресат (142), а дошла ли она — не спрашивал никто.
            # Замер 7 сентября: задача #355, вердикт вынесен, комментариев ноль.
            # ПО REST (001): `gh issue comment` идёт через GraphQL — площадка
            # сама назвала транспорт в отказе 7 сентября, «GraphQL: Resource
            # not accessible … (addComment)».
            код, ответ = gh("api", f"repos/{{owner}}/{{repo}}/issues/{номер}/comments",
                            "-f", "body=" +
                            f"{MARKER}\n\n{плохо}\n\nЗамечание оставлено прогоном "
                            "`task-state`: состояние задачи после слияния проверяется, а не "
                            "предполагается (правило 173). Закрывает задачу человек — "
                            "прогон только называет расхождение.")
            if код != 0:
                недоставлено.append(f"#{номер}: {ответ}")

    # ── исход 2: находка есть, а адресата у неё не оказалось ───────────────
    # НЕДОСТАВЛЕННАЯ НАХОДКА — ОТКАЗ МЕХАНИЗМА, А НЕ НАХОДКА. Исход 1 говорит
    # «в задаче написано»; если не написано, вызывающий узнаёт неправду, и
    # разойтись эти два состояния обязаны (039).
    if недоставлено:
        print("проверка не отработала: замечание не доставлено в задачу — "
              "у находки объявлен адресат, но она до него не дошла. Проверьте "
              "у MERGE_QUEUE_TOKEN право issues:write:", file=sys.stderr)
        for f in недоставлено:
            print(f"  • {f}", file=sys.stderr)
        for f in находки:
            print(f"  (находка, оставшаяся без адресата) {f}", file=sys.stderr)
        return 2

    # ── исход 1 ────────────────────────────────────────────────────────────
    if находки:
        print("задачи разошлись с тем, что обещало изменение:", file=sys.stderr)
        for f in находки:
            print(f"  • {f}", file=sys.stderr)
        return 1

    print(f"задачи в согласии с изменением: закрыто {len(closes)}, "
          f"частично {len(parts)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
