#!/usr/bin/env python3
"""Правило о механизмах держится во всём дереве механизмов, а не там, где родилось (220).

ИНЦИДЕНТ. 16.10 починка находки по 211 дважды вернула нарушение 217 — запасной
`python3` в хуке окна, — и все гейты были зелёными: мета-гейт 217 смотрел на
стиль, а не на то, чем хук исполняется. Анализ #879 нашёл, что охват мета-гейта
растёт от места рождения правила: 100 держался только для прогонов, 176 — без
хуков окна, и ответ «держится гейтом» снаружи выглядел одинаково для полного
и частичного охвата (182).

СПЕРВА СПРОСИЛИ СЕМЬЮ (162). Переписи мета-гейтов с охватом нет ни у кого из
пяти проектов; у механизмов есть файлы данных для гейтов в `.rules/` — форма
взята оттуда.

ЧТО ПРОВЕРЯЕТСЯ — перепись `.rules/mechanism-rules.json`:
  • каждое место дерева (`scripts`, `.claude/hooks`, `.github`) у каждого
    правила названо: гейтом, «исключено: причина» или «не построено: что»;
  • гейт существует и называет правило по номеру;
  • место стоит в коде гейта — признаком места или своим `признак` — либо в
    коде модуля проекта, который гейт импортирует (так `check_copies` берёт
    охват у `check_orphans`): перепись, разошедшаяся с кодом, — находка;
  • правило из переписи существует в каталоге.
«Не построено» — законный ответ, но это долг: печатается числом.

ГРАНИЦА. Полноту самой переписи гейт не судит: правило о механизмах, не
внесённое в неё, он не увидит. Перечень взят замером #879.

Исходы: 0 — перепись сходится с кодом · 1 — расхождение · 2 — перепись не
прочитана или пуста.

Реализует правила каталога:
  220 — механизм тоже предмет правил о механизмах; охват — всё дерево;
  182 — ответ о половине требования виден: место без гейта названо;
  162 — у семьи спросили до постройки; 039, 075, 158 — три исхода, предмет.
"""

import argparse
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ПЕРЕПИСЬ = Path(".rules") / "mechanism-rules.json"
ИСКЛЮЧЕНО = "исключено:"
ДОЛГ = "не построено:"


def импортируемые(root: Path, текст: str) -> list[str]:
    """Тексты модулей проекта из scripts/, которые импортирует гейт."""
    out = []
    for узел in ast.walk(ast.parse(текст)):
        имена = ([a.name for a in узел.names] if isinstance(узел, ast.Import)
                 else [узел.module] if isinstance(узел, ast.ImportFrom) and узел.module else [])
        for имя in имена:
            путь = root / "scripts" / f"{имя}.py"
            if путь.is_file():
                out.append(путь.read_text(encoding="utf-8"))
    return out


def сверить(root: Path, перепись: dict) -> tuple[list[str], list[str]]:
    """Находки и долги переписи против кода гейтов."""
    места: dict[str, str] = перепись.get("места", {})
    находки: list[str] = []
    долги: list[str] = []
    for номер, ответ in sorted(перепись.get("rules", {}).items()):
        if not list((root / "rules" / "ru").glob(f"{номер}-*.md")):
            находки.append(f"{номер}: правила нет в каталоге")
        for место, признак_места in места.items():
            значение = ответ.get(место)
            if значение is None:
                находки.append(f"{номер}: место {место} не названо — ни гейтом, ни исключением")
                continue
            if isinstance(значение, str) and значение.startswith(ИСКЛЮЧЕНО):
                if not значение[len(ИСКЛЮЧЕНО):].strip():
                    находки.append(f"{номер}: {место} исключено без причины")
                continue
            if isinstance(значение, str) and значение.startswith(ДОЛГ):
                долги.append(f"{номер} · {место}: {значение[len(ДОЛГ):].strip()}")
                continue
            гейт, признак = ((значение.get("гейт", ""), значение.get("признак", признак_места))
                             if isinstance(значение, dict) else (значение, признак_места))
            путь = root / гейт
            if not путь.is_file():
                находки.append(f"{номер}: {место} — гейта {гейт} нет")
                continue
            текст = путь.read_text(encoding="utf-8")
            if not re.search(rf"(?<!\d){номер}(?!\d)", текст):
                находки.append(f"{номер}: {гейт} не называет правило {номер}")
            if not any(признак in т for т in [текст, *импортируемые(root, текст)]):
                находки.append(f"{номер}: {место} — в коде {гейт} места нет (признак {признак}); "
                               "перепись разошлась с охватом")
    return list(dict.fromkeys(находки)), долги


def main(argv: list[str] | None = None) -> int:
    """Сверить перепись правил о механизмах с кодом гейтов."""
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)
    путь = args.root / ПЕРЕПИСЬ
    try:
        перепись = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"проверка не отработала: {путь} не прочитан — {exc} (075)", file=sys.stderr)
        return 2
    if not перепись.get("rules") or not перепись.get("места"):
        print(f"проверять нечего: в {путь} нет правил или мест — зеленеть на этом нельзя (075)",
              file=sys.stderr)
        return 2
    находки, долги = сверить(args.root, перепись)
    if находки:
        print("перепись правил о механизмах разошлась с кодом гейтов (220):", file=sys.stderr)
        for н in находки:
            print(f"  • {н}", file=sys.stderr)
        return 1
    print(f"правила о механизмах держатся по всему дереву: правил {len(перепись['rules'])}, "
          f"мест {len(перепись['места'])}, на суждении {len(перепись.get('суждение', {}))}, "
          f"не построено {len(долги)}")
    for д in долги:
        print(f"  · не построено: {д}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
