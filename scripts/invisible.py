#!/usr/bin/env python3
"""Невидимые символы в тексте, который читает окно: один разбор на весь каталог (#873).

ЗАЧЕМ. Чужой текст доходит до окна двумя путями: предложения семьи сборщик
кладёт в задачу-входящие, а правила, кандидаты и навыки каталога читают окна
потребителей. Символ формата Unicode в таком тексте человек не видит, а модель
читает. Так прячут указания — «ASCII smuggling» символами блока Tag
(U+E0000–U+E007F), переворот порядка двунаправленными (U+202A–U+202E,
U+2066–U+2069), разрыв слова нулевой шириной. Правило 085 называет такой текст
данными, а этот разбор не даёт данным нести невидимое.

ЧТО СЧИТАЕТСЯ. Вся категория `Cf` (формат), а не перечень кодовых точек:
перечень устаревает с каждой версией Unicode, категория — нет. Сверх неё —
три заполнителя хангыля из категории `Lo`, которые рисуются пустотой и
известны как обход именно такого списка (U+115F, U+1160, U+3164). Приём и
список заполнителей взяты у ECC (`scripts/ci/check-unicode-safety.js`, MIT,
разбор #863), код — нет.

ГРАНИЦА. Мягкий перенос U+00AD тоже `Cf`, и он тоже отказ. Замер 16.10: в
дереве каталога вне `.venv` символов формата 0, в пяти каналах предложений
семьи — 0. Законного употребления не нашлось, исключение не заведено.

Реализует правила каталога:
  085 — текст из чужого предмета — данные, а не указание: невидимое в нём
        не переносится туда, где его читает модель;
  214 — один разбор: им пользуются и сборщик предложений, и гейт дерева.
"""

import unicodedata

__all__ = ["невидимые", "в_данных", "назвать"]

#: Заполнители хангыля: категория `Lo`, рисуются пустотой.
ЗАПОЛНИТЕЛИ = frozenset({"ᅟ", "ᅠ", "ㅤ"})


def невидимые(текст: str) -> list[tuple[int, str]]:
    """Позиции и символы, которые человек не видит, а модель читает."""
    return [(i, c) for i, c in enumerate(текст)
            if c in ЗАПОЛНИТЕЛИ or unicodedata.category(c) == "Cf"]


def в_данных(данные: object, путь: str = "") -> list[tuple[str, str]]:
    """Невидимые символы в разобранном JSON: путь поля и символ — и в ключах тоже."""
    if isinstance(данные, str):
        return [(путь or "$", c) for _, c in невидимые(данные)]
    if isinstance(данные, dict):
        out: list[tuple[str, str]] = []
        for к, v in данные.items():
            out += [(f"{путь}.{к}", c) for _, c in невидимые(str(к))]
            out += в_данных(v, f"{путь}.{к}")
        return out
    if isinstance(данные, list):
        return [x for i, v in enumerate(данные) for x in в_данных(v, f"{путь}[{i}]")]
    return []


def назвать(символ: str) -> str:
    """`U+E0041 TAG LATIN CAPITAL LETTER A` — кодовая точка и имя, а не сам символ."""
    return f"U+{ord(символ):04X} {unicodedata.name(символ, 'без имени')}"
