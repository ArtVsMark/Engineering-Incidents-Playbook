#!/usr/bin/env python3
"""Проверяет ответ каталога о самом себе и печатает, чем правила держатся.

Каталог — такой же проект-потребитель, как и остальные: у него есть механизмы,
и он обязан отвечать за каждое правило (правило 129). Этот скрипт проверяет
ответ по контракту из export/README.md и считает метрику из 120.

Реализует правила каталога:
  129 — ответ потребителя: статус, чем держится, где, причина для отрицательных;
  128 — обязательное поле проверяется на полноту: ответ нужен по КАЖДОМУ правилу,
        а не по тем, до которых дошли руки;
  120 — «сколько правил не обеспечено ничем» — метрика, и она должна уменьшаться;
  039 — у проверки три исхода, а не два;
  026 — отрицательное решение записывается с причиной;
  004 — расхождение ответа — находка, а не поломка прогона потребителя;
  057 — правило, которое нельзя проверить машиной, называет это прямо — `mechanism: none` с причиной;
  096 — ответ каталога о себе живёт в .rules/bindings.json и нигде больше;
  154 — `active` + `none` без причины отвергается: молчание неотличимо от «не дошли руки»;
  044 — премиса вердикта проверяется прежде, чем ему поверят: каждый названный
        адрес есть утверждение о текущем коде, и оно сверяется с файлом;
  162 — очередь «ничем» называет, что из неё уже решено у соседа и чем: ответы
        потребителей лежат в собранной сводке, и не заданный вопрос неотличим
        от отсутствующих данных.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.
"""

from __future__ import annotations

import datetime as dt
import json
import re
import sys
from collections import Counter
from pathlib import Path

# Свёртка «что у меня ничем, а у соседа держится» одна на весь каталог:
# ею же собирается раздел во входящие потребителю. Второе выражение того же
# разошлось бы с первым молча (правила 090, 022).
import sync_inbox

ROOT = Path(__file__).resolve().parent.parent
BINDINGS = ROOT / ".rules" / "bindings.json"
EXPORT = ROOT / "export" / "rules.json"

STATUSES = ("active", "rejected", "not-applicable", "unreviewed")
#: Чем правило держится. Порядок канонический: сверху вниз — от того, что
#: отказывает машинно, к тому, что не отказывает вовсе.
#:
#: РАСКОЛ «ШАГА ПРОЦЕССА». Одно слово называло три разные вещи: проверку в
#: конвейере, которая просто не гейт изменения; абзац в документе, который
#: читают; и намерение, за которым нет ничего. Замер по собственному ответу
#: каталога: из 44 записей со «шагом процесса» 3 указывали на конвейер, 14 —
#: на документ, 27 — ни на что, кроме прозы. Слово, под которым 27 из 44
#: означают «ничем», меряет не механизм, а веру в него.
#:
#: `process-step` остаётся принятым: список значений расширен, а не заменён —
#: по контракту это MINOR (export/README.md). У потребителей ответы уже лежат,
#: и обязать их переписать разом каталог не может.
MECHANISMS = ("gate", "pipeline", "document", "none", "process-step")

#: То же в порядке показа. `process-step` сюда не входит: он принимается на
#: входе, но в отчёте ему места нет — иначе колонка жила бы вечно.
MECHANISM_ORDER = ("gate", "pipeline", "document", "none")

#: Ревизор входит от списка деклараций и ищет расхождение с фактом. Ответ
#: каталога — это список деклараций: «держится гейтом вот здесь». Проверять
#: надо не форму записи, а то, что заявленное существует (правило 082 —
#: направление без владельца; здесь владелец машинный).
PATH_RE = re.compile(r"[\w./-]+\.(?:py|yml|yaml|json|md|txt)")

#: Корневые документы, которые в прозе называют БЕЗ расширения: «CONTRIBUTING»,
#: «README». Под PATH_RE такой токен не попадает, и утверждение о нём проходило
#: молча — ровно так ответ по 065 год говорил «точки входа новичка нет», когда
#: CONTRIBUTING.md лежал в корне (задача #67).
BARE_DOCS = ("CONTRIBUTING", "README", "LICENSE", "CHANGELOG", "SECURITY",
             "HISTORY", "CLAUDE", "VERSIONING", "START", "TOP-10")
BARE_RE = re.compile(r"\b(" + "|".join(BARE_DOCS) + r")\b")

#: Образец адреса, годного в `where`. Шире, чем PATH_RE: сюда попадает и
#: образец `.github/workflows/*.yml` — набор файлов такой же адрес, как один
#: файл, и требовать перечислить их поимённо значило бы требовать список,
#: который устареет с первым новым прогоном.
ADDRESS_RE = re.compile(r"[\w./*-]+\.(?:py|yml|yaml|json|md|txt|toml|cfg|sh)\b")

#: Скрипт, названный механизмом. Отдельно от ADDRESS_RE: там любой адрес, здесь
#: только то, у чего можно спросить, какие правила оно держит.
SCRIPT_RE = re.compile(r"scripts/([\w_]+\.py)")

#: Блок «Реализует правила каталога:» в докстроке скрипта. Форма узкая и
#: проверяется: заголовок строкой, дальше строки вида «  NNN — что делает».
#: Продолжение строки допускается отступом — иначе объяснение не помещается,
#: а однострочные объяснения превращаются в ярлыки (154).
DECLARES_HEAD = "Реализует правила каталога:"
DECLARES_RE = re.compile(r"^\s+(\d{3})\s+—", re.M)


def declares(path) -> set[str] | None:
    """Правила, которые скрипт объявляет своими. `None` — блока нет вовсе.

    Разница между «нет блока» и «блок пустой» существенна: первое означает, что
    вопрос не задавали, второе — что на него ответили «никаких». Сливать их
    значит повторять ошибку, ради которой написано 154.
    """
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return None
    at = text.find(DECLARES_HEAD)
    if at < 0:
        return None
    rest = text[at + len(DECLARES_HEAD):]
    # Блок кончается пустой строкой: дальше идёт обычная проза докстроки.
    конец = rest.find("\n\n")
    return set(DECLARES_RE.findall(rest if конец < 0 else rest[:конец]))



def addressed(where: str) -> bool:
    """У механизма назван адрес, а не только рассказано, что он есть.

    ПОЧЕМУ ЭТО ВООБЩЕ ПРОВЕРЯЕТСЯ. «След» правила гейт требует РАЗРЕШИМЫМ:
    задача `владелец/репозиторий#номер` либо названный потребитель, и проза
    следом не считается (audit_catalogue). У поля `where` такого требования не
    было — проверялось только, что оно непустое. Асимметрия стоила ровно того,
    чего от неё ждали: чтобы разделить 44 ответа на конвейер, документ и ничто,
    пришлось разбирать прозу регулярным выражением, потому что адреса в ней
    могло и не быть.

    ЧТО ЭТО ЛОВИТ НА САМОМ ДЕЛЕ. Не форму записи, а ложный механизм: гейт, чей
    адрес нельзя назвать, обычно и не гейт. Замер по собственному ответу
    каталога — семь таких, и все семь оказались утверждениями обо ВСЕХ
    скриптах сразу («три исхода у каждого»), которых не проверяет ни один гейт.

    ГРАНИЦА. Существование файла здесь НЕ проверяется — это делает ревизия
    ниже, по тому же тексту. Здесь вопрос один: адрес назван или нет. И
    `mechanism: none` сюда не попадает вовсе: у отсутствия механизма адреса
    быть не может, а требовать его значило бы толкать к выдумыванию.
    """
    return bool(ADDRESS_RE.search(where) or BARE_RE.search(where))


#: Слова, которыми утверждают ОТСУТСТВИЕ. Не всякое отрицание годится:
#: «не проверяется» — про механизм, «нет» — про предмет. Ловим только второе,
#: иначе шум забьёт находку (правило 051).
ABSENCE_RE = re.compile(
    r"\b(нет|не существует|отсутству\w*|не заведён\w*|не заведена|не создан\w*)\b")

#: Окно разбора — фрагмент вокруг имени, а не всё поле: в длинном пояснении
#: «нет» из соседнего предложения относилось бы не к тому (правило 144).
ABSENCE_WINDOW = 60
#: Число словом внутри ответа устареет так же, как цифра (правила 005, 127).
COUNT_RE = re.compile(r"\b(два|две|три|четыре|пять|шесть|семь|восемь|девять|десять)\b")


#: Классы причин «ничем». Берутся из НАЧАЛА поля `why`: там, где 154 требует
#: назвать причину, авторы пишут её первым же оборотом. Список разрешительный —
#: непопавшее считается «прочим» и печатается числом, а не растворяется (068).
WHY_CLASSES = {
    "требует суждения": "суждением",
    "предмет вне досягаемости": "вне досягаемости",
    "не дошли руки": "очередь",
    "предмета ещё не было": "предмета нет",
}


def why_split(rules: dict) -> tuple[dict[str, int], int]:
    """Разбивка «ничем» по причине: класс → сколько, и сколько прочих.

    ПОЧЕМУ РАЗБИВКА, А НЕ НОВОЕ ЗНАЧЕНИЕ МЕХАНИЗМА. «Держится привычкой» и «не
    держится ничем» различаются для НАС, а не для контракта: потребителю оба
    означают «нарушение не заметит ничто». Новое значение подняло бы схему
    ответа и заставило каждого потребителя перечитать записи — цену этого
    измерил грейдер, когда раскололся `process-step` (правило 157). Данные для
    разбивки уже есть: причину при `none` требует 154.

    ПОЧЕМУ ТОЛЬКО В МЕТРИКЕ. В сводке и картинке «ничем» остаётся одной
    величиной: `why` обязателен у КАТАЛОГА, а контракт его от потребителя не
    требует. Колонка, полная у одного и пустая у двух, ломает то, ради чего
    картинка построена колонками, — сравнение соседей глазом.
    """
    counts: dict[str, int] = {}
    other = 0
    for rec in rules.values():
        if rec.get("status") != "active" or (rec.get("mechanism") or "none") != "none":
            continue
        why = (rec.get("why") or "").strip()
        for head, label in WHY_CLASSES.items():
            if why.startswith(head):
                counts[label] = counts.get(label, 0) + 1
                break
        else:
            other += 1
    return counts, other


#: Сводка ответов потребителей: производное, лежит в дереве и собирается ночным
#: прогоном. Читается только ради метрики, и её отсутствие — не отказ.
#: Путь считается от ROOT в момент вызова, а не на импорте: иначе подделка,
#: подменившая корень, читала бы сводку НАСТОЯЩЕГО каталога (правило 149).
WHERE = Path("export") / "where.json"


def next_door(rules: dict) -> list[str]:
    """Что у нас не держится ничем, а у соседа держится — строками метрики.

    ПОЧЕМУ ЭТО ЗДЕСЬ, А НЕ ОТДЕЛЬНОЙ КОМАНДОЙ. Вопрос «чем это держится у
    соседа» полезен ровно в тот момент, когда выбирают, что строить, — то есть
    рядом с числом «НИЧЕМ». Отдельной командой его надо помнить, а шаг, который
    надо помнить, пропускают (002). Инцидент 162: сводка собиралась ночным
    прогоном неделями, и в эту сторону её не читал никто.

    ПОЧЕМУ МЕТРИКА, А НЕ ОТКАЗ. Чужой приём не обязан подойти: стеки разные, и
    правило, закрытое у соседа гейтом, здесь может быть неприменимо вовсе.
    Красное на этом приучало бы пропускать красное (051).
    """
    where = ROOT / WHERE
    if not where.exists():
        return [f"решено у соседа: не считалось — нет {WHERE}"]
    try:
        consumers = json.loads(where.read_text(encoding="utf-8"))["consumers"]
        me = json.loads(BINDINGS.read_text(encoding="utf-8"))["project"]
    except (ValueError, KeyError, TypeError) as e:
        return [f"решено у соседа: не считалось — {WHERE} не разобрать ({e})"]

    solved = sync_inbox.solved_next_door(rules, consumers, me)
    if not solved:
        return ["решено у соседа: ни одного — очередь «ничем» здесь своя"]
    who = Counter(h["repo"].split("/")[-1] for row in solved for h in row["held"])
    return [
        f"решено у соседа {len(solved)}: "
        + " · ".join(f"{repo} {n}" for repo, n in who.most_common()),
        "  " + " ".join(row["rule"] for row in solved),
        f"  чем именно — поле where у соседа в {WHERE} (правило 162)",
    ]


def main() -> int:
    # ── исход 2 ────────────────────────────────────────────────────────────
    for path in (BINDINGS, EXPORT):
        if not path.exists():
            print(f"проверка не отработала: нет {path.relative_to(ROOT)}", file=sys.stderr)
            return 2
    try:
        answer = json.loads(BINDINGS.read_text(encoding="utf-8"))
        export = json.loads(EXPORT.read_text(encoding="utf-8"))
    except ValueError as e:
        print(f"проверка не отработала: не разобрать JSON — {e}", file=sys.stderr)
        return 2

    rules = answer.get("rules")
    if not isinstance(rules, dict) or not rules:
        print("проверка не отработала: в ответе нет записей — сверять нечего",
              file=sys.stderr)
        return 2

    known = {r["id"]: r for r in export["rules"]}

    # ── исход 1 ────────────────────────────────────────────────────────────
    problems: list[str] = []
    warnings: list[str] = []
    for rid in sorted(set(known) - set(rules)):
        problems.append(f"{rid}: ответа нет. «Не дошли руки» — это статус "
                        "unreviewed, а не отсутствующая запись")
    for rid in sorted(set(rules) - set(known)):
        problems.append(f"{rid}: ответ есть, а правила такого в каталоге нет")

    for rid, rec in sorted(rules.items()):
        status = rec.get("status")
        if status not in STATUSES:
            problems.append(f"{rid}: статус {status!r} вне набора {STATUSES}")
            continue
        if status == "active":
            if rec.get("mechanism") not in MECHANISMS:
                problems.append(f"{rid}: действует, но механизм "
                                f"{rec.get('mechanism')!r} вне набора {MECHANISMS}")
            if not rec.get("where"):
                problems.append(f"{rid}: действует, а где именно — не сказано")
            elif (rec.get("mechanism") or "none") != "none" \
                    and not addressed(rec["where"]):
                problems.append(
                    f"{rid}: держится {rec.get('mechanism')}, а адреса нет — "
                    f"«{rec['where'][:60]}». Механизм, который нельзя открыть, "
                    "проверить нечем")
        # ОБЕ СТОРОНЫ СВЯЗИ, А НЕ ОДНА. Правило называет свой механизм в
        # `where`; механизм называет свои правила блоком «Реализует правила
        # каталога». Обе декларации существовали и не сверялись — то есть были
        # двумя классификациями одной территории (022), и они разошлись:
        # замер 28 августа дал 32 случая «скрипт вообще без блока» и 25
        # «блок есть, правила в нём нет».
        #
        # СВЯЗЬ ОДНОСТОРОННЯЯ, И ЭТО НЕ УПУЩЕНИЕ. Проверяется «правило назвало
        # скрипт ⇒ скрипт называет правило». Обратное требовать нельзя: скрипт
        # исполняет 039 (три исхода) и 075 (не нашёл предмета — падает), не
        # будучи механизмом ни того ни другого, — их механизм в другом месте.
        # Требование обратной связи завалило бы отчёт шумом, а шум приучают
        # пропускать (051).
        if status == "active" and (rec.get("mechanism") or "none") != "none":
            for s in sorted(set(SCRIPT_RE.findall(rec.get("where") or ""))):
                path = ROOT / "scripts" / s
                if not path.exists():
                    continue  # о несуществующем файле скажет ревизия ниже
                names = declares(path)
                if names is None:
                    problems.append(
                        f"{rid}: назван механизмом scripts/{s}, а тот не "
                        "объявляет своих правил. Нужен блок «Реализует правила "
                        "каталога:» в докстроке, строкой «NNN — что он для "
                        "этого правила делает»")
                elif rid not in names:
                    problems.append(
                        f"{rid}: назван механизмом scripts/{s}, а тот его не "
                        f"называет. Связь односторонняя только на бумаге: "
                        f"{s} перечисляет {', '.join(sorted(names)) or '—'}")

        # Ревизия: заявленное должно существовать, а не звучать правдоподобно.
        claim = f"{rec.get('where', '')} {rec.get('why', '')}"
        for token in PATH_RE.findall(claim):
            if not (ROOT / token).exists():
                problems.append(f"{rid}: заявлено «{token}», а такого файла нет — "
                                "декларация разошлась с фактом")
        # Утверждение об отсутствии документа, который есть. Предупреждение,
        # а не отказ: «нет» рядом с именем — подозрение, а не факт, и живая
        # проза даёт достаточно законных сочетаний (правило 051).
        for m in BARE_RE.finditer(claim):
            near = claim[max(0, m.start() - ABSENCE_WINDOW):
                         m.end() + ABSENCE_WINDOW]
            if not ABSENCE_RE.search(near):
                continue
            name = m.group(1)
            found = [c for c in (name, f"{name}.md", f"{name}.txt")
                     if (ROOT / c).exists()]
            if found:
                warnings.append(
                    f"{rid}: сказано, что {name} нет, а {found[0]} есть — "
                    f"похоже на устаревший ответ")

        # Правило 051: запрещают достоверное, предупреждают о вероятном.
        # Несуществующий путь — факт. Число словом — подозрение: «два дерева»
        # не устареет, «четыре гейта» устареет. Отказ здесь был бы ложным.
        if COUNT_RE.search(claim):
            warnings.append(f"{rid}: число словом — «{claim.strip()[:60]}». "
                            "Считать должен тот, кто печатает метрику")

        if status in ("rejected", "not-applicable") and not rec.get("why"):
            problems.append(f"{rid}: статус {status!r} без причины — "
                            "решение без причины вернётся следующей ревизией")

        # Правило 154. `none` без причины означает сразу две разные вещи —
        # «пробовали, машинно нельзя» и «никто не пробовал», — а стоят они
        # по-разному: первое не очередь, второе и есть очередь. Замер при
        # заведении правила: 41 запись не держится ничем, причину называют 5.
        #
        # ПОЧЕМУ ПРИЧИНА, А НЕ ЗАПИСЬ В СВОД. Запись в свод — очевидное
        # лекарство, и оно было применено заранее и не удержало ни разу:
        # «старая помечается заменённой» стояло в 043, 120 И в запретах свода,
        # а запись 143 удалили; «метки проставлены» стояло в 064 и в чек-листе,
        # а меток не было на десяти изменениях подряд. Причину нельзя написать,
        # не подумав, — в этом вся разница.
        if status == "active" and (rec.get("mechanism") or "none") == "none" \
                and not rec.get("why"):
            problems.append(
                f"{rid}: не держится ничем, и почему — не сказано. `none` без "
                "причины неотличимо от «не дошли руки»: требует суждения · "
                "предмет чужой · проверка дороже нарушения — но названо это "
                "должно быть (правило 154)")

    if problems:
        print("ответ каталога о себе не в порядке:", file=sys.stderr)
        for p in problems:
            print(f"  • {p}", file=sys.stderr)
        return 1

    # ── исход 0 плюс метрика ───────────────────────────────────────────────
    by_status = Counter(r["status"] for r in rules.values())
    by_mech = Counter(r.get("mechanism") for r in rules.values()
                      if r["status"] == "active")

    unreviewed = [rid for rid, r in rules.items() if r["status"] == "unreviewed"]
    oldest = ""
    if unreviewed:
        dates = [known[rid]["added"] for rid in unreviewed if known[rid].get("added")]
        if dates:
            days = (dt.date.today() - dt.date.fromisoformat(min(dates))).days
            oldest = f", самому старому {days} дн."

    if warnings:
        print("на что стоит посмотреть (не отказ):")
        for w in warnings:
            print(f"  ~ {w}")
    print(f"ответ каталога о себе полон: {len(rules)} правил")
    legacy = by_mech["process-step"]
    tail = f", шагом процесса {legacy} (слово устарело)" if legacy else ""
    print(f"  действует {by_status['active']}: "
          f"гейтом {by_mech['gate']}, конвейером {by_mech['pipeline']}, "
          f"документом {by_mech['document']}, "
          f"НИЧЕМ {by_mech['none']}{tail}")
    by_why, other = why_split(rules)
    if by_why or other:
        parts = [f"{label} {n}" for label, n in
                 sorted(by_why.items(), key=lambda kv: -kv[1])]
        if other:
            parts.append(f"прочее {other}")
        print("    из них: " + " · ".join(parts))
    for line in next_door(rules):
        print(f"    {line}")
    print(f"  отклонено {by_status['rejected']}, "
          f"нет предмета {by_status['not-applicable']}")
    print(f"  не рассмотрено {by_status['unreviewed']}{oldest}")
    return 0


