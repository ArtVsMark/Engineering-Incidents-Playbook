"""Проверяет ответ каталога о самом себе и печатает, чем правила держатся.

Каталог — такой же проект-потребитель, как и остальные: у него есть механизмы,
и он обязан отвечать за каждое правило (правило 129). Этот скрипт проверяет
ответ по контракту из export/README.md и считает метрику из 120.

Реализует правила каталога:
  129 — ответ потребителя: статус, чем держится, где, причина для отрицательных;
  128 — обязательное поле проверяется на полноту: ответ нужен по КАЖДОМУ правилу,
        а не по тем, до которых дошли руки;
  177 — незакрытая работа по правилам идёт впереди новой: три числа ступени 0
        печатаются ВСЕГДА, и каталог спрашивает их с себя первым, а не только
        отдаёт потребителям;
  157 — подъём контракта означает перечитывание ОТВЕТОВ: своя схема сверяется
        с номером, который каталог сам же публикует в contracts.bindings;
  120 — «сколько правил не обеспечено ничем» — метрика, и она должна уменьшаться;
  039 — у проверки три исхода, а не два;
  026 — отрицательное решение записывается с причиной;
  004 — расхождение ответа — находка, а не поломка прогона потребителя;
  057 — правило, которое нельзя проверить машиной, называет это прямо — `mechanism: none` с причиной;
  096 — ответ каталога о себе живёт в .rules/bindings.json и нигде больше;
  154 — `active` + `none` без причины отвергается: молчание неотличимо от «не дошли руки»;
  182 — причины мало: у `none` спрашивается ещё и `machine_half` — что
        следует из данных целиком и почему оно не построено, а у `document` —
        `document_reason`: машинной половины нет вовсе или она не построена;
  139 — ответ «гейт» обязан назвать исполняемое, а не прозу: род
        названного проверяется, потому что «гейт» обещает остановку машиной;
  183 — поле «чем держится» есть утверждение о дереве: названный путь обязан
        существовать, а названный механизмом скрипт — объявлять это правило
        своим;
  184 — ответ «правило к нам не относится» проверяется свидетелем: скрипт,
        объявивший правило своим, опровергает такой ответ фактом;
  044 — премиса вердикта проверяется прежде, чем ему поверят: каждый названный
        адрес есть утверждение о текущем коде, и оно сверяется с файлом;
  178 — два числа об одной величине печатаются вместе и названными: «правил»
        и «записей» расходятся вдвое, и дешёвая гипотеза «считаем одно дважды»
        закрывается печатью, а не рассуждением;
  162 — очередь «ничем» называет, что из неё уже решено у соседа и чем: ответы
        потребителей лежат в собранной сводке, и не заданный вопрос неотличим
        от отсутствующих данных;
  175 — «не применимо» это утверждение о ПРОЕКТЕ, и оно устаревает молча:
        пробой опровергается то, что опровергается командой, а всё
        остальное считается и называется числом непроверенного.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.
"""

