#: .json и .md сюда НЕ входят намеренно. В настройках прозы нет вовсе — номер
#: там писать некуда, и требование было бы отказом на пустом месте (051); у
#: документов номер обычно стоит ссылкой, и его ловит ADDRESS_RE выше.
ВНЕ_SCRIPTS_RE = re.compile(r"(?:tests|\.claude|\.github)/[\w./-]+\.(?:py|ya?ml)")

#: Виды исполняемого, на которые вправе указывать ответ «гейт». Список
#: закрытый: «похоже на путь» приняло бы docs/*.md — законный адрес для
#: mechanism: document и незаконный для gate (099, 139).
ИСПОЛНЯЕМОЕ = (
    re.compile(r"scripts/[\w_]+\.py"),
    re.compile(r"\.github/workflows/[\w.-]+\.ya?ml"),
    re.compile(r"tests/[\w_]+\.py"),
    re.compile(r"(?:^|[\s/])action\.yml"),
    re.compile(r"\.claude/[\w./-]+"),
)

#: Блок «Реализует правила каталога:» в докстроке скрипта. Форма узкая и
#: проверяется: заголовок строкой, дальше строки вида «  NNN — что делает».
#: Продолжение строки допускается отступом — иначе объяснение не помещается,
#: а однострочные объяснения превращаются в ярлыки (154).
DECLARES_HEAD = "Реализует правила каталога:"
DECLARES_RE = re.compile(r"^\s+(\d{3})\s+—", re.M)


def declares(path) -> set[str] | None:
    """Правила, которые скрипт объявляет своими. `None` — блока нет вовсе.

    Разница между «нет блока» и «блок пустой» существенна: первое означает, что
    вопрос не задавали, второе — что на него ответили «никаких». Сливать их
    значит повторять ошибку, ради которой написано 154.
    """
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return None
    at = text.find(DECLARES_HEAD)
    if at < 0:
        return None
    rest = text[at + len(DECLARES_HEAD):]
    # Блок кончается пустой строкой: дальше идёт обычная проза докстроки.
    конец = rest.find("\n\n")
    return set(DECLARES_RE.findall(rest if конец < 0 else rest[:конец]))



def addressed(where: str) -> bool:
    """У механизма назван адрес, а не только рассказано, что он есть.

    ПОЧЕМУ ЭТО ВООБЩЕ ПРОВЕРЯЕТСЯ. «След» правила гейт требует РАЗРЕШИМЫМ:
    задача `владелец/репозиторий#номер` либо названный потребитель, и проза
    следом не считается (audit_catalogue). У поля `where` такого требования не
    было — проверялось только, что оно непустое. Асимметрия стоила ровно того,
    чего от неё ждали: чтобы разделить 44 ответа на конвейер, документ и ничто,
    пришлось разбирать прозу регулярным выражением, потому что адреса в ней
    могло и не быть.

    ЧТО ЭТО ЛОВИТ НА САМОМ ДЕЛЕ. Не форму записи, а ложный механизм: гейт, чей
    адрес нельзя назвать, обычно и не гейт. Замер по собственному ответу
    каталога — семь таких, и все семь оказались утверждениями обо ВСЕХ
    скриптах сразу («три исхода у каждого»), которых не проверяет ни один гейт.

    ГРАНИЦА. Существование файла здесь НЕ проверяется — это делает ревизия
    ниже, по тому же тексту. Здесь вопрос один: адрес назван или нет. И
    `mechanism: none` сюда не попадает вовсе: у отсутствия механизма адреса
    быть не может, а требовать его значило бы толкать к выдумыванию.
    """
    return bool(ADDRESS_RE.search(where) or BARE_RE.search(where))


#: ВТОРАЯ ЗАКОННАЯ ФОРМА АДРЕСА — ЗАДАЧА. `addressed` её не знает и знать не
#: должна: она судит адрес МЕХАНИЗМА в ответе потребителя, а механизм задачей
#: не бывает. Но у СЛЕДА задача законна наравне с файлом, и обе стороны обязаны
#: судить её одинаково.
#:
#: НЕ ЗАЯКОРЕНО, И ЭТО ЗАМЕР. Заякоренная форма `^…$` отвергала след
#: `владелец/репозиторий#181 — описание`, которым корпус пишет следы у 042 и
#: 043; то есть проверка была строже собственного корпуса — своя же
#: асимметрия (197), пойманная сборкой каркаса на годном предложении.
ЗАДАЧА_RE = re.compile(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+#\d+")


def разрешимый_адрес(текст: str) -> bool:
    """Назван ли в тексте адрес, по которому можно пройти: файл либо задача.

    ОДИН ОТВЕТ НА ОДИН ВОПРОС (022). Спрашивают трое: след записи у сборки
    каркаса, след предложения у сборщика предложений и — половиной — поле
    `where` в ответе потребителя. Три копии этого суждения разъехались бы
    молча, и две из трёх уже успели разойтись за одну смену.
    """
    return bool(addressed(текст) or ЗАДАЧА_RE.search(текст))


#: Слова, которыми утверждают ОТСУТСТВИЕ. Не всякое отрицание годится:
#: «не проверяется» — про механизм, «нет» — про предмет. Ловим только второе,
#: иначе шум забьёт находку (правило 051).
ABSENCE_RE = re.compile(
    r"\b(нет|не существует|отсутству\w*|не заведён\w*|не заведена|не создан\w*)\b")

#: Окно разбора — фрагмент вокруг имени, а не всё поле: в длинном пояснении
#: «нет» из соседнего предложения относилось бы не к тому (правило 144).
ABSENCE_WINDOW = 60
#: Число словом внутри ответа устареет так же, как цифра (правила 005, 127).
COUNT_RE = re.compile(r"\b(два|две|три|четыре|пять|шесть|семь|восемь|девять|десять)\b")


#: Классы причин «ничем». Берутся из НАЧАЛА поля `why`: там, где 154 требует
#: назвать причину, авторы пишут её первым же оборотом. Список разрешительный —
#: непопавшее считается «прочим» и печатается числом, а не растворяется (068).
WHY_CLASSES = {
    "требует суждения": "суждением",
    "предмет вне досягаемости": "вне досягаемости",
    "не дошли руки": "очередь",
    "предмета ещё не было": "предмета нет",
}


def why_split(rules: dict) -> tuple[dict[str, int], int]:
    """Разбивка «ничем» по причине: класс → сколько, и сколько прочих.

    ПОЧЕМУ РАЗБИВКА, А НЕ НОВОЕ ЗНАЧЕНИЕ МЕХАНИЗМА. «Держится привычкой» и «не
    держится ничем» различаются для НАС, а не для контракта: потребителю оба
    означают «нарушение не заметит ничто». Новое значение подняло бы схему
    ответа и заставило каждого потребителя перечитать записи — цену этого
    измерил грейдер, когда раскололся `process-step` (правило 157). Данные для
    разбивки уже есть: причину при `none` требует 154.

    ПОЧЕМУ ТОЛЬКО В МЕТРИКЕ. В сводке и картинке «ничем» остаётся одной
    величиной: `why` обязателен у КАТАЛОГА, а контракт его от потребителя не
    требует. Колонка, полная у одного и пустая у двух, ломает то, ради чего
    картинка построена колонками, — сравнение соседей глазом.
    """
    counts: dict[str, int] = {}
    other = 0
    for rec in rules.values():
        if rec.get("status") != "active" or (rec.get("mechanism") or "none") != "none":
            continue
        why = (rec.get("why") or "").strip()
        for head, label in WHY_CLASSES.items():
            if why.startswith(head):
                counts[label] = counts.get(label, 0) + 1
                break
        else:
            other += 1
    return counts, other


#: Сводка ответов потребителей: производное, лежит в дереве и собирается ночным
#: прогоном. Читается только ради метрики, и её отсутствие — не отказ.
#: Путь считается от ROOT в момент вызова, а не на импорте: иначе подделка,
#: подменившая корень, читала бы сводку НАСТОЯЩЕГО каталога (правило 149).
WHERE = Path("export") / "where.json"


def next_door(rules: dict) -> list[str]:
    """Что у нас не держится ничем, а у соседа держится — строками метрики.

    ПОЧЕМУ ЭТО ЗДЕСЬ, А НЕ ОТДЕЛЬНОЙ КОМАНДОЙ. Вопрос «чем это держится у
    соседа» полезен ровно в тот момент, когда выбирают, что строить, — то есть
    рядом с числом «НИЧЕМ». Отдельной командой его надо помнить, а шаг, который
    надо помнить, пропускают (002). Инцидент 162: сводка собиралась ночным
    прогоном неделями, и в эту сторону её не читал никто.

    ПОЧЕМУ МЕТРИКА, А НЕ ОТКАЗ. Чужой приём не обязан подойти: стеки разные, и
    правило, закрытое у соседа гейтом, здесь может быть неприменимо вовсе.
    Красное на этом приучало бы пропускать красное (051).
    """
    where = ROOT / WHERE
    if not where.exists():
        return [f"решено у соседа: не считалось — нет {WHERE}"]
    try:
        consumers = json.loads(where.read_text(encoding="utf-8"))["consumers"]
        me = json.loads(BINDINGS.read_text(encoding="utf-8"))["project"]
    except (ValueError, KeyError, TypeError) as e:
        return [f"решено у соседа: не считалось — {WHERE} не разобрать ({e})"]

    solved = sync_inbox.solved_next_door(rules, consumers, me)
    if not solved:
        return ["решено у соседа: ни одного — очередь «ничем» здесь своя"]
    # не проза: «владелец/репозиторий» — путь, а не предложение.
    who = Counter(h["repo"].split("/")[-1] for row in solved for h in row["held"])
    записей = sum(who.values())
    # ДВА ЧИСЛА ОБ ОДНОЙ ВЕЛИЧИНЕ ПЕЧАТАЮТСЯ ВМЕСТЕ И НАЗВАННЫМИ (правило 178).
    # Здесь их ровно два: ПРАВИЛ решено 12, а ЗАПИСЕЙ о том, что оно решено, —
    # 25, потому что одно правило держат сразу несколько соседей. Читатель,
    # сложивший числа по проектам, получит 25 и объяснит расхождение природой
    # данных — самым дорогим объяснением из возможных. Дешёвая гипотеза «мы
    # считаем одну величину дважды» закрывается не рассуждением, а печатью
    # числа уникальных идентификаторов рядом с числом строк.
    расхождение = ("" if записей == len(solved)
                   else f" (записей {записей} — одно правило держат несколько "
                        "соседей, 178)")
    return [
        f"решено у соседа: правил {len(solved)}{расхождение}",
        "  " + " · ".join(f"{repo} {n}" for repo, n in who.most_common()),
        "  " + " ".join(row["rule"] for row in solved),
        f"  чем именно — поле where у соседа в {WHERE} (правило 162)",
    ]


def print_tier_zero(answer: dict, export: dict) -> None:
    """Напечатать три числа ступени 0. Зовётся с КАЖДОГО исхода, кроме второго.

    ОДНО ВЫРАЖЕНИЕ НА ДВА ПУТИ, А НЕ ДВА ПОХОЖИХ (022). Печать жила внутри
    ветки «чисто», и обещание докстроки `tier_zero` — «ПЕЧАТАЮТСЯ ВСЕГДА,
    включая нули» — было неверно по коду: при непустом `problems` main()
    возвращал 1 раньше, чем доходил сюда. Находку дал внешний взгляд на
    изменении #402, замер подтвердил её запуском.

    Числа и находки отвечают на РАЗНЫЕ вопросы, и в этом весь смысл: находка
    говорит, что сломалось, а три числа — закрыт ли долг по правилам вообще
    (027, 041). Гася вторые первой, скрипт отвечал на вопрос, которого ему не
    задавали, и молчал о том, который свод велит задавать ПЕРВЫМ (177).

    Третий исход исключён намеренно: там не разобран сам ответ, и печатать
    было бы нечего — счёт по неразобранному был бы выдумкой, а не нулём.
    """
    строки, долг = tier_zero(
        answer.get("rules", {}), {r["id"] for r in export.get("rules", [])},
        answer.get("schema"), (export.get("contracts") or {}).get("bindings"))
    print()
    for line in строки:
        print(line)
    if долг:
        print("  пока эти числа не ноль, новая работа по правилам — очередь, "
              "а не работа (правило 177)")


def main() -> int:
    # ── исход 2 ────────────────────────────────────────────────────────────
    for path in (BINDINGS, EXPORT):
        if not path.exists():
            print(f"проверка не отработала: нет {path.relative_to(ROOT)}", file=sys.stderr)
            return 2
    try:
        answer = json.loads(BINDINGS.read_text(encoding="utf-8"))
        export = json.loads(EXPORT.read_text(encoding="utf-8"))
    except ValueError as e:
        print(f"проверка не отработала: не разобрать JSON — {e}", file=sys.stderr)
        return 2

    rules = answer.get("rules")
    if not isinstance(rules, dict) or not rules:
        print(f"проверка не отработала: в {BINDINGS.relative_to(ROOT)} нет ни "
              "одной записи — сверять нечего", file=sys.stderr)
        return 2

    known = {r["id"]: r for r in export["rules"]}

    # ── исход 1 ────────────────────────────────────────────────────────────
    problems: list[str] = []
    warnings: list[str] = []
    #: «Не применимо» без пробы. Не отказ — но и не молчание: непроверенное
    #: утверждение обязано быть названо числом, иначе оно неотличимо от
    #: проверенного (правила 075, 165).
    unproved: list[str] = []
    for rid in sorted(set(known) - set(rules)):
        problems.append(f"{rid}: ответа нет. «Не дошли руки» — это статус "
                        "unreviewed, а не отсутствующая запись")
    for rid in sorted(set(rules) - set(known)):
        problems.append(f"{rid}: ответ есть, а правила такого в каталоге нет")

    for rid, rec in sorted(rules.items()):
        status = rec.get("status")
        if status not in STATUSES:
            problems.append(f"{rid}: статус {status!r} вне набора {STATUSES}")
            continue
        if status == "active":
            if rec.get("mechanism") not in MECHANISMS:
                problems.append(f"{rid}: действует, но механизм "
                                f"{rec.get('mechanism')!r} вне набора {MECHANISMS}")
            if not rec.get("where"):
                problems.append(f"{rid}: действует, а где именно — не сказано")
            elif (rec.get("mechanism") or "none") != "none" \
                    and not addressed(rec["where"]):
                problems.append(
                    f"{rid}: держится {rec.get('mechanism')}, а адреса нет — "
                    f"«{rec['where'][:60]}». Механизм, который нельзя открыть, "
                    "проверить нечем")
        # ОБЕ СТОРОНЫ СВЯЗИ, А НЕ ОДНА. Правило называет свой механизм в
        # `where`; механизм называет свои правила блоком «Реализует правила
        # каталога». Обе декларации существовали и не сверялись — то есть были
        # двумя классификациями одной территории (022), и они разошлись:
        # замер 28 августа дал 32 случая «скрипт вообще без блока» и 25
        # «блок есть, правила в нём нет».
        #
        # СВЯЗЬ ОДНОСТОРОННЯЯ, И ЭТО НЕ УПУЩЕНИЕ. Проверяется «правило назвало
        # скрипт ⇒ скрипт называет правило». Обратное требовать нельзя: скрипт
        # исполняет 039 (три исхода) и 075 (не нашёл предмета — падает), не
        # будучи механизмом ни того ни другого, — их механизм в другом месте.
        # Требование обратной связи завалило бы отчёт шумом, а шум приучают
        # пропускать (051).
        # НЕСИММЕТРИЧНОЕ ТРЕБОВАНИЕ, И АСИММЕТРИЯ ЗДЕСЬ ОСОЗНАННАЯ. У скрипта
        # в scripts/ спрашивается БЛОК объявлений: он пишется под правило, и
        # список правил — его документация. У прогона, набора и хука
        # спрашивается только УПОМИНАНИЕ номера: они пишутся под задачу, а
        # правило исполняют попутно, и требовать от тринадцати прогонов блок
        # значило бы завести дисциплину ради формы. Гейт ловит «файл вообще не
        # знает о правиле», а не качество объявления.
        if status == "active" and (rec.get("mechanism") or "none") != "none":
            for путь in sorted(set(ВНЕ_SCRIPTS_RE.findall(rec.get("where") or ""))):
                файл = ROOT / путь
                if not файл.exists():
                    continue  # о несуществующем файле скажет ревизия ниже
                текст = файл.read_text(encoding="utf-8", errors="replace")
                if not re.search(rf"\b0*{int(rid)}\b", текст):
                    problems.append(
                        f"{rid}: назван механизмом {путь}, а тот о правиле не "
                        "упоминает. Механизм, не знающий, что он чей-то, — "
                        "совпадение, а не связь: назовите номер в комментарии "
                        "либо в докстроке рядом с тем, что его держит")
            for s in sorted(set(SCRIPT_RE.findall(rec.get("where") or ""))):
                path = ROOT / "scripts" / s
                if not path.exists():
                    continue  # о несуществующем файле скажет ревизия ниже
                names = declares(path)
                if names is None:
                    problems.append(
                        f"{rid}: назван механизмом scripts/{s}, а тот не "
                        "объявляет своих правил. Нужен блок «Реализует правила "
                        "каталога:» в докстроке, строкой «NNN — что он для "
                        "этого правила делает»")
                elif rid not in names:
                    problems.append(
                        f"{rid}: назван механизмом scripts/{s}, а тот его не "
                        f"называет. Связь односторонняя только на бумаге: "
                        f"{s} перечисляет {', '.join(sorted(names)) or '—'}")

        # Ревизия: заявленное должно существовать, а не звучать правдоподобно.
        #
        # ПРОИЗВОДНОЕ ИСКЛЮЧЕНО, И ЭТО НЕ ПОСЛАБЛЕНИЕ. Отсутствие такого файла
        # — факт о рабочей копии, а не о декларации: его пересобирает прогон и
        # держит на своей ветке, в общей ветке его нет вовсе. Появляется он
        # только после сборщика, и вердикт о ЧУЖОМ утверждении начинал зависеть
        # от того, гоняли ли в этой копии `aggregate_bindings.py` (037).
        #
        # ЦЕНА ИЗМЕРЕНА 8 СЕНТЯБРЯ, НА СВЕЖЕМ КЛОНЕ. Ступень 0 спрашивается с
        # каталога ПЕРВОЙ командой нового окна — и отвечала ДВУМЯ ложными
        # находками: 105 и 174 законно называют `export/where.json`. Хуже
        # находок было молчание: три числа ступени 0, о которых этот же скрипт
        # объявляет «печатаются ВСЕГДА» (177), не печатались ни одного. Тот же
        # вызов после сборщика — чисто. Один коммит, два вердикта.
        #
        # ГРАНИЦА ЗДЕСЬ УЗКАЯ И ЗАКРЫТАЯ: освобождён поимённо названный путь из
        # `OWNED_BY_JOB`, а не каталог `export/`. Соседнее имя, которого никто
        # не собирает, остаётся находкой — иначе ревизия перестала бы держать
        # то, ради чего заведена (068, 146).
        claim = f"{rec.get('where', '')} {rec.get('why', '')}"
        for token in PATH_RE.findall(claim):
            if token in OWNED_BY_JOB or token.startswith(PROJECTED_TO_BADGES):
                continue
            if not (ROOT / token).exists():
                problems.append(f"{rid}: заявлено «{token}», а такого файла нет — "
                                "декларация разошлась с фактом")
        # Утверждение об отсутствии документа, который есть. Предупреждение,
        # а не отказ: «нет» рядом с именем — подозрение, а не факт, и живая
        # проза даёт достаточно законных сочетаний (правило 051).
        for m in BARE_RE.finditer(claim):
            near = claim[max(0, m.start() - ABSENCE_WINDOW):
                         m.end() + ABSENCE_WINDOW]
            if not ABSENCE_RE.search(near):
                continue
            name = m.group(1)
            found = [c for c in (name, f"{name}.md", f"{name}.txt")
                     if (ROOT / c).exists()]
            if found:
                warnings.append(
                    f"{rid}: сказано, что {name} нет, а {found[0]} есть — "
                    f"похоже на устаревший ответ")

        # Правило 051: запрещают достоверное, предупреждают о вероятном.
        # Несуществующий путь — факт. Число словом — подозрение: «два дерева»
        # не устареет, «четыре гейта» устареет. Отказ здесь был бы ложным.
        if COUNT_RE.search(claim):
            warnings.append(f"{rid}: число словом — «{claim.strip()[:60]}». "
                            "Считать должен тот, кто печатает метрику")

        if status in ("rejected", "not-applicable") and not rec.get("why"):
            problems.append(f"{rid}: статус {status!r} без причины — "
                            "решение без причины вернётся следующей ревизией")

        if status == "not-applicable":
            улика = refuted(rid, ROOT)
            if улика:
                problems.append(
                    f"{rid}: ответ «не применимо», а условия проекта уже другие: "
                    f"{улика}. Такое утверждение устаревает молча и выглядит "
                    "решением — перечитайте его (175)")
            elif rid not in REFUTED_BY:
                unproved.append(rid)

        # Правило 154. `none` без причины означает сразу две разные вещи —
        # «пробовали, машинно нельзя» и «никто не пробовал», — а стоят они
        # по-разному: первое не очередь, второе и есть очередь. Замер при
        # заведении правила: 41 запись не держится ничем, причину называют 5.
        #
        # ПОЧЕМУ ПРИЧИНА, А НЕ ЗАПИСЬ В СВОД. Запись в свод — очевидное
        # лекарство, и оно было применено заранее и не удержало ни разу:
        # «старая помечается заменённой» стояло в 043, 120 И в запретах свода,
        # а запись 143 удалили; «метки проставлены» стояло в 064 и в чек-листе,
        # а меток не было на десяти изменениях подряд. Причину нельзя написать,
        # не подумав, — в этом вся разница.
        if status == "active" and (rec.get("mechanism") or "none") == "none" \
                and not rec.get("why"):
            problems.append(
                f"{rid}: не держится ничем, и почему — не сказано. `none` без "
                "причины неотличимо от «не дошли руки»: требует суждения · "
                "предмет чужой · проверка дороже нарушения — но названо это "
                "должно быть (правило 154)")

        # ПРИЧИНЫ МАЛО: НАДО РАЗЛОЖИТЬ ТРЕБОВАНИЕ НАДВОЕ (правило 182).
        # Требование — конъюнкция, а причина пишется, глядя на неё целиком:
        # если хоть одна часть требует суждения, ответ звучит как «требует
        # суждения» — истинно про конъюнкцию и ложно про каждую часть. Замер 4
        # сентября: 158, 170 и 144 стояли с честными причинами и все три
        # закрылись за один заход, потому что лёгкая половина всё это время
        # лежала рядом. Поэтому у `none` спрашивается ОТДЕЛЬНО: что следует из
        # данных целиком и почему оно всё-таки не построено.
        if status == "active" and (rec.get("mechanism") or "none") == "none" \
                and not rec.get("machine_half"):
            problems.append(
                f"{rid}: причина есть, а разбора надвое нет. Скажите в поле "
                "`machine_half`, ЧТО ИМЕННО следует из данных целиком — и "
                "почему оно не построено: половины нет · нашлась бы пустота "
                "(146) · очередь. Честный ответ про всё требование не "
                "перепроверяют, и потому он живёт месяцами (правило 182)")

        # ── РАЗБОР НАДВОЕ СПРАШИВАЕТСЯ И У `document` ────────────────────
        # АСИММЕТРИЯ, ИЗ КОТОРОЙ ЭТО ВЫРОСЛО. У `none` поле `machine_half`
        # обязательно; у `document` не требовалось НИЧЕГО — при том что предмет
        # ровно тот же: правило действует, машина его не держит. Разница между
        # ответами в наличии ТЕКСТА, а не машинной половины: документ не
        # проверяет ничего так же, как и её отсутствие.
        #
        # ЗАМЕР, ИЗ-ЗА КОТОРОГО ЭТО ЗАВЕДЕНО (встречное наблюдение проекта
        # механизмов, 10 сентября): у них `document` держит 30 правил против 25
        # у `gate` — больше половины активных ответов, — и доля машинного
        # соблюдения по семье (181 из 656) считается со знаменателем, где
        # «законно документом» и «пока документом» сложены в одно число.
        # У каталога таких ответов 28.
        #
        # ПОЧЕМУ ЗАКРЫТОЕ СЛОВО, А НЕ ПРОЗА. Счётчику семьи знаменатель нужно
        # РАЗДЕЛИТЬ, а прозу сложить нельзя. И почему слова мало: значение из
        # двух выбирается не думая, поэтому рядом обязательна причина — та же
        # связка, что у `none` (154).
        if status == "active" and rec.get("mechanism") == "document" \
                and разобран_документом(rec) is None:
            выбор = (rec.get("document_reason") or "").strip()
            if выбор not in ДОКУМЕНТ_ПРИЧИНЫ:
                problems.append(
                    f"{rid}: держится документом, а чем именно — не сказано. "
                    "Поле `document_reason` принимает одно из двух: "
                    "`impossible` — машинной половины нет вовсе, документ и "
                    "есть предел; `not-yet` — она есть и не построена. Без "
                    "него «законно документом» и «пока документом» "
                    "складываются в одно число, и счёт по семье врёт у всех "
                    "шестерых (182, 057)")
            else:
                problems.append(
                    f"{rid}: `document_reason` есть, а причины нет. Слово из "
                    "двух выбирается не думая — причину не написать, не "
                    "подумав, и в этом вся разница (154). Скажите, ЧТО именно "
                    "не проверяется машиной: у `impossible` — почему половины "
                    "нет, у `not-yet` — что построили бы и чего не хватает")

    # ── ОТВЕТ «ГЕЙТ» УКАЗЫВАЕТ НА ИСПОЛНЯЕМОЕ ────────────────────────────
    # ЧТО ИМЕННО ПРОВЕРЯЕТСЯ. `mechanism: gate` утверждает, что нарушение
    # ОСТАНОВИТ машина. Значит в поле where обязан стоять адрес чего-то, что
    # машина исполняет: скрипт, прогон, набор тестов, составное действие, хук
    # окна. Проза «держится договорённостью» рядом с ответом «гейт» — то же
    # самое утверждение о механизме, что и в 183, только про его РОД.
    #
    # ЗАМЕР 7 сентября: ответов gate 113; не называют скрипта 12, и все
    # двенадцать называют другой законный вид — прогон (10) и набор тестов (2).
    # Находок ноль. Это НЕ делает гейт украшением: предмет у него — все 113
    # ответов, они проверяются каждым прогоном, и ноль здесь означает «дрейфа
    # пока нет», а не «проверять нечего». Разница с 146 в том, что там предмет
    # ОТСУТСТВУЕТ, а здесь он есть и велик; охраняется будущая правка, которой
    # сегодня некому помешать написать в where прозу.
    #
    # ПОЧЕМУ ВИДЫ ПЕРЕЧИСЛЕНЫ, А НЕ ВЫВЕДЕНЫ. «Похоже на путь» ловило бы
    # docs/*.md — законный ответ для mechanism: document, но не для gate.
    # Список закрытый и растёт правкой: новый вид исполняемого — решение, а не
    # догадка регулярного выражения (099).
    for rid, rec in sorted(rules.items()):
        if rec.get("mechanism") != "gate":
            continue
        where = rec.get("where") or ""
        if not any(о.search(where) for о in ИСПОЛНЯЕМОЕ):
            problems.append(
                f"{rid}: ответ «гейт», а в where не назван ни один исполняемый "
                "адрес. Гейт — это утверждение, что нарушение остановит МАШИНА; "
                "значит должно быть названо то, что она исполняет: scripts/*.py, "
                ".github/workflows/*.yml, tests/*.py, action.yml или хук в "
                ".claude/. Проза рядом с «гейт» обещает больше, чем держит (139)")

    # ── ОТЛОЖЕННОЕ ОБЪЯВЛЯЕТСЯ ЗАМЕРОМ, А НЕ ОБЕЩАНИЕМ ───────────────────
    # ПОЛЕ `awaiting` — ЭТО ЛАЗЕЙКА, ЕСЛИ ЕГО НЕ ДЕРЖАТЬ. Оно выводит правило
    # из счётчика долга, а значит припиской «построим потом» можно очистить
    # ступень 0, не сделав ничего. Поэтому требование: отложено не «когда-
    # нибудь», а до НАЗВАННОГО события, и отсутствие предмета ИЗМЕРЕНО —
    # в тексте есть число. «Комплексных задач ноль», «контейнеров ноль»,
    # «103 ответа gate, 14 не называют скрипта» — замер; «пока рано» — нет.
    #
    # Число здесь то же, чего каталог требует от записи правила: утверждение
    # опирается на инцидент с числами, а не на принцип. Проверяется, что
    # вопрос ЗАМЕРЕН, а не что замер верен, — второе требует чтения (182).
    ЧИСЛО = re.compile(r"\d|\bноль\b|\bни одного\b|\bни одной\b|\bпервый\b|\bпервая\b|\bпервое\b", re.I)
    for rid, rec in sorted(rules.items()):
        ждёт = (rec.get("awaiting") or "").strip()
        if not ждёт:
            continue
        if (rec.get("mechanism") or "none") != "none":
            problems.append(
                f"{rid}: механизм назван, а поле awaiting осталось. Оно значит "
                "«ждём предмета, чтобы строить», и при готовом механизме "
                "утверждает неправду — уберите его")
        elif not ЧИСЛО.search(ждёт):
            problems.append(
                f"{rid}: отложено, но отсутствие предмета не измерено. В "
                "awaiting нет ни одного числа — значит сказано «построим "
                "потом», а не «предмета сейчас столько-то». Без замера поле "
                "выводит правило из долга даром (146, 177)")

    # ── МЕХАНИЗМ ДЕРЖИТ ПРАВИЛО, КОТОРОГО У НАС «НЕТ» ─────────────────────
    # ЭТО НЕ ТА АСИММЕТРИЯ, ЧТО ОБЪЯСНЕНА ВЫШЕ. Там сказано, почему нельзя
    # требовать «скрипт назвал правило ⇒ он его механизм»: скрипт исполняет
    # 039 и 075, не будучи механизмом ни того ни другого. Здесь утверждение
    # другое и одностороннее: скрипт объявил, что держит правило, а ответ
    # каталога говорит, что правило к нам НЕ ОТНОСИТСЯ. Оба верными быть не
    # могут — либо ответ устарел, либо ссылка не туда (181).
    #
    # ЗАМЕР 7 сентября, из-за которого это написано: 313 объявлений, СЕМЬ
    # спорных — 037, 050, 085, 116 и 137 (трижды). Все пять ответов разбирали
    # БУКВАЛЬНУЮ половину правила и не заметили обобщения, которым механизмы
    # уже пользовались: «сторож у источника» против «сырое против
    # производного», «параллельные исполнители» против «любой сборщик». Ровно
    # 182, только с другой стороны: надвое разбирается и «неприменимо».
    #
    # ПОЧЕМУ НАХОДКА, А НЕ АВТОМАТИЧЕСКАЯ ПРАВКА. Что именно неверно — ответ
    # или ссылка, — машина не решает: 085 стало применимым в тот день, когда
    # завели прогон ревью, а 116 у нас применимо не буквой, а обобщением.
    # Решает человек, гейт лишь не даёт противоречию стоять молча.
    for путь in sorted((ROOT / "scripts").glob("*.py")):
        объявлено = declares(путь)
        if not объявлено:
            continue
        for rid in sorted(объявлено):
            rec = rules.get(rid)
            if not isinstance(rec, dict):
                continue
            if rec.get("status") in ("not-applicable", "rejected"):
                problems.append(
                    f"{rid}: scripts/{путь.name} объявляет, что держит это "
                    f"правило, а ответ каталога — «{rec.get('status')}». Либо "
                    "ответ устарел, либо скрипт ссылается не туда: механизм "
                    "не может держать то, чего у нас нет (181)")

    if problems:
        print("ответ каталога о себе не в порядке:", file=sys.stderr)
        for p in problems:
            print(f"  • {p}", file=sys.stderr)
        print_tier_zero(answer, export)
        return 1

    # ── исход 0 плюс метрика ───────────────────────────────────────────────
    by_status = Counter(r["status"] for r in rules.values())
    by_mech = Counter(r.get("mechanism") for r in rules.values()
                      if r["status"] == "active")

    unreviewed = [rid for rid, r in rules.items() if r["status"] == "unreviewed"]
    oldest = ""
    if unreviewed:
        dates = [known[rid]["added"] for rid in unreviewed if known[rid].get("added")]
        if dates:
            days = (dt.date.today() - dt.date.fromisoformat(min(dates))).days
            oldest = f", самому старому {days} дн."

    if warnings:
        print("на что стоит посмотреть (не отказ):")
        for w in warnings:
            print(f"  ~ {w}")
    if unproved:
        print(f"  · «не применимо» без пробы: {len(unproved)} из "
              f"{len(unproved) + sum(1 for r in REFUTED_BY if r in rules)} — "
              "утверждение о проекте, которое ничем не перечитывается (175)")

    print(f"ответ каталога о себе полон: {len(rules)} правил")
    legacy = by_mech["process-step"]
    tail = f", шагом процесса {legacy} (слово устарело)" if legacy else ""
    print(f"  действует {by_status['active']}: "
          f"гейтом {by_mech['gate']}, конвейером {by_mech['pipeline']}, "
          f"документом {by_mech['document']}, "
          f"НИЧЕМ {by_mech['none']}{tail}")
    by_why, other = why_split(rules)
    if by_why or other:
        parts = [f"{label} {n}" for label, n in
                 sorted(by_why.items(), key=lambda kv: -kv[1])]
        if other:
            parts.append(f"прочее {other}")
        print("    из них: " + " · ".join(parts))
    for line in next_door(rules):
        print(f"    {line}")
    print(f"  отклонено {by_status['rejected']}, "
          f"нет предмета {by_status['not-applicable']}")
    print(f"  не рассмотрено {by_status['unreviewed']}{oldest}")

    # ЗАСЛОН 177 СПРОШЕН С СЕБЯ, И ЭТО НЕ УКРАШЕНИЕ. Каталог отдаёт потребителю
    # раздел «Ступень 0» через sync_inbox.py; не спрашивая того же с себя, он
    # требовал бы того, чего не делает сам. Печать, а не отказ: правило прямо
    # говорит, что заслон НАЗЫВАЕТ долг и не запрещает работу.
    print_tier_zero(answer, export)
    return 0


if __name__ == "__main__":
    sys.exit(main())
