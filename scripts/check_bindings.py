#: Ступень 0 каталога: то же, что механизм отдаёт потребителю, спрошенное с себя.
#: Правило 177 держится этим у нас, а sync_inbox.py — у них; одно правило, две
#: стороны, и обе обязаны быть, иначе каталог требует того, чего не делает сам
#: (правило 128 в его же формулировке: спрашивают с каждого, а не с тех, до кого
#: дошли руки).
def tier_zero(answered: dict, rules: set[str], schema: str | None,
              expected: str | None) -> tuple[list[str], bool]:
    """Три числа ступени 0 и признак «долг есть».

    ПЕЧАТАЮТСЯ ВСЕГДА, включая нули: число, видное лишь при поломке, отвечает на
    вопрос «что сломалось» и молчит о том, закрыт ли долг вообще (027, 041).
    """
    нет_ответа = sorted(rules - set(answered))
    не_рассмотрено = sorted(rid for rid, rec in answered.items()
                            if rec.get("status") == "unreviewed")
    без_механизма = [rid for rid, rec in answered.items()
                     if rec.get("status") == "active"
                     and (rec.get("mechanism") or "none") == "none"]
    # ОТЛОЖЕННОЕ — НЕ ДОЛГ, И БЕЗ ЭТОГО РАЗЛИЧИЯ 177 НЕИСПОЛНИМО. Правило 177
    # требует довести числа до нуля прежде новой работы. Правило 146 запрещает
    # строить гейт на нулевом предмете: он зеленел бы, не держа ничего. Три
    # правила попали ровно между: механизм для них строить НЕЛЬЗЯ, пока не
    # появится предмет, — значит счётчик долга не опустеет никогда, и очередь
    # 177 не откроется тоже никогда. Два правила спорили молча (181).
    #
    # Различие настоящее, а не бухгалтерское: «забыли построить» и «ждём
    # предмет, и вот какой» — разные состояния. Второе называется полем
    # `awaiting`: СОБЫТИЕ, при котором механизм строится. Поле необязательное
    # и читает его только каталог, поэтому контракт с потребителями не
    # двигается — в отличие от нового значения `mechanism`, цену которого
    # объясняет why_split ниже.
    отложено = sorted(rid for rid in без_механизма
                      if (answered[rid].get("awaiting") or "").strip())
    ничем = sorted(rid for rid in без_механизма if rid not in set(отложено))
    строки = [
        "ступень 0 — незакрытая работа по правилам у самого каталога:",
        f"  без ответа {len(нет_ответа)} · не рассмотрено {len(не_рассмотрено)} "
        f"· действует, но держится ничем {len(ничем)}",
    ]
    if ничем:
        строки.append("    " + " ".join(ничем))
    if отложено:
        строки.append(f"  отложено до появления предмета: {len(отложено)} — "
                      + " ".join(отложено))
        строки.append("    у каждого названо событие, при котором механизм "
                      "строится; это очередь с условием, а не долг (146)")
    # ── `document` РАЗЛОЖЕН, И ЧИСЛО ВИДНО СО СТОРОНЫ ────────────────────
    # ЗАЧЕМ ЭТО В СТУПЕНИ 0, А НЕ В ДОЛГЕ. Счёт по семье (181 механизм из 656
    # правил у шестерых) считается со знаменателем, где «законно документом» и
    # «пока документом» сложены в одно число, — и мерило зрелости конвейера от
    # этого сдвигается у ВСЕХ. Разложение печатается здесь потому, что здесь
    # уже стоит вопрос «сколько незакрытой работы», и второе место для того же
    # вопроса разошлось бы с первым молча (022).
    #
    # ДОЛГОМ `not-yet` НЕ СЧИТАЕТСЯ, И ЭТО НЕ УСТУПКА. Правило действует и
    # держится текстом — это не «без ответа» и не «держится ничем». Сделать
    # такую запись долгом значило бы закрыть очередь 177 навсегда: половина
    # у части этих правил ждёт ПРЕДМЕТА, которого сегодня нет (146). Число
    # печатается всегда — числа, видного лишь при поломке, здесь не бывает.
    #
    # НЕРАЗОБРАННОЕ СЧИТАЕТСЯ ТРЕТЬИМ, А НЕ ПРИБАВЛЯЕТСЯ К `impossible`. Здесь
    # стояло `len(документом) - len(не_построено)`, и запись без ответа —
    # поля нет, слово чужое — молча уезжала в «машинной половины нет», то есть
    # в разобранное. Тот же прогон её при этом ОТВЕРГАЕТ находкой строкой выше:
    # две половины одного прогона говорили о ней разное, и печатное число было
    # тем, которое читают (075). Не спрошенное не выдаётся за чистое (039).
    документом = [rid for rid, rec in answered.items()
                  if rec.get("status") == "active"
                  and rec.get("mechanism") == "document"]
    невозможна = sorted(rid for rid in документом
                        if разобран_документом(answered[rid]) == "impossible")
    не_построено = sorted(rid for rid in документом
                          if разобран_документом(answered[rid]) == "not-yet")
    без_разбора = sorted(rid for rid in документом
                         if разобран_документом(answered[rid]) is None)
    if документом:
        строки.append(
            f"  держится документом: {len(документом)} — машинной половины нет "
            f"у {len(невозможна)}, не построена у {len(не_построено)}")
        if не_построено:
            строки.append("    не построена: " + " ".join(не_построено))
        if без_разбора:
            строки.append(f"    без разбора: {len(без_разбора)} — "
                          + " ".join(без_разбора))
            строки.append("      их отвергает гейт выше; в счёт «половины нет» "
                          "они не идут, иначе неспрошенное встало бы в "
                          "разобранное (039)")

    # Сверка своей схемы с тем номером, который каталог сам публикует. Инцидент
    # правила 164 был ровно здесь: у потребителя стоял номер ЧУЖОГО формата, и
    # заметить это можно было только сверкой, а не чтением.
    if not expected:
        строки.append("  контракт: свой номер формата ответа не с чем сверить — "
                      "выгрузка не объявляет contracts.bindings")
    elif schema != expected:
        строки.append(f"  контракт: свой ответ объявлен как {schema}, а выгрузка "
                      f"публикует {expected} — ответы перечитываются (157)")
    else:
        строки.append(f"  контракт: свой ответ и выгрузка сходятся на {expected}")
    долг = bool(нет_ответа or не_рассмотрено or ничем
                or (expected and schema != expected))
    return строки, долг

def refuted(rid: str, root: Path) -> str:
    """Опровержение утверждения «не применимо», если оно нашлось.

    Пробы нет — возвращается пустое: это НЕ «проверено», и вызывающий обязан
    считать такие отдельно. Молчание о непроверенном неотличимо от чистого
    результата (075).
    """
    проба = REFUTED_BY.get(rid)
    if not проба:
        return ""
    где, игла, почему = проба
    цель = root / где
    файлы = sorted(цель.rglob("*")) if цель.is_dir() else [цель]
    for f in файлы:
        if not f.is_file():
            continue
        try:
            if игла in f.read_text(encoding="utf-8", errors="replace"):
                return f"{почему} ({f.relative_to(root)})"
        except OSError:
            continue
    return ""
#: Чем правило держится. Порядок канонический: сверху вниз — от того, что
#: отказывает машинно, к тому, что не отказывает вовсе.
#:
#: РАСКОЛ «ШАГА ПРОЦЕССА». Одно слово называло три разные вещи: проверку в
#: конвейере, которая просто не гейт изменения; абзац в документе, который
#: читают; и намерение, за которым нет ничего. Замер по собственному ответу
#: каталога: из 44 записей со «шагом процесса» 3 указывали на конвейер, 14 —
#: на документ, 27 — ни на что, кроме прозы. Слово, под которым 27 из 44
#: означают «ничем», меряет не механизм, а веру в него.
#:
#: `process-step` остаётся принятым: список значений расширен, а не заменён —
#: по контракту это MINOR (export/README.md). У потребителей ответы уже лежат,
#: и обязать их переписать разом каталог не может.
MECHANISMS = ("gate", "pipeline", "document", "none", "process-step")

#: То же в порядке показа. `process-step` сюда не входит: он принимается на
#: входе, но в отчёте ему места нет — иначе колонка жила бы вечно.
#: Чем именно держится ответ «документом». Слов ровно два, и словарь закрытый:
#: счётчик семьи обязан РАЗДЕЛИТЬ знаменатель, а прозу сложить нельзя.
#:   impossible — машинной половины нет вовсе, документ и есть предел;
#:   not-yet     — половина есть и не построена, это честный долг.
ДОКУМЕНТ_ПРИЧИНЫ = ("impossible", "not-yet")

MECHANISM_ORDER = ("gate", "pipeline", "document", "none")

def разобран_документом(rec: dict) -> str | None:
    """Слово разбора, если ответ «документом» разобран ЦЕЛИКОМ; иначе None.

    ОДИН ПРЕДИКАТ НА ГЕЙТ И НА СЧЁТ, И ЭТО ИЗМЕРЕНО. Гейт отвергает такую
    запись двумя условиями — слова нет либо оно чужое; слово есть, а причины
    нет, — а счёт ступени 0 смотрел только на первое. Запись с пустым `why`
    печаталась РАЗОБРАННОЙ тем же прогоном, который её отверг: два ответа на
    один вопрос разошлись молча (022, ревью #481). Приёмка теперь живёт здесь,
    а гейт лишь выбирает, какими словами сказать об отказе.

    ЧЕМ ДЕРЖИТСЯ ТРЕБОВАНИЕ ПРИЧИНЫ — 182, и это проверено по применимости, а
    не по звучанию. 182 работает «для любого реестра, где записывают „это не
    автоматизируется"», а признаком нарушения называет ответ, который приводит
    ОДНО препятствие на всё требование и не говорит, какая часть машинная.
    `mechanism: document` — такая же запись: документ не проверяет ничего.
    Слово без причины считается «не спрошено», а не «невозможно», и в счёт
    разобранного не идёт (039).

    ДВЕ ССЫЛКИ ЗДЕСЬ УЖЕ СТОЯЛИ И ОБЕ ПРОМАХНУЛИСЬ. 128 — про поле, чей
    предмет МНОЖЕСТВО, и проверяется там полнота перечисления (ревью #482).
    154 — про связку «слово и причина», но её применимость сама себя
    ограничивает `active` + `none` и второго случая не заводит; у `document`
    она годится АНАЛОГИЕЙ, как и помечено у гейта ниже, а не основанием
    (ревью #483). Обе взяты за фразу, а не за предмет.
    """
    выбор = (rec.get("document_reason") or "").strip()
    if выбор not in ДОКУМЕНТ_ПРИЧИНЫ:
        return None
    if not (rec.get("why") or "").strip():
        return None
    return выбор


#: Ревизор входит от списка деклараций и ищет расхождение с фактом. Ответ
#: каталога — это список деклараций: «держится гейтом вот здесь». Проверять
#: надо не форму записи, а то, что заявленное существует (правило 082 —
#: направление без владельца; здесь владелец машинный).
PATH_RE = re.compile(r"[\w./-]+\.(?:py|yml|yaml|json|md|txt)")

#: Корневые документы, которые в прозе называют БЕЗ расширения: «CONTRIBUTING»,
#: «README». Под PATH_RE такой токен не попадает, и утверждение о нём проходило
#: молча — ровно так ответ по 065 год говорил «точки входа новичка нет», когда
#: CONTRIBUTING.md лежал в корне (задача #67).
BARE_DOCS = ("CONTRIBUTING", "README", "LICENSE", "CHANGELOG", "SECURITY",
             "HISTORY", "CLAUDE", "VERSIONING", "START", "TOP-10")
BARE_RE = re.compile(r"\b(" + "|".join(BARE_DOCS) + r")\b")

#: Образец адреса, годного в `where`. Шире, чем PATH_RE: сюда попадает и
#: образец `.github/workflows/*.yml` — набор файлов такой же адрес, как один
#: файл, и требовать перечислить их поимённо значило бы требовать список,
#: который устареет с первым новым прогоном.
ADDRESS_RE = re.compile(r"[\w./*-]+\.(?:py|yml|yaml|json|md|txt|toml|cfg|sh)\b")

#: Скрипт, названный механизмом. Отдельно от ADDRESS_RE: там любой адрес, здесь
#: только то, у чего можно спросить, какие правила оно держит.
SCRIPT_RE = re.compile(r"scripts/([\w_]+\.py)")

#: Механизм ВНЕ scripts/: прогон, набор, хук окна. Спрашивается с них мягче —
