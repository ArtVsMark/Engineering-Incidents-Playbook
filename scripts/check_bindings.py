#: 155, и SCRIPT_RE сверял 110. Остальные 45 не проверялись НИЧЕМ — механизм,
#: названный прогоном или набором, мог не иметь к правилу никакого отношения, и
#: сказать это было некому. Ровно этот класс и есть инцидент у соседа: ответ по
#: 085 назвал механизмом tests/test_ai_grounding.py, где 12 случаев и ни одного
