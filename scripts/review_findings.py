#!/usr/bin/env python3
"""Находки внешнего взгляда переживают слияние: у них есть адресат.

ИНЦИДЕНТ, ЗАМЕР 8 сентября. За смену прогон ревью отработал 33 раза и дал
находки дважды. Первую партию окно применило. ВТОРУЮ НЕ УВИДЕЛ НИКТО: изменение
#392 слилось на 2,3 минуты раньше, чем ревьюер дописал вердикт, и две верные
находки — противоречие чисел внутри записи и неверное исключительное
утверждение — уехали в общую ветку вместе с изменением.

И это не единичный промах: из 29 слитых изменений с прогоном ревью вердикт
успел к слиянию у 10. Девятнадцать раз работа канала пропала целиком.

ПОЧЕМУ КОММЕНТАРИЯ НЕ ХВАТАЕТ. Пока изменение открыто, комментарий и есть
адресат — он на глазах у автора. После слияния изменение уходит из списка
открытых, и туда больше никто не смотрит: находка формально существует и
фактически недоступна. Ровно 142, только предмет не красное по расписанию, а
чужой разбор.

ПОЧЕМУ ЗАДАЧА, А НЕ КРАСНОЕ. Трекер — первый источник работы (091), и
единственный, куда окно смотрит обязательно. Красное же на необязательном канале
слияние не держит по 084 — и правильно: находка ревью это совет, а не запрет.
Значит остаётся адресат, переживающий слияние, и это задача.

ПОЧЕМУ ОДНА ЖИВАЯ, А НЕ ПО ЗАДАЧЕ НА ИЗМЕНЕНИЕ. Форма взята у дежурного по
общей ветке (scripts/main_red.py): ежедневная копия завалила бы трекер и
приучила листать его мимо. Тело обновляется по месту, идемпотентность держится
скрытым маркером, а не совпадением заголовка.

ЗАКРЫВАЕТ ЗАДАЧУ ЧЕЛОВЕК. Механизм не знает, разобрана находка или просто
надоела: «разобрал» — это суждение, и сказать его может только тот, кто читал.
Разобранные записи убираются из тела при следующем прогоне, а сама задача
остаётся, пока её не закроют.

ВЕРДИКТ И САМИ НАХОДКИ ЧИТАЮТСЯ СТРОКАМИ, А НЕ ПРОЗОЙ (166). Ревьюеру
предписано повторить каждую находку строкой «НАХОДКА: <что не так>» и закончить
ответ строкой «ВЕРДИКТ: находок N». Считать находки разбором прозы значило бы
угадывать чужую формулировку, а она меняется от прогона к прогону.

СНИМАЕТ НАХОДКУ МЕХАНИЗМ, А НЕ ГАЛОЧКА. У каждой записи есть ОТПЕЧАТОК — семь
знаков от хэша её заголовка. Автор починки называет его в теле своего изменения
строкой «Разобрано: <отпечаток>», и следующий заход уносит запись. Приём тот же,
которым площадка закрывает задачу по слову `Closes` в теле: снятие едет вместе с
работой, а не отдельным жестом, который забудут (002).

ПОЧЕМУ НЕ ГАЛОЧКА В ЗАДАЧЕ. Галочку ставят руками в трекере — это тот же жест
дисциплины, и он теряется ровно так же, как всё, что надо помнить. Отпечаток же
проверяем: он либо назван в слитом изменении, либо нет.

Запуск:
  python scripts/review_findings.py --repo o/r --pr 392          # разобрать
  python scripts/review_findings.py --repo o/r --pr 392 --apply  # и записать
  python scripts/review_findings.py --repo o/r --sweep --apply   # снять разобранное

Исходы:
  0 — вердикт есть и находок в нём нет, либо задача обновлена и пуста;
  1 — есть неразобранные находки (с --apply задача заведена или обновлена);
  2 — не отработал: площадка не ответила, вердикта нет вовсе.

Реализует правила каталога:
  142 — у находки есть адресат, и он переживает слияние;
  002 — снятие находки едет вместе с починкой, а не остаётся жестом дисциплины;
  084 — необязательный канал слияние не держит: находка идёт в задачу, а не в
        красное на изменении;
  105 — работа внешнего взгляда учитывается, а не пропадает вместе с окном;
  166 — вердикт ревьюера читается строкой с числом, а не разбором прозы;
  039 — три исхода, и третий не молчит;
  158 — третий исход называет предмет: номер изменения и команду, что молчала;
  001 — к площадке ходим по REST.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ghcli  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

#: Скрытый маркер живой задачи. По нему она находится снова — заголовок правят
#: руками, и тогда прогон завёл бы вторую вместо обновления (тот же приём, что
#: у дежурного по общей ветке).
МАРКЕР = "<!-- review-findings: не удаляйте, по этой строке задача находится снова -->"

ЗАГОЛОВОК = "Находки внешнего взгляда: не разобранные"

#: Начало строки: отступ, цитата, маркер списка, заголовок.
#: РАЗМЕТКУ ТЕРПЯТ, ПОТОМУ ЧТО ЕЁ СТАВИТ НЕ ЧЕЛОВЕК, А МОДЕЛЬ. Соседние
#: выражения этого же каталога терпели её с самого начала — `CLOSING_RE` и
#: `PART_RE` в pr_body.py, `OPEN_BOX_RE` в check_task_state.py, все с
#: `^[ \t>*-]*`, — а здесь про это забыли, и цена измерена: 8 сентября две
#: находки из четырёх ревьюер оформил жирным, вердикт посчитал их обе, а
#: механизм не извлёк НИ ОДНОЙ. Находка не доехала до живой задачи, то есть
#: потеряла адресата — ровно то, против чего 142 и заведён.
ПРЕФИКС = re.compile(r"^[ \t>#-]*")

#: ПАРНАЯ обёртка вокруг ВСЕЙ строки: `**жирным**`, `*курсивом*`, `__так же__`.
#: СНИМАЕТСЯ ПАРА, А НЕ ЗНАКИ ПО КРАЯМ, И ЭТО РАЗНЫЕ ВЕЩИ. Первая редакция
#: срезала `*` и `_` с концов заголовка через `str.strip` — и съедала их там,
#: где они принадлежат ТЕКСТУ: «**kwargs игнорируется» превращалось в «kwargs
#: игнорируется», «аргумент называется id_» — в «…id». Тот самый довод, которым
#: здесь защищены обратные кавычки, до них не дотянулся; нашёл это внешний
#: взгляд на изменении #413.
#:
#: СНИМАЕТСЯ СО СТРОКИ ЦЕЛИКОМ, А НЕ С ЗАГОЛОВКА. Если позволить префиксу съесть
#: открывающие `**`, у заголовка останется непарный хвост, и отличить его от
#: содержательного будет уже нечем. Порядок обратный: сняли префикс, сняли пару,
#: и только потом ищем `НАХОДКА:` — тогда заголовок не трогается вовсе.
ОБЁРТКА = re.compile(r"^(\*{1,2}|_{1,2})(.+?)\1$")

#: Вердикт ревьюера. Форма предписана промптом: одна строка, одно число.
ВЕРДИКТ = re.compile(r"^ВЕРДИКТ:\s*находок\s+(\d+)\s*$", re.I)

#: Сама находка. Заголовок в одну строку — по его отпечатку она узнаётся потом.
НАХОДКА = re.compile(r"^НАХОДКА:\s*(\S.*?)\s*$", re.I)


def без_оформления(строка: str) -> str:
    """Строка без префикса и без ПАРНОЙ обёртки. Одиночный знак — текст."""
    голая = ПРЕФИКС.sub("", строка.strip()).strip()
    пара = ОБЁРТКА.match(голая)
    return пара.group(2).strip() if пара else голая

#: Снятие: автор починки называет отпечаток в теле СВОЕГО изменения. Форма
#: намеренно близка к `Closes #N` — тому же приёму, которым площадка закрывает
#: задачу: снятие едет вместе с работой, а не отдельным жестом (002).
РАЗОБРАНО = re.compile(r"^\s*Разобрано:\s*([0-9a-f]{7})\b", re.M | re.I)

#: Учётная запись, под которой отвечает ревьюер. Проверяется, чтобы вердикт
#: из ЧУЖОГО комментария не считался нашим: текст изменения пишет тот, кого
#: проверяют, и вписать туда «ВЕРДИКТ: находок 0» он может свободно (085).
РЕВЬЮЕР = "claude[bot]"


def comments(repo: str, pr: int) -> tuple[list[dict] | None, str | None]:
    """Комментарии изменения по REST. Вторым — причина отказа с адресом."""
    code, out = ghcli.run(
        "api", f"repos/{repo}/issues/{pr}/comments?per_page=100",
        "--jq", "[.[] | {login: .user.login, body}]")
    if code != 0:
        return None, (f"gh api issues/{pr}/comments — "
                      f"{out.strip()[:160] or f'код {code}'}")
    try:
        return json.loads(out or "[]"), None
    except ValueError as e:
        return None, f"ответ gh api issues/{pr}/comments не разобран — {e}"


def отпечаток(заголовок: str) -> str:
    """Семь знаков от хэша заголовка находки.

    ПОЧЕМУ ОТ ЗАГОЛОВКА, А НЕ ОТ ФАЙЛА И СТРОКИ. Адрес «файл:строка» сдвигается
    первой же правкой выше по файлу — это измерено дважды: на парах правила 181
    и на исключении транспорта, где шесть строк комментария уронили гейт.
    Заголовок находки переживает починку, ради которой и назван.
    """
    return hashlib.sha1(" ".join(заголовок.split()).encode("utf-8")).hexdigest()[:7]


def findings_of(записи: list[dict]) -> list[str]:
    """Заголовки находок из комментария ревьюера, без повторов и по порядку."""
    вышло: list[str] = []
    for c in записи:
        if c.get("login") != РЕВЬЮЕР:
            continue
        for строка in (c.get("body") or "").splitlines():
            # Оформление снимается ЗДЕСЬ и только здесь, со строки целиком:
            # второе место очистки разошлось бы с первым молча (022).
            найдено = НАХОДКА.match(без_оформления(строка))
            if найдено and найдено.group(1) not in вышло:
                вышло.append(найдено.group(1))
    return вышло


def verdict_of(записи: list[dict]) -> int | None:
    """Число находок из вердикта ревьюера. None — вердикта нет вовсе.

    Берётся ПОСЛЕДНИЙ вердикт: действие обновляет свой комментарий по ходу, и
    промежуточное «находок 0» до разбора не должно перекрывать итог.
    """
    найдено = None
    for c in записи:
        if c.get("login") != РЕВЬЮЕР:
            continue
        for строка in (c.get("body") or "").splitlines():
            m = ВЕРДИКТ.match(без_оформления(строка))
            if m:
                найдено = int(m.group(1))
    return найдено


def live_issue(repo: str) -> tuple[int | None, str | None, str | None]:
    """Номер живой задачи, её тело и причина отказа.

    СПИСКОМ, А НЕ ПОИСКОМ, и это не вкус: поисковый индекс площадки догоняет с
    задержкой в минуты, и дежурный по общей ветке на этом уже завёл две задачи
    вместо одной. Изменения отсеиваются явно — REST кладёт их в /issues
    наравне с задачами.
    """
    code, out = ghcli.run(
        "api", f"repos/{repo}/issues?state=open&per_page=100",
        "--jq", "[.[] | select(.pull_request == null) | {number, body}]")
    if code != 0:
        return None, None, (f"gh api issues — {out.strip()[:160] or f'код {code}'}")
    try:
        задачи = json.loads(out or "[]")
    except ValueError as e:
        return None, None, f"ответ gh api issues не разобран — {e}"
    for з in задачи:
        if МАРКЕР in (з.get("body") or ""):
            return з["number"], з.get("body") or "", None
    return None, None, None


#: Запись находки в теле задачи: отпечаток, изменение, заголовок.
ЗАПИСЬ = re.compile(r"^- `([0-9a-f]{7})` · #(\d+) — (.+?)\s*$", re.M)


def записи_из(тело: str | None) -> dict[str, tuple[int, str]]:
    """Разбирает тело живой задачи обратно в записи по отпечатку."""
    return {о: (int(pr), з) for о, pr, з in ЗАПИСЬ.findall(тело or "")}


def body_for(записи: dict[str, tuple[int, str]], repo: str) -> str:
    """Тело живой задачи: сами заметки, а не счётчики.

    ЗАПИСЫВАЕТСЯ ЗАГОЛОВОК НАХОДКИ, А НЕ ЧИСЛО. «Находок 2» не говорит ничего:
    чтобы понять, что делать, придётся идти в слитое изменение и читать
    комментарий целиком. Заметка в задаче отвечает на вопрос сразу, а ссылка на
    изменение остаётся для подробностей.

    СНИМАЕТ ЗАПИСЬ МЕХАНИЗМ: строка «Разобрано: <отпечаток>» в теле любого
    слитого изменения. Галочка в трекере была бы тем же жестом дисциплины, что
    и всё, что надо помнить, — и терялась бы так же (002).
    """
    строки = [f"- `{о}` · #{pr} — {з}"
              for о, (pr, з) in sorted(записи.items(), key=lambda x: (-x[1][0], x[0]))]
    хвост = "\n".join(строки) if строки else "_пусто — всё разобрано_"
    return (
        f"{МАРКЕР}\n\n"
        "Внешний взгляд нашёл здесь то, чего не увидело окно, писавшее "
        "изменение, — и слияние его не задержало: канал необязательный, находка "
        "советует, а не запрещает (084). Поэтому адресат здесь, а не на "
        "изменении: слитое изменение уходит из списка открытых, и туда больше "
        "никто не смотрит (142).\n\n"
        "**Как снять запись.** В теле СВОЕГО изменения-починки напишите строку\n"
        "`Разобрано: <отпечаток>` — и следующий заход её унесёт. Отпечаток стоит\n"
        "слева от каждой заметки. Снятие едет вместе с починкой, а не остаётся\n"
        "жестом, который забудут (002).\n\n"
        "Ведётся прогоном, руками не правится: правка потеряется при следующем\n"
        "обновлении. Задачу закрывает человек — механизм не знает, кончилась ли\n"
        "работа или просто опустел список.\n\n"
        f"## Не разобрано: {len(строки)}\n\n{хвост}\n\n"
        f"Подробности — в комментариях ревьюера на самих изменениях: "
        f"https://github.com/{repo}/pulls?q=is%3Apr\n")


def снятые(repo: str, сколько: int = 30) -> tuple[set[str] | None, str | None]:
    """Отпечатки, названные разобранными в телах последних слитых изменений.

    ПО REST (001): `gh pr list` идёт через GraphQL, а один запрос сюда — это
    один и тот же список, который дежурный и так читает.

    ГЛУБИНА ОГРАНИЧЕНА НАМЕРЕННО. Снятие едет вместе с починкой, то есть
    появляется В БЛИЖАЙШИХ изменениях; читать всю историю значило бы платить
    за то, чего там нет. Запись, чьё снятие уехало за горизонт, останется в
    задаче — и это честнее, чем тихо потерять её из виду.
    """
    code, out = ghcli.run(
        "api", f"repos/{repo}/pulls?state=closed&per_page={сколько}",
        "--jq", "[.[] | select(.merged_at != null) | .body]")
    if code != 0:
        return None, f"gh api pulls?state=closed — {out.strip()[:160] or f'код {code}'}"
    try:
        тела = json.loads(out or "[]")
    except ValueError as e:
        return None, f"ответ gh api pulls не разобран — {e}"
    вышло: set[str] = set()
    for тело in тела:
        вышло |= {о.lower() for о in РАЗОБРАНО.findall(тело or "")}
    return вышло, None


def write_issue(repo: str, записи: dict[str, tuple[int, str]]) -> tuple[int, str]:
    """Заводит или обновляет живую задачу. Возвращает исход и что сделано."""
    номер, тело, почему = live_issue(repo)
    if почему:
        return 2, почему
    новое = body_for(записи, repo)
    if номер is not None:
        code, out = ghcli.run("api", "--method", "PATCH",
                              f"repos/{repo}/issues/{номер}", "-f", f"body={новое}")
        что = f"задача #{номер} обновлена: записей {len(записи)}"
    else:
        if not записи:
            return 0, "записей нет и задачи нет — заводить нечего"
        code, out = ghcli.run("api", f"repos/{repo}/issues",
                              "-f", f"title={ЗАГОЛОВОК}", "-f", f"body={новое}")
        что = f"задача заведена: {out.strip()[:120]}"
    if code != 0:
        return 2, f"трекер не принял запись — {out.strip()[:160]}"
    return 0, что


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", required=True, help="владелец/репозиторий")
    parser.add_argument("--pr", type=int, help="номер изменения")
    parser.add_argument("--sweep", action="store_true",
                        help="только снять разобранное, новых находок не искать")
    parser.add_argument("--apply", action="store_true",
                        help="завести или обновить задачу-адресата")
    args = parser.parse_args(argv)
    if not args.pr and not args.sweep:
        print("не отработал: нужен либо --pr NNN, либо --sweep", file=sys.stderr)
        return 2

    # ── уборка: снятое механизмом уходит из задачи ─────────────────────────
    if args.sweep:
        было_снято, почему = снятые(args.repo)
        if почему:
            print(f"не отработал: {почему}", file=sys.stderr)
            return 2
        номер, тело, почему = live_issue(args.repo)
        if почему:
            print(f"не отработал: {почему}", file=sys.stderr)
            return 2
        if номер is None:
            print("живой задачи нет — снимать нечего")
            return 0
        имелось = записи_из(тело)
        осталось = {о: v for о, v in имелось.items() if о not in было_снято}
        ушло = len(имелось) - len(осталось)
        print(f"записей было {len(имелось)}, названо разобранными {ушло}, "
              f"осталось {len(осталось)}")
        if not ушло:
            return 0 if not осталось else 1
        if not args.apply:
            print("--apply не задан: задачу не трогаю")
            return 1
        code, что = write_issue(args.repo, осталось)
        print(что, file=sys.stderr if code == 2 else sys.stdout)
        return code if code == 2 else (0 if not осталось else 1)

    записи, почему = comments(args.repo, args.pr)
    if почему:
        print(f"не отработал: {почему}", file=sys.stderr)
        return 2

    находок = verdict_of(записи)
    if находок is None:
        print(f"не отработал: у изменения #{args.pr} нет вердикта ревьюера — "
              "строки «ВЕРДИКТ: находок N» в его комментариях не найдено. "
              "Либо ревью не отработало, либо промпт разошёлся с этим разбором",
              file=sys.stderr)
        return 2

    if находок == 0:
        print(f"#{args.pr}: вердикт есть, находок нет — адресата не требуется")
        return 0

    заголовки = findings_of(записи)
    if not заголовки:
        # ЧИСЛО ЕСТЬ, А ЗАМЕТОК НЕТ — это отказ, а не «чисто». Записывать в
        # задачу нечего, и «находок 2» без текста ничем не поможет читателю
        # (075): предмет проверки не найден там, где он объявлен.
        print(f"не отработал: вердикт называет {находок} находок, а строк "
              "«НАХОДКА: …» в комментарии ревьюера нет — промпт разошёлся с "
              "этим разбором", file=sys.stderr)
        return 2

    print(f"#{args.pr}: находок {находок}, заметок разобрано {len(заголовки)} — "
          "слияние их не задержало (084), адресат нужен")
    for з in заголовки:
        print(f"  {отпечаток(з)} · {з}")
    if not args.apply:
        print("--apply не задан: задачу не трогаю")
        return 1

    номер, тело, почему = live_issue(args.repo)
    if почему:
        print(f"не отработал: {почему}", file=sys.stderr)
        return 2
    имелось = записи_из(тело)
    имелось.update({отпечаток(з): (args.pr, з) for з in заголовки})
    code, что = write_issue(args.repo, имелось)
    print(что, file=sys.stderr if code == 2 else sys.stdout)
    return 2 if code == 2 else 1


