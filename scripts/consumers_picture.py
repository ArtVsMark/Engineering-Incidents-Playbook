def rows(doc: dict) -> list[dict]:
    """Строки картинки: имя, состояние и три числа. Порядок — как в реестре."""
    out = []
    for c in doc.get("consumers", []):
        mech = c.get("by_mechanism") or {}
        # Статус приходит из другого поля сводки, чем механизм: складывать их в
        # один словарь до этого места значило бы потерять, откуда число.
        статус = c.get("by_status") or {}
        out.append({
            "name": (c.get("repo") or "?").split("/")[-1],
            "state": c.get("state", ""),
            "connected": bool(c.get("rules")),
            **{k: mech.get(k, 0) for k in tuple(MECHANISM_ORDER) + LEGACY_KEYS},
            **{k: статус.get(k, 0) for k in STATUS_KEYS},
            # СКЛАДЫВАЕТСЯ ЗДЕСЬ, А НЕ ПРИ РИСОВАНИИ: числа обоих слагаемых
            # остаются в строке по своим именам, и кто захочет разложить —
            # разложит, не считая заново (022).
            UNVERIFIABLE: mech.get("none", 0) + статус.get("not-applicable", 0),
            "trails": c.get("trails", 0),
            "born": c.get("born", 0),
            "answered": c.get("answered") or 0,
        })
    return out


def esc(text: str) -> str:
    """SVG — это XML: пять знаков в нём значат не то, что кажется."""
    return (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                .replace('"', "&quot;").replace("'", "&apos;"))


def text(x, y, s, fill, size, weight=500, extra=""):
    return (f'<text x="{x}" y="{y}" fill="{fill}" font-family="{FONT}" '
            f'font-size="{size}" font-weight="{weight}"{extra}>{esc(s)}</text>')


def shown(data: list[dict]) -> list[str]:
    """Какие механизмы вообще показывать.

    Канонические — всегда: ноль у гейта это ответ, а не пустая клетка.
    Устаревшее слово — только пока им отвечают: вписанная навсегда колонка
    пережила бы последнего потребителя, и вычеркнуть её было бы некому
    (правило 049).
    """
    used = {k for r in data if r["connected"] for k in ALL_KEYS if r.get(k)}
    # «НИЧЕМ» СТОИТ ВСЕГДА И ПОСЛЕДНИМ, как и канонический механизм:
    # ноль в нём — ответ («слепых мест нет»), а пропуск колонки читался бы как
    # «не спрашивали». Слагаемые — `none` и `not-applicable` — своих колонок
    # больше не получают: порознь они обещают определённость, которой нет
    # (см. довод у UNVERIFIABLE).
    return ([k for k in MECHANISM_ORDER if k != "none"]
            + [k for k in LEGACY_KEYS if k in used]
            + [UNVERIFIABLE])


def render(data: list[dict], total: int, dark: bool, lang: str = "ru") -> str:
    """Собирает SVG одной темы: строка на проект, колонки друг под другом.

    ПОЧЕМУ КОЛОНКАМИ, А НЕ БЛОКАМИ. Блок на проект читается по одному
    проекту за раз, а вопрос картинки сравнительный: у кого чем держится и
    насколько это отличается от соседа. Сравнивать глазом можно только то,
    что стоит друг под другом, — поэтому колонки фиксированные, а ширина
    плашечной колонки берётся максимальной по всем строкам: иначе число из
    трёх знаков сдвигало бы соседнюю колонку у одного проекта и не сдвигало
    у другого.

    СКОЛЬКО КОЛОНОК — РЕШАЮТ ДАННЫЕ. Канонические механизмы стоят всегда,
    даже нулём: ноль у гейта — это ответ, а пропущенная колонка читается как
    «такого вопроса не задавали». Устаревшее слово держится ровно пока им
    отвечают.

    ПОЧЕМУ ПОЛОС БОЛЬШЕ НЕТ. Полоса показывала долю и молчала об объёме: у
    проекта с сотней правил и у проекта с десятком она выглядела одинаково.
    Число отвечает на один вопрос и читается целиком; доля, которую надо
    мерить глазом, не читается никак.

    ДВА БЛОКА, А НЕ СЕМЬ КОЛОНОК ПОДРЯД. Вопросов у картинки два, и разные:
    сколько у проекта ПРАВИЛ и ЧЕМ он их держит. Прежде оба ряда чисел стояли
    сплошняком, и граница между вопросами была видна только тому, кто её уже
    знает. Теперь блок назван подписью сверху, отделён просветом вдвое шире
    внутреннего, а второй — ещё и подложкой.
    """
    t = THEME[dark]
    w = LANG[lang]
    keys = shown(data)
    band = полоса(data, w, keys)
    width = max(MIN_WIDTH, край(band, keys)[1] + PAD)
    # Высота растёт только если перенос случился — и тогда у ВСЕХ строк.
    lines = {r.get("name") or "": wrap_name(r.get("name") or "") for r in data}
    row = ROW_WRAPPED if any(len(v) > 1 for v in lines.values()) else ROW
    #: Нижний край таблицы: под ним сноска, и высота считается от него.
    низ = TOP + row * len(data)
    height = низ + FOOT
    держится = край(band, keys)
    p = [
        f'<svg width="{width}" height="{height}" viewBox="0 0 {width} {height}" '
        # Подпись для чтения с экрана — на языке витрины: она и есть то,
        # что услышит читатель вместо картинки.
        f'xmlns="http://www.w3.org/2000/svg" role="img" '
        f'aria-label="{esc(w["title"])}">',
        f'<rect x="0.5" y="0.5" width="{width - 1}" height="{height - 1}" '
        f'rx="16" fill="{t["card"]}" stroke="{t["stroke"]}"/>',
        f'<rect x="{PAD}" y="28" width="46" height="4" rx="2" fill="{t["accent"]}"/>',
        # ВТОРОЙ БЛОК ВЫДЕЛЕН ПОДЛОЖКОЙ, А НЕ РАМКОЙ, и подложка идёт вторым
        # прямоугольником — сразу за карточкой и до всякого текста: нарисуй её
        # позже, она легла бы поверх чисел, которые обязана выделять.
        f'<rect x="{держится[0] - COL_IN}" y="{TOP - 56}" '
        f'width="{держится[1] - держится[0] + 2 * COL_IN}" '
        f'height="{низ - TOP + 50}" rx="12" fill="{t["tint"]}"/>',
        text(PAD, 68, w["title"], t["name"], SIZE["title"], 800, ' letter-spacing="-0.6"'),
    ]
    # ШАПКА ДВУХЭТАЖНАЯ: подпись БЛОКА над подписями его колонок. Один этаж
    # отвечал бы на два вопроса подряд и не говорил, где кончается первый.
    for подпись, блок in ((w["group_rules"], ЧИСЛА), (w["group_held"], keys)):
        слева, справа = край(band, блок)
        p.append(text((слева + справа) // 2, TOP - 40, подпись, t["label"],
                      SIZE["group"], 700,
                      ' letter-spacing="1.4" text-anchor="middle"'))
    # ПОДПИСЬ КОЛОНКИ СТОИТ ОДИН РАЗ, СВЕРХУ И ПО СЕРЕДИНЕ СВОЕЙ КОЛОНКИ, а у
    # механизма — ещё и своим цветом: слово наверху, цвет держит связь подписи
    # со значением, и блок читается блоком без рамок.
    for key in ЧИСЛА:
        p.append(text(середина(band[key]), TOP - 16, w[key], t["label"],
                      SIZE["column"], 600,
                      ' letter-spacing="0.3" text-anchor="middle"'))
    for key in keys:
        p.append(text(середина(band[key]), TOP - 16, w[key], t[key],
                      SIZE["column"], 700,
                      ' letter-spacing="0.3" text-anchor="middle"'))

    y = TOP
    for r in data:
        куски = lines[r["name"]]
        # Одна строка стоит там же, где стояла всегда; две — симметрично
        # вокруг того же места, чтобы ряд не «поехал» относительно чисел.
        база = y + 17 if len(куски) == 1 else y + 8
        for n, кусок in enumerate(куски):
            p.append(text(PAD, база + n * 19, кусок, t["name"], SIZE["name"], 800,
                          ' letter-spacing="-0.4"'))
        # «Родил» показывается и у НЕподключённого проекта: происхождение
        # записи не зависит от того, ответил ли проект каталогу, и прочерк
        # здесь означал бы «не знаем», хотя знаем (правило 027).
        for key, value, live in (("answered", r["answered"], r["connected"]),
                                 ("trails", r["trails"], r["trails"] > 0),
                                 ("born", r["born"], r["born"] > 0)):
            cell = str(value) if live else "—"
            p.append(text(середина(band[key]), y + 19, cell,
                          t["accent"] if live else t["muted"], SIZE["number"], 800,
                          ' text-anchor="middle"'))
        if r["connected"]:
            for key in keys:
                p.append(text(середина(band[key]), y + 19, str(r[key]), t[key],
                              SIZE["number"], 800, ' text-anchor="middle"'))
        else:
            # Данных нет — СОСТОЯНИЕ словом, а не прочерк: «не подключён» и
            # «неизвестно» разные ответы, и ноль здесь означал бы третий (027).
            # Выключка влево, а не по середине: это фраза, а не столбик чисел,
            # и по середине блока она читалась бы как значение одной колонки.
            state = w.get(STATE.get(r["state"], ""), r["state"])
            p.append(text(держится[0], y + 19, state, t["muted"], SIZE["name"], 600))
        # ЛИНИЯ МЕЖДУ ПРОЕКТАМИ, А НЕ ПОД КАЖДЫМ. Последняя строка её не
        # получает: черта под нижним рядом читается как край таблицы, которого
        # нет, — карточка уже обведена рамкой.
        if r is not data[-1]:
            p.append(f'<rect x="{PAD}" y="{y + row - 9}" width="{width - 2 * PAD}" '
                     f'height="1" fill="{t["stroke"]}" opacity="0.55"/>')
        y += row
    # ПОДЗАГОЛОВОК СТОИТ ПОД ТАБЛИЦЕЙ, А НЕ НАД НЕЙ. Он картинку не
    # представляет, а ОГОВАРИВАЕТ: числа — ответы самих проектов, не наша
    # оценка их. Оговорку читают после того, что она оговаривает, а место в
    # шапке она занимала у подписей блоков — у того, что без неё не читается.
    p.append(text(PAD, низ + 24, w["sub"].format(total=total), t["label"],
                  SIZE["sub"], 500))
    p.append("</svg>")
    return "\n".join(p) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--out-dir", type=Path, default=None)
    args = ap.parse_args(argv)
    root: Path = args.root
    out_dir = args.out_dir or (root / OUT_DIR)

    # ── исход 2: рисовать нечем ────────────────────────────────────────────
    try:
        doc = json.loads((root / SOURCE).read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        print(f"рисовать нечем: {SOURCE} не прочитан — {e}", file=sys.stderr)
        return 2
    data = rows(doc)
    if not data:
        print(f"рисовать нечем: в {SOURCE} нет ни одного потребителя",
              file=sys.stderr)
        return 2
    try:
        total = len(json.loads(
            (root / "export" / "rules.json").read_text(encoding="utf-8"))["rules"])
    except (OSError, ValueError, KeyError) as e:
        print(f"рисовать нечем: экспорт правил не прочитан — {e}", file=sys.stderr)
        return 2

    out_dir.mkdir(parents=True, exist_ok=True)
    for (lang, dark), name in NAMES.items():
        (out_dir / name).write_text(render(data, total, dark, lang),
                                    encoding="utf-8")
    live = sum(1 for r in data if r["connected"])
    print(f"нарисовано: потребителей {len(data)}, подключено {live}, "
          f"правил {total}; файлов {len(NAMES)} (язык × тема)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
