def ширина_колонки(key: str, data: list[dict], w: dict) -> int:
    """Ширина одной колонки: что шире — подпись сверху или самое широкое число.

    ОДНА НА ВСЕ СТРОКИ, а не своя у каждой: иначе число из трёх знаков
    сдвигало бы соседнюю колонку у одного проекта и не сдвигало у другого, а
    сравнивать глазом можно только то, что стоит друг под другом.

    ЧИСЛА ПЕРВОГО БЛОКА СЧИТАЮТСЯ И У НЕПОДКЛЮЧЁННОГО: «родил» у него своё, а
    на месте остальных стоит прочерк. У второго блока чисел там нет вовсе —
    вместо них стоит состояние словом.
    """
    подпись = len(w[key]) * LABEL_K
    числа = [len(str(r[key])) * NUMBER_K for r in data
             if r["connected"] or key in ЧИСЛА]
    return int(max([подпись] + числа))


def полоса(data: list[dict], w: dict,
           keys: list[str] | None = None) -> dict[str, tuple[int, int]]:
    """Колонки слева направо: ключ → (x левого края, ширина).

    ДВА БЛОКА РАЗДЕЛЕНЫ ПРОСВЕТОМ, А НЕ РАМКОЙ: между блоками COL_BETWEEN,
    внутри блока COL_IN. Просвет — это и есть механизм деления, и случай
    стережёт именно его, а не комментарий о нём.
    """
    из: dict[str, tuple[int, int]] = {}
    x = COL_MIN
    блоки = (ЧИСЛА, tuple(keys if keys is not None else shown(data)))
    for n, блок in enumerate(блоки):
        for m, key in enumerate(блок):
            ш = ширина_колонки(key, data, w)
            из[key] = (x, ш)
            последняя_в_блоке = m == len(блок) - 1
            x += ш + (COL_BETWEEN if последняя_в_блоке and n < len(блоки) - 1
                      else COL_IN)
    return из


def середина(колонка: tuple[int, int]) -> int:
    """Середина колонки: по ней стоят и подпись, и число.

    ПОЧЕМУ ПО СЕРЕДИНЕ, А НЕ ПО ЛЕВОМУ КРАЮ. У колонки подпись одной длины, а
    значения разной: «9» и «154» при выключке влево расходятся вправо на два
    знака, и глаз читает это как сдвиг самой колонки. По середине столбик
    чисел стоит столбиком, а подпись стоит над ним, а не левее него.
    """
    x, ш = колонка
    return x + ш // 2


def край(band: dict[str, tuple[int, int]], блок) -> tuple[int, int]:
    """Левый и правый край блока целиком — по крайним его колонкам."""
    левый, _ = band[блок[0]]
    x, ш = band[блок[-1]]
    return левый, x + ш

