#: По этой метке задача находится снова. Заголовок для этого не годится: его
#: правят руками, и тогда прогон заведёт вторую задачу вместо обновления.
MARKER = "<!-- rules-inbox: не удаляйте, по этой строке задача находится снова -->"


def fetch_export(catalogue: str, ref: str) -> tuple[dict | None, str | None]:
    """Выгрузка целиком: нужны и правила, и объявленные номера контрактов.

    Раньше читались только правила. Номера контрактов лежат в том же файле, и
    второй запрос за ними был бы лишним обращением к сети ради данных, которые
    уже приехали.
    """
    url = f"https://raw.githubusercontent.com/{catalogue}/{ref}/export/rules.json"
    try:
        with urllib.request.urlopen(url, timeout=30) as resp:
            return json.loads(resp.read().decode("utf-8")), None
    except (urllib.error.URLError, OSError, ValueError) as e:
        return None, f"{url} — {e}"


def fetch_rules(catalogue: str, ref: str) -> tuple[list[dict] | None, str | None]:
    doc, err = fetch_export(catalogue, ref)
    return (None, err) if doc is None else (doc.get("rules", []), None)


def fetch_where(catalogue: str, ref: str) -> tuple[list[dict] | None, str | None]:
    """Сводка «чем держат другие» — чтобы соседский механизм доехал сюда.

    Раздел «Чем держат другие» существует в сводке каталога с самого её
    появления, и отвечает он ровно на нужный вопрос: кто уже сталкивался и чем
    закрыл. Но лежит он в ЧУЖОМ репозитории, файлом в двести строк, и приходят
    в него те, кто УЖЕ выбрал, чем держать правило. Знание собрано и никому не
    доставлено — та же поломка, что у красного без адресата (правило 142).

    ТРЕТИЙ ИСХОД НАЗЫВАЕТ ПРЕДМЕТ (158): адрес возвращается вместе с ошибкой,
    иначе на два источника выйдет одно неразличимое «не ответил».
    """
    url = f"https://raw.githubusercontent.com/{catalogue}/{ref}/export/where.json"
    try:
        with urllib.request.urlopen(url, timeout=30) as resp:
            return json.loads(resp.read().decode("utf-8")).get("consumers", []), None
    except (urllib.error.URLError, OSError, ValueError) as e:
        return None, f"{url} — {e}"


def solved_next_door(answered: dict, consumers: list[dict], me: str) -> list[dict]:
    """Правила, что у меня не держатся ничем, а у соседа держатся — с адресом.

    ГРАНИЦА. Чужой механизм не обязан подойти: стеки разные, и правило,
    закрытое у соседа гейтом, здесь может быть неприменимо вовсе. Раздел
    отвечает не «сделай так», а «вот кто уже сталкивался»; решение остаётся за
    тем, кто правит свой ответ.

    Берутся только записи с РАЗРЕШИМЫМ адресом: пересказ соседа помогает не
    больше, чем его отсутствие, и это та же граница, что у поля `where`.
    """
    свои = {rid for rid, rec in answered.items()
            if rec.get("status") == "active"
            and (rec.get("mechanism") or "none") == "none"}
    out: list[dict] = []
    for rid in sorted(свои):
        для_него = []
        for c in consumers:
            if c.get("repo") == me:
                continue
            held = (c.get("holds") or {}).get(rid) or {}
            mech, where = held.get("mechanism"), (held.get("where") or "").strip()
            if mech and mech != "none" and where:
                для_него.append({"repo": c["repo"], "mechanism": mech, "where": where})
        if для_него:
            out.append({"rule": rid, "held": для_него})
    return out


#: Вызов gh живёт в одном месте на весь каталог: у четырёх копий
#: разъехалось поведение при отсутствии самого gh (правила 090, 022).
gh = ghcli.run


#: Слово короче этого в счёт не идёт: в русском тексте это почти всегда
#: служебное, и совпадение по нему связывает что угодно с чем угодно.
WORD_MIN = 5
#: Слово, которое связывает само по себе. Порог выше обычного: одно совпадение
#: — это совпадение, а не связь, если только слово не редкое.
WORD_ALONE = 9
#: Общие слова каталога: они стоят в половине правил и в половине задач, и
#: связывают всё со всем. Список РАЗРЕШИТЕЛЬНЫМ быть не может — перечислить
#: значимые слова заранее нельзя, — поэтому он именно запретительный и короткий,
#: а каждое слово в нём стоит по измеренной причине: встречается и там и там.
NOISE = {"правило", "правила", "правил", "механизм", "механизма", "проекта",
         "проект", "каталог", "каталога", "изменение", "изменения", "должен",
         "должна", "должно", "который", "которая", "которое"}
WORD_RE = re.compile(r"[\w-]+", re.UNICODE)


def значимые(text: str) -> set[str]:
    """Слова, по которым имеет смысл связывать. Регистр и знаки убраны."""
    return {w for w in (m.group(0).lower() for m in WORD_RE.finditer(text))
            if len(w) >= WORD_MIN and w not in NOISE}


#: Задача «про правила»: в заголовке назван номер правила либо путь в дерево.
#: Ищется ССЫЛКА, а не слово «правило»: заголовок «правила игры» предметом не
#: является, и мягкий порог здесь стоил бы дороже пропуска (166).
RULE_IN_TITLE = re.compile(r"(?i)правил\w*\s*№?\s*(\d{3})\b|\brule\s*(\d{3})\b|rules/(?:ru|en)/(\d{3})-")


def tier_of(rule: dict) -> int:
    """Ступень правила из выгрузки. Нет поля — последняя: старый контракт.

    ПОЧЕМУ НЕ ОТКАЗ. Потребитель может читать выгрузку версии до 1.4, где
    поля нет вовсе. Отказ здесь означал бы, что подъём контракта ломает
    доставку правил у того, кто ещё не перечитал (157); молчаливая пятая
    ступень означает только «порядок неизвестен, берите последним».
    """
    t = rule.get("tier")
    n = t.get("n") if isinstance(t, dict) else t
    return n if isinstance(n, int) and 1 <= n <= 5 else 5


def contract_gap(answered_schema: str | None, expected: str | None) -> str | None:
    """Разошлась ли своя схема ответа со схемой первоисточника.

    ЭТО ТРЕТЬЕ ЛИЦО СТУПЕНИ 0, и оно из [157]: смена версии чужого контракта —
    повод ПЕРЕЧИТАТЬ ответы, а не только поправить формат. Сверка возможна
    сегодня и без новых полей: каталог публикует ожидаемый номер в
    `contracts.bindings`, проект объявляет свой в `schema`.

    Замер, ради которого это заведено (инцидент правила 164): у подключённого
    проекта стояло `"schema": "1.2"` — номер формата ВЫГРУЗКИ в поле формата
    ОТВЕТА, где контракт требует 1.1. Файл валиден, гейт зелёный, расхождение
    видно только сверкой.

    Третий исход отдельно: номера нет ни с одной стороны — это «не знаем», а не
    «сходится». Молчание здесь означало бы, что несверенное считается сверенным.
    """
    if not expected:
        return "каталог не объявил ожидаемый номер формата ответа — сверить нечем"
    if not answered_schema:
        return (f"в ответе не объявлен `schema`, а каталог ждёт {expected} — "
                "несверенное не считается сошедшимся")
    if answered_schema != expected:
        return (f"формат ответа объявлен как {answered_schema}, каталог ждёт "
                f"{expected} — ответы перечитываются под новый контракт")
    return None


def held_by_nothing(answered: dict) -> list[str]:
    """Правила, признанные действующими и не держащиеся ничем.

    ЭТО И ЕСТЬ «НЕ ОТРАБОТАНО», а не «не дошли руки»: ответ дан, статус
    `active`, механизма нет. Отличие от `unreviewed` существенно — там честно
    сказано «ещё не смотрели», здесь сказано «действует», и это неправда.

    Замер 3 сентября: 47 таких правил на трёх подключённых проектах из четырёх.
    """
    return sorted(rid for rid, rec in answered.items()
                  if rec.get("status") == "active"
                  and (rec.get("mechanism") or "none") == "none")


def started_here(issues: list[dict]) -> list[dict]:
    """Открытые задачи проекта, в заголовке которых назван номер правила.

    ЗАЧЕМ ЭТО ПЕРВЫМ РАЗДЕЛОМ. Ступень 0 — не тема, а СОСТОЯНИЕ: пока по
    правилам есть начатое и незакрытое, порядок ступеней не начинается.
    Владелец каталога назвал предмет прямо: «если есть задачи по правилам или
    не все правила отработаны, в первую очередь надо отработать их».

    Иначе получается то, что каталог уже видел на себе: задача #186 шесть дней
    называла уже починенное, а рядом заводились новые.
    """
    found = []
    for i in issues:
        m = RULE_IN_TITLE.search(i.get("title") or "")
        if m:
            found.append({"number": i["number"], "title": i["title"],
                          "rule": next(g for g in m.groups() if g)})
    return found


def candidates_here(unreviewed: list[dict], issues: list[dict]) -> list[dict]:
    """Задачи ЭТОГО проекта, на которые правило, возможно, отвечает.

    ЗАЧЕМ ЭТО ВООБЩЕ. Доставить правило мало (130). Правило без предмета в
    своём проекте остаётся абстракцией, которую откладывают: «понятно, но не
    про нас». Список кандидатов из СВОЕГО бэклога превращает его в вопрос о
    конкретной задаче, а на такой вопрос отвечают.

    ГРАНИЦА, И ОНА НАЗВАНА В САМОМ РАЗДЕЛЕ: совпадение по словам — ПОДСКАЗКА,
    а не вердикт. Ни принять правило, ни отклонить его этот список не может;
    он говорит «посмотрите сюда», и смотрит человек. Порог поэтому мягкий:
    ложная подсказка стоит одного взгляда, а пропущенная — правила, которое
    отложили как абстрактное.
    """
    out: list[dict] = []
    словари = [(i, значимые(i.get("title") or "")) for i in issues]
    for rule in unreviewed:
        свои = значимые(" ".join(filter(None, [
            (rule.get("title") or {}).get("ru") if isinstance(rule.get("title"), dict)
            else rule.get("title"),
            " ".join((rule.get("areas") or {}).get("ru") or []
                     if isinstance(rule.get("areas"), dict)
                     else rule.get("areas") or []),
        ])))
        if not свои:
            continue
        похожие = []
        for issue, слова in словари:
            общие = свои & слова
            if len(общие) >= 2 or any(len(w) >= WORD_ALONE for w in общие):
                похожие.append((len(общие), issue, sorted(общие)))
        if not похожие:
            continue
        похожие.sort(key=lambda p: (-p[0], p[1].get("number", 0)))
        out.append({"rule": rule, "issues": [
            {"number": i.get("number"), "title": i.get("title"), "words": w}
            for _, i, w in похожие[:2]]})
    return out


def stale_here(answered: dict, rules: list[dict]) -> list[str]:
    """Ответы ЭТОГО проекта о правилах, которых в каталоге нет.

    Половина вопроса, которой у потребителя не было. Каталог такой ответ у
    себя отвергает гейтом, и с этого прогона видит его у потребителей — но
    ПОЧИНИТЬ оттуда не может: файл чужой. Чинится здесь, и потому называется
    здесь же.

    Правило снимают, номер остаётся занятым навсегда — а ответ о снятом
    правиле нет: пока номер свободен, это мусор, а как только номер займёт
    новая запись, тот же ответ прочитается как решение по НЕЙ. Не покраснеет
    ничто: статус есть, механизм назван, полнота ответа сойдётся.
    """
    return sorted(set(answered) - {r["id"] for r in rules})


#: Имена ступеней для печати. Порядок и есть смысл: ступень 0 — состояние
#: проекта, ступени 1–5 — темы. Номер приезжает из выгрузки каталога.
TIER_NAMES = {
    1: "правила и роли",
    2: "конвейер и CI",
    3: "гейты и процессы",
    4: "код и тесты",
    5: "всё остальное",
}


def body_for(missing: list[dict], unreviewed: list[dict], catalogue: str,
             stale: list[str] | None = None, total: int | None = None,
             answered: int | None = None,
             solved: list[dict] | None = None,
             candidates: list[dict] | None = None,
             started: list[dict] | None = None,
             nothing: list[str] | None = None,
             contract: str | None = None) -> str:
    lines = [
        MARKER,
        "",
        f"Правила каталога [`{catalogue}`](https://github.com/{catalogue}), по "
        "которым этот проект ещё не ответил.",
        "",
        "Ответ живёт здесь, в `.rules/bindings.json`, потому что здесь живёт "
        "механизм: одно правило в разных проектах держится по-разному. Статус — "
        "`active`, `rejected`, `not-applicable` или `unreviewed`; у двух "
        "отрицательных обязательна причина.",
        "",
    ]
    # ПЕРЕПИСЬ ПЕЧАТАЕТСЯ ВСЕГДА, а не только когда есть очередь. Число,
    # видное лишь при поломке, отвечает на вопрос «что сломалось» и не
    # отвечает на вопрос «куда мы движемся»; второй здесь и есть предмет.
    if total is not None:
        разобрано = answered if answered is not None else 0
        lines += [
            f"**Правил в каталоге: {total}. Разобрано здесь: {разобрано}.** "
            f"Ответа нет вовсе у {len(missing)}, записано `unreviewed` "
            f"у {len(unreviewed)}.",
            "",
        ]

    # СТУПЕНЬ 0 СТОИТ ПЕРВОЙ И ПЕЧАТАЕТСЯ ВСЕГДА (правило 177). Три числа,
    # видные только при поломке, отвечают на вопрос «что сломалось» и молчат о
    # том, закрыт ли долг вообще; «ноль» здесь — состояние, а не пустота (027).
    задач = len(started or [])
    ничем = len(nothing or [])
    очередь = len(missing) + len(unreviewed)
    держит = задач or ничем or очередь or contract
    lines += [
        "## Ступень 0 — незакрытая работа по правилам",
        "",
        f"**Задач по правилам: {задач}. Правил без ответа или «не рассмотрено»: "
        f"{очередь}. Признано действующими, но держится ничем: {ничем}.**",
        "",
    ]
    if contract:
        lines += [
            f"⚠️ **Контракт разошёлся.** {contract}",
            "",
            "Это [правило 157](https://github.com/ArtVsMark/Engineering-Incidents-Playbook/blob/main/rules/ru/157-a-contract-bump-is-a-re-read.md): "
            "смена версии чужого контракта — повод перечитать ОТВЕТЫ, а не "
            "только поправить формат. Пока номера расходятся, ответы ниже "
            "собраны под другой контракт.",
            "",
        ]
    if started:
        lines += ["| Задача | Про правило |", "|---|---|"]
        for i in started:
            lines.append(f"| #{i['number']} {i['title']} | {i['rule']} |")
        lines.append("")
    if nothing:
        lines += [
            "**Действует, но не держится ничем:** " + ", ".join(
                f"`{rid}`" for rid in nothing) + ".",
            "",
            "Это не «не дошли руки» — там честно сказано `unreviewed`. Здесь "
            "сказано «действует», и это неправда: механизма нет.",
            "",
        ]
    if держит:
        lines += [
            "**Пока эти числа не ноль, разбор новых правил ниже — очередь, а "
            "не работа.** Ступень 0 — состояние, а не тема: своих правил у неё "
            "нет. Механизм называет долг и не запрещает работу: остановить "
            "чужую работу он не может и не притворяется, что может. Закрытие "
            "задачи оставлено человеку — оно говорит «я посмотрел».",
            "",
        ]
    else:
        lines += ["Долга по правилам нет. Это состояние, а не пустая строка.", ""]

    if solved:
        lines += [
            "## У соседей это уже решено",
            "",
            "Правила, которые здесь признаны действующими и **не держатся "
            "ничем**, а у соседнего проекта держатся — с адресом механизма.",
            "",
            "Чужой механизм не обязан подойти: стеки разные, и правило, "
            "закрытое у соседа гейтом, здесь может быть неприменимо вовсе. "
            "Раздел отвечает не «сделай так», а «вот кто уже сталкивался».",
            "",
            "| № | Кто держит | Чем и где |",
            "|---|---|---|",
        ]
        for item in solved:
            for h in item["held"]:
                где = h["where"].split(";")[0].strip()
                lines.append(f"| {item['rule']} | `{h['repo'].split('/')[-1]}` | "
                             f"{h['mechanism']}: {где} |")
        lines.append("")

    if candidates:
        lines += [
            "## Возможно, про это ваши задачи",
            "",
            "Правила, ещё не разобранные здесь, рядом с **открытыми задачами "
            "этого проекта**, чьи заголовки говорят о том же. Доставить правило "
            "мало: без предмета в своём проекте оно остаётся абстракцией, "
            "которую откладывают.",
            "",
            "**Совпадение по словам — подсказка, а не вердикт.** Ни принять "
            "правило, ни отклонить его этот список не может; он говорит "
            "«посмотрите сюда», и смотрит человек.",
            "",
            "| Правило | Ваша задача | Общие слова |",
            "|---|---|---|",
        ]
        for item in candidates:
            rid = item["rule"].get("id") or "?"
            имя = item["rule"].get("title")
            имя = имя.get("ru") if isinstance(имя, dict) else имя
            for i in item["issues"]:
                lines.append(
                    f"| {rid} — {имя} | #{i['number']} {i['title']} | "
                    + ", ".join(i["words"]) + " |")
        lines.append("")

    if stale:
        # ЭТО НАХОДКА, А НЕ ОЧЕРЕДЬ, и потому стоит выше очереди: очередь
        # рассосётся решением, лишний ответ не рассосётся никогда.
        lines += [
            "## Ответ о правиле, которого в каталоге нет",
            "",
            "Правило снято, а ответ о нём остался: " + ", ".join(
                f"**{rid}**" for rid in stale) + ".",
            "",
            "Номера не переиспользуются, но ответ о снятом правиле лежать не "
            "должен: как только номер займёт новая запись, этот ответ "
            "прочитается как решение по НЕЙ — и не покраснеет ничто, потому "
            "что статус есть и механизм назван. Запись удаляется из "
            "`.rules/bindings.json` целиком.",
            "",
        ]

    if not missing and not unreviewed:
        lines += ["**Нерассмотренных нет.** Это состояние, а не пустая задача: "
                  "ответ есть по каждому правилу каталога."]
        return "\n".join(lines) + "\n"

    # ПОРЯДОК РАЗБОРА — ПО СТУПЕНЯМ, А НЕ ПО НОМЕРАМ. Номер говорит, когда
    # правило завелось; ступень — когда его берут. Новому проекту нужен
    # второй порядок: без ответа по 062 («роль заводится, если способна
    # возразить») разбор всего остального некому исполнять.
    def по_ступеням(rules: list[dict]) -> list[str]:
        out: list[str] = []
        for n in sorted(TIER_NAMES):
            свои = [r for r in rules if tier_of(r) == n]
            if not свои:
                continue
            out += [f"**Ступень {n} — {TIER_NAMES[n]}** ({len(свои)})", ""]
            out += [f"- **{r['id']}** — {r['title']['ru']}" for r in свои]
            out += [""]
        return out

    if missing:
        lines += ["## Ответа нет вовсе", "",
                  "Правило появилось в каталоге, а записи о нём в ответе нет.", ""]
        lines += по_ступеням(missing)
    if unreviewed:
        lines += ["## Записано `unreviewed`", "",
                  "Очередь на рассмотрение, а не позор: «не дошли руки» — "
                  "честный статус, пока он не застаивается.", ""]
        lines += по_ступеням(unreviewed)
    return "\n".join(lines) + "\n"



def found_issue(out: str) -> tuple[str, str]:
    """Разобрать ответ трекера о задаче-«входящих»: номер и состояние.

    ПУСТОТА ОТ jq — ЭТО СТРОКА "null null", А НЕ ПУСТАЯ СТРОКА. Индексация
    пустого массива даёт `null`, а интерполяция `"\\(.number) \\(.state)"`
    печатает его словом. Дальше «null» — непустая строка, то есть истинная, и
    ветка «завести задачу» не выполняется никогда: вместо неё уходит
    `gh issue edit null`, а площадка отвечает `invalid issue format: "null"`.

    То есть у потребителя, у которого задачи-«входящих» ещё нет, механизм
    отказывал на КАЖДОМ прогоне и завести первую задачу не мог в принципе.
    Замер: ArtVsMark/Claude-Code_Usage-Token, четыре прогона подряд с 29 августа —
    все красные, ни одного зелёного.

    Само выражение jq теперь отдаёт пустоту (`// empty`), и «null» сюда
    приходить перестал. Разбор всё равно его переживает: ответ внешней команды
    — контракт, который нам не принадлежит, и второй способ ошибиться здесь
    дороже одной строки кода.
    """
    number, state = (out.split() + ["", ""])[:2]
    if number == "null":
        return "", ""
    return number, state


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--catalogue", default="ArtVsMark/Engineering-Incidents-Playbook")
    ap.add_argument("--ref", default="main")
    ap.add_argument("--bindings", default=".rules/bindings.json")
    # КТО Я — чтобы не показывать проекту его собственный механизм как
    # соседский. Умолчание берётся из окружения площадки: там это уже есть, и
    # требовать его руками значило бы завести второй источник того же факта.
    ap.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", ""),
                    help="владелец/репозиторий этого проекта; по умолчанию из "
                         "GITHUB_REPOSITORY")
    ap.add_argument("--title", default="Правила каталога: входящие")
    ap.add_argument("--dry-run", action="store_true",
                    help="показать тело задачи и не трогать трекер")
    args = ap.parse_args()

    # ── исход 2: проверка не отработала ────────────────────────────────────
    выгрузка, err = fetch_export(args.catalogue, args.ref)
    rules = None if выгрузка is None else выгрузка.get("rules", [])
    if err:
        print(f"проверка не отработала: экспорт каталога не прочитан — {err}",
              file=sys.stderr)
        return 2
    if not rules:
        print("проверка не отработала: каталог отдал пустой список правил — "
              "сверять не с чем, а молча пропускать нельзя", file=sys.stderr)
        return 2

    try:
        with open(args.bindings, encoding="utf-8") as fh:
            свой_ответ = json.load(fh)
        answered = свой_ответ.get("rules", {})
        своя_схема = свой_ответ.get("schema")
    except FileNotFoundError:
        # Проект ещё не подключён. Это не поломка: все правила нерассмотрены,
        # и задача-«входящие» именно об этом и скажет.
        #
        # Схема здесь НЕ «сходится», а НЕИЗВЕСТНА, и это разные ответы: сверка
        # скажет «не объявлен», а не промолчит (039). Пока переменная
        # заводилась только в удачной ветке, скрипт падал UnboundLocalError
        # вместо третьего исхода — поймано тестом отсутствия gh.
        answered = {}
        своя_схема = None
    except (OSError, ValueError) as e:
        print(f"проверка не отработала: {args.bindings} не разобран — {e}",
              file=sys.stderr)
        return 2

    missing = [r for r in rules if r["id"] not in answered]
    unreviewed = [r for r in rules
                  if answered.get(r["id"], {}).get("status") == "unreviewed"]

    stale = stale_here(answered, rules)
    # СОСЕДСКИЙ МЕХАНИЗМ — ДОПОЛНЕНИЕ, И ОНО НЕ РОНЯЕТ ОСНОВНУЮ РАБОТУ (084).
    # Сводка лежит в чужом репозитории; её недоступность делает раздел пустым,
    # а не задачу — неоткрытой. Отказ называет адрес (158) и печатается, чтобы
    # молчание не выдавалось за «у соседей ничего нет» (046).
    neighbours, err = fetch_where(args.catalogue, args.ref)
    if err:
        print(f"сводка соседей не прочитана — {err}; раздел пропущен",
              file=sys.stderr)
    solved = solved_next_door(answered, neighbours or [], args.repo)
    # ЗАДАЧИ СПРАШИВАЮТСЯ ОДИН РАЗ И БЕЗ ОТКАЗА. Трекер может не ответить —
    # тогда раздела просто нет: правило 130 говорит «приходит вместе с», а не
    # «не приходит без». Ронять доставку правил из-за подсказки значило бы
    # менять предмет на украшение (084).
    свои_задачи: list[dict] = []
    code_i, out_i = gh("issue", "list", "--state", "open", "--limit", "100",
                       "--json", "number,title")
    if code_i == 0:
        try:
            свои_задачи = [i for i in json.loads(out_i)
                           if MARKER not in (i.get("title") or "")]
        except ValueError:
            свои_задачи = []
    else:
        print("задачи проекта не спрошены — раздела кандидатов не будет",
              file=sys.stderr)
    candidates = candidates_here(unreviewed, свои_задачи)
    начатое = started_here(свои_задачи)
    ничем = held_by_nothing(answered)
    расхождение = contract_gap(
        своя_схема, ((выгрузка or {}).get("contracts") or {}).get("bindings"))
    решено = sum(1 for r in rules
                 if answered.get(r["id"], {}).get("status") not in (None, "unreviewed"))
    body = body_for(missing, unreviewed, args.catalogue, stale=stale,
                    total=len(rules), answered=решено, solved=solved,
                    candidates=candidates, started=начатое,
                    nothing=ничем, contract=расхождение)
    if args.dry_run:
        print(body)
        return 1 if (missing or unreviewed or stale) else 0

    if not os.environ.get("GH_TOKEN"):
        print("проверка не отработала: GH_TOKEN не задан — обновлять задачу "
              "нечем", file=sys.stderr)
        return 2

    # Ищется среди ВСЕХ состояний, а не только открытых. Пока искали среди
    # открытых, закрыть задачу было нельзя ни рукой, ни механизмом: следующий
    # прогон не находил её и заводил вторую. Потребитель это и наблюдал —
    # ArtVsMark/ArtVsMark#52 висел открытым с нулём нерассмотренных, потому что
    # иначе он бы раздвоился.
    code, found = gh("issue", "list", "--state", "all", "--limit", "100",
                     "--json", "number,body,state",
                     "--jq", f'[.[] | select(.body | contains("{MARKER}"))][0] '
                             f'// empty | "\\(.number) \\(.state)"')
    if code != 0:
        print(f"проверка не отработала: трекер не ответил — {found}", file=sys.stderr)
        return 2

    number, state = found_issue(found)
    pending = bool(missing or unreviewed or stale)

    if number:
        code, out = gh("issue", "edit", number, "--body", body)
        where = f"задача #{number} обновлена"
    elif pending:
        code, out = gh("issue", "create", "--title", args.title, "--body", body)
        where = f"задача заведена: {out}"
    else:
        # Завести задачу, чтобы тут же закрыть, — шум без адресата.
        print("нерассмотренных нет, задачи-«входящих» тоже: заводить нечего")
        return 0
    if code != 0:
        print(f"проверка не отработала: задача не записана — {out}", file=sys.stderr)
        return 2

    # ОТКРЫТА ЛИ ЗАДАЧА — ЭТО УТВЕРЖДЕНИЕ, А НЕ ОФОРМЛЕНИЕ. Открытая задача
    # говорит «здесь есть работа». При нуле нерассмотренных это неправда, и
    # ежедневная неправда в трекере приучает листать его мимо — тем самым
    # способом, каким ломается 091: трекер и есть первый источник работы.
    #
    # ПОЧЕМУ ЗАКРЫВАЕТ МЕХАНИЗМ, А НЕ ЧЕЛОВЕК. Пустота здесь — ФАКТ, который
    # машина проверяет целиком: ответ есть по каждому правилу и лишних ответов
    # нет. Это отличает «входящие» от дежурного по красной ветке: там закрытие
    # говорит «я посмотрел», а такого механизм сказать не может (142).
    want = "OPEN" if pending else "CLOSED"
    if state and state.upper() != want:
        code, out = gh("issue", "reopen" if pending else "close", number)
        if code != 0:
            print(f"проверка не отработала: состояние задачи #{number} не "
                  f"изменено — {out}", file=sys.stderr)
            return 2
        where += ", открыта заново" if pending else ", закрыта: работы в ней нет"

    print(f"{where}; правил {len(rules)}, разобрано {решено}, ответа нет "
          f"у {len(missing)}, не рассмотрено {len(unreviewed)}, "
          f"лишних {len(stale)}")
    return 1 if (missing or unreviewed or stale) else 0


if __name__ == "__main__":
    sys.exit(main())
