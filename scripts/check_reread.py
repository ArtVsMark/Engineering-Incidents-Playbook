#!/usr/bin/env python3
"""Подпись под перечитыванием не едет одна: сдвинулся номер — назови работу.

ИНЦИДЕНТ, ЗАМЕР 8 сентября по собственной истории. Коммит 9bfa9d1 поднял
выгрузку каталога 1.4 → 1.5, ответ 1.1 → 1.2 и проставил себе
`answers_to: "1.5"`. Записей ответа в том коммите тронуто РОВНО ОДНА — сама 157,
и то ради описания механизма. Перечитывания не было; подпись под ним стояла.

И это при том, что сообщение соседнего гейта требует от потребителей ровно
обратного, теми же словами: «номер `answers_to` проставляется последним —
подписью под перечитыванием, а не вместо него». Издатель освободил себя от
требования, которое разослал пятерым. Заметил не механизм, а вопрос владельца:
«после изменения контракта мы сами отработали все правила, согласно правилу?»

ЧТО ЗДЕСЬ МАШИННОЕ, А ЧТО НЕТ, И ЭТО ГРАНИЦА, А НЕ ОГОВОРКА (182). Правда ли
человек перечитал записи — из дерева не следует ничем. Но следует другое:
НАЗВАН ЛИ РАЗМЕР ОБХОДА. Подпись сдвинулась — автор обязан сказать числом,
сколько записей составляли предмет перечитывания. Гейт судит только об этом.

ЧИСЛО ПРАВОК ДОКАЗАТЕЛЬСТВОМ НЕ СЧИТАЕТСЯ, И ЭТО НАЙДЕНО ПРОБОЙ НА САМОМ
ИНЦИДЕНТЕ. Первая редакция принимала «изменена хотя бы одна запись» за след
перечитывания — и прогон по коммиту 9bfa9d1 вернул «чисто»: там правда изменена
одна запись, та самая 157. Гейт, не отвергающий собственный повод, не проверяет
ничего (140). Правок бывает одна при предмете в семьдесят восемь записей и
семьдесят восемь при предмете в одну; их число не говорит о размере обхода
ничего, и знает его только автор.

ПОЧЕМУ ПУСТОЙ ОТВЕТ ЗАКОНЕН. Перечитывание, честно не давшее изменений, —
обычный исход: контракт мог двинуться там, где наших ответов не касается.
Требовать правку записей значило бы учить менять их ради галочки, а гейт,
который так учит, вреднее отсутствующего (051). Поэтому проверяется замер, а не
правка, — и замер требует ЧИСЛА: «перечитано» без числа неотличимо от
«я посмотрел» (166).

ЧЕГО ГЕЙТ НЕ ДЕЛАЕТ. Не судит, верен ли новый ответ, и не проверяет само число:
сказать «перечитано 200 записей» при ста восьмидесяти четырёх он не помешает.
Предмет здесь — назван обход или нет, а не правдив ли он; враньё числом ловится
чтением, и это честная граница, а не дыра. Изменение, где подпись стоит на
месте, гейт не трогает вовсе: предмета там нет.

Запуск:
  python scripts/check_reread.py --base origin/main [--body-file ФАЙЛ|-]

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.

Реализует правила каталога:
  157 — подъём версии контракта требует перечитать ОТВЕТЫ, а не только формат;
  182 — «машинно нельзя» разобрано надвое: суждение о перечитывании остаётся
        человеку, наличие следа держит машина;
  166 — замер числом, а не прозой: «перечитано» без числа ничего не утверждает;
  051 — запрещается достоверное: подпись без следа — факт, а не подозрение;
  039 — три исхода, и третий не молчит;
  158 — третий исход называет предмет: файл и команду, которые не ответили.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ОТВЕТ = ".rules/bindings.json"

#: Номера, чей сдвиг и есть подпись: версия своего ответа и версия выгрузки,
#: по которой он построен. Оба двигаются порознь — в этом и был смысл их
#: развести (157), — и любой из двух требует перечитывания.
ПОДПИСЬ = ("schema", "answers_to")

#: Замер в теле изменения: слово о перечитывании и ЧИСЛО рядом с ним. Форма
#: намеренно широкая — гейт ловит отсутствие замера, а не его красоту (051).
ЗАМЕР = re.compile(r"перечит\w*[^.\n]{0,120}?\d|\d[^.\n]{0,120}?перечит\w*", re.I)


def git(root: Path, *args: str) -> tuple[int, str, str]:
    """Вызов git с явной кодировкой (176)."""
    done = subprocess.run(["git", "-C", str(root), *args],
                          capture_output=True, text=True, encoding="utf-8")
    return done.returncode, done.stdout, done.stderr


def версия_в_базе(root: Path, base: str) -> tuple[dict | None, str | None]:
    """Ответ каталога, каким он был в общей ветке. None+None — файла там нет."""
    code, out, err = git(root, "show", f"{base}:{ОТВЕТ}")
    if code != 0:
        текст = (err or "").lower()
        # «Файла в базе нет» и «базу не спросить» — разные ответы (027).
        # Первый законен: так выглядит первый ответ проекта.
        if "does not exist" in текст or "exists on disk, but not in" in текст:
            return None, None
        return None, (f"`git show {base}:{ОТВЕТ}` — "
                      f"{(err or '').strip()[:160] or f'код {code}'}")
    try:
        return json.loads(out), None
    except ValueError as e:
        return None, f"{base}:{ОТВЕТ} не разобран — {e}"


def подпись_сдвинулась(было: dict, стало: dict) -> list[str]:
    """Какие из номеров подписи изменились. Пустой список — ни один."""
    return [к for к in ПОДПИСЬ
            if (было.get(к) or "") != (стало.get(к) or "")]


def записей_изменилось(было: dict, стало: dict) -> int:
    """Сколько записей ответа отличается: добавленные, убранные и правленые."""
    б, с = было.get("rules") or {}, стало.get("rules") or {}
    ключи = set(б) | set(с)
    return sum(1 for к in ключи if б.get(к) != с.get(к))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT,
                        help="корень дерева; по умолчанию сам этот репозиторий")
    parser.add_argument("--base", default="origin/main",
                        help="общая ветка, с которой сравнивается ответ")
    parser.add_argument("--body-file",
                        help="тело изменения; «-» читает stdin")
    args = parser.parse_args(argv)
    root: Path = args.root

    # ── исход 2: сверять нечем ─────────────────────────────────────────────
    свой = root / ОТВЕТ
    if not свой.exists():
        print(f"проверка не отработала: {ОТВЕТ} не найден в {root}",
              file=sys.stderr)
        return 2
    try:
        стало = json.loads(свой.read_text(encoding="utf-8"))
    except ValueError as e:
        print(f"проверка не отработала: {ОТВЕТ} не разобран — {e}",
              file=sys.stderr)
        return 2

    было, почему = версия_в_базе(root, args.base)
    if почему:
        print(f"проверка не отработала: {почему}", file=sys.stderr)
        return 2
    if было is None:
        print(f"{ОТВЕТ} в {args.base} ещё нет — это первый ответ, "
              "перечитывать нечего")
        return 0

    # ── предмета нет: подпись стоит на месте ───────────────────────────────
    сдвинулось = подпись_сдвинулась(было, стало)
    if not сдвинулось:
        нынешние = " · ".join(f"{к} {стало.get(к) or '—'}" for к in ПОДПИСЬ)
        print(f"подпись не двигалась ({нынешние}) — перечитывания это "
              "изменение не требует")
        return 0

    двинулись = ", ".join(
        f"{к}: {было.get(к) or '—'} → {стало.get(к) or '—'}" for к in сдвинулось)
    изменено = записей_изменилось(было, стало)

    # ── подпись сдвинулась: нужен замер обхода ─────────────────────────────
    if not args.body_file:
        print("проверка не отработала: подпись сдвинулась, а тела изменения "
              "не дали (--body-file) — судить о замере не по чему",
              file=sys.stderr)
        return 2
    try:
        тело = (sys.stdin.read() if args.body_file == "-"
                else Path(args.body_file).read_text(encoding="utf-8"))
    except OSError as e:
        print(f"проверка не отработала: тело {args.body_file} не "
              f"прочитано — {e}", file=sys.stderr)
        return 2
    if ЗАМЕР.search(тело):
        print(f"подпись сдвинулась ({двинулись}), обход назван в теле "
              f"изменения; записей изменено {изменено}")
        return 0

    print(f"подпись под перечитыванием едет одна:\n"
          f"  • {ОТВЕТ}: {двинулись}, а размер обхода не назван "
          f"(записей изменено {изменено} — это не замер обхода)\n\n"
          "  Подъём версии контракта требует перечитать ОТВЕТЫ, а не только\n"
          "  проверить, что они разбираются: записи остаются валидными, означая\n"
          "  уже другое (157). Пройдите по записям, где стояло старое значение,\n"
          "  и назовите обход в теле изменения ЧИСЛОМ: «перечитано N записей\n"
          "  предмета, изменено M». Число правок замером не считается — их\n"
          "  бывает одна при предмете в семьдесят восемь. Слово без числа\n"
          "  неотличимо от «я посмотрел» (166).", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
