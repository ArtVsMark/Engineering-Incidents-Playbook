#!/usr/bin/env python3
"""Хук окна исполняется интерпретатором планки, а не системным `python3` (217).

ИНЦИДЕНТ ВЕРНУЛСЯ ПОЧИНКОЙ. Правило 217 выросло из хука, которого звал голый
`python3` окна (3.11) при планке 3.14. 16.10 его повторил журнал навыков:
находка обзора по 211 сказала «без планки журнал пустеет молча», и починка
(#869) добавила запасной `python3`, а #875 сузил его до «не младше 3.11».
Оба изменения прошли все гейты: гейт стиля проверяет, на какой версии код
НАПИСАН, а не чем его ИСПОЛНЯЮТ. Заметил владелец; снято в #877.

СПЕРВА СПРОСИЛИ СЕМЬЮ (162). Замер 16.10 по пяти деревьям: такого гейта нет ни
у кого. Механизмы и Token держат стиль хуков (`test_py_style.py`,
`py_style.py`), грейдер зовёт хуки голым `python` и объявил их младшей целью,
у глоссария `pre_tool_use.sh` падает на `python3` без проверки версии —
та же ошибка, живая. Законных форм обхода планки две, и обе названы ниже.

ЧТО ПРОВЕРЯЕТСЯ.
  • `.claude/settings.json`: команда хука не зовёт интерпретатор ни в какой
    позиции — ни первым словом, ни путём (`/usr/bin/python3`), ни через `env`
    или `bash -c "python3 …"`: хук зовётся обёрткой, которая ищет планку
    (обзор #878);
  • `.claude/hooks/*.sh`: слово-команда `python`/`python3` не встречается вне
    имени с планкой (`python$floor`) и вне `uv python` — это подкоманда
    установщика, а не интерпретатор.
Комментарии и команды `echo` не читаются: там это проза. Комментарий — `#` в
начале слова, как в оболочке: `$#`, `${#x}` и `${x#p}` комментарием не
считаются. `echo` снимает только свою команду: после `;`, `&&`, `||` или `|`
читается следующая (обзор #878).

ИСКЛЮЧЕНИЕ ОДНО, И ОНО ПО РОЛИ, А НЕ ПО ИМЕНИ. Хук события `SessionStart` сам
ставит интерпретатор планки и до этого обязан звать системный `python3`.
Какой хук стартовый, гейт берёт из `.claude/settings.json`, а не из имени
файла: переименование не открыло бы дыру.

ГРАНИЦА. Форму механизмов — `python3` после проверки, что его версия не ниже
планки, — гейт тоже отвергает: у каталога её нет, а различать проверенную
развилку от непроверенной по тексту оболочки — суждение. Появится нужда — её
добавят явным исключением с причиной. Косвенный вызов (`p=python3; $p`) гейт
не видит. `#` в начале слова внутри кавычек (`echo " #x"`) срезается как
комментарий — разбор кавычек здесь не ведётся, и вызов после такой строки на
ней же не виден. По той же причине `;`, `&&` и `|` внутри кавычек `echo` режут
строку: проза после них читается как команда, и `echo "шаг; python3 …"` даст
ложный отказ — гейт краснеет, а не пропускает (обзор #906).

Исходы: 0 — чисто · 1 — найдено, названы файл, строка и форма · 2 — проверять
нечего: нет `.claude/settings.json` или хуков в нём (075).

Реализует правила каталога:
  217 — всё, что исполняет код проекта, исполняет его интерпретатор планки;
  162 — прежде чем строить, спросили семью: у соседей механизма нет;
  075 — ноль предметов — отказ, а не чисто;
  039 — три исхода.
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
НАСТРОЙКИ = Path(".claude") / "settings.json"
ХУКИ = Path(".claude") / "hooks"
#: Слово-команда интерпретатора. Не годится: часть имени с планкой
#: (`python$floor`, `python3.14`), подкоманда `uv python`, часть пути или слова.
ГОЛЫЙ = re.compile(r'(?<![\w$/{.-])(?<!uv )(?<!uv" )(python3?)(?![\w.$/-])')
#: Команда хука в настройках, которая сама и есть интерпретатор.
#: После имени — не буква, `$`, точка или дефис: `python-guard.sh` и
#: `python.sh` — имена обёрток, а не интерпретатор (обзор #906).
КОМАНДА_PYTHON = re.compile(r"(?:^|[\s\"'/=])python[\d.]*(?![\w$.-])")
#: Комментарий оболочки: `#` в начале строки или после пробела.
КОММЕНТАРИЙ = re.compile(r"(?:^|(?<=\s))#.*")
#: Разделители команд в строке оболочки.
РАЗДЕЛИТЕЛИ = re.compile(r"&&|\|\||[;|&]")
СТАРТ = "SessionStart"


def команды(настройки: dict) -> list[tuple[str, str]]:
    """Пары (событие, команда) всех хуков из настроек."""
    return [(событие, str(h.get("command", "")))
            for событие, группы in настройки.get("hooks", {}).items()
            for г in группы for h in г.get("hooks", [])]


def стартовые(пары: list[tuple[str, str]]) -> set[str]:
    """Имена файлов хуков, зарегистрированных на старт окна."""
    return {m[1] for событие, к in пары if событие == СТАРТ
            for m in [re.search(r"hooks/([\w.-]+)", к)] if m}


def голые_вызовы(текст: str) -> list[tuple[int, str]]:
    """Строки оболочки, где интерпретатор зовётся не по планке."""
    out = []
    for n, строка in enumerate(текст.splitlines(), 1):
        код = КОММЕНТАРИЙ.sub("", строка)
        команды_строки = [к for к in РАЗДЕЛИТЕЛИ.split(код)
                          if not re.match(r"\s*echo\b", к)]
        if any(ГОЛЫЙ.search(к) for к in команды_строки):
            out.append((n, строка.strip()))
    return out


def main(argv: list[str] | None = None) -> int:
    """Проверить настройки и обёртки хуков окна."""
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)
    путь = args.root / НАСТРОЙКИ
    try:
        пары = команды(json.loads(путь.read_text(encoding="utf-8")))
    except (OSError, ValueError) as exc:
        print(f"проверка не отработала: {путь} не прочитан — {exc} (075)", file=sys.stderr)
        return 2
    if not пары:
        print(f"проверять нечего: в {путь} нет ни одного хука — зеленеть на этом нельзя (075)",
              file=sys.stderr)
        return 2
    находки = [f"{НАСТРОЙКИ}: {событие} зовёт интерпретатор напрямую — «{к[:80]}». "
               "Хук зовётся обёрткой, которая ищет планку через floor.sh"
               for событие, к in пары if КОМАНДА_PYTHON.search(к)]
    исключены = стартовые(пары)
    for f in sorted((args.root / ХУКИ).glob("*.sh")):
        if f.name in исключены:
            continue
        for n, строка in голые_вызовы(f.read_text(encoding="utf-8")):
            находки.append(f"{ХУКИ / f.name}:{n}: «{строка[:90]}» — интерпретатор не по планке")
    if находки:
        print("хук окна исполняется не интерпретатором планки — ровно инцидент 217:",
              file=sys.stderr)
        for н in находки:
            print(f"  • {н}", file=sys.stderr)
        return 1
    print(f"хуки окна исполняются планкой: команд {len(пары)}, "
          f"стартовых исключено {len(исключены)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
