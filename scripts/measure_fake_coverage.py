#!/usr/bin/env python3
"""Полнота подделок в наборе, измеренная ОТРАВОЙ, а не перечнем (правило 170).

Перечень подделок есть рукописное знание о механизме и устаревает молча. Отрава
подменяет настоящий канал наружу на тот, что падает с внятной ошибкой, — и
пропуск становится громким отказом того, кто его допустил.

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ИНСТРУМЕНТ, А НЕ ШАГ ПРОГОНА. Отрава постоянным шагом
меняет устройство набора: каждый прогон шёл бы под подменённым транспортом, и
цена ошибки в самой отраве легла бы на все изменения сразу. Такое здесь
предлагают владельцу прежде, чем делать. Замер при этом обязан быть
ВОСПРОИЗВОДИМЫМ, иначе число в записи правила подтверждено пересказом, а не
прогоном (139) — этот файл и есть ответ на то возражение.

ТРИ ЗАХОДА, И ОНИ ОТВЕЧАЮТ НА РАЗНОЕ:

  сокет   — ходит ли тест наружу по-настоящему. Петля (127.0.0.1, ::1)
            пропускается: локальная заглушка — законная подделка. Первая версия
            этого различия не делала и красила 17 тестов, будучи сама
            косметической;
  gh-нет  — зовёт ли кто-нибудь настоящий инструмент площадки. Заглушка на его
            месте падает с внятной ошибкой;
  gh-есть — не держится ли зелёное на ОТСУТСТВИИ инструмента. Заглушка успешна
            и отдаёт пустой ответ. Это второй конец проверки (140): первый конец
            показывает, что настоящего никто не зовёт, и МОЛЧИТ о том, стояло ли
            зелёное на пустоте.

ОТРАВА СТАВИТСЯ И В ДОЧЕРНИЕ ПРОЦЕССЫ. Набор запускает скрипты подпроцессом, а
подмена, сделанная в родителе, до них не доходит; `sitecustomize` на пути
импорта интерпретатор подхватывает сам в каждом процессе.

Реализует правила каталога:
  170 — полнота набора подделок проверяется отравленным входом, а не перечнем;
  140 — отрава проверяется с обоих концов: падающей заглушкой и успешной;
  039 — три исхода: подделки полны · есть пропуск · проверка не отработала.

ЭТО ПРОБА ПО ТРЕБОВАНИЮ, А НЕ ШАГ ПРОГОНА, и в .github/workflows/ci.yml его нет
намеренно: постоянная отрава меняет устройство набора, и цена ошибки в самой
отраве легла бы на все изменения разом. Значит и держать правило 170 этот файл
НЕ может — держит его scripts/check_forgeries.py, а здесь лежит способ
перепроверить число, которым запись правила хвалится (139).

Запуск:  python scripts/measure_fake_coverage.py [--root <корень>]
Исходы:  0 — подделки полны;  1 — есть пропуск;  2 — проверка не отработала.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ЧИСТО, НАХОДКИ, СЛОМАНО = 0, 1, 2

ОТРАВА_СОКЕТА = '''\
import socket

ПЕТЛЯ = {"127.0.0.1", "::1", "localhost", "0.0.0.0", ""}
_c, _ce, _cc = socket.socket.connect, socket.socket.connect_ex, socket.create_connection


class ТестПошёлВСеть(RuntimeError):
    pass


def _наружу(адрес):
    return isinstance(адрес, tuple) and bool(адрес) and str(адрес[0]) not in ПЕТЛЯ


def _обёртка(настоящая, позиция):
    def обёртка(*a, **k):
        if len(a) > позиция and _наружу(a[позиция]):
            raise ТестПошёлВСеть(f"пошёл наружу: {a[позиция]} — подделка пропущена")
        return настоящая(*a, **k)
    return обёртка


socket.socket.connect = _обёртка(_c, 1)
socket.socket.connect_ex = _обёртка(_ce, 1)
socket.create_connection = _обёртка(_cc, 0)
'''

ЗАГЛУШКА_ПАДАЮЩАЯ = '#!/bin/sh\necho "ОТРАВА: позван настоящий gh: $*" >&2\nexit 66\n'
ЗАГЛУШКА_УСПЕШНАЯ = '#!/bin/sh\necho "[]"\nexit 0\n'

ОТКАЗ = re.compile(r"^(FAILED|ERROR)\s+(\S+?)(?:::|\s|$)", re.M)


def прогон(root: Path, окружение: dict[str, str]) -> tuple[int, list[str]]:
    """Набор под данным окружением. Второй элемент — файлы, которые отказали."""
    сказано = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "--no-header"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        cwd=root,
        env=окружение,
    )
    отказали = sorted({m.group(2) for m in ОТКАЗ.finditer(сказано.stdout + сказано.stderr)})
    return сказано.returncode, отказали


def заходы(root: Path, стол: Path) -> list[tuple[str, dict[str, str]]]:
    """Три окружения замера: отравленный сокет, gh падающий, gh успешный."""
    (стол / "sitecustomize.py").write_text(ОТРАВА_СОКЕТА, encoding="utf-8")
    корзина = стол / "bin"
    корзина.mkdir(exist_ok=True)

    def с_gh(тело: str) -> dict[str, str]:
        (корзина / "gh").write_text(тело, encoding="utf-8")
        (корзина / "gh").chmod(0o755)
        среда = dict(os.environ)
        среда["PATH"] = f"{корзина}{os.pathsep}{среда.get('PATH', '')}"
        return среда

    сокет = dict(os.environ)
    сокет["PYTHONPATH"] = f"{стол}{os.pathsep}{сокет.get('PYTHONPATH', '')}"
    return [
        ("сокет отравлен, включая дочерние процессы", сокет),
        ("на месте gh — падающая заглушка", с_gh(ЗАГЛУШКА_ПАДАЮЩАЯ)),
        ("на месте gh — успешная заглушка с пустым ответом", с_gh(ЗАГЛУШКА_УСПЕШНАЯ)),
    ]


def main(argv: list[str] | None = None) -> int:
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--root", type=Path, default=Path.cwd())
    аргументы = разбор.parse_args(argv)
    root = аргументы.root.resolve()
    if not (root / "tests").is_dir():
        print(f"набора нет: {root / 'tests'}", file=sys.stderr)
        return СЛОМАНО

    находки: list[str] = []
    with tempfile.TemporaryDirectory(prefix="отрава-") as стол:
        for имя, среда in заходы(root, Path(стол)):
            код, отказали = прогон(root, среда)
            if отказали:
                находки.append(f"{имя}: отказали {len(отказали)} — {', '.join(отказали)}")
                print(f"✗ {имя}: отказали {len(отказали)}")
                for файл in отказали:
                    print(f"    {файл}")
            elif код not in (0, 5):
                находки.append(f"{имя}: прогон вернул {код} без разбираемых отказов")
                print(f"✗ {имя}: прогон вернул {код}, отказов не разобрано")
            else:
                print(f"✓ {имя}: не отказал ни один тест")

    if находки:
        print(f"\nподделки неполны: заходов с отказом {len(находки)} из 3")
        return НАХОДКИ
    print("\nподделки полны: три захода, отказов нет — "
          "зелёное не держится ни на пропущенной подделке, ни на пустоте")
    return ЧИСТО


if __name__ == "__main__":
    raise SystemExit(main())
