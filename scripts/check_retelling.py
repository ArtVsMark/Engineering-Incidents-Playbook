#!/usr/bin/env python3
"""Пересказ своей работы в теле изменения сверяется с источником — там, где это машинно.

Правило 215: число и перечень о только что сделанном снимаются командой, а не
пишутся по памяти. Верность пересказа — суждение о смысле, и машина её не
судит. Но две формы полноты проверяются без чтения смысла, и обе здесь:

  1. НАЗВАННЫЙ ПУТЬ, КОТОРОГО НЕТ НИГДЕ. Путь в обратных кавычках из тела,
     которого нет ни в составе изменения, ни в дереве, — пересказ о файле,
     которого не существует. Путь, который в дереве есть, но не тронут, —
     законный контекст, и о нём не говорится: предупреждение на каждой
     ссылке на соседний файл приучило бы его пролистывать (051).
  2. ЧИСЛО НАХОДОК ПРОТИВ СТРОК СНЯТИЯ. Тело говорит «N находок» и несёт
     строки «Разобрано:» в другом числе — так было в #631 («две находки» при
     трёх снятиях).

ПРЕДУПРЕЖДЕНИЕ, А НЕ ОТКАЗ, И ЭТО РЕШЕНИЕ, А НЕ МЯГКОСТЬ. Замер 01.10 по 34
изменениям с пересказом, опровергнутым самим изменением: предикат 2 поймал
бы один случай, предикат 1 — ни одного. Ложных срабатываний на 99 слитых
телах 14.10 — 0 (запись 215; выборка не сохранена), а число рядом со словом
«находка» чаще говорит о другом предмете. Вероятное предупреждают, достоверное запрещают (051); здесь
вероятное. Гейт заведён решением владельца 14.10 (#816) вопреки рекомендации
окна не строить его, и поэтому он только говорит.

Реализует правила каталога:
  215 — пересказ своей работы сверяется с источником, машинная часть — полнота;
  051 — вероятное предупреждают, а не запрещают;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  158 — третий исход называет предмет: какой файл не прочитан.

Запуск:
  python scripts/check_retelling.py --paths-from <файл путей> --body-file <тело>

Исходы:
  0 — проверено (предупреждения печатаются, кода не меняют);
  2 — проверка не отработала.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: Путь в обратных кавычках: с косой чертой и расширением файла. Образцы со
#: звездой и подстановки — не утверждение о конкретном файле.
ПУТЬ_RE = re.compile(r"`([\w.-]+(?:/[\w.-]+)+\.[A-Za-z0-9]+)`")
#: «две находки», «3 находки» — число ПЕРЕД словом: так говорит автор о своей
#: работе. «находок 0» — обычно цитата вердикта обзора, и в сверку не идёт; текст
#: в «ёлочках» — тоже цитата, и вырезается до поиска (замер на #631: там рядом
#: стояли «Две находки» автора и «находок 0» обзора).
СЛОВА = {"одна": 1, "одну": 1, "две": 2, "три": 3, "четыре": 4, "пять": 5,
         "шесть": 6, "семь": 7, "восемь": 8, "девять": 9, "десять": 10}
ЧИСЛО_RE = re.compile(r"(?i)\b(\d+|" + "|".join(СЛОВА) + r")\s+находк\w*")
ЦИТАТА_RE = re.compile(r"«[^»\n]*»")
СНЯТИЕ_RE = re.compile(r"(?im)^[ \t>*-]*Разобрано:[ \t]*\S")


def пути_мимо(тело: str, пути: set[str], root: Path) -> list[str]:
    """Названные путём файлы, которых нет ни в изменении, ни в дереве."""
    return sorted({п for п in ПУТЬ_RE.findall(тело)
                   if п not in пути and not (root / п).exists()})


def числа_находок(тело: str) -> list[int]:
    out = []
    for m in ЧИСЛО_RE.finditer(ЦИТАТА_RE.sub("", тело)):
        слово = m[1].lower()
        out.append(int(слово) if слово.isdigit() else СЛОВА[слово])
    return out


def расхождение_снятий(тело: str) -> str | None:
    """Названо одно число находок, а строк снятия другое — пересказ разошёлся."""
    снятий = len(СНЯТИЕ_RE.findall(тело))
    числа = set(числа_находок(тело))
    if снятий and len(числа) == 1 and (n := числа.pop()) != снятий:
        return f"тело называет находок {n}, а строк «Разобрано:» {снятий}"
    return None


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--paths-from", type=Path, required=True)
    ap.add_argument("--body-file", type=Path, required=True)
    args = ap.parse_args(argv)
    try:
        пути = {p.strip() for p in args.paths_from.read_text(encoding="utf-8").splitlines()
                if p.strip()}
        тело = args.body_file.read_text(encoding="utf-8")
    except OSError as exc:
        print(f"проверка не отработала: не прочитан {exc.filename}: {exc.strerror}",
              file=sys.stderr)
        return 2

    мимо = пути_мимо(тело, пути, args.root)
    снятия = расхождение_снятий(тело)
    for п in мимо:
        print(f"::warning::тело изменения называет `{п}`, а такого файла нет ни в "
              "изменении, ни в дереве — пересказ сверяется с `git diff --stat` (215)")
    if снятия:
        print(f"::warning::{снятия} — пересчитайте по телу (215)")
    print(f"пересказ сверен: путей в теле {len(set(ПУТЬ_RE.findall(тело)))}, "
          f"мимо {len(мимо)}; снятий {len(СНЯТИЕ_RE.findall(тело))}"
          + (", число разошлось" if снятия else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
