#!/usr/bin/env python3
"""Новый механизм называет, у кого из семьи спросили, прежде чем строить (162).

ВТОРАЯ ПОЛОВИНА 162. Первую держит метрика `check_bindings.py`: очередь правил
«держится ничем» называет, что из неё решено у соседа. Механизм же строят и по
другим поводам — по находке обзора, разбору чужого проекта, вопросу владельца,
— и тогда вопрос «а у семьи?» не задаёт никто. 16.10 так случилось трижды за
смену: свой прогон подъёма закреплений рядом с перехватом механизмов, гейт
интерпретатора хуков (у соседей его не было, зато у глоссария нашлась живая
ошибка), дедлайн подпроцесса (у Token гейт был). Навык `ask-the-family-first`
говорит, КАК спросить; этот гейт — что ответ ЗАПИСАН.

ЗАМЕР, ИЗ КОТОРОГО ГЕЙТ ВЫРОС. Механизмов, добавленных в общую ветку с 15.09 и
живых 16.10, — 35; семью (номер 162) называют 2.

СПЕРВА СПРОСИЛИ СЕМЬЮ (162). У всех пяти проектов 162 держится одним и тем же
разделом «У соседей это уже решено» во входящих, у механизмов — ещё разрезом
`family.py`; гейта на момент постройки нового механизма нет ни у кого.

ЧТО ПРОВЕРЯЕТСЯ. Механизм, ДОБАВЛЕННЫЙ изменением (пути нет на базе):
`scripts/check_*.py`, `.claude/hooks/*.py|*.sh`, `.github/workflows/*.yml`,
`.github/actions/*/action.yml`, `.claude/skills/*/SKILL.md`. В его тексте
названо правило 162 — там, где записано, у кого спросили и что нашли. Прежние
механизмы задним числом не спрашиваются: это долг, объявленный замером, а не
повод переписать 33 описания за раз (051).

ГРАНИЦЫ, И ОНИ НАЗВАНЫ.
  • Гейт видит, что ответ записан, а не что он верен: «спросили — нет ни у
    кого» при живом механизме соседа он пропустит. Это судит обзор.
  • Расширение СТАРОГО механизма гейт не видит: путь уже есть на базе. Из трёх
    случаев 16.10 он поймал бы два — свой прогон подъёма закреплений (новый
    файл в `.github/workflows/`) и гейт интерпретатора хуков (новый
    `scripts/check_*.py`), — а дедлайн подпроцесса пришёл расширением
    `check_subprocess.py` и прошёл бы мимо (обзор #884). Что считать
    расширением по диффу — суждение; держит навык `ask-the-family-first`.
  • Механизм вне названных путей (скрипт без приставки `check_`) не виден.

Исходы: 0 — новых механизмов нет или каждый называет семью · 1 — названы
механизмы без записи · 2 — не отработал: список путей не прочитан или база не
разобрана.

Реализует правила каталога:
  162 — прежде чем строить механизм, спросили семью, и это записано;
  220 — механизм — тоже предмет правил о механизмах;
  039 — три исхода; 158 — третий исход называет предмет.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
#: Что считается механизмом — те же места, что у мета-гейтов (220).
МЕХАНИЗМ_RE = re.compile(
    r"^(scripts/check_[^/]+\.py|\.claude/hooks/[^/]+\.(py|sh)|\.github/workflows/[^/]+\.ya?ml"
    r"|\.github/actions/[^/]+/action\.yml|\.claude/skills/[^/]+/SKILL\.md)$")
#: Запись о семье — строка, где рядом с номером 162 названы семья, соседи или
#: вопрос к ним. Голое «162» записью не считается: число в тексте ничего не
#: говорит о том, кого спросили (обзор #884).
НОМЕР_RE = re.compile(r"(?<!\d)162(?!\d)")
СЕМЬЯ_RE = re.compile(r"сем[ьеиюя]|сосед|спрос|family|neighbo", re.I)


def записано(текст: str) -> bool:
    """Есть строка, где номер 162 стоит рядом со словом о семье или соседях."""
    return any(НОМЕР_RE.search(с) and СЕМЬЯ_RE.search(с) for с in текст.splitlines())


class НеОтработал(Exception):
    """Базу не разобрать — сказать, есть ли путь на ней, нечем."""


def проверить_базу(root: Path, base: str) -> None:
    """База — коммит, иначе НеОтработал.

    Отдельно, а не по ответу `cat-file -e`: тот отвечает одинаково и на битую
    базу, и на отсутствующий путь — «path does not exist», код 128 (замер
    16.10), и битая база молча превратила бы каждый механизм в новый.
    """
    done = subprocess.run(["git", "-C", str(root), "rev-parse", "--verify", "--quiet",
                           f"{base}^{{commit}}"],
                          capture_output=True, text=True, encoding="utf-8", timeout=60)
    if done.returncode != 0:
        raise НеОтработал(f"база {base} не разобрана как коммит в {root}")


def на_базе(root: Path, base: str, путь: str) -> bool:
    """Есть ли путь на базе изменения; база уже проверена."""
    done = subprocess.run(["git", "-C", str(root), "cat-file", "-e", f"{base}:{путь}"],
                          capture_output=True, text=True, encoding="utf-8", timeout=60)
    return done.returncode == 0


def main(argv: list[str] | None = None) -> int:
    """Проверить механизмы, добавленные изменением."""
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--paths-from", type=Path, required=True,
                    help="файл со списком путей изменения, по одному в строке")
    ap.add_argument("--base", required=True, help="коммит базы изменения")
    args = ap.parse_args(argv)
    try:
        пути = [p.strip() for p in args.paths_from.read_text(encoding="utf-8").splitlines()
                if p.strip()]
    except OSError as exc:
        print(f"проверка не отработала: не прочитан {exc.filename}: {exc.strerror}",
              file=sys.stderr)
        return 2
    кандидаты = [p for p in пути if МЕХАНИЗМ_RE.match(p) and (args.root / p).is_file()]
    try:
        проверить_базу(args.root, args.base)
        новые = [p for p in кандидаты if not на_базе(args.root, args.base, p)]
    except НеОтработал as exc:
        print(f"проверка не отработала: {exc}", file=sys.stderr)
        return 2
    if not новые:
        print("новых механизмов в изменении нет — спрашивать нечего")
        return 0
    молчат = [p for p in новые if not записано((args.root / p).read_text(encoding="utf-8"))]
    if молчат:
        print("новый механизм не называет, у кого из семьи спросили (162):", file=sys.stderr)
        for p in молчат:
            print(f"  • {p}", file=sys.stderr)
        print("\n  Запишите в описании механизма, чем этот предмет держится у проектов\n"
              "  семьи и что из этого следует: подключили, взяли идею или ни у кого нет\n"
              "  — со ссылкой на 162. Как спросить — навык ask-the-family-first.",
              file=sys.stderr)
        return 1
    print(f"новые механизмы называют семью: {len(новые)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
