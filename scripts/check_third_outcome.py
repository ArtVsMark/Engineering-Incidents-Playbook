#!/usr/bin/env python3
"""Третий исход называет ПРЕДМЕТ отказа, а не только его причину.

Правило 158: «проверка не отработала» без адреса неотличима от «сломалось
что-то». Читатель такого сообщения знает, что стало плохо, и не знает, ГДЕ, —
а третий исход тем и отличается от первого, что чинят его не в предмете
проверки, а в самой проверке.

ЧТО ЗДЕСЬ МАШИННОГО, А ЧТО НЕТ, И ЭТО ГРАНИЦА, А НЕ ОГОВОРКА. Прежний ответ
каталога о 158 был «требует суждения: что считать адресом отказа, из кода не
следует». Половина этого верна: отличить в прозе причину от предмета разбором
нельзя. Но есть половина, которая следует из кода целиком, — НАЗВАН ЛИ ПРЕДМЕТ
ВООБЩЕ. Предмет называется одним из двух способов, и оба видны в дереве:

  • подстановкой — `f"... {путь}"`: предмет берётся из прогона, значит он есть;
  • буквальным адресом — `.github/workflows`, `rules/ru`, `#123`, `http…`,
    `--paths-from`: предмет постоянен и назван прямо. Длинный ключ считается
    адресом наравне с путём — он называет предмет ЗАПУСКА, и «не сказано, какие
    пути тронуты (--paths-from)» отвечает на вопрос «где искать» полностью.

Сообщение, где нет ни того, ни другого, предмета не называет ни в каком
прочтении, и суждения тут не требуется. Гейт судит только об этом.

ЗАМЕР, РАДИ КОТОРОГО ЗАВЕДЕНО (4 сентября): из 42 скриптов каталога третий
исход объявляют 39, и у двух он не называл предмета вовсе — check_links.py
(«не найдено ни одного документа — проверять нечего»: каких документов и где
искали?) и coverage_badge.py («нет данных покрытия»: какого файла нет?). Оба
случая — ровно тот, о котором правило: сломано у проверяющего, а искать негде.

ЧЕГО ГЕЙТ НЕ ДЕЛАЕТ. Не читает прозу и не решает, хорош ли адрес: «rules/ru» и
«файл не прочитан — {e}» для него одинаково законны. Не трогает третий исход,
объявленный не печатью в stderr, — молчаливый отказ ловится правилом 045 и
другим предметом.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.

Реализует правила каталога:
  158 — третий исход называет предмет отказа, а не только его причину;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  075 — ноль просмотренных файлов это отказ, а не чистый прогон;
  051 — запрещается достоверное: «подстановки и адреса нет» — факт, а не
        подозрение, поэтому это отказ, а не предупреждение;
  165 — печатается ОХВАТ: сколько скриптов просмотрено и сколько из них вообще
        объявляют третий исход.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: Похоже на АДРЕС: путь, имя файла с расширением, номер задачи, ссылка. Список
#: намеренно широкий — гейт ловит отсутствие предмета, а не его качество (051).
АДРЕС = re.compile(
    r"[\w.-]+/[\w./*-]*"          # путь: rules/ru, .github/workflows, templates/
    r"|\.(?:py|json|yml|yaml|md|txt|svg)\b"   # имя файла с расширением
    r"|#\d+"                      # номер задачи или изменения
    r"|https?://"                 # ссылка
    r"|--[a-zA-Z][\w-]+"          # длинный ключ: адрес ЗАПУСКА, а не файла
    r"|\b[A-Z][A-Z0-9_]{2,}\b")   # имя в верхнем регистре: GH_TOKEN, SOURCE

#: Сколько соседних строк выше `return 2` считается его сообщением. Три хватает
#: с запасом: в дереве самый длинный такой блок — две печати и возврат.
ОКНО = 3


def третий_исход(node: ast.AST) -> bool:
    """Оператор, отдающий код 2: `return 2`, `return 2, ...` или `sys.exit(2)`."""
    if isinstance(node, ast.Return):
        знач = node.value
        if isinstance(знач, ast.Constant) and знач.value == 2:
            return True
        if isinstance(знач, ast.Tuple) and знач.elts:
            первый = знач.elts[0]
            return isinstance(первый, ast.Constant) and первый.value == 2
        return False
    if isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
        зов = node.value
        имя = getattr(зов.func, "attr", None) or getattr(зов.func, "id", None)
        if имя == "exit" and зов.args:
            первый = зов.args[0]
            return isinstance(первый, ast.Constant) and первый.value == 2
    return False


def сообщения(node: ast.AST) -> list[ast.Call]:
    """Все сообщения третьего исхода в этом операторе, включая вложенные.

    ВЛОЖЕННОСТЬ ОБЯЗАТЕЛЬНА, и это третий класс ложных находок первой редакции.
    Обычный вид отказа со списком причин таков:

        print("проверка не отработала:", file=sys.stderr)
        for b in blockers:
            print(f"  • {b}", file=sys.stderr)
        return 2

    Предмет здесь назван внутри `for`, а не соседним оператором, и разбор,
    смотрящий только на прямых соседей, объявил бы нарушением build_rules_index
    и refresh_derived — оба сообщают предмет исчерпывающе.
    """
    найдено: list[ast.Call] = []
    один = несёт_сообщение(node)
    if один is not None:
        найдено.append(один)
    for вложенный in ast.walk(node):
        if вложенный is node:
            continue
        ещё = несёт_сообщение(вложенный)
        if ещё is not None:
            найдено.append(ещё)
    return найдено


def несёт_сообщение(node: ast.AST) -> ast.Call | None:
    """Оператор, задающий сообщение третьего исхода, — или None.

    СПОСОБОВ ТРИ, И ВСЕ ТРИ ЗАКОННЫ. Это найдено ложными находками, а не
    придумано: первая редакция знала только печать в stderr и объявила
    нарушителями refresh_derived.py и preflight.py, у которых сообщение уезжает
    ВОЗВРАЩАЕМЫМ ЗНАЧЕНИЕМ и печатается вызывающим, — восемь ложных находок
    подряд. Ровно тот случай, о котором 180: ложная находка приглашает
    «починить» работающий код.

      • print(..., file=sys.stderr) — печать на месте;
      • problems.append(...) / .extend(...) — сообщение копится и уезжает вверх;
      • parser.error(...) — печатает argparse, и адрес запуска он ставит сам.
    """
    if not (isinstance(node, ast.Expr) and isinstance(node.value, ast.Call)):
        return None
    зов = node.value
    имя = getattr(зов.func, "attr", None) or getattr(зов.func, "id", None)
    if имя == "print":
        for kw in зов.keywords:
            if kw.arg == "file" and getattr(kw.value, "attr", None) == "stderr":
                return зов
        return None
    if имя in ("append", "extend"):
        return зов
    if имя == "error":
        # argparse печатает usage с именем программы — адрес ставит библиотека.
        return зов
    return None


def называет_предмет(зов: ast.Call) -> bool:
    """У сообщения есть подстановка либо буквальный адрес.

    Подстановка засчитывается без разбора: раз значение берётся из прогона,
    предмет у сообщения есть по построению. Читать, ЧТО именно подставлено, —
    та половина, которая требует суждения и здесь не делается.
    """
    return any(называет_предмет_узла(a) for a in зов.args)


def любой_элемент_называет(кортеж: ast.Tuple) -> bool:
    """У возврата `return 2, "..."` предмет назван в самом кортеже."""
    return any(называет_предмет_узла(э) for э in кортеж.elts[1:])


def называет_предмет_узла(узел: ast.AST) -> bool:
    """Подстановка, вычисленное значение либо буквальный адрес внутри узла.

    ВЫЧИСЛЕННОЕ ЗНАЧЕНИЕ РАВНОСИЛЬНО ПОДСТАНОВКЕ, и это тоже найдено ложной
    находкой: `"тронул файлы вне набора: " + ", ".join(stray)` называет предмет
    не хуже f-строки, а первая редакция видела в узле только FormattedValue и
    объявила это нарушением. Признак один — в сообщении есть НЕ константа,
    то есть что-то, берущееся из прогона.
    """
    for часть in ast.walk(узел):
        if isinstance(часть, (ast.FormattedValue, ast.Call, ast.Name,
                              ast.Attribute, ast.Subscript)):
            return True
        if isinstance(часть, ast.Constant) and isinstance(часть.value, str):
            if АДРЕС.search(часть.value):
                return True
    return False


def безымянные(source: str) -> list[tuple[int, str]]:
    """Третьи исходы, чьё сообщение не называет предмета.

    Разбор идёт по СПИСКАМ операторов, а не по ast.walk: сообщение принадлежит
    исходу соседством в одном блоке, и это отношение walk теряет — он отдаёт
    узлы вперемешку из разных ветвей (166: проверка отношения без отношения).
    """
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return []
    находки: list[tuple[int, str]] = []
    for узел in ast.walk(tree):
        for поле in ("body", "orelse", "finalbody"):
            блок = getattr(узел, поле, None)
            if not isinstance(блок, list):
                continue
            for i, оператор in enumerate(блок):
                if not третий_исход(оператор):
                    continue
                соседи = блок[max(0, i - ОКНО):i]
                печати = [p for с in соседи for p in сообщения(с)]
                # СООБЩЕНИЕ БЫВАЕТ В САМОМ ВОЗВРАТЕ: `return 2, f"..."`. Тогда
                # печатает вызывающий, и предмет назван здесь же, рядом с кодом.
                if isinstance(оператор, ast.Return) and \
                        isinstance(оператор.value, ast.Tuple) and \
                        любой_элемент_называет(оператор.value):
                    continue
                if not печати:
                    находки.append((оператор.lineno,
                                    "третий исход без единого слова в stderr"))
                elif not any(называет_предмет(p) for p in печати):
                    находки.append((оператор.lineno,
                                    "сообщение называет причину, но не предмет"))
    return sorted(set(находки))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)

    файлы = sorted((args.root / "scripts").glob("*.py"))
    # ── исход 2 ────────────────────────────────────────────────────────────
    if not файлы:
        print(f"проверка не отработала: в {args.root / 'scripts'} нет ни одного "
              "исходника — проверять нечего, и зеленеть на этом нельзя",
              file=sys.stderr)
        return 2

    находки: list[str] = []
    с_третьим = 0
    for f in файлы:
        текст = f.read_text(encoding="utf-8")
        свои = безымянные(текст)
        if "return 2" in текст or "exit(2)" in текст:
            с_третьим += 1
        for строка, чем in свои:
            находки.append(f"{f.relative_to(args.root)}:{строка} — {чем}")

    # ── исход 1 ────────────────────────────────────────────────────────────
    if находки:
        print("третий исход говорит, что сломалось, и молчит, где искать:",
              file=sys.stderr)
        for n in находки:
            print(f"  • {n}", file=sys.stderr)
        print("\n  Допишите в сообщение адрес: путь, файл, номер задачи или "
              "ссылку —\n  подстановкой `{путь}` либо прямо в тексте. Третий "
              "исход чинят\n  не в предмете проверки, а в самой проверке, и "
              "искать её надо по адресу (158).", file=sys.stderr)
        return 1

    print(f"третий исход называет предмет: просмотрено скриптов {len(файлы)}, "
          f"третий исход объявляют {с_третьим}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
