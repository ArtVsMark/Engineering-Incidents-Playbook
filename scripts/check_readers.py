#!/usr/bin/env python3
"""У каждого документа назван читатель, и у каждого читателя есть документ.

Правило 021 держалось ничем: «делим по читателю» было записью в каталоге и
намерением в голове. Проверить намерение нечем, и цену этого мы заплатили в тот
же день — обнаружилось, что у **подключающегося проекта документа не было
вовсе**: команда подключения жила в журнале изменений, а первый день нового
проекта состоял из копирования заготовок (правило 163).

ПОЧЕМУ НЕ КАТАЛОГИ, КАК У СОСЕДА. У грейдера 021 держится раскладкой
`docs/use|dev|agent|archive` и гейтом на полноту индексов. Приём взят, файл —
нет (правило 162): у каталога документы лежат в корне не по небрежности, а
потому что там их ищет площадка и человек — `README`, `CONTRIBUTING`, `AGENTS`
имеют для GitHub своё значение, и переезд в `docs/use/` спрятал бы их. Значит,
раскладка ответить на вопрос «кто это читает» не может, и отвечает **строка в
самом документе**.

ЧТО ПРОВЕРЯЕТСЯ.

  • каждый документ — файл в корне или README папки — несёт строку
    `> **Читатель:** <кто> — <на какой вопрос отвечает>`;
  • «кто» берётся из закрытого словаря: опечатка иначе заводит шестого читателя
    молча (правило 099 на своём материале);
  • вопрос непуст: читатель без вопроса — половина ответа;
  • у каждого читателя из словаря есть хотя бы один документ. Это и есть та
    проверка, которой не хватало: словарь называет аудиторию, а пустая строка
    в нём означает, что аудитории писать некуда.

ЧЕГО ЗДЕСЬ НЕТ. Суждения о том, тому ли читателю адресован текст на самом
деле, и не отвечает ли документ на два вопроса сразу. Это приёмка, а не
машина; гейт держит объявление и полноту словаря.

Реализует правила каталога:
  021 — документацию делят по читателю, а не по теме;
  099 — значение берётся из закрытого словаря, иначе опечатка заводит новое;
  128 — обязательное поле проверяется на полноту, а не на непустоту;
  046 — «читателя нет» и «читатель не назван» различаются только вслух;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  075 — ноль документов это отказ, а не чистый прогон;
  158 — третий исход называет предмет.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: Закрытый словарь читателей: кто приходит и с каким вопросом. Пятеро, и
#: каждый обязан иметь свой документ — иначе аудитория объявлена и брошена.
#: Английские имена нужны потому, что каталог двуязычен и у английской
#: страницы русская строка была бы разрывом в её же собственном тексте.
READERS: dict[str, str] = {
    "посетитель": "visitor",
    "подключающийся": "adopter",
    "участник": "contributor",
    "агент": "agent",
    "историк": "historian",
}
EN = {en: ru for ru, en in READERS.items()}

#: Строка объявления. Сверяется целиком: «читатель» внутри фразы — это проза.
LINE_RE = re.compile(r"^>\s*\*\*(?:Читатель|Reader):\*\*\s*([^\s—-]+)\s*[—-]\s*(.*)$")
#: Сколько строк от начала документа считается объявлением. Дальше — текст, и
#: строка, найденная в середине, объявлением не является.
HEAD = 8


def documents(root: Path) -> list[Path]:
    """Документы каталога: файлы в корне и README каждой папки.

    Записи правил, фрагменты журнала, заготовки и картинки документами не
    считаются: их читатель задан документом папки, а требовать строку с
    каждого файла значило бы требовать её со ста шестидесяти двух правил.
    """
    found = sorted(root.glob("*.md"))
    for folder in sorted(p for p in root.iterdir() if p.is_dir()):
        if folder.name.startswith(".") or folder.name in ("scripts", "tests"):
            continue
        readme = folder / "README.md"
        if readme.exists():
            found.append(readme)
    return found


def reader_of(path: Path) -> tuple[str | None, str]:
    """Читатель документа и вопрос, на который тот отвечает."""
    for line in path.read_text(encoding="utf-8").splitlines()[:HEAD]:
        m = LINE_RE.match(line.strip())
        if m:
            name = m.group(1).strip("*` ")
            return EN.get(name, name), m.group(2).strip().rstrip(".")
    return None, ""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT,
                        help="корень каталога; по умолчанию сам этот репозиторий")
    args = parser.parse_args(argv)
    root: Path = args.root

    # ── исход 2 ────────────────────────────────────────────────────────────
    if not root.is_dir():
        print(f"проверка не отработала: нет {root} — читать нечего",
              file=sys.stderr)
        return 2
    docs = documents(root)
    if not docs:
        print(f"проверка не отработала: в {root} не нашлось ни одного "
              "документа. Пустой корень — это ошибка обхода, а не проект без "
              "документации", file=sys.stderr)
        return 2

    # ── исход 1 ────────────────────────────────────────────────────────────
    problems: list[str] = []
    by_reader: dict[str, list[str]] = {r: [] for r in READERS}
    for path in docs:
        name = path.relative_to(root).as_posix()
        reader, question = reader_of(path)
        if reader is None:
            problems.append(
                f"{name}: не сказано, кто это читает. Строкой под заголовком: "
                "«> **Читатель:** <кто> — <на какой вопрос отвечает>»")
            continue
        if reader not in READERS:
            problems.append(
                f"{name}: читатель «{reader}» вне словаря {sorted(READERS)}. "
                "Опечатка иначе заводит новую аудиторию молча")
            continue
        if not question:
            problems.append(
                f"{name}: читатель назван, а вопрос — нет. «Кому» без «зачем» "
                "не разводит документы: два текста для одного читателя "
                "остаются неразличимы")
            continue
        by_reader[reader].append(name)

    for reader, found in by_reader.items():
        if not found:
            problems.append(
                f"читатель «{reader}» объявлен словарём, а документа для него "
                "нет ни одного. Аудитория, которой некуда прийти, — это не "
                "пустая полка, а обещание, которого никто не выполнил")

    if problems:
        print("документы разошлись с читателями:", file=sys.stderr)
        for p in problems:
            print(f"  • {p}", file=sys.stderr)
        return 1

    print(f"документы разведены по читателю: {len(docs)}")
    for reader in READERS:
        print(f"  {reader}: " + " · ".join(by_reader[reader]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
