#!/usr/bin/env python3
"""Каталог называет себя одним именем, и это имя сверяется с площадкой.

2 сентября 2026 репозиторий переименован, и в дереве осталось 245 упоминаний
старого имени: контракт потребления, действия, заготовка ответа, реестр,
значки, прогоны. Перенаправление площадки сработало — и потому расхождение
НЕ ПРОЯВИЛОСЬ НИЧЕМ: и старый, и новый адрес отвечали 200. Узналось оно
случайно, из предупреждения `git push`, а не из проверки.

Это ровно то, о чём 022: два имени одной территории расходятся молча. Пока
работает перенаправление, дерево обещает читателю имя, которого больше нет; а
перестанет оно работать в тот день, когда владелец заведёт под старым именем
что-то другое, — и тогда контракт поведёт потребителей не туда.

ЧТО ПРОВЕРЯЕТСЯ. Любая ссылка вида `<владелец>/<репозиторий>` на репозиторий
ТОГО ЖЕ ВЛАДЕЛЬЦА обязана быть либо самим каталогом, либо записью реестра
потребителей. Список разрешительный, а не запретительный: запрет по списку
старых имён пережил бы свою причину молча (068) — именно так и вышло с
исключением у дежурного по общей ветке.

ОТКУДА БЕРЁТСЯ СВОЁ ИМЯ. Из адреса `origin`, а не из константы: константа —
это то же вписанное рукой число, только словом (005). Нет клона или нет
`origin` — третий исход, а не молчаливый пропуск.

ЧЕГО ЗДЕСЬ НЕТ. Проверки чужих владельцев: `chokmah-me/claude-code-playbook`
это другой проект с похожим именем, и он законен. Территория правила — свои
репозитории, и только они.

Реализует правила каталога:
  022 — одно имя на одну территорию: два имени расходятся молча;
  049 — состояние выводится из живого артефакта: имя берётся у origin;
  068 — список разрешительный: запрет по старым именам переживает причину;
  005 — своё имя не вписывается константой рядом с текстом;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  075 — нет клона или нет реестра — это отказ, а не чистый прогон;
  158 — третий исход называет предмет;
  172 — перепись вместо сигнала: редирект площадки оставляет старое имя
        рабочим, поэтому места, где оно записано, сверяются с живым
        источником — адресом origin.

ЧТО ГЕЙТ НЕ ПРОСМАТРИВАЕТ — свой собственный набор: он обязан содержать имена,
которые гейт отвергает, и просмотр сделал бы находку из набора. Первая редакция
именно так и покраснела на самой себе. Исключение одно и названо путём.

Запуск:  python scripts/check_own_name.py [--root <корень>]

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = Path(".rules") / "consumers.json"
#: Ссылка на репозиторий площадки: владелец/имя. Хвост (`/blob/...`, `@main`,
#: `.git`) отсекается сам — в имя репозитория косая черта не входит.
SLUG_RE = re.compile(r"(?<![\w./-])([A-Za-z0-9][\w.-]*)/([A-Za-z0-9][\w.-]*)")
#: Где ищем. Дерево целиком: имя расходится не только в прозе — оно живёт в
#: действиях, заготовках и реестре, и первым разошлось именно там.
SUFFIXES = (".md", ".json", ".yml", ".yaml", ".py", ".html", ".txt")
#: Отсекаем хвосты, которые площадка ссылкой не считает: `.git` и знаки
#: препинания на конце предложения. Замер на живом дереве: без этого
#: `ArtVsMark/ArtVsMark.` в конце фразы становился отдельным репозиторием.
TAIL = re.compile(r"(?:\.git)?[.,;:!?)»\]]*$")

#: Репозитории владельца, названные в тексте законно и в реестр не входящие.
#: Список РАЗРЕШИТЕЛЬНЫЙ и каждая запись несёт причину: без причины он через
#: месяц станет свалкой, куда дописывают, чтобы гейт замолчал (068).
ASIDE = {
    "ArtVsMark/Other": "подделка в самопроверке scripts/link_trails.py — "
                       "«чужой проект», у которого следа быть не должно",
    "ArtVsMark/claude-code-usage-dat": "бывший потребитель, убранный из "
                                       "реестра 28 августа; назван в журнале "
                                       "как факт истории, а не как адрес",
}


def own_slug(root: Path) -> tuple[str, str]:
    """«владелец/имя» по адресу origin. Ошибка строкой, а не трассировкой."""
    done = subprocess.run(["git", "-C", str(root), "remote", "get-url", "origin"],
                          capture_output=True, text=True, encoding="utf-8")
    if done.returncode != 0 or not done.stdout.strip():
        return "", ("не спросить адрес origin: "
                    + (done.stderr.strip() or "пустой ответ"))
    url = done.stdout.strip()
    m = re.search(r"[:/]([^/:]+)/([^/]+?)(?:\.git)?/?$", url)
    if not m:
        return "", f"адрес origin не разобран: {url}"
    return f"{m.group(1)}/{m.group(2)}", ""


def known(root: Path) -> tuple[set[str], str]:
    """Разрешённые чужие репозитории: реестр потребителей."""
    path = root / REGISTRY
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return set(), f"реестр потребителей не прочитан — {path}: {exc}"
    out: set[str] = set()
    for item in data.get("consumers") or []:
        repo = (item or {}).get("repo")
        if repo:
            out.add(repo)
    return out, ""


#: Собственный набор гейта. Он ОБЯЗАН содержать имена, которые гейт отвергает,
#: — иначе проверять нечего, — и потому просматривать его значит находить самого
#: себя. Тот же приём, что у входа в проект: сторож пропускает свой файл.
#: Исключение одно, названо путём и не расширяется: всякое другое место, где
#: понадобилось чужое имя, — это находка, а не неудобство.
OWN_SUITE = "tests/test_check_own_name.py"


def files(root: Path) -> list[Path]:
    done = subprocess.run(["git", "-C", str(root), "ls-files", "-z"],
                          capture_output=True, text=True, encoding="utf-8")
    if done.returncode != 0:
        return []
    return [root / f for f in done.stdout.split("\0")
            if f.endswith(SUFFIXES) and f != OWN_SUITE and (root / f).exists()]


def strangers(root: Path, mine: str, allowed: set[str]) -> list[str]:
    """Ссылки на репозитории СВОЕГО владельца, которых нет в разрешённых."""
    owner = mine.split("/")[0].lower()
    seen: dict[str, str] = {}
    ok = {s.lower() for s in allowed} | {mine.lower()} | {s.lower() for s in ASIDE}
    for path in files(root):
        try:
            text = path.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        for m in SLUG_RE.finditer(text):
            slug = TAIL.sub("", f"{m.group(1)}/{m.group(2)}")
            if slug.split("/")[0].lower() != owner:
                continue
            if slug.lower() in ok:
                continue
            seen.setdefault(slug, str(path.relative_to(root)))
    return [f"{slug} — впервые в {where}" for slug, where in sorted(seen.items())]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT,
                    help="корень каталога; по умолчанию сам этот репозиторий")
    ap.add_argument("--slug", help="своё имя вместо ответа origin: так набор "
                                   "подставляет подделку, не трогая машину")
    args = ap.parse_args(argv)
    root: Path = args.root

    # ── исход 2 ────────────────────────────────────────────────────────────
    mine, err = (args.slug, "") if args.slug else own_slug(root)
    if err:
        print(f"проверка не отработала: {err}. Своё имя брать неоткуда, а "
              "константой оно быть не должно (005)", file=sys.stderr)
        return 2
    allowed, err = known(root)
    if err:
        print(f"проверка не отработала: {err}", file=sys.stderr)
        return 2
    looked = files(root)
    if not looked:
        print(f"проверка не отработала: под {root} просмотрено ноль файлов — "
              "это отказ, а не чистый прогон (075)", file=sys.stderr)
        return 2

    # ── исход 1 ────────────────────────────────────────────────────────────
    # КАТАЛОГ ОБЯЗАН ЧИСЛИТЬСЯ В СОБСТВЕННОМ РЕЕСТРЕ ПОД ИМЕНЕМ ПЛОЩАДКИ, и
    # это не формальность, а единственная нецикличная точка опоры. Реестр
    # разрешает имена; если бы своё имя бралось из него же, переименование
    # прошло бы молча: старое имя лежало бы в реестре, а значит считалось бы
    # законным — и гейт пропустил бы ровно тот случай, ради которого построен
    # (146). Поэтому имя приходит СНАРУЖИ, от origin, и сверяется с реестром.
    found: list[str] = []
    if mine not in allowed:
        found.append(
            f"своего имени нет в реестре потребителей: площадка знает каталог "
            f"как {mine}, а {REGISTRY} называет "
            + (", ".join(sorted(s for s in allowed
                                if s.split('/')[0] == mine.split('/')[0]))
               or "другого владельца")
            + ". После переименования это первое, что расходится")
    found += strangers(root, mine, allowed)
    if found:
        print(f"дерево называет репозитории владельца, которых оно не знает "
              f"(своё имя — {mine}):", file=sys.stderr)
        for f in found:
            print(f"  • {f}", file=sys.stderr)
        print("\n  Либо это устаревшее имя — тогда перепишите его; либо новый "
              "потребитель —\n  тогда заведите его в .rules/consumers.json. "
              "Перенаправление площадки\n  скрывает расхождение до того дня, "
              "когда старое имя займут (022).", file=sys.stderr)
        return 1

    print(f"каталог знает своё имя: {mine}; просмотрено файлов {len(looked)}, "
          f"чужих репозиториев владельца нет, в реестре {len(allowed)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
