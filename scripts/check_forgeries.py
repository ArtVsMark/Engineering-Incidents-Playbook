#!/usr/bin/env python3
"""У подделки чужой стороны назван источник — адрес, по которому её сверяют.

Правило 170: зелёное на подделке — гипотеза. Набор, гоняемый на значениях,
которые придумал автор, доказывает согласованность кода с представлением автора
о чужой стороне и ничего не говорит о самой стороне.

ЧТО ЗДЕСЬ МАШИННОГО, А ЧТО НЕТ, И ЭТО ГРАНИЦА, А НЕ ОГОВОРКА. Прежний ответ
каталога был «сверять образцы с живой площадкой сейчас нечем: прогон гейтов
наружу не ходит намеренно». Это верно — и относится к СВЕРКЕ. Требование
правила шире и начинается раньше: у подделки должен БЫТЬ источник. Назвать
адрес, по которому снимается настоящий ответ, можно без единого сетевого
вызова, и без этого сверка невозможна вообще никогда — расхождение подделки с
живой стороной обнаруживается только тогда, когда её однажды сверили, а сверить
нечем, пока не сказано с чем.

Поэтому гейт держит ПРЕДПОСЫЛКУ: у каждого набора, подменяющего шов наружу,
назван адрес — команда площадки, ссылка, путь или номер задачи. Сама сверка
остаётся человеку и названа здесь как то, чего гейт не делает.

ШОВ — ЭТО ГРАНИЦА С ЧУЖОЙ СТОРОНОЙ, А НЕ ЛЮБАЯ ПОДМЕНА. Набор подменяет и свои
константы — путь к файлу, корень дерева, argv, — и требовать от них источника
значило бы краснеть на верном (051). Список швов разрешительный и с причиной у
каждой строки: запретительный завтра пропустит новый.

ЗАМЕР, РАДИ КОТОРОГО ЗАВЕДЕНО (4 сентября): наборов, подменяющих шов наружу,
четыре; источник назван у одного.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.

Реализует правила каталога:
  170 — у подделки чужого интерфейса назван источник, по которому её сверяют;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  075 — ноль наборов это отказ, а не чистый прогон;
  051 — свои константы под правило не подпадают: красное на них было бы ложным;
  158 — третий исход называет предмет отказа, а не только причину;
  165 — печатается ОХВАТ: сколько наборов просмотрено и сколько из них с швом.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: Имена, подмена которых означает подделку ЧУЖОЙ стороны. Разрешительный
#: список: у каждой строки своя причина, и новый шов надо вписать осознанно.
ШВЫ = {
    "run": "вызов площадки через ghcli либо подпроцесс",
    "gh": "он же под коротким именем в скриптах трекера",
    "gh_json": "он же, отдающий разобранный JSON",
    "остаток": "запрос квоты площадки",
    "urlopen": "чтение по HTTP напрямую",
    "fetch": "чтение чужого ответа по адресу",
    "fetch_rules": "выгрузка правил каталога у потребителя",
    "fetch_export": "выгрузка целиком",
    "fetch_where": "сводка «где действует»",
    "check_output": "подпроцесс, отдающий вывод",
    "Popen": "подпроцесс потоком",
}

#: Как объявляется источник. Слово-маркер плюс АДРЕС: одно слово без адреса
#: отвечало бы на вопрос «сказано ли», а не «с чем сверять» (166).
МАРКЕР = re.compile(r"снят\w*\b|источник\b|подделк\w*\s+снят", re.I)
АДРЕС = re.compile(
    r"`[^`]*\b(?:gh|git|curl)\b[^`]*`"   # команда, которой снимают
    r"|https?://"                        # ссылка
    r"|[\w.-]+/[\w./-]+"                 # путь либо владелец/репозиторий
    r"|#\d+")                            # номер задачи


def швы(source: str) -> list[str]:
    """Швы наружу, подменённые в этом наборе."""
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return []
    найдено: set[str] = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call) or len(node.args) < 2:
            continue
        имя = getattr(node.func, "attr", "") or getattr(node.func, "id", "")
        if имя != "setattr":
            continue
        второй = node.args[1]
        if isinstance(второй, ast.Constant) and второй.value in ШВЫ:
            найдено.add(второй.value)
    return sorted(найдено)


def назван_источник(source: str) -> bool:
    """В тексте набора есть объявление источника с адресом.

    Ищется В СТРОКЕ: маркер и адрес должны стоять рядом, иначе засчиталось бы
    слово «источник» в одном месте и путь в другом — проверка отношения без
    отношения (166).
    """
    for строка in source.splitlines():
        if МАРКЕР.search(строка) and АДРЕС.search(строка):
            return True
    # Объявление бывает разложено на две строки docstring; тогда адрес стоит на
    # следующей. Окно в две строки — та же граница, что у разбора прозы (144).
    строки = source.splitlines()
    for i, строка in enumerate(строки[:-1]):
        if МАРКЕР.search(строка) and АДРЕС.search(строки[i + 1]):
            return True
    return False


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)

    наборы = sorted((args.root / "tests").glob("test_*.py"))
    # ── исход 2 ────────────────────────────────────────────────────────────
    if not наборы:
        print(f"проверка не отработала: в {args.root / 'tests'} нет ни одного "
              "test_*.py — проверять нечего, и зеленеть на этом нельзя",
              file=sys.stderr)
        return 2

    находки: list[str] = []
    со_швом = 0
    for f in наборы:
        текст = f.read_text(encoding="utf-8")
        свои = швы(текст)
        if not свои:
            continue
        со_швом += 1
        if not назван_источник(текст):
            находки.append(f"{f.relative_to(args.root)} — подменяет "
                           f"{', '.join(свои)}, а источника не называет")

    if со_швом == 0:
        print(f"проверка не отработала: среди {len(наборы)} наборов ни один не "
              f"подменяет шов наружу ({', '.join(sorted(ШВЫ))}) — предмета нет, "
              "и зеленеть на этом нельзя (075)", file=sys.stderr)
        return 2

    # ── исход 1 ────────────────────────────────────────────────────────────
    if находки:
        print("подделка чужой стороны не говорит, с чем её сверять:",
              file=sys.stderr)
        for n in находки:
            print(f"  • {n}", file=sys.stderr)
        print("\n  Назовите источник одной строкой: слово «снято»/«источник» и "
              "АДРЕС —\n  команда в обратных кавычках, ссылка, путь или номер "
              "задачи.\n  Зелёное на придуманных значениях доказывает "
              "согласованность кода\n  с представлением автора о чужой стороне, "
              "и ничего больше (170).", file=sys.stderr)
        return 1

    print(f"у подделок назван источник: наборов {len(наборы)}, "
          f"со швом наружу {со_швом}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
