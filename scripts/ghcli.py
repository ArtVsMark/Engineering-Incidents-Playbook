#!/usr/bin/env python3
"""Один вызов `gh` на весь каталог: три исхода, а не два.

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ. Помощник был у четырёх скриптов, и все четыре
написали его по-своему: два падали трассировкой при отсутствии `gh`, третий
возвращал код 2 — который у самого `gh` тоже занят, — четвёртый отдавал 127.
Одна утилита, нужная нескольким потребителям, поднимается уровнем выше обоих,
а не копируется вбок (правило 090); четыре реализации одного алгоритма
расходятся при первой же правке (022).

ЧТО ЭТО СТОИЛО, ИЗМЕРЕНО. У потребителя действие каталога разбирает код
возврата так: 2 — механизм не отработал, красим; иначе зелено. Скрипт без
`gh` умирал трассировкой и отдавал 1 — то есть «очередь, всё в порядке».
Механизм у потребителя не работал ВООБЩЕ и рапортовал успех. Ровно 075:
проверка, не нашедшая предмета, обязана падать, а не молчать.

КОД ОТСУТСТВИЯ ВЫБРАН ВНЕ НАБОРА `gh`. Тот возвращает 1 и 2; совпадение
сделало бы «инструмента нет» неотличимым от находки — и это ровно то, что
здесь чинится.

ОСТАТОК КВОТЫ СПРАШИВАЕТСЯ ПРИ ПЕРВОМ ЖЕ ОТКАЗЕ, А НЕ ПО ПОДОЗРЕНИЮ (017).
Диагностика начинается с фактов о квоте, а не с гипотез о причинах, и решать по
тексту сообщения «похоже ли это на лимит» значит гадать ровно там, где есть
измерение. Запрос `gh api rate_limit` квоту НЕ расходует — асимметрия цены
полная: измерение бесплатно, час догадок нет. Замер держится один на процесс:
цена «look first» ограничена одним лишним вызовом, а следующим отказам факт
отдаётся с отметкой, когда он снят.

ИСЧЕРПАННАЯ КВОТА — ТРЕТИЙ ИСХОД, А НЕ НАХОДКА (058). До этой правки `gh`
отдавал 1, и «лимит кончился» было неотличимо от «ничего не нашлось»: вызывающий
читал отрицательный ответ как нормальный. Так и вышло 2 сентября — agent-pr упал
на первой команде, четыре изменения подряд не открылись, и никто не покраснел.
Теперь у исчерпания свой код, `failed()` его знает, и работа останавливается
вместо того, чтобы идти дальше на исчерпанной квоте.

Реализует правила каталога:
  075 — не нашёл gh — падает третьим исходом, а не зеленеет;
  090 — вызов площадки поднят в один модуль, а не скопирован вбок по скриптам;
  017 — остаток квоты МЕРИТСЯ при первом отказе, а не угадывается по тексту;
  058 — исчерпав квоту, работа останавливается: у исчерпания свой терминальный
        код, и повтор на исчерпанной квоте невозможен по построению;
  039 — исходов три, и третий не растворяется во втором.
"""

from __future__ import annotations

import json
import subprocess

#: Код, которым сообщается «инструмента нет». Не из набора кодов gh.
NO_GH = 127
#: Код, которым сообщается «квота исчерпана». Тоже вне набора кодов gh (1 и 2) и
#: отличен от NO_GH: «инструмента нет» чинит человек установкой, «квота кончилась»
#: — ожиданием окна, и путать их значит советовать не то.
QUOTA_OUT = 126

#: Что в ответе площадки означает исчерпание. Список нужен НЕ для решения —
#: решает измерение, — а для того, чтобы понять, стоит ли вообще мерить: ответ
#: 404 про квоту ничего не говорит. Вторичный лимит назван отдельно: он приходит
#: с другим текстом и лечится так же — остановкой.
ИСЧЕРПАНИЕ = ("rate limit exceeded", "secondary rate limit",
              "have exceeded a secondary rate limit", "403")

#: Замер держится один на процесс: «смотреть первым шагом» не значит «смотреть
#: на каждом». None — ещё не мерили.
_замер: tuple[str, bool] | None = None
#: Что сказать человеку. Причина называется целиком, а не «ошибка вызова».
NO_GH_WHY = ("нет команды gh — поставьте GitHub CLI либо задайте PATH. "
             "Механизм без неё не работает и не должен зеленеть")


def остаток() -> tuple[str, bool]:
    """Факты о квоте и признак «исчерпана». Запрос квоту НЕ расходует.

    Возвращает строку со счётчиками — у каждого свой остаток и своё время
    сброса, и время сброса косвенно говорит, КТО тратил окно, — плюс признак
    того, что хотя бы один счётчик на нуле.
    """
    try:
        done = subprocess.run(  # noqa: S603 — аргументы свои
            ["gh", "api", "rate_limit"],
            capture_output=True, text=True, encoding="utf-8")
    except OSError as e:
        return f"остаток не измерен: {NO_GH_WHY} ({e.strerror or e})", False
    if done.returncode != 0:
        # ЧЕСТНЕЕ СКАЗАТЬ «НЕ ИЗМЕРЕН», ЧЕМ ПОДСТАВИТЬ НОЛЬ: неизмеренное,
        # выданное за измеренное, — это гипотеза в одежде факта (037).
        return ("остаток не измерен: gh api rate_limit ответил "
                f"{done.returncode}"), False
    try:
        данные = json.loads(done.stdout)["resources"]
    except (ValueError, KeyError, TypeError) as e:
        return f"остаток не измерен: ответ rate_limit не разобрать — {e}", False
    части, пусто = [], False
    for имя in ("core", "graphql", "search"):
        счётчик = данные.get(имя)
        if not isinstance(счётчик, dict):
            continue
        было, всего = счётчик.get("remaining"), счётчик.get("limit")
        части.append(f"{имя} {было}/{всего}")
        if было == 0:
            пусто = True
    if not части:
        return "остаток не измерен: в ответе rate_limit нет счётчиков", False
    return "остаток квоты: " + " · ".join(части), пусто


def run(*args: str) -> tuple[int, str]:
    """Код возврата и вывод `gh`. Отсутствие gh и исчерпание квоты — тоже исходы.

    При ОТКАЗЕ к сообщению приписываются факты о квоте: диагностика начинается
    с них, а не с гипотез о причинах (017). Меряется один раз на процесс.
    """
    global _замер
    try:
        done = subprocess.run(["gh", *args], capture_output=True, text=True, encoding="utf-8")
    except OSError as e:
        return NO_GH, f"{NO_GH_WHY} ({e.strerror or e})"
    вывод = (done.stdout or done.stderr).strip()
    if done.returncode == 0:
        return 0, вывод

    # ── отказ: сначала факт о квоте, потом суждение ────────────────────────
    впервые = _замер is None
    if впервые:
        _замер = остаток()
    факт, пусто = _замер
    когда = "" if впервые else " (замер этого процесса)"
    похоже = any(м in вывод.lower() for м in ИСЧЕРПАНИЕ)
    if пусто or (похоже and "не измерен" in факт):
        # Исчерпание доказано измерением; либо измерить не удалось, а ответ
        # площадки говорит о лимите — тогда останавливаемся тоже: работа на
        # возможно исчерпанной квоте оставляет систему в несогласованном
        # состоянии, и это хуже простоя (058).
        return QUOTA_OUT, f"{вывод}\n{факт}{когда}"
    return done.returncode, f"{вывод}\n{факт}{когда}"


def failed(code: int) -> bool:
    """Вызов не отработал — это третий исход, а не находка."""
    return code in (NO_GH, QUOTA_OUT)
