#!/usr/bin/env python3
"""Навыки окна и плагина названы списком, и каждый несёт форму, по которой его позовут.

ЗАЧЕМ ОТДЕЛЬНЫЙ ГЕЙТ, ЕСЛИ НАВЫК УЖЕ ПРОВЕРЯЕТ `check_bindings.py`. Тот
спрашивает навык только тогда, когда его НАЗВАЛ ответ каталога — полем `skill`
у какого-нибудь правила. Навык, заведённый в дерево и не названный ни одним
ответом, не спрашивал никто: площадка его позовёт, а гейт о нём не знает.
Замер на заведении: навыков в дереве появляется первый, ответов с полем `skill`
ноль — то есть без этой проверки у навыка каталога не было бы проверки вовсе.

Гейт заведён ВМЕСТЕ с первым навыком, а не раньше: без предмета он отвечает
третьим исходом (075), и раньше навыка в конвейере стоять не мог бы.

ЧТО ПРОВЕРЯЕТСЯ.

  • у каждого места навыков один список — навыки окна названы таблицей в
    `.claude/skills/README.md`, навыки плагина — в `plugins/<имя>/README.md`,
    — и он сходится с деревом в обе стороны: названный навык существует,
    существующий назван. Места два, потому что читателей два: навыки плагина
    уходят к потребителю и не ссылаются на пути нашего дерева (076); форма у
    них одна, и сверяет её этот гейт, а не второй (214). Плагин без списка
    или без навыков — находка.
    Строка списка повторяться не может: два упоминания одного имени — это
    уже два списка;
  • у списка назван читатель из закрытого словаря `check_readers.py`: сам тот
    гейт скрытые папки не обходит, и без этой строки документ остался бы без
    читателя молча (021);
  • у каждого навыка `SKILL.md` с заголовком, `name` совпадает с именем
    каталога, `description` непусто — это спрашивает `check_bindings`, и здесь
    зовётся ЕГО разбор, а не второй: два разбора одного заголовка разошлись бы
    на первом же блочном скаляре. Пустое описание не мелочь: окно его не
    позовёт никогда, и навык лежит в дереве и выглядит механизмом, не будучи
    им (183);
  • у каждого навыка есть строка читателя и все разделы заготовки
    `templates/skill-template.md`: «зачем» с инцидентом, «что сделать» и
    граница «чего навык НЕ делает». Разделы берутся из самой заготовки, а не
    перечисляются здесь — заготовку, которой не пользуешься сам, отличить от
    разошедшейся нечем (155, 197).

ЧЕГО ЗДЕСЬ НЕТ — И ЭТО ГРАНИЦА, А НЕ УПУЩЕНИЕ. Сработал ли навык и верно ли
его суждение: навык не краснеет, его срабатывание — выбор модели по описанию.
Применимо ли правило, на которое навык ссылается: это спрашивает ревью по
разделу «Применимость» (204), а машина видит только, что ссылка цела
(`check_links.py`). Гейт держит, что ВОПРОСЫ заготовки заданы, а не то, как на
них ответили, — тот же приём, что у 182: от немашинного требования отделена
его машинная половина.

Реализует правила каталога:
  022 — список навыков один, остальные документы на него ссылаются;
  155 — разделы навыка сверяются с заготовкой, которую каталог раздаёт;
  197 — издатель заготовки навыка пользуется ею сам, и сверяет тем же гейтом;
  021 — у списка навыков назван читатель;
  075 — нет каталога навыков, списка или заготовки — отказ, а не чистый прогон;
  158 — третий исход называет предмет: какой из трёх файлов не прочитался.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# Разбор заголовка навыка один на каталог — у гейта ответа. Своя копия
# разошлась бы с ним молча, и первым на блочном скаляре: его чинили трижды
# (ревью #497, #500, #501), и каждая починка шла бы теперь в двух местах.
from check_bindings import навык_в_дереве
# Строка читателя и словарь — тоже чужие: читателей закрытый список, и второй
# словарь разошёлся бы с первым на первом же новом читателе.
from check_readers import EN, HEAD, LINE_RE, READERS, reader_of
# Где лежат плагины, знает гейт витрины: папка плагина — его имя там же (035).
from check_plugins import PLUGINS

ROOT = Path(__file__).resolve().parent.parent

SKILLS = Path(".claude") / "skills"
LIST = SKILLS / "README.md"
TEMPLATE = Path("templates") / "skill-template.md"

#: Строка списка навыков: первая ячейка — имя навыка в обратных кавычках.
#: Таблицы с другими первыми ячейками (пути, команды) строками списка не
#: считаются: в том же документе законно стоят и они.
ROW_RE = re.compile(r"^\|\s*`([a-z0-9][a-z0-9-]*)`\s*\|")
#: Форма `SKILL.md` в заготовке — блок ```markdown … ```, и разделы берутся из
#: него, а не из самого документа заготовки: у того свои заголовки о гейте.
FORM_RE = re.compile(r"^```markdown\n(.*?)^```$", re.S | re.M)
#: Заголовок раздела второго уровня — строка целиком (141).
SECTION_RE = re.compile(r"^## .+$", re.M)
#: Заголовок `SKILL.md` — между двумя `---`; строка читателя ищется ПОСЛЕ него.
FRONT_RE = re.compile(r"\A---\r?\n.*?\r?\n---\s*(?:\r?\n|\Z)", re.S)


def listed(text: str) -> list[str]:
    """Имена навыков из таблицы списка, в порядке документа, с повторами."""
    return [m.group(1) for m in (ROW_RE.match(line) for line in text.splitlines())
            if m]


def sections(template: str) -> list[str]:
    """Разделы, которые заготовка требует у каждого `SKILL.md`."""
    form = FORM_RE.search(template)
    return SECTION_RE.findall(form.group(1)) if form else []


def body_reader(text: str) -> str | None:
    """Читатель навыка: строка объявления в первых строках ПОСЛЕ заголовка.

    `reader_of` читает первые строки файла, а у `SKILL.md` их занимает
    заголовок площадки. Строка объявления и окно поиска — те же, что у
    `check_readers`: иначе «объявлен» значило бы здесь другое, чем там.
    """
    body = FRONT_RE.sub("", text, count=1)
    for line in body.splitlines()[:HEAD]:
        m = LINE_RE.match(line.strip())
        if m and m.group(2).strip():
            name = m.group(1).strip("*` ")
            return EN.get(name, name)
    return None


def места(root: Path) -> list[tuple[Path, Path]]:
    """Где лежат навыки и какой список их называет — пути от корня.

    ДВА ЧИТАТЕЛЯ, ОДНА ФОРМА. Навыки окна зовёт окно этого репозитория, навыки
    плагина — окно проекта, поставившего плагин. Лежат они порознь, потому что
    вторые уходят к потребителю и не могут ссылаться на пути нашего дерева
    (076), а форма у них одна — заготовка, которую каталог раздаёт, — и
    сверяет их один гейт, а не два (214).
    """
    вышло = [(SKILLS, LIST)]
    плагины = root / PLUGINS
    if плагины.is_dir():
        for плагин in sorted(п for п in плагины.iterdir() if п.is_dir()):
            имя = плагин.relative_to(root)
            вышло.append((имя / "skills", имя / "README.md"))
    return вышло


def сверить_место(root: Path, папка: Path, список: Path,
                  required: list[str]) -> tuple[int, int, list[str]]:
    """Список против дерева и форма каждого навыка одного места.

    Возвращает: сколько названо в списке, сколько лежит в дереве, находки.
    """
    problems: list[str] = []
    folder, index = root / папка, root / список
    tree = sorted(p.name for p in folder.iterdir() if p.is_dir()) \
        if folder.is_dir() else []
    if not index.is_file():
        problems.append(f"{список.as_posix()} нет — навыки в {папка.as_posix()} "
                        "не названы списком, и сверять дерево не с чем")
        return 0, len(tree), problems
    if not tree:
        problems.append(f"{папка.as_posix()}: навыков нет — место, которое "
                        "ничего не отдаёт, выглядит механизмом, не будучи им")
    names = listed(index.read_text(encoding="utf-8"))

    reader, question = reader_of(index)
    if reader not in READERS or not question:
        problems.append(
            f"{список.as_posix()}: не назван читатель из словаря {sorted(READERS)} "
            "с вопросом. check_readers.py скрытые папки не обходит, и спросить "
            "это, кроме здесь, некому")

    seen: set[str] = set()
    for name in names:
        if name in seen:
            problems.append(
                f"{список.as_posix()}: «{name}» назван дважды — две строки одного "
                "навыка расходятся при первой правке")
        seen.add(name)
        if name not in tree:
            problems.append(
                f"{список.as_posix()} называет «{name}», а каталога "
                f"{(папка / name).as_posix()} нет. За названным навыком придут "
                "и не найдут ничего")

    for name in tree:
        if name not in seen:
            problems.append(
                f"{(папка / name).as_posix()} есть, а в {список.as_posix()} не "
                "назван. Навык, о котором молчит список, человек не позовёт — "
                "а окно позовёт, не сказав никому")
        missing = навык_в_дереве(name, root, папка)
        if missing:
            problems.append(f"{(папка / name).as_posix()}: {missing}")
            continue
        text = (folder / name / "SKILL.md").read_text(encoding="utf-8")
        who = body_reader(text)
        if who not in READERS:
            problems.append(
                f"{(папка / name).as_posix()}/SKILL.md: под заголовком нет "
                "строки «> **Читатель:** <кто> — <когда зовут>» с читателем из "
                f"словаря {sorted(READERS)}")
        present = set(SECTION_RE.findall(text))
        for section in required:
            if section not in present:
                problems.append(
                    f"{(папка / name).as_posix()}/SKILL.md: нет раздела "
                    f"«{section}» — его требует {TEMPLATE.as_posix()}, "
                    "заготовка, которую каталог раздаёт и обязан держать у "
                    "себя сам (155)")
    return len(names), len(tree), problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT,
                        help="корень каталога; по умолчанию сам этот репозиторий")
    args = parser.parse_args(argv)
    root: Path = args.root
    folder, index, template = root / SKILLS, root / LIST, root / TEMPLATE

    # ── исход 2 ────────────────────────────────────────────────────────────
    if not folder.is_dir():
        print(f"проверка не отработала: нет {folder} — навыков нет, и гейт без "
              "предмета не зеленеет (075)", file=sys.stderr)
        return 2
    if not index.is_file():
        print(f"проверка не отработала: нет {index} — списка навыков, с которым "
              "сверяется дерево", file=sys.stderr)
        return 2
    if not template.is_file():
        print(f"проверка не отработала: нет {template} — заготовки, из которой "
              "берутся разделы навыка", file=sys.stderr)
        return 2
    names = listed(index.read_text(encoding="utf-8"))
    if not names:
        print(f"проверка не отработала: в {index} не разобралось ни одной строки "
              "списка «| `имя` | …». Это ошибка разбора, а не пустой список: "
              "каталог навыков существует", file=sys.stderr)
        return 2
    required = sections(template.read_text(encoding="utf-8"))
    if not required:
        print(f"проверка не отработала: в {template} не нашлось формы "
              "```markdown … ``` с разделами `## …` — сверять навыки не с чем",
              file=sys.stderr)
        return 2

    # ── исход 1 ────────────────────────────────────────────────────────────
    problems: list[str] = []
    всего_в_списках = всего_в_дереве = 0
    for папка, список in места(root):
        названо, в_дереве, найдено = сверить_место(root, папка, список, required)
        problems += найдено
        всего_в_списках += названо
        всего_в_дереве += в_дереве

    if problems:
        print("навыки разошлись со списком или с заготовкой:",
              file=sys.stderr)
        for p in problems:
            print(f"  • {p}", file=sys.stderr)
        return 1

    print(f"навыки в порядке: мест {len(места(root))}, в списках "
          f"{всего_в_списках}, в дереве {всего_в_дереве}, у каждого заголовок, "
          f"читатель и разделов заготовки {len(required)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
