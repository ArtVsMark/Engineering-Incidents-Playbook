#!/usr/bin/env python3
"""Производное, которым владеет прогон, в изменении не едет.

ЗАПРЕТ БЫЛ, МЕХАНИЗМА НЕ БЫЛО. Ядро говорит дословно: «НЕ править
export/where.* руками — это сводка ответов потребителей, её пересобирает
scripts/aggregate_bindings.py». Запрет читался как «не правь текстом», и
пересборка сборщиком под него не попадала. Цена измерена: 3 сентября сводка
дала ТРИ конфликта за смену — изменения #280 и #285 против плановой пересборки
#284, — и каждый разрешался одинаково, прогоном сборщика поверх слитого.

ПОЧЕМУ ЭТОТ ГЕЙТ ОДНАЖДЫ УЖЕ БЫЛ ОТОЗВАН. Первая его редакция отвергала любое
изменение, добавляющее правило: `aggregate_bindings --check` тогда ТРЕБОВАЛ от
такого изменения пересобранную сводку, и два гейта требовали противоположного.
Это 146 в чистом виде — гейт зелёный, аккуратный и держащий не то утверждение,
ради которого заведён; изменение было закрыто с разбором, а не подпёрто.

Теперь причина устранена: у сводки объявлен ОДИН писатель — прогон
`consumers-sync`, просыпающийся на каждый толчок в общую ветку, — а шаг
изменения зовёт `--check --not-my-summary` и свежести не требует. Гейт стал
верен ровно тогда, когда перестало быть верным его прежнее основание.

ТО ЖЕ РЕШЕНИЕ УЖЕ ПРИНИМАЛОСЬ — ДЛЯ ЗНАЧКОВ. Они живут на отдельной ветке
именно потому, что «гейт свежести значка требовал пересборки от каждого
изменения и краснел на верной работе». Здесь предмет тот же, а ответ был
другим: сводка осталась в общей ветке, и её пересобирали обе стороны.

ГРАНИЦА, И ОНА НЕ ФОРМАЛЬНАЯ. Если изменение правит САМ СБОРЩИК, новый вид
сводки принадлежит ему: без неё нельзя ни отревьюить смену формата, ни
проверить её. Запрет действует на изменение, которое сборщик не трогает.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.

Реализует правила каталога:
  125 — производный файл не может быть хранилищем: у него один владелец;
  160 — производное, обновляемое чаще изменений, живёт вне пути изменений;
  068 — список разрешительный: освобождённая ветка названа поимённо и с причиной;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  051 — отказ на достоверном: файл в диапазоне — факт, а не подозрение.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: Производные, которыми владеет прогон, и кто именно их пересобирает.
#: Разрешительно и с причиной у каждой строки: список «всё, кроме…» завтра
#: пропустил бы новый файл (068).
OWNED_BY_JOB = {
    "export/where.md": "badges.yml → ветка `badges`: сводка живёт там же, где "
                       "картинка витрины, и в общей ветке её нет вовсе",
    "export/where.json": "badges.yml → ветка `badges`: тот же владелец и то же "
                         "место",
}

#: Ветка, на которой эти файлы и есть предмет работы. Одна и названа поимённо.
#: ИСКЛЮЧЕНИЙ БОЛЬШЕ НЕТ, И ЭТО ЗАМЕР, А НЕ УЖЕСТОЧЕНИЕ. Их было два: ветка
#: пересборки и «правка сборщика везёт новую сводку с собой». Пока файл лежал в
#: общей ветке, оба были осмысленны — сводку кто-то должен был обновлять. Теперь
#: файла в дереве нет вовсе, и любое его появление означает одно: он вернулся.
#:
#: Половинчатая починка стоила ровно этого. 3 сентября сводке объявили одного
#: писателя, оставив её в дереве: рутинные конфликты исчезли, а предмет остался
#: — писателей снова стало двое, как только правило поехало вместе с ответом о
#: нём, и конфликт вернулся тем же вечером на изменении #329.


def changed(rng: str, root: Path) -> tuple[list[str] | None, str]:
    """Пути, тронутые диапазоном. None — спросить не удалось."""
    # УДАЛЕНИЕ ПОД ОХРАНУ НЕ ПОПАДАЕТ, И ЭТО ПОЙМАЛ ТЕСТ. Гейт запрещает
    # ДЕРЖАТЬ производное в дереве; изменение, которое его оттуда убирает,
    # делает ровно то, чего гейт хочет, — и первая редакция отвергала его,
    # потому что путь стоит в разнице в обе стороны. Ложный отказ на верной
    # работе (051), и притом на единственной работе, которая гейт удовлетворяет.
    # `--diff-filter=d` — строчная буква исключает удалённые.
    done = subprocess.run(["git", "-C", str(root), "diff", "--name-only", "-z",
                           "--diff-filter=d", rng],
                          capture_output=True, text=True, encoding="utf-8")
    if done.returncode != 0:
        return None, (done.stderr or "").strip()
    # По NUL, а не по строкам: имя с не-ASCII символами git отдаёт
    # экранированным, и путь молча выпадает из проверки (правило 165).
    return [p for p in done.stdout.split("\0") if p], ""


def findings(paths: list[str], branch: str, tracked: set[str] | None = None) -> list[str]:
    """Производные, вернувшиеся в дерево общей ветки.

    ДВА ПРЕДМЕТА, А НЕ ОДИН. Путь в разнице означает, что файл везут изменением;
    путь в списке отслеживаемых — что он лежит в дереве и без изменения.
    Второе важнее: `.gitignore` при слиянии не спрашивают, и файл возвращается
    молча. Ровно та же пара стоит у картинок витрины (`check_showcase.py`).
    """
    вернулись = {p for p in paths if p in OWNED_BY_JOB}
    вернулись |= {p for p in (tracked or set()) if p in OWNED_BY_JOB}
    return sorted(вернулись)


def tracked_paths(root: Path) -> set[str]:
    """Что git отслеживает в дереве. Пусто — спросить не удалось."""
    done = subprocess.run(  # noqa: S603 — аргументы свои
        ["git", "-C", str(root), "ls-files", "-z", "--", "export/"],
        capture_output=True, text=True, encoding="utf-8")
    if done.returncode != 0:
        return set()
    return {p for p in done.stdout.split("\0") if p}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--range", default="origin/main...HEAD",
                        help="диапазон изменения")
    parser.add_argument("--branch", default="", help="имя ветки изменения")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args(argv)

    paths, err = changed(args.range, args.root)
    # ── исход 2 ────────────────────────────────────────────────────────────
    if paths is None:
        print(f"проверка не отработала: диапазон {args.range} не разобран — "
              f"{err or 'git промолчал'}. Мелкий клон или ветка без основания",
              file=sys.stderr)
        return 2

    found = findings(paths, args.branch, tracked_paths(args.root))
    # ── исход 1 ────────────────────────────────────────────────────────────
    if found:
        print("производные вернулись в общую ветку, а место им на `badges`:",
              file=sys.stderr)
        for p in found:
            print(f"  • {p} — {OWNED_BY_JOB[p]}", file=sys.stderr)
        print("\n  Уберите их из дерева: `git rm --cached "
              + " ".join(found) + "`.\n  Собирает и публикует их badges.yml на "
              "ветке `badges`, рядом с картинкой витрины; читатели ходят туда.\n"
              "  Замер: шесть конфликтов за одну смену, и все — в этих файлах; "
              "ни один не был поломкой.", file=sys.stderr)
        return 1

    print(f"производные в порядке: тронуто путей {len(paths)}, "
          f"чужого владения нет ({len(OWNED_BY_JOB)} под охраной)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
