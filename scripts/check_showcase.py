#!/usr/bin/env python3
"""Витрина отвечает на объявленный набор вопросов — или называет, чего нет.

ЗАЧЕМ НАБОР ОДИН НА ВСЕ ПРОЕКТЫ. Замер по пяти публичным проектам (#105): из
восьми вопросов пять отвечает один грейдер, остальные четыре проекта — ни
одного. Пока набор у каждого свой, проекты не сравнить, и то, что один
перестал отвечать, не заметит никто. Это 022 в применении к витрине.

ЗАЧЕМ НАЗЫВАТЬ ОТСУТСТВУЮЩИЙ ВОПРОС. Значок, которого нет, и значок, который
застыл, с витрины НЕОТЛИЧИМЫ. «У нас нет покрытия, потому что нет кода» и
«механизм покрытия сломался и молчит» — разные вещи, и разница видна только
если пробел назван (правила 046, 075). Поэтому у каждого вопроса набора либо
живой значок, либо строка `absent` с причиной; пропуск не проходит.

ЧЕГО ЭТОТ ГЕЙТ НЕ ДЕЛАЕТ. Он не судит, верное ли число в значке, и не судит
его свежесть: значки живут на ветке `badges`, в дереве общей ветки их нет.
Он проверяет, что на каждый объявленный вопрос ЕСТЬ ответ и что живой ответ
назван в витрине — значок, который никто не показывает, отвечает в пустоту.

У ВОПРОСА ЕСТЬ АДРЕСАТ, И ОТВЕТ ЗАВИСИТ ОТ НЕГО. Поле `for` делит набор
надвое. `visitor` — вопрос посетителя витрины, «стоит ли это брать»: ответ ему
значок либо `absent` с причиной. `maintainer` — вопрос сопровождающего,
«здоров ли проект»: значок ему не нужен и вреден — число дёргается от каждого
изменения и шумит там, куда смотрят один раз, — зато обязателен `where`,
РАЗРЕШИМЫЙ АДРЕС живого источника.

ПОЧЕМУ «ЗНАЧКА НЕТ» ПЕРЕСТАЛО БЫТЬ ОТВЕТОМ СОПРОВОЖДАЮЩЕМУ. До схемы 1.1 у
трёх вопросов из десяти стояло `absent`: «значка нет; получается прогоном
`pytest -q`». Причина верная, а ответ — прозой: источник назван человеку и не
проверяется ничем. Разошёлся бы он молча, ровно как декларация без ревизии
(044). Теперь адрес сверяется с деревом тем же приёмом, что и `where` в ответе
каталога: несуществующий путь — отказ.

ЗДЕСЬ БОЛЬШЕ НИЧЕГО НЕ СОБИРАЕТСЯ. Гейт вычислял три значка сам: тесты,
тестовые модули и число проверок. Все три сняты с витрины — они отвечают на
вопрос СОПРОВОЖДАЮЩЕГО, а не посетителя, и снаружи их не читал никто: витрина
профиля берёт у каждого проекта version, ci, coverage и package, и этих трёх
в её списке нет. Оставить сборку без витрины было бы значком, который отвечает
в пустоту, — то самое, что этот гейт и запрещает.

Запуск:  python scripts/check_showcase.py [--root <корень>]
Коды:    0 чисто · 1 есть находки · 2 проверка не отработала

Реализует правила каталога:
  009 — считаются уникальные вопросы набора, а не строки витрины;
  096 — набор вопросов витрины живёт в .rules/showcase.json — отдельно от ответа каталога;
  160 — артефакт витрины не возвращается в дерево общей ветки: он
        пересобирается чаще, чем идут изменения, и место ему на ветке;
  106 — витрина не показывает то, на что ответить нечем: у вопроса либо живой
        значок, либо названная причина его отсутствия;
  021 — у вопроса назван читатель, и ответ ему разный: посетителю значок,
        сопровождающему адрес источника;
  044 — премиса проверяется прежде, чем вердикту поверят: адрес источника
        сверяется с деревом, а не принимается на слово;
  049 — состояние выводится из живого артефакта: у вопроса сопровождающего
        обязан быть адрес, по которому число живёт, а не рецепт для человека;
  175 — утверждение «предмета нет» сверяется с деревом: у прозы есть
        подкласс, сводимый к наличию объекта, и он устаревает молча.
        Асимметрия односторонняя — предмет найден отказ, не найден молчание.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SET = ROOT / ".rules" / "showcase.json"
SHOWCASES = ("README.md", "README.en.md")

#: Артефакты витрины, чьё место — ветка `badges`, а не дерево общей ветки.
#: Игнор их накрывает, но при слиянии его не спрашивают: `git checkout --theirs`
#: вернул сюда четыре значка разом, и заметить это было нечем (правило 160).
BADGES_DIR = ".github/badges"

#: Адресаты вопроса. Список закрытый: «кому это» с открытым словарём означает
#: столько ответов, сколько авторов (правило 068).
READERS = ("visitor", "maintainer")
#: Путь в адресе источника. Тот же образец, что у ревизии ответа каталога:
#: вторая формулировка «что считать путём» разошлась бы с первой (022).
PATH_RE = re.compile(r"[\w./-]+\.(?:py|yml|yaml|json|md|txt)")


def badges_in_tree(root) -> list[str]:
    """Значки и картинки, вернувшиеся в дерево общей ветки.

    ПОЧЕМУ ЭТО СТОРОЖ, А НЕ ИГНОР. `.gitignore` отвечает на вопрос «добавлять
    ли новый файл», и на слиянии его никто не спрашивает. Возврат происходит
    именно там: конфликт разрешают, `--theirs` тянет файл обратно, и он снова
    начинает давать коммит на каждый пересбор.

    ГРАНИЦА. Смотрятся ОТСЛЕЖИВАЕМЫЕ файлы, а не лежащие на диске: прогон
    рисует их локально и обязан это делать — он кладёт их на свою ветку.
    """
    import subprocess
    try:
        out = subprocess.run(["git", "-C", str(root), "ls-files", "-z", BADGES_DIR],
                             capture_output=True, text=True, encoding="utf-8", check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return []
    return sorted(line for line in out.split("\0") if line.strip())


#: УТВЕРЖДЕНИЕ «ПРЕДМЕТА НЕТ» СВЕРЯЕТСЯ С ДЕРЕВОМ (правило 175). Проза целиком
#: непроверяема, и гейт её не трогает; но у неё есть подкласс, сводимый к
#: наличию объекта, — и он обязан проверяться, потому что устаревает молча.
#: Инцидент соседа: ответ «проект не выпускался ни разу» пережил ДВА выпуска и
#: звучал уверенно, при зелёном гейте формы.
ABSENCE_PREFIX = "предмета нет"

#: Чем опровергается каждое такое утверждение. Ключ — вопрос набора, значение —
#: пути, существование которых делает ответ ложным. Список разрешительный: для
#: вопроса без пробы гейт не молчит, а НАЗЫВАЕТ её отсутствие (046, 154).
#:
#: ПЕРВАЯ ЖЕ ПРОБА ОКАЗАЛАСЬ ГРУБОЙ, и это записано, а не заглажено. Она
#: опровергала «в PyPI не публикуется» наличием `pyproject.toml` — и покраснела
#: на верном ответе: манифест у каталога есть, он держит обвязку тестов и прямо
#: говорит «пакетом не публикуется». Утверждение было о ПУБЛИКАЦИИ, а проба
#: смотрела на существование манифеста, то есть проверяла не тот предмет (175
#: об этом и предупреждает: «предмета нет» и «своего показателя нет» — разные
#: ответы, и гейт, их не различающий, краснеет на верном).
REFUTED_BY: dict[str, tuple[str, ...]] = {
    # Публикацию опровергает ПРОГОН, который её делает, а не наличие манифеста.
    "pypi": (".github/workflows/publish.yml", ".github/workflows/pypi.yml"),
}


def refuted(qid: str, root: Path) -> str:
    """Опровержение утверждения «предмета нет», если оно нашлось.

    АСИММЕТРИЯ НАМЕРЕННАЯ: предмет найден — отказ; предмет не найден — молчание.
    «Не нашли» и «нет» — разные ответы, и в мелком клоне облачного окна первое
    происходит постоянно (039, 175).
    """
    for путь in REFUTED_BY.get(qid, ()):
        if (root / путь).exists():
            return путь
    return ""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT,
                    help="корень дерева; по умолчанию сам репозиторий")
    args = ap.parse_args(argv)
    root: Path = args.root
    declared = root / ".rules" / "showcase.json"

    # ── исход 2 ────────────────────────────────────────────────────────────
    try:
        doc = json.loads(declared.read_text(encoding="utf-8"))
        questions = doc["questions"]
    except (OSError, ValueError, KeyError) as e:
        print(f"проверка не отработала: набор вопросов витрины не прочитан — {e}",
              file=sys.stderr)
        return 2
    if not questions:
        print(f"проверка не отработала: {root / SET} не называет ни одного "
              "вопроса — витрина без вопросов не витрина", file=sys.stderr)
        return 2

    shown = "\n".join((root / name).read_text(encoding="utf-8")
                      for name in SHOWCASES if (root / name).exists())
    if not shown:
        print(f"проверка не отработала: под {root} нет ни одной витрины из "
              f"{list(SHOWCASES)} — показывать ответы негде", file=sys.stderr)
        return 2

    # ── исход 1 ────────────────────────────────────────────────────────────
    problems: list[str] = []
    unchecked: list[str] = []
    for q in questions:
        qid, ask = q.get("id", "?"), q.get("ask", "")
        badge, absent, where = q.get("badge"), q.get("absent"), q.get("where")

        # ── адресат: без него неизвестно, какой ответ считать ответом ──────
        reader = q.get("for")
        if reader not in READERS:
            problems.append(
                f"{qid} «{ask}»: не назван адресат. `for` — одно из "
                + " · ".join(READERS)
                + ". Без него «значка нет» и «источник назван» неразличимы")
            continue

        # ── вопрос сопровождающего: адрес источника, а не значок ───────────
        if reader == "maintainer":
            if badge:
                problems.append(
                    f"{qid}: вопросу сопровождающего отвечает значок. Число, "
                    "которое дёргается от каждого изменения, шумит там, куда "
                    "смотрят один раз, — ответ ему адрес источника")
                continue
            if not where:
                problems.append(
                    f"{qid} «{ask}»: нет `where`. «Значка нет» сопровождающему "
                    "не ответ: источник, названный прозой, не проверяется "
                    "ничем и расходится молча (044)")
                continue
            найдено = PATH_RE.findall(where)
            if not найдено:
                problems.append(
                    f"{qid}: в `where` нет ни одного разрешимого пути — это "
                    "рецепт для человека, а не адрес живого источника (049)")
                continue
            пропали = [p for p in найдено if not (root / p).exists()]
            if пропали:
                problems.append(
                    f"{qid}: источник назван, а его нет — "
                    + ", ".join(пропали)
                    + ". Декларация разошлась с деревом (044)")
            continue

        # ── вопрос посетителя: значок либо названная причина ───────────────
        if where:
            problems.append(
                f"{qid}: `where` у вопроса посетителя. Посетитель не ходит в "
                "исходники — ему отвечает значок либо причина его отсутствия")
            continue
        if badge and absent:
            problems.append(f"{qid}: и значок, и причина отсутствия — ответ один")
            continue
        if not badge and not absent:
            problems.append(
                f"{qid} «{ask}»: ответа нет вовсе. Либо значок, либо строка "
                "absent с причиной — пропуск и отсутствие предмета обязаны "
                "выглядеть по-разному")
            continue
        if absent:
            if len(absent.strip()) < 20:
                problems.append(f"{qid}: причина отсутствия слишком коротка, "
                                "чтобы ею что-то объяснить")
            elif absent.strip().lower().startswith(ABSENCE_PREFIX):
                улика = refuted(qid, root)
                if улика:
                    problems.append(
                        f"{qid}: ответ утверждает «{ABSENCE_PREFIX}», а в дереве "
                        f"есть {улика}. Такое утверждение устаревает молча и "
                        "выглядит осознанным решением — хуже выдуманного числа "
                        "(175)")
                elif qid not in REFUTED_BY:
                    unchecked.append(qid)
            continue
        # Значок с отдельной ветки в этом дереве не лежит и лежать не должен:
        # она заводится ровно для того, чтобы пересборка значка не двигала
        # общую ветку. Требовать файл здесь значило бы требовать того, чего
        # быть не может, — ложный отказ (правило 097).
        if q.get("branch", "main") == "main" and not (root / badge).exists():
            problems.append(f"{qid}: значок {badge} объявлен, а файла нет — "
                            "витрина обещает ответ, которого не существует")
            continue
        if Path(badge).name not in shown:
            problems.append(f"{qid}: значок {badge} есть, но в витрине его "
                            "нет — ответ в пустоту")

    # ВЕРНУВШИЙСЯ АРТЕФАКТ — НАХОДКА, А НЕ МЕЛОЧЬ (правило 160). Игнор его
    # накрывает, но при слиянии не спрашивается: `--theirs` вернул сюда четыре
    # значка разом. А картинки витрины простояли в дереве с самого своего
    # появления, давая коммит в общую ветку на каждый пересбор — при том что
    # читаются они с ветки `badges`.
    for f in badges_in_tree(root):
        problems.append(
            f"{f}: артефакт витрины лежит в дереве общей ветки. Он "
            "пересобирается чаще, чем идут изменения, и потому даёт коммит на "
            "каждый пересбор; его место — ветка `badges`, откуда витрина его и "
            "читает (160)")

    # СВЕЖЕСТЬ ЗДЕСЬ НЕ ПРОВЕРЯЕТСЯ, И ЭТО РЕШЕНИЕ. Значки живут на ветке
    # `badges`, в дереве общей ветки их нет — сверять не с чем. Держать их в
    # `main` под гейтом значило бы требовать пересборки от каждого изменения:
    # за одно окно это дало конфликт на каждом слиянии и красное на общей
    # ветке не потому, что сломалось, а потому что число сдвинулось (051).
    # Свежесть держит badges.yml на каждый толчок в main.

    if problems:
        print("витрина отвечает не на весь объявленный набор:", file=sys.stderr)
        for p in problems:
            print(f"  • {p}", file=sys.stderr)
        print("\n  Значок, которого нет, и значок, который застыл, с витрины "
              "неотличимы.\n  Поэтому вопрос без предмета называется, а не "
              "опускается (правила 046, 075).", file=sys.stderr)
        return 1

    # ── исход 0 ────────────────────────────────────────────────────────────
    # ТРИ ГРУППЫ, А НЕ ДВЕ. Вопрос сопровождающего отвечен адресом источника,
    # и складывать его с «предмета нет» значило бы врать итогом (158): у него
    # предмет есть, просто не значок.
    live = sum(1 for q in questions if q.get("badge"))
    sourced = sum(1 for q in questions if q.get("where"))
    named = len(questions) - live - sourced
    for qid in unchecked:
        print(f"  · «{ABSENCE_PREFIX}» у вопроса {qid} ничем не опровергается — "
              "пробы нет, и утверждение держится словом (175)")
    print(f"витрина отвечает на весь набор: вопросов {len(questions)}, "
          f"живым числом {live}, адресом источника {sourced}, "
          f"названо без предмета {named}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
