#!/usr/bin/env python3
"""Ссылка на собственную ветку `badges` указывает на собранный файл.

Машинная половина правила 196. Само правило говорит о ПОРЯДКЕ: ссылка на
производное не уезжает в общую ветку раньше, чем производное нарисовано.
Порядок на изменении не проверяется ничем — событие, о котором идёт речь,
наступает ПОСЛЕ слияния, а в дереве изменения предмета нет и быть не должно
(160). Гейт «файл существует» на изменении краснел бы на каждой правке
витрины, а такую проверку приучаются пропускать (051).

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ ВМЕСТО ПОРЯДКА. Что каждая ссылка на собственную ветку
`badges` ведёт в файл, который прогон значков ТОЛЬКО ЧТО собрал. Проверка
стоит там, где оба предмета уже под рукой: текст витрины из общей ветки и
набор, уехавший на ветку.

ЧЕГО ОНА НЕ ЛОВИТ — И ЭТО ГРАНИЦА, А НЕ НЕДОРАБОТКА. Собственно «не пустить
вперёд»: нарушение обнаруживается не до, а сразу после слияния. Зелёное здесь
не значит «порядок соблюдён» — оно значит «сегодня всё, на что ссылается
витрина, собрано». Выигрыш в другом: красное приходит в минутах и адресовано
автору последнего изменения, а не всякому, кто однажды зайдёт на витрину.
Сегодня же оно не приходит вовсе.

НАБОР БЕРЁТСЯ У САМОЙ ВЕТКИ, а не из списка рядом и не из того, что собрал
один прогон. Второй список значков разошёлся бы с первым молча (022), и
`badges.yml` про это говорит дважды в собственных комментариях. А сверка с
одним лишь СОБРАННЫМ СЕЙЧАС дала бы ложное красное: пока нет тега схемы,
значков версии и выпуска этот прогон законно не строит, ветка при этом держит
прежние, и проверка краснела бы на верной работе (051, 039 — третий исход у
сборки значков объявлен). Поэтому вход у проверки — каталог, СОДЕРЖИМОЕ
КОТОРОГО и есть ветка: пути считаются относительно него.

АДРЕСА ДЕКОДИРУЮТСЯ, И ЭТО ЗАМЕР, А НЕ ПРЕДОСТОРОЖНОСТЬ. Восемь ссылок из
двадцати одной живут внутри параметра `url=` у shields.io, где адрес
URL-кодирован: сырым поиском они не находятся вовсе, и предмет правила 196
дважды был измерен меньше, чем он есть. Каждая строка читается дважды — как
есть и раскодированной.

ДВА ПРЕДМЕТА ЛЕЖАТ НА РАЗНЫХ ВЕТКАХ, И ЭТО ВИДНО В ЗАПУСКЕ. Витрина живёт в
общей ветке, набор — на `badges`, где ни витрины, ни скриптов нет вовсе.
Поэтому `badges.yml` снимает ветку в отдельный каталог и возвращается в общую:
проверка читает документы рабочего дерева, а ветку — по снимку.

Исходы:
  0 — каждая ссылка ведёт в собранное;
  1 — есть ссылка на путь, которого в собранном наборе нет;
  2 — проверка не отработала: нечего сверять либо не с чем.

Реализует правила каталога:
  196 — ссылка на производное не публикуется раньше самого производного:
        держится машинная половина — обнаружение сразу после;
  160 — производное живёт вне пути изменений, поэтому проверка стоит не на
        изменении, а на прогоне, который это производное и рисует;
  022 — набор собранного один: он читается у того, что уехало на ветку;
  005 — своё имя берётся у `origin`, а не вписывается константой;
  075 — ни одной ссылки на ветку не нашлось — это отказ разбора, а не чистый
        прогон: витрина без них не работает;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  158 — третий исход называет предмет: где искали и чего не нашли;
  140 — набор бьёт в оба конца: ссылка на несобранное находится, ссылка на
        собранное, чужой адрес и относительная ссылка — нет;
  051 — отвергается достоверное: путь либо есть в уехавшем наборе, либо нет.

Запуск:
  python scripts/check_badges_published.py --published <снимок ветки>
  python scripts/check_badges_published.py --selftest
"""

from __future__ import annotations

import argparse
import re
import sys
import tempfile
from difflib import get_close_matches
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))

from check_own_name import own_slug  # noqa: E402

#: Ветка, на которой живут производные каталога. Одна, названа поимённо.
BRANCH = "badges"

#: Имя узла остаётся буквальным и в URL-кодированной форме — см. докстринг.
HOST = "raw.githubusercontent.com"

#: Путь внутри ветки: то, что раскодированный адрес продолжает после имени
#: ветки. Класс узкий намеренно — он сам обрывается на `&`, `)`, кавычке и
#: прочем, чем адрес кончается в разметке, и разбирать эти границы отдельно
#: не приходится.
ССЫЛКА = re.compile(
    re.escape(HOST) + r"/([^/\s]+)/([^/\s]+)/" + BRANCH + r"/([A-Za-z0-9._/-]+)")

#: Обход не втягивает служебное (119).
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".pytest_cache"}


def ссылки(текст: str) -> list[tuple[int, str, str]]:
    """Ссылки на ветку в тексте: (строка, «владелец/имя», путь внутри ветки)."""
    out: list[tuple[int, str, str]] = []
    for номер, строка in enumerate(текст.split("\n"), 1):
        # Дважды: как есть и раскодированной. Дубли снимаются множеством —
        # ссылка, читаемая обеими формами, находка одна, а не две.
        for форма in {строка, unquote(строка)}:
            for m in ССЫЛКА.finditer(форма):
                # Точка в конце предложения адресу не принадлежит.
                out.append((номер, f"{m.group(1)}/{m.group(2)}",
                            m.group(3).rstrip(".")))
    return sorted(set(out))


def собранное(каталог: Path) -> tuple[set[str], str]:
    """Пути внутри ветки — по СОДЕРЖИМОМУ каталога, который её и составляет."""
    if not каталог.is_dir():
        return set(), f"нет каталога собранного: {каталог}"
    пути = {p.relative_to(каталог).as_posix()
            for p in каталог.rglob("*")
            if p.is_file() and not SKIP_DIRS & set(p.parts)}
    if not пути:
        return set(), f"в каталоге собранного ни одного файла: {каталог}"
    return пути, ""


def из_дерева(корень: Path) -> list[tuple[str, str]]:
    """Документы рабочего дерева: (путь, текст). Двоичное пропускается."""
    out: list[tuple[str, str]] = []
    for path in sorted(корень.rglob("*")):
        if not path.is_file() or SKIP_DIRS & set(path.parts):
            continue
        try:
            out.append((path.relative_to(корень).as_posix(),
                        path.read_text(encoding="utf-8")))
        except (UnicodeDecodeError, OSError):
            continue
    return out


def находки(документы: list[tuple[str, str]], набор: set[str],
            slug: str) -> tuple[list[str], int]:
    """Находки и число просмотренных ссылок на СВОЮ ветку."""
    плохо: list[str] = []
    всего = 0
    for путь, текст in документы:
        for номер, репозиторий, цель in ссылки(текст):
            # Чужой репозиторий законен: его ветку рисуем не мы (см. 022 у
            # check_own_name — территория проверки только своё).
            if репозиторий.lower() != slug.lower():
                continue
            всего += 1
            if цель in набор:
                continue
            близкое = get_close_matches(цель, sorted(набор), n=1, cutoff=0.6)
            подсказка = f"; ближе всего лежит {близкое[0]}" if близкое else ""
            плохо.append(
                f"{путь}:{номер}: ссылка ведёт в {BRANCH}/{цель}, а такого "
                f"файла на ветке нет{подсказка}")
    return плохо, всего


def selftest() -> int:
    """Гейт прогоняется тем, что обязан найти И что обязан пропустить (140)."""
    СВОЁ = "Хозяин/Каталог"
    НАБОР = {".github/badges/version.json", "export/where.json"}
    ЕСТЬ = f"https://{HOST}/{СВОЁ}/{BRANCH}/.github/badges/version.json"
    НЕТ = f"https://{HOST}/{СВОЁ}/{BRANCH}/.github/badges/tests.json"
    КОДИРОВАННАЯ = ("https://img.shields.io/endpoint?url=https%3A%2F%2F" + HOST
                    + "%2F" + СВОЁ.replace("/", "%2F") + "%2F" + BRANCH
                    + "%2F.github%2Fbadges%2Ftests.json&style=flat")
    случаи: list[tuple[str, str, bool]] = [
        # ── обязан НАЙТИ ──────────────────────────────────────────────────
        ("ссылка на несобранный путь", НЕТ, True),
        ("тот же путь внутри url= у shields.io: адрес URL-кодирован",
         КОДИРОВАННАЯ, True),
        ("ссылка в конце предложения: точка адресу не принадлежит",
         f"Значок лежит в {НЕТ}.", True),
        ("несобранный путь в разметке ссылки", f"[значок]({НЕТ})", True),
        # ── обязан ПРОПУСТИТЬ ─────────────────────────────────────────────
        ("ссылка на собранный путь", ЕСТЬ, False),
        ("собранный путь внутри url= у shields.io",
         КОДИРОВАННАЯ.replace("tests", "version"), False),
        ("та же ветка у ЧУЖОГО репозитория: её рисуем не мы",
         f"https://{HOST}/Сосед/Проект/{BRANCH}/.github/badges/tests.json", False),
        ("файл общей ветки, а не ветки значков",
         f"https://{HOST}/{СВОЁ}/main/README.md", False),
        ("относительная ссылка: её держит check_links.py (022)",
         "[правило](rules/ru/196-a-link-is-not-published-before-the-file.md)", False),
        ("внешний адрес без нашей ветки", "https://example.org/badges/x.json", False),
    ]
    сломано: list[str] = []
    for имя, текст, ждём in случаи:
        вышло, _ = находки([("проба.md", текст)], НАБОР, СВОЁ)
        if bool(вышло) != ждём:
            сломано.append(f"{имя}: вышло {вышло or 'пусто'}")
        print(f"  {'находка' if вышло else 'чисто  '} — {имя}")

    # ГЕЙТ ОТВЕЧАЕТ ЧЕРЕЗ main(), А НЕ ТОЛЬКО РАЗБОРОМ (правило 150). Набор без
    # такого случая проверяет функцию, а не проверку: вердикт, исход и третий
    # путь живут в main(), и они же ломаются.
    with tempfile.TemporaryDirectory() as tmp:
        корень = Path(tmp) / "дерево"
        собрано = Path(tmp) / "уехало" / ".github" / "badges"
        собрано.mkdir(parents=True)
        (собрано / "version.json").write_text("{}", encoding="utf-8")
        корень.mkdir()
        через_main: list[tuple[str, str, int]] = [
            ("ссылка на несобранное", НЕТ, 1),
            ("ссылка на собранное", ЕСТЬ, 0),
            ("ни одной ссылки на ветку — разбор пуст, а витрина без них не "
             "работает (075)", "просто текст", 2),
        ]
        for имя, текст, ждём in через_main:
            (корень / "README.md").write_text(текст, encoding="utf-8")
            вышло = main(["--published", str(Path(tmp) / "уехало"),
                          "--docs", str(корень), "--slug", СВОЁ])
            if вышло != ждём:
                сломано.append(f"main(): {имя}: исход {вышло}, ждали {ждём}")
            print(f"  исход {вышло}  — main(): {имя}")

        # Третий исход у ВХОДА, а не у предмета: сверять не с чем.
        вышло = main(["--published", str(Path(tmp) / "нет-такого"),
                      "--docs", str(корень), "--slug", СВОЁ])
        if вышло != 2:
            сломано.append(f"main(): нет каталога собранного: исход {вышло}, ждали 2")
        print(f"  исход {вышло}  — main(): каталога собранного нет")

    if сломано:
        print("самопроверка не сошлась:", file=sys.stderr)
        for s in сломано:
            print(f"  • {s}", file=sys.stderr)
        return 1
    print(f"самопроверка пройдена: случаев {len(случаи) + 4}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--published", type=Path,
                    help="каталог, СОДЕРЖИМОЕ которого уехало на ветку "
                         f"`{BRANCH}`: пути считаются относительно него")
    ap.add_argument("--docs", type=Path, default=ROOT,
                    help="корень документов; по умолчанию рабочее дерево")
    ap.add_argument("--slug", help="своё имя вместо ответа origin")
    ap.add_argument("--selftest", action="store_true",
                    help="прогнать набор: что обязан найти и что пропустить")
    args = ap.parse_args(argv)

    if args.selftest:
        return selftest()

    # ── исход 2: сверять не с чем ──────────────────────────────────────────
    if args.published is None:
        print("проверка не отработала: не задан каталог собранного "
              "(--published) — сверять ссылки не с чем", file=sys.stderr)
        return 2
    набор, почему = собранное(args.published)
    if почему:
        print(f"проверка не отработала: {почему}", file=sys.stderr)
        return 2

    slug = args.slug or ""
    if not slug:
        slug, почему = own_slug(args.docs)
        if почему:
            print(f"проверка не отработала: {почему} — чья ветка `{BRANCH}` "
                  "в ссылке, неизвестно", file=sys.stderr)
            return 2

    документы = из_дерева(args.docs)
    где = str(args.docs)
    if not документы:
        print(f"проверка не отработала: ни одного читаемого документа в {где}",
              file=sys.stderr)
        return 2

    плохо, всего = находки(документы, набор, slug)

    # ── исход 2: разбор пуст ───────────────────────────────────────────────
    # НИ ОДНОЙ ССЫЛКИ — ЭТО ОТКАЗ РАЗБОРА, А НЕ ЧИСТЫЙ ПРОГОН (075). Витрина
    # без них не работает вовсе: значки и сводка живут только на этой ветке.
    # Зелёное на пустом входе означало бы «проверено», когда не проверено
    # ничего, — и первым же это скрыло бы протухший разбор адреса.
    if not всего:
        print(f"проверка не отработала: в {где} ({len(документы)} док.) нет ни "
              f"одной ссылки на свою ветку `{BRANCH}` — витрина без них не "
              "работает, значит сломан разбор адреса, а не витрина",
              file=sys.stderr)
        return 2

    # ── исход 1 ────────────────────────────────────────────────────────────
    if плохо:
        print(f"ссылки ведут в то, чего на ветке `{BRANCH}` нет "
              f"(файлов на ней: {len(набор)}):", file=sys.stderr)
        for f in плохо:
            print(f"  • {f}", file=sys.stderr)
        return 1

    print(f"ссылок на ветку `{BRANCH}`: {всего}, и каждая ведёт в файл, "
          f"который на ней есть ({len(набор)} файлов)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
