#!/usr/bin/env python3
"""Поле слияния записи изменения не служит доказательством слияния — кроме названных мест.

Правило 148: запись изменения — кэш, а не состояние. Поле `merged`
(`merged_at`, `merged_by`) отстаёт от события: коммит уже в общей ветке, а
запись ещё говорит «не слито», и ожидание по ней не кончается. Доказательство
слияния — коммит в общей ветке; так и устроен `automerge.yml`.

ЗАСЛОН, А НЕ ПРОВЕРКА НАСТОЯЩЕГО. Мест, где поле решает ожидание или действие,
в дереве нет; гейт держит, чтобы такое не появилось молча. Это названо, а не
выдано за «проверено» (146): зелёный здесь значит «нового чтения поля нет».
Гейт заведён решением владельца 14.10 (#816).

ЗАКОННОЕ ЧТЕНИЕ НАЗЫВАЕТСЯ ПОИМЁННО — МЕСТОМ, А НЕ ФАЙЛОМ (068). Граница
правила: поле годится там, где его отставание ничего не решает. Запись в
`ЗАКОННЫЕ` — пара «файл, выражение в строке» с причиной: новое чтение в том же
файле исключением не прикрыто. Таких мест четыре в двух файлах, и у каждого
причина названа рядом с ним. Названное место, которого в файле больше нет, —
находка: исключение пережило свою причину молча.

ЧТО СЧИТАЕТСЯ ЧТЕНИЕМ — ПЕРЕЧЕНЬ ФОРМ (210), у каждой проверка в наборе:
  1. путь `.merged`, `.merged_at`, `.merged_by` — атрибут Python, путь jq;
  2. ключ в кавычках `"merged"`, `"merged_at"`, `"merged_by"`;
  3. голое имя `merged_at` / `merged_by` — сборка объекта в jq `{merged_at}`;
  4. верблюжье `mergedAt` / `mergedBy` — `gh --json`, GraphQL;
  5. состояние `"MERGED"` в кавычках — `gh pr view --json state`.
Голое `merged` формой не считается: это обычное имя переменной
(`collect_changelog.py`, `version.py`), а поле записи без точки или кавычек
не читается.

ГДЕ ИЩЕТСЯ. `scripts/**` (`.py`, `.sh`), `.github/workflows/**` и
`.github/actions/**` (`.yml`, `.yaml`, `.py`, `.sh`), `.claude/hooks/**`
(`.py`, `.sh`) — всё, что исполняется конвейером или окном. Строки-комментарии
(`#`) не предмет. Пропускается только сам гейт: его выражение называет поле, а
не читает. Прежнее исключение всех `check_*.py` прятало настоящее чтение в
`check_task_state.py`.

Реализует правила каталога:
  148 — запись изменения — кэш: её поле слияния доказательством не служит;
  146 — зелёный на пустом предмете назван заслоном, а не проверкой;
  068 — исключение названо поимённо, с причиной;
  039 — три исхода: чисто · есть находки · проверка не отработала.

Запуск:  python scripts/check_record_cache.py [--root <корень>]
Исходы:  0 — чисто;  1 — есть находки;  2 — проверка не отработала.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

ПОЛЕ_RE = re.compile(
    r"\.merged(?:_at|_by)?\b"  # 1. путь
    r"|[\"']merged(?:_at|_by)?[\"']"  # 2. ключ в кавычках
    r"|\bmerged_(?:at|by)\b"  # 3. голое имя с суффиксом
    r"|\bmerged(?:At|By)\b"  # 4. верблюжье
    r"|[\"']MERGED[\"']"
)  # 5. состояние
КОММЕНТАРИЙ_RE = re.compile(r"^\s*#")
САМ = "scripts/check_record_cache.py"
#: Где ищется: каталог → расширения. Ищется вглубь.
ОХВАТ: dict[str, tuple[str, ...]] = {
    "scripts": (".py", ".sh"),
    ".github/workflows": (".yml", ".yaml"),
    ".github/actions": (".yml", ".yaml", ".py", ".sh"),
    ".claude/hooks": (".py", ".sh"),
}
#: Законные чтения: (файл, выражение в строке) → причина. Разрешительно (068).
ЗАКОННЫЕ: dict[tuple[str, str], str] = {
    ("scripts/review_findings.py", "select(.merged_at != null)"): (
        "отбирает тела СЛИТЫХ изменений среди закрытых, чтобы снять находки по "
        "строкам «Разобрано:». Отставание поля откладывает снятие до следующего "
        "захода и ничего не решает — граница 148 «состояние на запрос»"
    ),
    ("scripts/check_task_state.py", "{number, body, merged_at, merge_commit_sha}"): (
        "запрос полей у площадки; решает не он, а отбор ниже"
    ),
    ("scripts/check_task_state.py", 'if p.get("merged_at")'): (
        "выбирает, чьё тело несёт обещание: своё изменение узнаётся по "
        "merge_commit_sha, то есть по коммиту. Отставание поля даёт откат к "
        "телу коммита, и прогон называет подмену источника вслух (158) — "
        "молча оно ничего не решает"
    ),
    ("scripts/check_task_state.py", '"merged_at": m'): (
        "данные самопроверки: подделанная запись, а не чтение площадки"
    ),
}


def файлы(root: Path) -> list[Path]:
    """Исполняемые файлы охвата, по порядку."""
    out: list[Path] = []
    for каталог, расширения in ОХВАТ.items():
        база = root / каталог
        if база.is_dir():
            out += sorted(f for f in база.rglob("*") if f.is_file() and f.suffix in расширения)
    return out


def законно(имя: str, строка: str) -> bool:
    """Названо ли это место поимённо: файл и выражение в строке."""
    return any(имя == ф and в in строка for ф, в in ЗАКОННЫЕ)


def чтения(root: Path) -> tuple[list[str], list[str]]:
    """Чтения поля слияния «путь:строка: текст» и мёртвые законные места."""
    out: list[str] = []
    живые: set[tuple[str, str]] = set()
    for f in файлы(root):
        имя = f.relative_to(root).as_posix()
        if имя == САМ:
            continue
        for номер, строка in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
            if КОММЕНТАРИЙ_RE.match(строка) or not ПОЛЕ_RE.search(строка):
                continue
            if законно(имя, строка):
                живые |= {(ф, в) for ф, в in ЗАКОННЫЕ if ф == имя and в in строка}
            else:
                out.append(f"{имя}:{номер}: {строка.strip()[:120]}")
    мёртвые = [f"{ф} · «{в}»" for ф, в in ЗАКОННЫЕ if (ф, в) not in живые]
    return out, мёртвые


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    root = ap.parse_args(argv).root
    if not (root / "scripts").is_dir():
        print(f"проверка не отработала: нет каталога {root / 'scripts'}", file=sys.stderr)
        return 2
    try:
        найдено, мёртвые = чтения(root)
    except (OSError, UnicodeDecodeError) as exc:
        print(f"проверка не отработала: {exc}", file=sys.stderr)
        return 2

    if найдено or мёртвые:
        print("поле слияния записи читается как доказательство (148):", file=sys.stderr)
        for н in найдено:
            print(f"  • {н}", file=sys.stderr)
        for м in мёртвые:
            print(
                f"  • {м}: законное место названо, а в дереве его нет — уберите запись",
                file=sys.stderr,
            )
        print(
            "\n  Слияние доказывает коммит в общей ветке, а не поле записи: оно\n"
            "  отстаёт от события. Если отставание здесь ничего не решает — назовите\n"
            "  место в ЗАКОННЫЕ с причиной.",
            file=sys.stderr,
        )
        return 1
    print(
        f"поле слияния записи не читается как доказательство: законных мест "
        f"{len(ЗАКОННЫЕ)}, каждое с причиной — заслон, а не проверка настоящего (146)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
