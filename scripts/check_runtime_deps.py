def импорты(путь: Path) -> set[str]:
    """Пакеты верхнего уровня, которые скрипт импортирует напрямую."""
    try:
        дерево = ast.parse(путь.read_text(encoding="utf-8"))
    except (OSError, SyntaxError):
        return set()
    имена: set[str] = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            # не проза: путь модуля — берётся его верхний уровень
            имена |= {a.name.split(".")[0] for a in узел.names}
        elif isinstance(узел, ast.ImportFrom) and узел.level == 0 and узел.module:
            # не проза: путь модуля — берётся его верхний уровень
            имена.add(узел.module.split(".")[0])
    return имена


def чужие(имена: set[str], root: Path) -> set[str]:
    """Отсев своего и стандартного: предмет — только внешние пакеты."""
    свои = {p.stem for p in (root / "scripts").glob("*.py")}
    return {и for и in имена
            if и not in sys.stdlib_module_names and и not in свои}


def находки(text: str, root: Path) -> tuple[list[str], int]:
    """Разрывы «зовёт, но не поставлено К ЭТОМУ ШАГУ», и число вызовов.

    ПОРЯДОК ШАГОВ РЕШАЕТ, И ЭТО НАШЛА ПРОБА, А НЕ РАССУЖДЕНИЕ. Первая редакция
    считала «ставит ли работа» — и на живом дереве промолчала о воспроизведённой
    поломке: PyYAML в `catalogue` ставится, но ШЕСТЬЮ шагами НИЖЕ гейта, а
    падение было выше. Гейт зеленел бы, не держа ровно того случая, ради
    которого написан (146). Считается накопление: доступно то, что установлено
    выше по тексту работы.
    """
    список, разобрано = [], 0
    for работа, тело in работы(text).items():
        доступно: set[str] = set()
        for шаг in разбить_на_шаги(тело):
            доступно |= ставится(шаг, root)
            for имя_скрипта in sorted(set(ВЫЗОВ.findall(шаг))):
                путь = root / имя_скрипта
                if not путь.exists():
                    continue
                разобрано += 1
                for пакет in sorted(чужие(импорты(путь), root)):
                    if пакет.lower() not in доступно:
                        список.append(
                            f"работа «{работа}» зовёт {имя_скрипта}, а тот "
                            f"импортирует «{пакет}» — к этому шагу пакет ещё "
                            "не поставлен")
    return список, разобрано


def разбить_на_шаги(тело: str) -> list[str]:
    """Шаги работы по порядку. Шаг начинается строкой `- ` в списке шагов."""
    шаги: list[list[str]] = []
    for строка in тело.splitlines():
        голая = строка.lstrip()
        if голая.startswith("- ") and len(строка) - len(голая) >= 6:
            шаги.append([строка])
        elif шаги:
            шаги[-1].append(строка)
        else:
            шаги.append([строка])
    return ["\n".join(ш) for ш in шаги]


def selftest() -> int:
    основа = ("jobs:\n  catalogue:\n    steps:\n"
              "      - run: python scripts/{s}\n")
    с_установкой = ("jobs:\n  tests:\n    steps:\n"
                    "      - run: python -m pip install -r requirements-test.txt\n"
                    "      - run: python scripts/{s}\n")
    случаи = [
        (основа, "check_bindings.py", 0, "скрипт без внешних пакетов"),
        (с_установкой, "check_bindings.py", 0, "он же в работе с установкой"),
    ]
    плохо = []
    for шаблон, скрипт, ждём, что in случаи:
        сп, _ = находки(шаблон.format(s=скрипт), ROOT)
        print(f"  {'находка ' if сп else 'чисто   '} — {что}")
        if len(сп) != ждём:
            плохо.append(f"{что}: ждали {ждём}, вышло {len(сп)} ({сп})")

    # ЖИВОЙ ПРЕДМЕТ: скрипт, который зовёт внешний пакет. Берётся из дерева, а
    # не выдумывается: подделка разошлась бы с деревом молча (170).
    подопытный = ROOT / "scripts" / "_проба_зависимости.py"
    подопытный.write_text("import yaml\n", encoding="utf-8")
    try:
        сп, _ = находки(основа.format(s=подопытный.name), ROOT)
        print(f"  {'находка ' if сп else 'чисто   '} — пакет, которого работа не ставит")
        if len(сп) != 1:
            плохо.append(f"внешний пакет: ждали 1, вышло {len(сп)}")
        сп2, _ = находки(с_установкой.format(s=подопытный.name), ROOT)
        print(f"  {'находка ' if сп2 else 'чисто   '} — он же там, где пакет ставится")
        if сп2:
            плохо.append(f"установленный пакет принят за находку: {сп2}")
    finally:
        подопытный.unlink(missing_ok=True)

    for с in плохо:
        print(f"РАСХОЖДЕНИЕ: {с}", file=sys.stderr)
    if плохо:
        return 1
    print("самопроверка пройдена: разрыв отличается от обеспеченности, "
          "стандартная библиотека и свои модули предметом не являются")
    return 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--root", type=Path, default=ROOT)
    p.add_argument("--selftest", action="store_true",
                   help="прогнать гейт по случаям, а не по дереву (140)")
    args = p.parse_args(argv)
    if args.selftest:
        return selftest()

    прогон = args.root / ".github" / "workflows" / "ci.yml"
    if not прогон.exists():
        print(f"проверка не отработала: нет {прогон.relative_to(args.root)} — "
              "предмет берётся из него, и зеленеть без него нельзя",
              file=sys.stderr)
        return 2

    список, разобрано = находки(прогон.read_text(encoding="utf-8"), args.root)

    if разобрано == 0:
        print(f"проверка не отработала: в {прогон.relative_to(args.root)} не "
              "нашлось ни одного шага вида `python scripts/…` — либо форма "
              "вызова изменилась, либо разбор работ сломан", file=sys.stderr)
        return 2

    if список:
        print("окно и прогон разошлись окружением:", file=sys.stderr)
        for с in список:
            print(f"  • {с}", file=sys.stderr)
        print("  Локально пакет есть, и «чисто» печатается с поверхности, на "
              "которой изменение не поедет (018). Либо поставьте пакет в этой "
              "работе, либо уберите импорт.", file=sys.stderr)
        return 1

    print(f"окружение сходится: разобрано вызовов {разобрано}, "
          "каждый обеспечен своей работой")
    return 0


if __name__ == "__main__":
    sys.exit(main())
