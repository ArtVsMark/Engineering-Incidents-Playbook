"""Скрипт из шага конвейера не зовёт пакет, которого в этой работе нет.

ИНЦИДЕНТ 7 СЕНТЯБРЯ, СВОЙ И В ДВУХ ЭКЗЕМПЛЯРАХ. В `check_workflows.py`
добавился `import yaml`, прогон перед толчком напечатал «чисто: 42 шага», а
работа `catalogue` упала за семь секунд: `ModuleNotFoundError: No module named
'yaml'`. PyYAML стоит в requirements-test.txt, который ставит ДРУГАЯ работа —
та, что гоняет тесты. В окне пакет был, поэтому локально всё зеленело.

Тот же класс за три дня до этого: окно работало версией языка ниже прогонной, и
«чисто» печаталось с поверхности, на которой изменение не поедет. Общее у обоих
— окружение окна ШИРЕ прогонного, и разница видна только запуском в прогоне.

ПРЕДМЕТ. Шаг работы зовёт `python scripts/X.py`; X импортирует пакет, который
не из стандартной библиотеки, не лежит рядом в scripts/ и не ставится ни одним
шагом ЭТОЙ ЖЕ работы. Установка в соседней работе не считается: работы идут на
разных машинах.

ЧЕГО ГЕЙТ НЕ ДЕЛАЕТ (051). Он не проверяет, что пакет вообще существует, и не
разбирает транзитивные импорты чужих библиотек: предмет — разрыв между тем, что
скрипт зовёт, и тем, что работа ставит, а не полнота дерева зависимостей.

Реализует правила каталога:
  018 — у каждой проверки есть окружение, где она осмысленна: зелёное в среде
        без нужных звеньев доказательством не является;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  075 — ноль разобранных шагов это отказ, а не чистый прогон;
  158 — третий исход называет предмет отказа, а не только причину.

Исходы:
  0 — каждый вызванный скрипт обеспечен своей работой;
  1 — есть скрипт, зовущий пакет, которого в его работе нет;
  2 — проверка не отработала.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: Строка, начинающая работу: два пробела отступа под `jobs:`.
РАБОТА = re.compile(r"^  ([A-Za-z0-9_-]+):\s*$")
#: Вызов скрипта каталога из шага.
ВЫЗОВ = re.compile(r"python[0-9.]*\s+(scripts/[\w_]+\.py)")
#: Установка зависимостей внутри шага.
СТАВИТ = re.compile(r"pip install[^\n]*?(?:-r\s+(\S+)|\s([A-Za-z][\w.-]*))")

#: Имя пакета на площадке против имени модуля в коде. Список короткий и
#: закрытый: догадка «убрать дефисы и понизить регистр» ошибается ровно там,
#: где это дороже всего, — на пакетах с историей.
ИМЕНА = {"pyyaml": "yaml", "python-dateutil": "dateutil", "pillow": "PIL"}


def работы(text: str) -> dict[str, str]:
    """Тело каждой работы прогона. Разбор построчный: YAML-парсера здесь нет.

    Его отсутствие — не аскеза, а тот же инцидент: парсер стоит только в
    наборе тестов, и гейт, зависящий от него, падал бы ровно там, где должен
    находить.
    """
    из_текста: dict[str, list[str]] = {}
    имя: str | None = None
    в_работах = False
    for строка in text.splitlines():
        if строка.startswith("jobs:"):
            в_работах = True
            continue
        if не_отступ(строка) and строка.strip():
            в_работах = False
        if not в_работах:
            continue
        м = РАБОТА.match(строка)
        if м:
            имя = м.group(1)
            из_текста[имя] = []
        elif имя:
            из_текста[имя].append(строка)
    return {k: "\n".join(v) for k, v in из_текста.items()}


def не_отступ(строка: str) -> bool:
    return bool(строка) and not строка.startswith(" ")


def ставится(тело: str, root: Path) -> set[str]:
    """Модули, доступные работе: из requirements и из прямых установок."""
    есть: set[str] = set()
    for файл, пакет in СТАВИТ.findall(тело):
        if пакет:
            есть.add(ИМЕНА.get(пакет.lower(), пакет.lower()))
        if файл:
            путь = root / файл
            if not путь.exists():
                continue
            for строка in путь.read_text(encoding="utf-8").splitlines():
                имя = строка.split("#")[0].strip().split("[")[0]
                имя = re.split(r"[<>=!;]", имя)[0].strip()
                if имя:
                    есть.add(ИМЕНА.get(имя.lower(), имя.lower()))
