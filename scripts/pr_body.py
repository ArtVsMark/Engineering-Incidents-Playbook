#!/usr/bin/env python3
"""Строка связи изменения с задачей: собирается и проверяется машинно.

Реализует правило 064. Оно говорит прямо: «изменение без строки связи НЕ
закрывает задачу при слиянии — трекер начинает врать, и задача висит открытой
после того, как сделана». Половину правила про метки держал labels-sync, эту
не держало ничто, и замер это показал: двенадцать слияний подряд, задача
названа в заголовке, `closed_by_pull_requests` у каждой — ноль.

ПОЧЕМУ ЗАГОЛОВОК НЕ СЧИТАЕТСЯ. Ссылка `(#83)` в заголовке рисуется площадкой
как упоминание, а не как связь. Для человека это неотличимо: ссылка синяя,
номер верный, клик открывает задачу. Именно поэтому дефект прожил двенадцать
слияний — он невидим при чтении, и первым его заметил владелец, а не механизм.

ОСВОБОЖДЕНИЕ ЗАПОЛНЯЕТСЯ, А НЕ ПРОПУСКАЕТСЯ. 064 требует именно этой формы:
«явное освобождение — заполненное поле с причиной, а не пустота». Изменение,
которое не отвечает ни на какую задачу, пишет строку «Без задачи, потому что…»
и проходит. Пустота не проходит: пропуск и осознанный отказ обязаны выглядеть
по-разному, иначе первый прячется за вторым.

ГРАНИЦА, КОТОРУЮ СКРИПТ НЕ ПЕРЕХОДИТ. Он не решает, ту ли задачу закрывает
изменение, и не проверяет, что она открыта. Задачу можно закрыть неверную —
это решение автора, а не форма записи. Держится здесь только то, что
проверяется без чужого сервера.

Запуск:
  python scripts/pr_body.py --build --subject <заголовок> --body-file <файл>
  python scripts/pr_body.py --check --body-file <файл>

Коды: 0 чисто · 2 проверять нечего · 1 — у него ДВА источника, и оба про форму
тела: связи с задачей нет и освобождение не заполнено; либо строка снятия
заметки не снимет ничего. Перечислены порознь потому, что перечисление и есть
объявление предмета: источник, не названный здесь, читается как отсутствующий
(039, 183).

Реализует правила каталога:
  064 — строка связи с задачей — вторая половина 064: без неё слияние не закрывает задачу;
  002 — снятие заметки внешнего взгляда проверяется машинно: строка, чей
        отпечаток набран не той формой, не снимет ничего и отвергается здесь;
  173 — ответов у изменения три, и «сделана часть» — отдельный: `Part of #NNN`
        с названным остатком. Площадка такого слова не знает и закрыть по нему
        ничего не может, поэтому держится оно здесь. Проверка того, что стало
        с задачей ПОСЛЕ слияния, живёт в scripts/check_task_state.py.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

#: Закрывающие слова площадки. Список её, а не наш: сузить его значило бы
#: отвергать связь, которую площадка признаёт, — ложный отказ (правило 097).
CLOSING_RE = re.compile(
    r"(?im)^[ \t>*-]*(clos(?:e|es|ed)|fix(?:es|ed)?|resolv(?:e|es|ed))\s+"
    r"(?:#|https://github\.com/[\w.-]+/[\w.-]+/issues/)(\d+)\b")

#: Задача в хвосте заголовка — местное соглашение: `… (#83)`. Отсюда берётся
#: номер, когда автор его не назвал явно.
MENTION_RE = re.compile(r"\(#(\d+)\)\s*$")

#: Заполненное освобождение. Причина обязана быть непустой: «Без задачи.» —
#: это пустота с точкой, и она не проходит.
EXEMPT_RE = re.compile(r"(?im)^[ \t>*-]*без задачи,\s*потому что\s+\S+")

EXEMPT_HINT = "Без задачи, потому что <причина одной строкой>"

#: ТРЕТИЙ ОТВЕТ — «сделана часть» (правило 173). Площадка такого слова не знает
#: и закрыть по нему ничего не может: `Part of` — наше соглашение, и держится
#: оно здесь. Без него частичное выполнение неотличимо от полного, и автор
#: вынужден соврать в одну из сторон — закрыть недоделанное или промолчать.
PART_RE = re.compile(r"(?im)^[ \t>*-]*part of\s+#(\d+)\b")

#: Остаток называется В ТЕЛЕ, непустой строкой. Проверить галочки в самой
#: задаче отсюда нечем — трекер живёт на чужом сервере, а гейт изменения
#: наружу не ходит; это делает проверка по ту сторону слияния.
REST_RE = re.compile(r"(?im)^[ \t>*-]*(?:остаётся|остается|remaining):\s+\S+")

REST_HINT = "Остаётся: <что именно не сделано>"

#: СНЯТИЕ ЗАМЕТКИ ВНЕШНЕГО ВЗГЛЯДА. Механизм находок уносит запись из живой
#: задачи по строке «Разобрано: <отпечаток>» в теле СЛИТОГО изменения — приём
#: тот же, каким площадка закрывает задачу по `Closes`. Отпечаток — семь
#: шестнадцатеричных знаков от заголовка находки.
#:
#: ПОЧЕМУ ФОРМА ЖИВЁТ ЗДЕСЬ, А НЕ У УБОРЩИКА. Предмет этого скрипта — форма
#: тела изменения, и проверяется она БЕЗ чужого сервера; уборщик спрашивает
#: тем же выражением, импортируя его отсюда. Два разбора одной строки разошлись
#: бы молча — в этом файле такое уже случалось с заголовком против тела (022).
СНЯТИЕ_RE = re.compile(r"(?im)^[ \t>*-]*Разобрано:[ \t]*(.*)$")

#: То, что уборщик ПРИМЕТ. Выражение обязано совпадать с ним знак в знак:
#: принять здесь больше — значит пропустить строку, которая ничего не снимет.
РАЗОБРАНО = re.compile(r"^\s*Разобрано:\s*([0-9a-f]{7})\b", re.M | re.I)

СНЯТИЕ_HINT = "Разобрано: <семь шестнадцатеричных знаков отпечатка>"


#: Строка трейлера: «Ключ-Слово: значение». Нужна, чтобы отличить
#: завершающий блок подписей от обычного абзаца.
TRAILER_RE = re.compile(r"^[A-Za-z][A-Za-z-]*:\s")


def linked(body: str) -> str | None:
    """Номер задачи, которую тело закрывает. None — связи нет."""
    m = CLOSING_RE.search(body)
    return m.group(2) if m else None


def exempt(body: str) -> bool:
    return bool(EXEMPT_RE.search(body))


def partial(body: str) -> str | None:
    """Номер задачи, которую тело закрывает ЧАСТИЧНО. None — такого ответа нет."""
    m = PART_RE.search(body)
    return m.group(1) if m else None


def names_rest(body: str) -> bool:
    """Назван ли остаток. Пустое «Остаётся:» остатком не считается."""
    return bool(REST_RE.search(body))


def dead_marks(body: str) -> list[str]:
    """Строки «Разобрано:», которые не снимут НИЧЕГО. Пусто — все годны.

    ЧТО ЗДЕСЬ ДОСТОВЕРНО, А ЧТО НЕТ. Достоверно одно: строка, чей хвост не
    начинается с семи шестнадцатеричных знаков, не совпадёт с записью НИКОГДА —
    какой бы ни была живая задача. Это проверяется без сети и потому отвергается
    (051: запрещают достоверное).

    ВТОРАЯ ПОЛОВИНА НЕ ПОСТРОЕНА, И ЭТО НАЗВАНО. Отпечаток может быть верным по
    форме и не значиться в задаче — опечатка в знаке либо запись, снятая раньше.
    Различить их можно только спросив трекер, а этот гейт наружу не ходит по
    построению; там же и цена ошибки другая — снятие лишнего безвредно, отказ на
    нём был бы ложным (182: сказано, какая половина машинная и почему вторая
    не здесь).

    ИНЦИДЕНТ 10 сентября: в теле #475 снятия были написаны словами —
    `Разобрано: 202-boundary`, `Разобрано: 202-delete`. Для человека тело
    выглядело разобранным, для машины не совпадало ни с чем, и ни один гейт об
    этом не сказал; поймано чтением, за минуты до слияния. Замер по 58 слитым
    изменениям: строк снятия 26, все 26 отпечатком — прозы, которую эта
    проверка задела бы, в корпусе нет ни одной.
    """
    мёртвые: list[str] = []
    for m in СНЯТИЕ_RE.finditer(body):
        if not РАЗОБРАНО.match(m.group(0).strip()):
            мёртвые.append(m.group(0).strip())
    return мёртвые


def build(subject: str, body: str) -> tuple[str, str | None]:
    """Тело изменения со строкой связи. Второй элемент — что не так, или None."""
    # «Часть» — такой же ответ, как закрытие: дописать поверх него `Closes`
    # значило бы закрыть задачу, которая сделана наполовину (173).
    if linked(body) or partial(body) or exempt(body):
        return body, None
    m = MENTION_RE.search(subject.strip())
    if not m:
        return body, ("ни закрывающей строки в теле, ни задачи в хвосте "
                      f"заголовка, ни строки «{EXEMPT_HINT}»")
    line = f"Closes #{m.group(1)}"
    # Строка встаёт ПЕРЕД блоком трейлеров, а не после него. Иначе трейлеры
    # перестают быть последним абзацем, и `git log --format=%(trailers:…)`
    # их не находит — гейт атрибуции остался бы без предмета там, где текст
    # переиспользуют как сообщение коммита (правило 123).
    paras = body.rstrip("\n").split("\n\n")
    if paras and paras[-1].strip() and all(
            TRAILER_RE.match(ln) for ln in paras[-1].strip().split("\n")):
        paras.insert(len(paras) - 1, line)
    else:
        paras.append(line)
    return "\n\n".join(paras) + "\n", None


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--build", action="store_true",
                      help="собрать тело изменения со строкой связи")
    mode.add_argument("--check", action="store_true",
                      help="проверить готовое тело изменения")
    ap.add_argument("--subject", default="", help="заголовок первого коммита ветки")
    ap.add_argument("--body-file", type=Path, help="файл с телом; «-» — стандартный ввод")
    args = ap.parse_args(argv)

    # ── исход 2 ────────────────────────────────────────────────────────────
    if args.body_file is None:
        print("проверка не отработала: --body-file не передан — тело "
              "изменения брать неоткуда", file=sys.stderr)
        return 2
    if str(args.body_file) == "-":
        body = sys.stdin.read()
    elif args.body_file.exists():
        body = args.body_file.read_text(encoding="utf-8")
    else:
        print(f"проверка не отработала: нет файла {args.body_file}", file=sys.stderr)
        return 2

    if args.check:
        if not body.strip():
            print(f"проверка не отработала: {args.body_file} пуст — "
                  "проверять нечего", file=sys.stderr)
            return 2
        # СНЯТИЕ ПРОВЕРЯЕТСЯ ПЕРВЫМ И НЕЗАВИСИМО ОТ СВЯЗИ С ЗАДАЧЕЙ: это
        # другой предмет, и тело с верной связью бывает с мёртвым снятием.
        мёртвые = dead_marks(body)
        if мёртвые:
            print("в теле изменения есть строка снятия, которая ничего не "
                  "снимет:\n  "
                  + "\n  ".join(мёртвые)
                  + "\n  Механизм находок ищет СЕМЬ шестнадцатеричных знаков "
                    "сразу за двоеточием;\n  всё остальное для человека "
                    "выглядит разобранным, а для машины не совпадает ни с чем.\n"
                    f"  Форма: «{СНЯТИЕ_HINT}» — отпечаток стоит слева от "
                    "заметки в задаче.", file=sys.stderr)
            return 1
        rid = linked(body)
        if rid:
            print(f"изменение закрывает задачу #{rid}")
            return 0
        part = partial(body)
        if part:
            if names_rest(body):
                print(f"изменение делает часть задачи #{part}, остаток назван")
                return 0
            # ── исход 1 ────────────────────────────────────────────────────
            print(f"изменение объявлено частью задачи #{part}, а остаток не "
                  "назван.\n  «Часть» без остатка неотличима от полного "
                  "закрытия: площадка о частичности\n  не знает ничего, и "
                  "сказать о ней может только автор (правило 173).\n"
                  f"  Допишите строку «{REST_HINT}».", file=sys.stderr)
            return 1
        if exempt(body):
            print("изменение объявлено без задачи, причина названа")
            return 0
        # ── исход 1 ────────────────────────────────────────────────────────
        print("в теле изменения нет строки связи с задачей.\n"
              "  Площадка закрывает задачу по слову в ТЕЛЕ; ссылка `(#NNN)` в "
              "заголовке — упоминание,\n  и при слиянии не закроет ничего "
              "(правило 064).\n"
              f"  Ответов три: «Closes #NNN», «Part of #NNN» с остатком, либо "
              f"«{EXEMPT_HINT}».", file=sys.stderr)
        return 1

    out, problem = build(args.subject, body)
    if problem:
        # Сборка НЕ отказывает: изменение без строки связи всё равно должно
        # открыться, иначе отмена останется без адресата (правило 147). Отказ
        # живёт в `--check`, на самом изменении, где его видно.
        print(f"::warning::строка связи с задачей не найдена — {problem}",
              file=sys.stderr)
    sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
