#!/usr/bin/env python3
"""У каждой роли карты направлений — своё возражение, адресованное другой роли.

Правило 062 держалось ничем с ответом «карта принимает роль только со СВОИМ
возражением; „хранитель заготовок" проходил приёмку именно по нему». Ответ
описывал приёмку, которую проводит человек, — а признак при этом машинный и
доступный: возражение либо стоит в строке, либо его нет.

ПОЧЕМУ ЭТО НЕ ПРИДИРКА К ФОРМЕ. Направление без своего возражения — это раздел
документации, а не роль: оно не может ничего остановить, и его «покрытие»
измеряет пустоту. Проверялось это чтением, и цена известна — карта дважды
объявляла покрытыми направления, у которых возражения не было вовсе, и оба
раза расхождение нашёл владелец, а не прогон.

ЧТО ПРОВЕРЯЕТСЯ.

  • у каждой строки заполнены все колонки: вопрос, возражение, артефакт,
    покрытие;
  • возражение НАЗЫВАЕТ АДРЕСАТА, и адресат — другая роль этой же карты:
    возражение в пустоту не останавливает никого;
  • роль не возражает сама себе: спор с собой проходит всегда;
  • возражения РАЗЛИЧНЫ. Два направления с одним возражением — одно
    направление, записанное дважды (правило 009).

ПОЧЕМУ ИМЯ АДРЕСАТА ПИШЕТСЯ ИМЕНИТЕЛЬНЫМ ПАДЕЖОМ. Сверять «Инженеру гейтов» с
«Инженер гейтов» значит разбирать русскую морфологию ради одной таблицы —
и ошибаться на каждой новой роли. Форма выбрана так, чтобы сверка была
посимвольной: имя роли, тире, кавычки (правило 013).

ЧЕГО ЗДЕСЬ НЕТ. Суждения о том, СОДЕРЖАТЕЛЬНО ли возражение — можно написать
пустую фразу нужной формы, и гейт её пропустит. Отличить довод от отписки
машинно нечем, и это граница самого правила: приёмку проводит человек, а гейт
держит то, что человек проверяет чтением дольше всего, — полноту перебора.

Приём взят у грейдера: у него та же карта с колонкой возражения и свой
`check_roles.py` над `.rules/roles.md`. Файл не взят — у него роли живут
отдельным документом и профили заведены профилями; здесь карта стоит в своде
рядом с тем, что она объясняет (правило 162).

Запуск:  python scripts/check_roles.py [--root <корень>]

Реализует правила каталога:
  062 — направление становится ролью, только если у него своё возражение;
  009 — считаются РАЗЛИЧНЫЕ возражения, а не строки таблицы;
  013 — форма выбрана под посимвольную сверку, а не под разбор морфологии;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  075 — нет карты или нет строк — это отказ, а не чистый прогон;
  158 — третий исход называет предмет: какой файл и какого заголовка в нём нет.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHARTER = "AGENTS.md"
#: Шапка карты направлений. По ней таблица и опознаётся: искать «таблицу с
#: пятью колонками» значило бы находить чужие.
HEAD_RE = re.compile(r"^\|\s*Направление\s*\|")
SEP_RE = re.compile(r"^\|\s*-{3,}")
#: Возражение: имя роли именительным падежом, тире, текст.
CLAIM_RE = re.compile(r"^(.+?)\s+—\s+(.+)$")
COLUMNS = ("вопрос", "возражение", "артефакт", "покрытие")


def cells(row: str) -> list[str]:
    return [c.strip() for c in row.strip().strip("|").split("|")]


def rows(text: str) -> list[list[str]] | None:
    """Строки карты направлений. None — карты нет вовсе (третий исход)."""
    lines = text.splitlines()
    try:
        start = next(i for i, s in enumerate(lines) if HEAD_RE.match(s))
    except StopIteration:
        return None
    out: list[list[str]] = []
    for line in lines[start + 1:]:
        if not line.startswith("|"):
            break
        if SEP_RE.match(line):
            continue
        out.append(cells(line))
    return out


def plain(name: str) -> str:
    """Имя роли без разметки: «**Диспетчер**» и «Диспетчер» — одна роль."""
    return name.replace("*", "").strip()


def problems(table: list[list[str]]) -> list[str]:
    known = {plain(r[0]) for r in table}
    seen: dict[str, str] = {}
    out: list[str] = []
    for row in table:
        роль = plain(row[0])
        if len(row) < 5:
            out.append(f"{роль}: в строке {len(row)} колонок вместо пяти — "
                       "какой из них нет, читателю не видно")
            continue
        for имя, значение in zip(COLUMNS, row[1:]):
            if not значение:
                out.append(f"{роль}: колонка «{имя}» пуста")
        возражение = row[2]
        m = CLAIM_RE.match(возражение)
        if not m:
            out.append(
                f"{роль}: возражение не называет адресата. Форма — «Роль — "
                "«довод»»: возражение в пустоту не останавливает никого")
            continue
        адресат, довод = plain(m.group(1)), m.group(2).strip()
        if адресат not in known:
            out.append(f"{роль}: возражает «{адресат}», а такой роли в карте "
                       "нет — адресат должен быть тут же")
        elif адресат == роль:
            out.append(f"{роль}: возражает сама себе — спор с собой проходит "
                       "всегда и не останавливает ничего")
        прежняя = seen.get(довод)
        if прежняя:
            out.append(f"{роль}: возражение дословно повторяет «{прежняя}». "
                       "Два направления с одним возражением — одно "
                       "направление, записанное дважды (009)")
        else:
            seen[довод] = роль
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT,
                    help="корень каталога; по умолчанию сам этот репозиторий")
    args = ap.parse_args(argv)
    path = args.root / CHARTER

    # ── исход 2 ────────────────────────────────────────────────────────────
    if not path.exists():
        print(f"проверка не отработала: нет {path} — документа, в котором "
              "живёт карта направлений", file=sys.stderr)
        return 2
    table = rows(path.read_text(encoding="utf-8"))
    if table is None:
        print(f"проверка не отработала: в {CHARTER} нет таблицы с шапкой "
              "«| Направление |» — проверять нечего", file=sys.stderr)
        return 2
    if not table:
        print(f"проверка не отработала: карта направлений в {CHARTER} пуста. "
              "Ноль ролей — это отказ, а не чистый прогон (075)",
              file=sys.stderr)
        return 2

    # ── исход 1 ────────────────────────────────────────────────────────────
    found = problems(table)
    if found:
        print("карта направлений принимает то, что ролью не является:",
              file=sys.stderr)
        for p in found:
            print(f"  • {p}", file=sys.stderr)
        print("\n  Направление без своего возражения — раздел документации, а "
              "не роль:\n  оно не может ничего остановить (правило 062).",
              file=sys.stderr)
        return 1

    print(f"карта направлений в порядке: ролей {len(table)}, "
          "у каждой своё возражение и назван его адресат")
    return 0


if __name__ == "__main__":
    sys.exit(main())
