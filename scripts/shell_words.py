#!/usr/bin/env python3
"""Слова строки оболочки до первого места, которое не разбирается: один разбор на каталог.

ЛЕНИВО, А НЕ `shlex.split` ЦЕЛИКОМ. Апостроф в постороннем аргументе —
`--msg 'it's'` — роняет разбор всей строки, хотя нужное слово стоит раньше и
прочитано без помех. Прежняя редакция на такой строке называла находкой весь
сырой хвост, и законный вызов краснел (находка обзора на #587). Дальше места
отказа разбор не идёт — это открытый провал с записанным риском (070):
прочитанное верно, непрочитанное не проверено.

ОДИН РАЗБОР (214). До 16.10 эта функция была написана дважды — в
`check_workflows.py` и `check_paging.py`, — и различались они только
разделителями команд. `check_copies` этого не видел: он ищет копии
регулярных выражений, а не функций (находка анализа #879, правило 220).

Реализует правила каталога:
  214 — один предмет разбирает одна реализация;
  070 — эвристика открыта с записанным риском.
"""

import shlex

__all__ = ["слова_оболочки"]


def слова_оболочки(хвост: str, разделители: str = "") -> list[str]:
    """Слова до первого неразбираемого места; `разделители` — знаки, режущие команды (`|&;`)."""
    if разделители:
        лексер = shlex.shlex(хвост, posix=True, punctuation_chars=разделители)
    else:
        лексер = shlex.shlex(хвост, posix=True)
    лексер.whitespace_split = True
    слова: list[str] = []
    try:
        for слово in лексер:
            слова.append(слово)
    except ValueError:
        pass                        # дальше не разбирается; прочитанное — верно
    return слова
