#!/usr/bin/env python3
"""Исключительные утверждения документа сверяются друг с другом, а не с дублями.

Правило 181: «X читают ТОЛЬКО отсюда» связывает весь документ, а не раздел, где
написано. Два таких утверждения об одном предмете друг друга не уточняют —
каждое запрещает второе, и оба перестают действовать.

ПОЧЕМУ ЭТОГО НЕ ЛОВИТ НИЧТО ДРУГОЕ. check_duplicates ищет БЛИЗОСТЬ между
правилами; check_overlap — пересечение файлов. Ни один не ищет
ПРОТИВОПОЛОЖНОСТЬ, а она и не ищется прямо: «всегда отменяй» и «никогда не
отменяй» ближе по смыслу, чем по словам. Зато пара находится по общему
ПРЕДМЕТУ, и это проверено на живом случае, а не предположено.

ЗАМЕР НА ИНЦИДЕНТЕ (4 сентября). Способ прогнан по `CLAUDE.md` грейдера — 1245
строк, 39 исключительных абзацев, 741 пара. Настоящая противоречащая пара
(строки 842 и 1013: «состояние живёт только в issue» против «состояние читают
только из реестра») встала ВТОРЫМ МЕСТОМ с близостью 0,151. То есть человеку
достаточно прочитать несколько верхних пар, чтобы наткнуться на неё.

МАШИНА НЕ СУДИТ, А ЗАСТАВЛЯЕТ ЗАДАТЬ ВОПРОС. Порога у меры нет и быть не может:
0,216 в том же замере — законная пара. Поэтому `--check` требует не отсутствия
близких пар, а ОТВЕТА по каждой из верхних; ровно так устроен check_duplicates,
и по той же причине.

ОКНО — АБЗАЦ, А НЕ ПРЕДЛОЖЕНИЕ (правило 144). Резать по точке здесь нельзя
вдвойне: в наших документах точка стоит внутри имён файлов и номеров версий, а
предмет утверждения часто назван соседней фразой.

Запуск:
  --near          показать верхние пары и их близость
  --check         гейт: у каждой из верхних пар есть ответ в .rules/exclusives.json

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.

Реализует правила каталога:
  181 — исключительные утверждения документа сверяются друг с другом;
  144 — окно разбора прозы — абзац, а не предложение до ближайшей точки;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  075 — ноль исключительных утверждений это отказ, а не чистый прогон;
  158 — третий исход называет предмет отказа, а не только причину;
  051 — гейт не судит о противоречии: порога у меры нет, и красное на законной
        паре приучало бы пропускать красное.
"""

from __future__ import annotations

import argparse
import hashlib
import itertools
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_duplicates import jaccard, shingles  # noqa: E402 — путь задан выше

ROOT = Path(__file__).resolve().parent.parent
ОТВЕТ = Path(".rules") / "exclusives.json"

#: Документы, которые ИСПОЛНЯЮТ, а не описывают. Список разрешительный: свод
#: правил (rules/) сюда не входит — там исключительность и есть предмет записи.
ДОКУМЕНТЫ = ("AGENTS.md", "CLAUDE.md", "CONTRIBUTING.md", "START.md",
             "CONNECT.md", "VERSIONING.md", "README.md")

#: Слова, делающие утверждение исключительным. Именно они превращают два верных
#: ответа в один неверный: без «только» оба утверждения совместимы.
МАРКЕР = re.compile(r"\b(только|лишь|единственн\w*|исключительно)\b", re.I)

#: Сколько верхних пар требуют ответа. Число объявлено, а не выведено: у меры
#: нет порога, и «сколько читать» — решение человека. Двигать его можно вверх.
ВЕРХУШКА = 5

#: Короткие строки отбрасываются: «только» в заголовке или подписи таблицы
#: предметом не является, а шумит.
МИНИМУМ = 60

#: ТАБЛИЦА — НЕ АБЗАЦ, И ЭТО НАЙДЕНО ЗАМЕРОМ, А НЕ ПРИДУМАНО. Первая редакция
#: брала абзац целиком, и три верхние пары из пяти оказались таблица-против-
#: таблицы: близость давала РАЗМЕТКА (`| --- |`, повторяющиеся разделители), а
#: не предмет. Строка таблицы к тому же описывает предмет своей строки и
#: документ не связывает — «только» в ячейке про гейт не запрещает ничего
#: соседнему разделу. Проверено после правки на самом инциденте: настоящая пара
#: грейдера осталась на втором месте.
СТРОКА_ТАБЛИЦЫ = "|"


def имя_пары(файл: str, текст: str) -> str:
    """Устойчивое имя утверждения: файл и отпечаток ЕГО ТЕКСТА.

    ПОЧЕМУ НЕ НОМЕР СТРОКИ, И ЭТО НАЙДЕНО ЖИВЫМ ОТКАЗОМ. Первая редакция звала
    пару «файл:строка», и первая же правка выше по документу — строка в таблице
    гейтов — сдвинула номера у всего, что ниже: пять записанных вердиктов
    разом перестали находиться, а гейт объявил несверенным то, что было
    разобрано десять минут назад. Номер строки — свойство ОКРУЖЕНИЯ абзаца, а
    не его самого (125 в его же формулировке: производное не может быть
    хранилищем).

    Отпечаток текста даёт обратное и нужное: правка соседнего раздела вердикт
    не трогает, а правка САМОГО утверждения его сбрасывает — изменившееся
    утверждение и правда надо разбирать заново.
    """
    отпечаток = hashlib.sha256(текст.encode("utf-8")).hexdigest()[:8]
    return f"{файл}#{отпечаток}"


def утверждения(root: Path) -> list[tuple[str, str, str]]:
    """Исключительные утверждения документов: (имя, адрес для чтения, текст).

    Окно — АБЗАЦ (144). Имя устойчиво к правкам соседей, адрес — «файл:строка»,
    чтобы находку можно было открыть, а не искать (158).
    """
    найдено: list[tuple[str, str, str]] = []
    for имя in ДОКУМЕНТЫ:
        p = root / имя
        if not p.exists():
            continue
        текст = p.read_text(encoding="utf-8")
        номер = 1
        for абзац in re.split(r"\n\s*\n", текст):
            без_таблиц = [l for l in абзац.splitlines()
                          if not l.lstrip().startswith(СТРОКА_ТАБЛИЦЫ)]
            строка = " ".join(" ".join(без_таблиц).split())
            if МАРКЕР.search(строка) and len(строка) >= МИНИМУМ:
                найдено.append((имя_пары(имя, строка), f"{имя}:{номер}", строка))
            номер += абзац.count("\n") + 2
    return найдено


def пары(утв: list[tuple[str, str, str]],
         сколько: int) -> list[tuple[float, tuple, tuple]]:
    """Верхние пары по близости предмета. Мера та же, что у check_duplicates.

    Мера берётся у соседа, а не пишется здесь заново: две формулировки
    «насколько это похоже» разошлись бы молча (022).
    """
    оценки = [(jaccard(shingles(a[2]), shingles(b[2])), a, b)
              for a, b in itertools.combinations(утв, 2)]
    return sorted(оценки, key=lambda x: x[0], reverse=True)[:сколько]


def ключ(a: str, b: str) -> str:
    """Имя пары, не зависящее от порядка."""
    return " ↔ ".join(sorted((a, b)))


def режим_near(root: Path) -> int:
    утв = утверждения(root)
    if not утв:
        print(f"проверка не отработала: в {', '.join(ДОКУМЕНТЫ)} под {root} нет "
              "ни одного исключительного утверждения — предмета нет, и зеленеть "
              "на этом нельзя (075)", file=sys.stderr)
        return 2
    print(f"исключительных утверждений {len(утв)}, "
          f"пар {len(утв) * (len(утв) - 1) // 2}; верхние {ВЕРХУШКА}:\n")
    for бл, a, b in пары(утв, ВЕРХУШКА):
        print(f"  {бл:.3f}  {a[1]} ↔ {b[1]}")
        print(f"         {ключ(a[0], b[0])}")
    print("\n  Близость — повод прочитать, а не приговор: порога у меры нет,\n"
          "  и самая близкая пара обычно законна. Ответ записывается\n"
          f"  в {ОТВЕТ} (правило 181).")
    return 0


def режим_check(root: Path) -> int:
    утв = утверждения(root)
    if not утв:
        print(f"проверка не отработала: в {', '.join(ДОКУМЕНТЫ)} под {root} нет "
              "ни одного исключительного утверждения — предмета нет, и зеленеть "
              "на этом нельзя (075)", file=sys.stderr)
        return 2
    путь = root / ОТВЕТ
    if not путь.exists():
        print(f"проверка не отработала: нет {ОТВЕТ} — ответы о парах живут там "
              "и нигде больше", file=sys.stderr)
        return 2
    try:
        ответы = json.loads(путь.read_text(encoding="utf-8")).get("answers", {})
    except ValueError as e:
        print(f"проверка не отработала: {ОТВЕТ} не разобрать — {e}",
              file=sys.stderr)
        return 2

    верхние = пары(утв, ВЕРХУШКА)
    без_ответа = [(бл, ключ(a[0], b[0]), a[1], b[1]) for бл, a, b in верхние
                  if ключ(a[0], b[0]) not in ответы]
    if без_ответа:
        print("исключительные утверждения не сверены друг с другом:",
              file=sys.stderr)
        for бл, к, аа, аб in без_ответа:
            print(f"  • {бл:.3f}  {аа} ↔ {аб}\n      ключ: {к}",
                  file=sys.stderr)
        print(f"\n  Прочитайте пару и запишите вердикт в {ОТВЕТ}: предметы "
              "разные,\n  либо одно уточняет другое, либо это противоречие и "
              "одно из двух\n  неверно. Гейт не решает — порога у меры нет "
              "(181, 051).", file=sys.stderr)
        return 1

    print(f"исключительные утверждения сверены: их {len(утв)}, "
          f"верхних пар {len(верхние)}, ответов {len(ответы)}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    режим = ap.add_mutually_exclusive_group(required=True)
    режим.add_argument("--near", action="store_true",
                       help="показать верхние пары и их близость")
    режим.add_argument("--check", action="store_true",
                       help="гейт: у каждой из верхних пар есть ответ")
    args = ap.parse_args(argv)
    return режим_near(args.root) if args.near else режим_check(args.root)


if __name__ == "__main__":
    sys.exit(main())
