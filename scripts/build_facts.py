#!/usr/bin/env python3
"""Факты о каталоге для витрины: их публикует он сам, а не считают за него.

ПОЧЕМУ ФАЙЛ, А НЕ «ВИТРИНА ПОСЧИТАЕТ». Считать чужие числа со стороны значит
держать копию чужого устройства: где лежат тесты, как назван их каталог, какие
работы стоят на изменении. Копия верна до первой правки на этой стороне и
расходится молча. Замер витрины, из-за которого контракт и появился: медиана по
семи изменениям дала 19 проверок, точный ответ издателя — 16. Это правило 174,
и каталог его сам же и принял.

ЧИСЛА БЕРУТСЯ У ТЕХ, КТО ИХ СЧИТАЕТ, А НЕ СЧИТАЮТСЯ ЗАНОВО:
  • имя репозитория — `check_own_name.own_slug`, то есть адрес `origin`;
  • покрытие — `coverage_badge.measured`, то есть сам замер, а не его
    округлённая отрисовка в значке;
  • планка языка — `check_python_version.floor`, версии прогонов — его же
    `in_workflows`;
  • события и работы прогонов — `check_workflows.sections`/`events`;
  • версия и выпуск — `version.version`/`latest_tag`, то есть git-тег, тот же,
    из которого рисуются значки `version.json` и `release.json`.
Второе выражение любого из этих чисел разошлось бы с первым молча.

БЕЗ YAML-ПАРСЕРА, И ЭТО НЕ ВКУС. Работа `catalogue` идёт на голой стандартной
библиотеке: первая редакция `check_workflows.py` звала `yaml.safe_load` и
падала с `ModuleNotFoundError`. Разбор прогонов здесь тот же, построчный, и
берётся он оттуда же, а не пишется второй раз.

ПО КАЖДОМУ ПОКАЗАТЕЛЮ — ЗНАЧЕНИЕ ИЛИ ПРИЧИНА, ТРЕТЬЕГО НЕТ (договор 1.2,
ArtVsMark/Engineering-Incidents-Playbook#632). Неизмеренный показатель
ОТСУТСТВУЕТ, а не выставляется в ноль, и причина его отсутствия лежит в самом
файле, в разделе `none`: до 1.2 она печаталась только в журнал прогона, и
читатель файла отличить «не измеряли» от «забыли» не мог (039, 075).

ФАЙЛ НЕ ЗАВОДИТСЯ ПУСТЫМ. Контракт говорит прямо: проекту, которому измерять
нечего, файл не заводится — пустой ответ хуже отсутствующего, он выглядит
измеренным отсутствием. Обязательный минимум измерением НЕ является: `schema`
константа, `generated_at` часы, `repo` адрес origin. Не собрался ни один
раздел — исход 1 и файла нет.

Запуск:
  python scripts/build_facts.py            # собрать .github/badges/facts.json
  python scripts/build_facts.py --print    # показать, ничего не записывая

Исходы:
  0 — файл собран;  1 — измерять нечего, файл не записан;
  2 — сбор не отработал.

Реализует правила каталога:
  174 — факты о проекте публикует сам проект, а не считает читатель;
  160 — производное, обновляемое чаще изменений, живёт вне общей ветки:
        файл пишется в `.github/badges/`, откуда `badges.yml` уносит его на
        ветку `badges`, и в общей ветке его нет вовсе;
  164 — номер схемы говорит, ЧЕГО он: рядом стоит `schema_of`, потому что
        ключ `schema` в этой экосистеме носят четыре разных предмета;
  039 — три исхода, и «не измеряли» отличается от «ноль»;
  075 — пропущенный раздел называется вслух, а не молчит.
"""


import argparse
import datetime as dt
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_own_name  # noqa: E402
import check_python_version  # noqa: E402
import check_workflows  # noqa: E402
import coverage_badge  # noqa: E402
import version  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
FACTS = ROOT / ".github" / "badges" / "facts.json"
WORKFLOWS = ROOT / ".github" / "workflows"

#: Версия ФОРМАТА этого файла, строкой. Числом её писать нельзя: `1.0` и `1.10`
#: неразличимы, и расхождение уже случилось — сосед публикует `1`, а не `"1"`.
#:
#: 1.1: в разбивке активного появился ключ `skill` — словарь механизмов вырос
#: на навык агента. Ключ стоит ВСЕГДА, включая ноль, как и остальные роды:
#: состав полей публикуемого файла изменился, и молчание об этом сделало бы
#: номер бесполезным (164). Читателя прежней версии прибавление не ломает — он
#: незнакомый ключ просто не видит, — но номер двигается всё равно.
#:
#: 1.2: договор витрины «один файл, единые требования» (#632). Обязательны
#: `commit` и `ci`; появились `version` и `release`, которые витрина прежде
#: брала из значков; пропуск показателя называет причину в разделе `none`.
#: Раздел `rules` договору не нужен, но сверх схемы поля не запрещены, и он
#: остаётся: его читают помимо витрины. СНЯТО В 1.4: утверждение о читателях
#: стояло без замера, и замер 09.10 его не подтвердил — `rules` из этого файла
#: не читал ни каталог, ни витрина (она берёт доли из export/where.json), ни
#: соседние издатели (181).
#:
#: 1.3: договор витрины 1.3 (ArtVsMark/ArtVsMark#265, решение владельца
#: 2 октября, задача #658). `release` — серия из двух чисел `X.Y`, а не тег:
#: третья цифра тега выпуска всегда 0 (docs/VERSIONING.md), а `v` — запись
#: тега, не выпуска. `version` — сборка `X.Y.Z` и начинается с серии и точки.
#:
#: 1.4: договор витрины 1.4 (тег facts-v1.4.0; номер договора лежит в
#: ArtVsMark/ArtVsMark:.rules/facts.version — файле витрины, не каталога).
#: Раздела `rules` в корне больше нет: доли механизмов
#: витрина берёт из сводки каталога `export/where.json`, а второй источник того
#: же числа расходится с первым (090) — с 1.4 договор его называет, с 2.0
#: отвергает. Своё сверх договора проект кладёт в `exchange.<тема>`; у каталога
#: такого нет.
#:
#: 1.5: форма та же, договор поднимает минор на КАЖДУЮ свою правку, включая
#: прозу и проверку (тег facts-v1.5.0). С 1.5 издатель сверяет файл проверкой
#: витрины, прибитой к тегу, до публикации — шаг стоит в badges.yml.
SCHEMA = "1.5"

#: Прогон CI, чей статус витрина спрашивает у площадки. Файл называется, а не
#: выводится: обязательная проверка у каталога одна, и живёт она здесь (168).
CI_WORKFLOW = "ci.yml"

#: Показатели, у которых договор 1.2 принимает «значение либо причина». Ключи
#: `none` вне этого списка схема отвергает, поэтому причина пропуска `rules`
#: туда не идёт: этого показателя договор не спрашивает.
#:
#: КОПИЯ ЧУЖОЙ СХЕМЫ, И СВЕРКА У НЕЁ РУЧНАЯ — это названо, а не скрыто (071,
#: 209). Канон — `properties.none.propertyNames.enum` в
#: ArtVsMark/ArtVsMark:.rules/facts.schema.json. Сверяется валидатором витрины:
#: `python <клон ArtVsMark>/scripts/check_facts.py --file
#: .github/badges/facts.json --repo ArtVsMark/Engineering-Incidents-Playbook`.
#: Пересверять при каждом подъёме договора фактов. Витрина гоняет ту же
#: проверку по всем соседям ежедневно. С договора 1.5 та же проверка стоит
#: и у нас — шагом badges.yml перед публикацией, по тегу и с прибитыми хэшами
#: файлов: чужой код в конвейер входит, но только прочитанный (обзор #803).
ДОГОВОРНЫЕ = ("version", "release", "coverage_percent", "tests", "python",
              "checks_per_pr")

SCHEMA_OF = ("формат ЭТОГО файла — факты каталога для витрины профиля. Не "
             "версия каталога, не номер выпуска и не схема выгрузки правил: "
             "ключ `schema` в этой экосистеме носят четыре разных предмета "
             "(выгрузка, ответ потребителя, сводка, факты) — правило 164")

#: Что именно здесь считается проверкой на изменении. Определение публикуется
#: вместе с числом намеренно: снаружи проверок ВИДНО БОЛЬШЕ — работа `open` из
#: `agent-pr.yml` просыпается на толчок в ветку и попадает в тот же коммит.
#: Она не «на изменение»: у изменения из форка её не будет. Контракт запрещает
#: публиковать оценки, поэтому здесь стоит то, что издатель знает точно.
CHECKS_OF = ("работы прогонов, просыпающихся на событие pull_request. Проверок "
             "у коммита может быть видно больше: работа, разбуженная толчком в "
             "ветку, попадает в ту же голову, но изменением не вызвана")

#: Поля, без которых договор 1.2 отвергает файл целиком: причины в `none` у
#: них не бывает. Пропал любой — файл не пишется, исход 2: витрина отвергла бы
#: его в тот же день, а у нас это выглядело бы публикацией (находка ревью #634).
ОБЯЗАТЕЛЬНЫЕ = ("commit", "ci")

#: Разделы, которые и есть ИЗМЕРЕНИЕ. Обязательный минимум сюда не входит
#: намеренно: schema — константа, generated_at — часы, repo — адрес origin, и
#: файл из них одних измеренным отсутствием только выглядит. Список читается
#: исходом 1: не собрался ни один — публиковать нечего.
ИЗМЕРЯЕМОЕ = ("tests", "checks_per_pr", "python", "coverage_percent")

#: Тестовая функция и тестовый модуль. Считается то же, что считает pytest по
#: своим умолчаниям, и границы названы здесь, а не подразумеваются.
TEST_DEF_RE = re.compile(r"^\s*(?:async\s+)?def\s+(test_\w*)", re.M)

#: `runs-on: ubuntu-latest` — исполнитель работы. Матрицы у каталога нет, и
#: значения из неё здесь не раскрываются: раскрытие было бы вторым разбором.
RUNS_ON_RE = re.compile(r"^\s*runs-on:\s*\"?([\w.-]+)\"?\s*$", re.M)


def git(*args: str) -> tuple[int, str]:
    """Вызов git с прочитанным выводом. Отказ — значение, а не исключение."""
    try:
        done = subprocess.run(["git", "-C", str(ROOT), *args],
                              capture_output=True, text=True, encoding="utf-8")
    except OSError as exc:
        return 1, str(exc)
    return done.returncode, (done.stdout or done.stderr).strip()


def tests() -> tuple[dict | None, str]:
    """Функции и модули набора. Вторая строка — почему раздела не будет."""
    каталог = ROOT / "tests"
    if not каталог.is_dir():
        return None, "каталога tests/ нет"
    модули = sorted(p for p in каталог.glob("test_*.py"))
    if not модули:
        return None, "в tests/ нет ни одного модуля test_*.py"
    функций = sum(len(TEST_DEF_RE.findall(p.read_text(encoding="utf-8",
                                                      errors="replace")))
                  for p in модули)
    return {"functions": функций, "modules": len(модули)}, ""


def checks_per_pr() -> tuple[dict | None, str]:
    """Работы прогонов, которые будит само изменение."""
    if not WORKFLOWS.is_dir():
        return None, "каталога .github/workflows нет"
    имена: list[str] = []
    for файл in sorted(WORKFLOWS.glob("*.yml")):
        текст = файл.read_text(encoding="utf-8", errors="replace")
        if "pull_request" not in check_workflows.events(текст):
            continue
        блок = check_workflows.sections(текст).get("jobs") or []
        имена += [m.group(1) for m in
                  (check_workflows.KEY_RE.match(line) for line in блок) if m]
    if not имена:
        return None, "ни один прогон не просыпается на pull_request"
    return {"count": len(имена), "names": sorted(имена), "counts_": CHECKS_OF}, ""


def python() -> tuple[dict | None, str]:
    """Версии языка и исполнители. Планка отдельно от того, на чём гоняем."""
    манифест = ROOT / "pyproject.toml"
    if not манифест.is_file():
        return None, "нет pyproject.toml — планку языка назвать нечем"
    планка = check_python_version.floor(манифест.read_text(encoding="utf-8"))
    версии = sorted({v for _, v in check_python_version.in_workflows(ROOT)})
    if планка is None and not версии:
        return None, "ни планки в манифесте, ни python-version в прогонах"
    исполнители = sorted({m.group(1) for файл in WORKFLOWS.glob("*.yml")
                          for m in RUNS_ON_RE.finditer(
                              файл.read_text(encoding="utf-8", errors="replace"))})
    раздел: dict = {}
    if версии:
        раздел["supported"] = [f"{a}.{b}" for a, b in версии]
    if планка is not None:
        раздел["floor"] = f"{планка[0]}.{планка[1]}"
    if исполнители:
        раздел["os"] = исполнители
    return (раздел or None), ("" if раздел else "нечего сказать о языке")


def coverage() -> tuple[float | None, str]:
    """Покрытие — у того, кто его замерил, а не из отрисованного значка.

    ЧИСЛО БЕРЁТСЯ У ЗАМЕРА, А НЕ У КАРТИНКИ. Первая редакция разбирала поле
    `message` значка — а оно округлено до целого (`{:.0f}%`), и 99.2 приезжало
    бы как 99. Контракт витрины просит число ИМЕННО затем, что оно точнее
    значка: «дублирует значок; число удобнее для сравнения». Разбирать
    отрисованное значило бы публиковать копию картинки вместо замера (122).
    """
    try:
        percent = coverage_badge.measured()
    except coverage_badge.Unreadable as отказ:
        # Данные есть и не разбираются — пропуск с названной причиной, а не
        # исключение сквозь всю сборку фактов: остальные разделы от этого не
        # хуже, и молчать о покрытии нельзя, а падать всем — незачем (158).
        return None, f"замер покрытия не разобран: {отказ}"
    if percent is None:
        return None, ("замера покрытия в этом прогоне не было: "
                      f"{coverage_badge.DATA.name} отсутствует либо пакет "
                      "coverage не установлен")
    return round(float(percent), 1), ""


def версия() -> tuple[str | None, str]:
    """Версия каталога «X.Y.N» — у того же тега, что значок `version.json`."""
    пара = version.version()
    if пара is None:
        return None, ("тега схемы vX.Y.Z не видно: версия выводится из тега, "
                      "и без него она недостоверна (scripts/version.py)")
    return пара[1], ""


def выпуск() -> tuple[str | None, str]:
    """Последний выпуск — серия `X.Y` (договор 1.3), а не тег `vX.Y.0`.

    Серию даёт version.version — тот же разбор тега, из которого рисуются
    значки и `version` этого же файла (214): так `version` по построению
    начинается с `release` и точки."""
    пара = version.version()
    if пара is None:
        return None, "тега выпуска vX.Y.0 не видно — выпусков не было либо клон мелкий"
    return пара[0], ""


def build() -> tuple[dict | None, list[str], str]:
    """Факты, список названных пропусков и причина отказа сборки."""
    slug, беда = check_own_name.own_slug(ROOT)
    if not slug:
        return None, [], f"имя репозитория не спросить — {беда}"

    факты: dict = {
        "schema": SCHEMA,
        "schema_of": SCHEMA_OF,
        "repo": slug,
        "generated_at": dt.datetime.now(dt.UTC).isoformat(timespec="seconds"),
    }

    пропуски: list[str] = []
    код, голова = git("rev-parse", "HEAD")
    if код == 0 and голова:
        факты["commit"] = голова
    else:
        пропуски.append(f"commit: {голова or 'git не ответил'}")
    if (WORKFLOWS / CI_WORKFLOW).is_file():
        факты["ci"] = {"workflow": CI_WORKFLOW}
    else:
        пропуски.append(f"ci: прогона {CI_WORKFLOW} в .github/workflows нет")

    причины: dict[str, str] = {}
    for ключ, значение, почему in (
            ("version", *версия()),
            ("release", *выпуск()),
            ("tests", *tests()),
            ("checks_per_pr", *checks_per_pr()),
            ("python", *python()),
            ("coverage_percent", *coverage())):
        if значение is None:
            пропуски.append(f"{ключ}: {почему}")
            if ключ in ДОГОВОРНЫЕ:
                причины[ключ] = почему
        else:
            факты[ключ] = значение
    if причины:
        факты["none"] = причины
    return факты, пропуски, ""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--print", action="store_true", dest="show",
                    help="показать собранное, ничего не записывая")
    args = ap.parse_args(argv)

    факты, пропуски, беда = build()
    if беда or факты is None:
        print(f"сбор не отработал: {беда or 'фактов не собрано'}", file=sys.stderr)
        return 2
    # ИСХОД 1 — «ИЗМЕРЯТЬ НЕЧЕГО», И ЭТО ТРЕБОВАНИЕ КОНТРАКТА, А НЕ ФОРМАЛЬНОСТЬ.
    # Он говорит прямо: проекту, которому измерять нечего, файл НЕ ЗАВОДИТСЯ —
    # пустой ответ хуже отсутствующего, он выглядит измеренным отсутствием.
    # Обязательный минимум сам по себе не измерение: schema — константа,
    # generated_at — часы, repo — адрес origin. Не измерился ни один раздел —
    # публиковать нечего.
    #
    # ПЕРВАЯ РЕДАКЦИЯ ОБЪЯВЛЯЛА ЭТОТ ИСХОД И НЕ МОГЛА ЕГО ДАТЬ. Условием стояла
    # неполнота минимума — а она недостижима: `build()` отдаёт пустые факты
    # только вместе с названной бедой, то есть исходом 2 строкой выше. Найдено
    # внешним взглядом; объявленный, но недостижимый исход — то же, что
    # мёртвый разбор кода возврата (039, 145).
    if not any(k in факты for k in ИЗМЕРЯЕМОЕ):
        print("измерять нечего: ни один раздел не собрался — файл не записан. "
              "Пустой ответ хуже отсутствующего, он выглядит измеренным "
              "отсутствием", file=sys.stderr)
        for п in пропуски:
            print(f"  не измерено — {п}", file=sys.stderr)
        return 1
    нет = [k for k in ОБЯЗАТЕЛЬНЫЕ if k not in факты]
    if нет:
        print(f"сбор не отработал: нет обязательных полей договора 1.2 — "
              f"{', '.join(нет)}. Файл без них витрина отвергает, и "
              "публиковать его значило бы выдать отказ за факты", file=sys.stderr)
        for п in пропуски:
            print(f"  не измерено — {п}", file=sys.stderr)
        return 2

    текст = json.dumps(факты, ensure_ascii=False, indent=2) + "\n"
    if args.show:
        print(текст, end="")
    else:
        try:
            FACTS.parent.mkdir(parents=True, exist_ok=True)
            FACTS.write_text(текст, encoding="utf-8")
        except OSError as exc:
            print(f"сбор не отработал: {FACTS} не записан — {exc}",
                  file=sys.stderr)
            return 2
        print(f"факты собраны: {FACTS.relative_to(ROOT)}, "
              f"разделов {len(факты)}")
    # ПРОПУСК НАЗЫВАЕТСЯ, А НЕ МОЛЧИТ. «Ключа нет» — законное состояние, но
    # только если известно, ПОЧЕМУ его нет: иначе оно неотличимо от забытого.
