#!/usr/bin/env python3
"""Зелёное со второй попытки на общей ветке записано как нестабильность — или названо.

Правило 124: перезапуск разрешён, но зелёное со второго раза — находка, а не
починка. Таблица случаев стоит в AGENTS.md § Перезапуск — это диагностика, и
у каждого случая названо, что записывается: работа зеленела раньше на этом же
коммите или умерла до первого теста — фрагмент журнала с номером прогона.
Держалось это чтением: число «сколько раз зелёное пришло со второй попытки» не
собирал никто, хотя площадка отдаёт его в каждом прогоне полем `run_attempt`.

ЧТО ЗДЕСЬ МАШИННОЕ. Прогон общей ветки с `run_attempt > 1` и исходом
`success` — зелёный не с первой попытки. Записан он, если в журнале —
фрагментах `changelog.d/**` и `CHANGELOG.md` — есть абзац, где его номер стоит
целым числом рядом со словом записи: «нестабильн…» или «до первого теста» (два
случая из таблицы 124, у которых запись обязательна). Номер в чужой ссылке или
в абзаце о другом записью не считается (обзор #833). Не записан — пункт в одной
живой задаче с маркером; записаны все — задача, если открыта, обновляется на
«пусто», а закрывает её человек.

ПУНКТ ЖИВЁТ, ПОКА НЕ ЗАПИСАН, А НЕ ПОКА В ОКНЕ (обзор #833). Окно в двое суток
задаёт, какие прогоны просматриваются, но не сколько ждёт запись: пункты
прежнего тела задачи переносятся в новое и уходят только записью. Без переноса
прогон, незаписанный за двое суток, выпадал из окна, и задача сама писала
«каждый повторный зелёный записан».

ЧЕГО ЗДЕСЬ НЕТ. Связаны ли работы общим состоянием (граница 124) и тот ли это
из трёх законных случаев — машина не различает: она называет прогон, судит
человек. Совещательно: красное здесь — источник работы, а не здоровье ветки,
и слияние оно не держит (084).

СПИСОК ЧИТАЕТСЯ ДО КОНЦА (212), А ОКНО ЗАДАНО ДАТОЙ. Предел «свежие 100» здесь
не годится: в день с десятком слияний прогонов на общей ветке больше сотни, и
хвост пропадал бы молча. Поэтому окно — зелёные прогоны за последние
`--days` суток (по умолчанию двое: заход суточный, и сутки запаса покрывают
опоздание расписания), а внутри окна обходятся все страницы. Число страниц —
оценка, а не предел: кода, который его держит, нет, и оно растёт с числом
прогонов.

ГРАНИЦА: ОКНО ПО `created`, А НЕ ПО ПЕРЕЗАПУСКУ (обзор #833). Площадка фильтрует
прогоны по дате создания, и у перезапуска она остаётся датой первой попытки:
прогон, перезапущенный позже `--days` суток после создания, в окно не попадает.
Фильтра по времени попытки площадка не даёт, а читать без окна значит читать
всю историю. Это названная граница, а не исправленная.

Реализует правила каталога:
  124 — зелёное со второй попытки записывается нестабильностью с номером прогона;
  142 — у красного по расписанию есть адресат: одна живая задача;
  084 — совещательный канал слияние не держит;
  212 — список площадки читается до названного предела, и предел объявлен;
  039 — три исхода: чисто · есть находки · проверка не отработала.

Запуск:
  python scripts/flaky_reruns.py [--apply] [--run-url URL]

Исходы:
  0 — все повторные зелёные записаны;  1 — есть незаписанные;
  2 — проверка не отработала (площадка или трекер не ответили).
"""

import argparse
import datetime as dt
import re
import sys
from pathlib import Path

import ghcli
import main_red

ROOT = Path(__file__).resolve().parent.parent
MARKER = "<!-- flaky-reruns: не удаляйте, по этой строке задача находится снова -->"
TITLE = "Зелёное со второй попытки не записано как нестабильность"
#: Слова записи: два случая таблицы 124, у которых запись обязательна.
ЗАПИСЬ_RE = re.compile(r"нестабильн|до первого теста", re.IGNORECASE)
#: Пункт тела задачи — его же пишет `тело()`; по нему пункт переносится.
ПУНКТ_RE = re.compile(
    r"^- `(?P<name>[^`]*)` · попытка (?P<attempt>\d+) · "
    r"\[(?P<id>\d+)\]\((?P<url>[^)]*)\) · `(?P<sha>[^`]*)`$",
    re.M,
)


def повторные(прогоны: list[dict]) -> list[dict]:
    """Зелёные не с первой попытки."""
    return [
        п
        for п in прогоны
        if п.get("conclusion") == "success" and int(п.get("run_attempt") or 1) > 1
    ]


def журнал(root: Path) -> str:
    """Весь текст журнала: фрагменты, вышедшие и нет, и собранный файл."""
    части = [p.read_text(encoding="utf-8") for p in sorted((root / "changelog.d").rglob("*.md"))]
    if (root / "CHANGELOG.md").is_file():
        части.append((root / "CHANGELOG.md").read_text(encoding="utf-8"))
    return "\n".join(части)


def записан(номер: object, текст: str) -> bool:
    """Есть ли абзац журнала, где номер стоит целым числом рядом со словом записи."""
    число = re.compile(rf"(?<!\d){re.escape(str(номер))}(?!\d)")
    return any(
        число.search(абзац) and ЗАПИСЬ_RE.search(абзац) for абзац in re.split(r"\n\s*\n", текст)
    )


def прежние(body: str) -> list[dict]:
    """Пункты прежнего тела задачи — прогоны, ещё ждущие записи."""
    return [
        {
            "id": int(m["id"]),
            "name": m["name"],
            "run_attempt": int(m["attempt"]),
            "conclusion": "success",
            "html_url": m["url"],
            "head_sha": m["sha"],
        }
        for m in ПУНКТ_RE.finditer(body)
    ]


def незаписанные(прогоны: list[dict], текст: str, ждущие: list[dict] | None = None) -> list[dict]:
    """Повторные зелёные из окна и прежние пункты, которых журнал не записал."""
    по_номеру = {п.get("id"): п for п in [*(ждущие or []), *повторные(прогоны)]}
    return [п for п in по_номеру.values() if not записан(п.get("id"), текст)]


def тело(найдено: list[dict], run_url: str) -> str:
    строки = [
        f"- `{п.get('name')}` · попытка {п.get('run_attempt')} · "
        f"[{п.get('id')}]({п.get('html_url')}) · `{str(п.get('head_sha'))[:7]}`"
        for п in найдено
    ]
    return (
        "\n".join(
            [
                MARKER,
                "",
                "Прогоны общей ветки, позеленевшие не с первой попытки, чьих номеров нет "
                "в журнале (правило 124):",
                "",
                *(строки or ["- нет: каждый повторный зелёный записан"]),
                "",
                "Зелёное со второго раза — находка, а не починка. Запишите фрагментом "
                "журнала, что упало и на каком шаге, с номером прогона: «нестабильность», "
                "если та же работа зеленела на этом коммите раньше, или «умерла до первого "
                "теста». Пункт уйдёт следующим заходом. Задачу закрывает человек.",
                "",
                f"Прогон: {run_url}" if run_url else "",
            ]
        ).rstrip()
        + "\n"
    )


def тело_задачи() -> tuple[int | None, str, str | None]:
    """Номер открытой задачи с маркером, её тело и причина отказа."""
    номер, отказ = main_red.find_issue(MARKER)
    if отказ is not None or номер is None:
        return None, "", отказ
    code, out = ghcli.run("api", f"repos/{{owner}}/{{repo}}/issues/{номер}", "--jq", ".body")
    return (номер, out, None) if code == 0 else (None, "", f"тело задачи #{номер} — {out}")


def записать(body: str, есть_что: bool) -> tuple[int, str]:
    """Одна задача на маркер: найти и обновить; нет её — завести, если есть что."""
    номер, отказ = main_red.find_issue(MARKER)
    if отказ is not None:
        return 2, f"трекер не прочитан — {отказ}"
    if номер is None and not есть_что:
        return 0, "задачи нет, и заводить нечего"
    if номер is not None:
        code, out = ghcli.run(
            "api",
            "--method",
            "PATCH",
            f"repos/{{owner}}/{{repo}}/issues/{номер}",
            "-f",
            f"body={body}",
        )
        что = f"задача #{номер} обновлена"
    else:
        code, out = ghcli.run(
            "api",
            "repos/{owner}/{repo}/issues",
            "-f",
            f"title={TITLE}",
            "-f",
            f"body={body}",
            "-f",
            "labels[]=area/gates",
        )
        что = "задача заведена"
    return (0, что) if code == 0 else (2, f"трекер не принял запись — {out}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    ap.add_argument("--apply", action="store_true", help="вести живую задачу")
    ap.add_argument("--run-url", default="")
    ap.add_argument("--days", type=int, default=2, help="окно в сутках")
    args = ap.parse_args(argv)

    с = (dt.datetime.now(dt.UTC) - dt.timedelta(days=args.days)).date().isoformat()
    code, прогоны, почему = ghcli.список(
        f"repos/{{owner}}/{{repo}}/actions/runs?branch=main&status=success"
        f"&created=>={с}&per_page=100",
        ".workflow_runs[]",
    )
    if code != 0:
        print(
            f"проверка не отработала: прогоны общей ветки с {с} не прочитаны — {почему}",
            file=sys.stderr,
        )
        return 2
    try:
        текст = журнал(args.root)
    except OSError as exc:
        print(f"проверка не отработала: журнал не прочитан — {exc.filename}", file=sys.stderr)
        return 2

    ждущие: list[dict] = []
    if args.apply:
        _, прежнее, отказ = тело_задачи()
        if отказ is not None:
            print(f"проверка не отработала: трекер не прочитан — {отказ}", file=sys.stderr)
            return 2
        ждущие = прежние(прежнее)
    найдено = незаписанные(прогоны, текст, ждущие)
    print(
        f"зелёных прогонов с {с}: {len(прогоны)}, не с первой попытки: "
        f"{len(повторные(прогоны))}, ждали записи из задачи: {len(ждущие)}, "
        f"не записано: {len(найдено)}"
    )
    for п in найдено:
        print(f"  · {п.get('name')} · попытка {п.get('run_attempt')} · {п.get('html_url')}")

    if args.apply:
        code, что = записать(тело(найдено, args.run_url), bool(найдено))
        if code:
            print(f"проверка не отработала: задача с маркером {MARKER} — {что}", file=sys.stderr)
            return 2
        print(что)
    return 1 if найдено else 0


if __name__ == "__main__":
    sys.exit(main())
