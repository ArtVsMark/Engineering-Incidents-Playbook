#!/usr/bin/env python3
"""Разрез текста по точке объявляет, что режет, — иначе это проза.

Правило 144: машинный разбор человеческого текста берёт контекст АБЗАЦЕМ, а не
«предложением до ближайшей точки». В технической прозе точка стоит внутри имён
— `SECURITY.md`, `v1.2.0`, `re.finditer`, — и резать по ней значит отрезать
половину смысла у случайно выбранных фрагментов.

ПРЕЖНИЙ ОТВЕТ КАТАЛОГА БЫЛ «ГЕЙТ ЛОВИЛ БЫ ЗАКОННОЕ ЧАЩЕ НАРУШЕНИЙ». Он верен
для гейта, который РЕШАЕТ, проза перед ним или нет: различить путь модуля и
абзац по коду нельзя. Но решать и не требуется. Требуется, чтобы решение было
ПРИНЯТО ВСЛУХ у каждого разреза — тем же приёмом, каким пропущенный тест
называет причину (check_skips.py), а подделка — источник (check_forgeries.py).
Машина держит не суждение, а то, что вопрос задан.

ЗАМЕР ПРИ ЗАВЕДЕНИИ (4 сентября): разрезов по точке в дереве ЧЕТЫРЕ, и все
четыре законны — два режут путь модуля (`a.name.split(".")[0]`), два номер
версии. Это и есть цена правила: нарушений сегодня нет, а следующий разрез
пишется через месяц и молча.

ЧЕГО ГЕЙТ НЕ ДЕЛАЕТ. Не судит, верна ли пометка: «не проза: путь модуля» на
абзаце он пропустит. Не смотрит на положительную половину правила — что окно
уже абзаца задаётся РАЗМЕТКОЙ, — она принадлежит форме разборщика, а не одному
вызову, и проверяется чтением.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.

Реализует правила каталога:
  144 — контекст берётся абзацем; разрез по точке объявляет, что он режет;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  075 — ноль исходников это отказ, а не чистый прогон;
  158 — третий исход называет предмет отказа, а не только причину;
  165 — печатается ОХВАТ: сколько файлов просмотрено и сколько разрезов найдено.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: Чем режут строку. Список разрешительный: новый способ вписывается осознанно.
РЕЗАКИ = ("split", "rsplit", "partition", "rpartition", "find", "index")

#: Разделители, режущие по пунктуации. Регулярка с классом сюда же: `[.!?]`
#: режет по предложениям ровно тем способом, о котором правило.
ТОЧКИ = (".", "\\.", "[.!?]", ". ", "\\. ", "[.?!]")

#: Пометка, которой разрез объявляет свой предмет. Слово выбрано утвердительным
#: («не проза»), а не вопросительным: пометка — это РЕШЕНИЕ автора, и читаться
#: она должна как решение.
ПОМЕТКА = "не проза:"


def разрезы(source: str) -> list[tuple[int, str]]:
    """Строки, где текст режут по точке. Разбор дерева, а не поиск подстроки.

    Поиск по тексту нашёл бы `split(".")` в докстроке этого самого файла и
    пропустил бы вызов, разложенный по строкам (166).
    """
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return []
    найдено: list[tuple[int, str]] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call) or not node.args:
            continue
        имя = getattr(node.func, "attr", "") or getattr(node.func, "id", "")
        if имя not in РЕЗАКИ:
            continue
        # У re.split разделитель первым аргументом, у метода строки — тоже
        # первым; смотрим оба первых, чтобы не зависеть от формы вызова.
        for arg in node.args[:2]:
            if isinstance(arg, ast.Constant) and arg.value in ТОЧКИ:
                найдено.append((node.lineno, имя))
                break
    return sorted(set(найдено))


def объявлено(строки: list[str], номер: int) -> bool:
    """Пометка стоит на самой строке разреза либо на предыдущей.

    Окно в две строки, а не в одну: вызов часто переносят, и пометка тогда
    естественно оказывается над ним. Больше двух — уже не «рядом», и пометка
    начала бы засчитываться от чужого разреза.
    """
    for i in (номер - 1, номер - 2):
        if 0 <= i < len(строки) and ПОМЕТКА in строки[i]:
            return True
    return False


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)

    файлы = sorted(list((args.root / "scripts").glob("*.py"))
                   + list((args.root / "tests").glob("*.py"))
                   + list((args.root / "templates").glob("*.py")))
    # ── исход 2 ────────────────────────────────────────────────────────────
    if not файлы:
        print(f"проверка не отработала: в {args.root}/{{scripts,tests,"
              "templates}} нет ни одного *.py — проверять нечего, и зеленеть "
              "на этом нельзя", file=sys.stderr)
        return 2

    находки: list[str] = []
    всего = 0
    for f in файлы:
        текст = f.read_text(encoding="utf-8")
        строки = текст.splitlines()
        for номер, имя in разрезы(текст):
            всего += 1
            if not объявлено(строки, номер):
                находки.append(f"{f.relative_to(args.root)}:{номер} — "
                               f"{имя} по точке без пометки «{ПОМЕТКА}»")

    # ── исход 1 ────────────────────────────────────────────────────────────
    if находки:
        print("текст режут по точке, не сказав, что режут:", file=sys.stderr)
        for n in находки:
            print(f"  • {n}", file=sys.stderr)
        print(f"\n  Допишите рядом `# {ПОМЕТКА} <что именно>` — путь модуля, "
              "номер версии,\n  расширение файла. Если же режется ПРОЗА, "
              "разрез неверен: точка стоит\n  внутри имён (SECURITY.md, "
              "v1.2.0), и контекст берут абзацем (144).", file=sys.stderr)
        return 1

    print(f"разрезы объявлены: просмотрено файлов {len(файлы)}, "
          f"разрезов по точке {всего}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
