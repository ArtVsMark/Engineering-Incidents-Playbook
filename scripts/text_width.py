#!/usr/bin/env python3
"""Ширина надписи в SVG — суммой ширин знаков по таблице шрифта, одна на каталог.

Реализует правила каталога:
  214 — один вопрос — одна реализация: ширину надписи считали два генератора
        картинок, каждый своей формулой «длина × коэффициент» (`python_badge`,
        `consumers_picture`), и обе ошибались по-своему. Следующий генератор
        берёт эту функцию, а не заводит третий коэффициент — держит это
        tests/test_text_width.py.

Знак вне таблицы не сжимается: ему дана ширина самого широкого знака того же
начертания, и надпись скорее просторнее, чем обрезана.

ПОЧЕМУ ТАБЛИЦА, А НЕ КОЭФФИЦИЕНТ (#792). У Verdana 11px `l`, `i` и пробел
занимают 3–4 px, а `m` и `w` — 9–11: одна ширина на знак раздувала значок
на 20–25 % (`coverage / all (os)` — 151 px вместо 113). Таблица в
`text_widths.json` снята с файлов шрифта (hmtx), а не подобрана глазом.

ГРАНИЦА. Считается ширина начертания, названного в таблице. Какой шрифт
нарисует зритель, решает его площадка: если в списке `font-family` первым не
найдётся табличный, надпись выйдет другой ширины, и это отсюда не видно.
"""

import json
from functools import cache
from pathlib import Path

ТАБЛИЦА = Path(__file__).resolve().parent / "text_widths.json"


@cache
def _шрифты() -> dict:
    return json.loads(ТАБЛИЦА.read_text(encoding="utf-8"))["fonts"]


def _начертание(шрифт: str, вес: int) -> tuple[dict[str, int], int]:
    """Таблица ближайшего начертания НЕ ЛЕГЧЕ запрошенного и единиц на кегль.

    Тяжелее — значит шире: ошибка в эту сторону даёт воздух, а не обрезку.
    """
    данные = _шрифты()[шрифт]
    веса = sorted(int(w) for w in данные["weights"])
    подходящий = next((w for w in веса if w >= вес), веса[-1])
    return данные["weights"][str(подходящий)], данные["units"]


def ширина(текст: str, шрифт: str = "Verdana", кегль: float = 11.0,
           вес: int = 400, разрядка: float = 0.0) -> float:
    """Ширина надписи в пикселях: сумма ширин знаков плюс разрядка между ними."""
    таблица, единиц = _начертание(шрифт, вес)
    запас = max(таблица.values())
    единицы = sum(таблица.get(знак, запас) for знак in текст)
    return единицы * кегль / единиц + разрядка * len(текст)
