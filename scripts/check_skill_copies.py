#!/usr/bin/env python3
"""Копия навыка каталога у потребителя совпадает с навыком на закреплённом теге.

ОТДАЁТСЯ ПОТРЕБИТЕЛЮ.

ЗАЧЕМ КОПИЯ, ЕСЛИ ЕСТЬ ПЛАГИН. Плагин `catalogue` в облачном окне
(claude.ai/code) не загружается: облачная сессия не читает ни плагинов из
`.claude/settings.json` репозитория, ни поставленных на своей машине
(plugins/catalogue/README.md, «Чего плагин не умеет»). Окна семьи облачные,
поэтому навык каталога до них доезжает только файлом в их `.claude/skills/`.
Замер 01.10: `answer-a-rule` уже жил двумя копиями — в плагине каталога и в
дереве проекта механизмов, — и описания у них разошлись.

ПОЭТОМУ КОПИЯ ДЕРЖИТСЯ ПРОВЕРКОЙ, А НЕ ДОГОВОРЁННОСТЬЮ. Это тот же приём, что
у 214: копия, оставленная намеренно, подписывается, и совпадение держит
проверка. Подпись — СПИСОК ИМЁН в прогоне проекта (`--skills`, вход `skills`
действия), а не присутствие папки. Первая редакция объявляла копию самой
папкой, и ревью #638 нашло цену: удалённая копия неотличима от никогда не
объявленной, а копия навыка, удалённого или переименованного в каталоге,
выпадает из сверки молча. Список ловит оба случая — названной копии нет,
названного навыка у каталога нет.

С ЧЕМ СВЕРЯЕТСЯ — С ДЕРЕВОМ, ИЗ КОТОРОГО ЗАПУЩЕНА ПРОВЕРКА, А НЕ С СЕТЬЮ.
Составное действие исполняется из дерева каталога на теге из строки `uses:`;
этот скрипт лежит там же, и навыки плагина рядом с ним — того же тега. Тег
закрепляет и проверку, и эталон одной строкой. Подъём тега у потребителя
делает копию устаревшей, и проверка краснеет до переноса — подъём версии есть
перечитывание (157).

ДОРАБОТКА НЕ ПРАВИТ КОПИЮ. Правка копии у себя — это расхождение, которое
проверка и ловит. Доработка едет в каталог предложением `kind: skill` с
`amends` и `base` (export/README.md, «Навык вместо правила»), и возвращается
к проекту следующим тегом.

Запуск у потребителя (из клона каталога на нужном теге):
  python scripts/check_skill_copies.py --repo <проект> --skills answer-a-rule
  python scripts/check_skill_copies.py --repo <проект> --apply answer-a-rule

Исходы:
  0 — копии совпадают с каталогом либо записаны с --apply;
  1 — копия расходится с каталогом или названной копии нет;
  2 — не отработал: навыков у каталога нет, список пуст или не задан, имя
      неизвестно каталогу.

Реализует правила каталога:
  214 — намеренная копия подписана, и её совпадение держит проверка;
  157 — подъём закреплённой версии есть перечитывание: копия обновляется;
  039 — три исхода, и «сверять нечего» не выдаётся за «совпадает»;
  075 — проверка, не нашедшая предмета, падает, а не зеленеет;
  158 — третий исход называет предмет.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_plugins import PLUGINS  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
#: Где навыки лежат у потребителя: там их читает окно Claude Code.
SKILLS = Path(".claude") / "skills"


def навыки_каталога(root: Path) -> dict[str, Path]:
    """Навыки всех плагинов каталога: имя папки → папка."""
    вышло: dict[str, Path] = {}
    for папка in sorted((root / PLUGINS).glob("*/skills/*")):
        if (папка / "SKILL.md").is_file():
            вышло[папка.name] = папка
    return вышло


def файлы(папка: Path) -> dict[str, bytes]:
    """Все файлы навыка по относительному пути — навык не обязан быть одним файлом."""
    return {p.relative_to(папка).as_posix(): p.read_bytes()
            for p in sorted(папка.rglob("*")) if p.is_file()}


def расхождения(эталон: Path, копия: Path) -> list[str]:
    """Чем копия отличается от эталона — по файлам, с первой разной строкой."""
    а, б = файлы(эталон), файлы(копия)
    out = [f"нет файла {путь}" for путь in sorted(set(а) - set(б))]
    out += [f"лишний файл {путь} — в навыке каталога его нет"
            for путь in sorted(set(б) - set(а))]
    for путь in sorted(set(а) & set(б)):
        if а[путь] == б[путь]:
            continue
        строки_а = а[путь].decode("utf-8", "replace").splitlines()
        строки_б = б[путь].decode("utf-8", "replace").splitlines()
        номер = next((i for i, (x, y) in enumerate(zip(строки_а, строки_б), 1)
                      if x != y), min(len(строки_а), len(строки_б)) + 1)
        out.append(f"{путь} расходится с каталогом, первая разная строка {номер}")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", type=Path, required=True,
                    help="корень репозитория проекта")
    ap.add_argument("--catalogue-root", type=Path, default=ROOT,
                    help="дерево каталога; по умолчанию то, откуда запущен скрипт")
    ap.add_argument("--skills", nargs="*", default=None,
                    help="какие копии сверять — объявление копий проекта")
    ap.add_argument("--apply", nargs="+", metavar="ИМЯ",
                    help="положить или обновить копии названных навыков")
    args = ap.parse_args(argv)

    каталог = навыки_каталога(args.catalogue_root)
    if not каталог:
        print(f"не отработала: в {args.catalogue_root / PLUGINS} нет ни одного "
              "навыка плагина — сверять не с чем", file=sys.stderr)
        return 2
    у_проекта = args.repo / SKILLS

    if args.apply:
        неизвестные = [и for и in args.apply if и not in каталог]
        if неизвестные:
            print(f"не отработала: у каталога нет навыков {', '.join(неизвестные)}; "
                  f"есть {', '.join(каталог)}", file=sys.stderr)
            return 2
        for имя in args.apply:
            куда = у_проекта / имя
            if куда.exists():
                shutil.rmtree(куда)
            shutil.copytree(каталог[имя], куда)
            print(f"{имя}: копия записана в {SKILLS / имя}")
        return 0

    # СПИСОК ОБЯЗАТЕЛЕН И НЕПУСТ. Без него объявлением служила бы сама папка,
    # и пропажа копии выглядела бы так же, как её отсутствие. Пустой список —
    # «сверять нечего», и зелёным это не отвечается (075, ревью #638).
    if not args.skills:
        print("не отработала: не назван ни один навык — список --skills и есть "
              f"объявление копий; у каталога есть {', '.join(каталог)}",
              file=sys.stderr)
        return 2
    неизвестные = [и for и in args.skills if и not in каталог]
    if неизвестные:
        print(f"не отработала: у каталога нет навыков {', '.join(неизвестные)}; "
              f"есть {', '.join(каталог)}. Навык удалён или переименован в "
              "каталоге — копию у себя убрать или перенести под новое имя",
              file=sys.stderr)
        return 2
    имена = list(args.skills)

    находки: list[str] = []
    for имя in имена:
        копия = у_проекта / имя
        if not копия.is_dir():
            находки.append(f"{имя}: копии нет — положить её можно ключом "
                           f"--apply {имя}")
            continue
        находки += [f"{имя}: {р}" for р in расхождения(каталог[имя], копия)]

    if находки:
        print(f"копии навыков расходятся с каталогом: {len(находки)}")
        for н in находки:
            print(f"  • {н}")
        print("  Обновить копию — ключом --apply. Доработать навык — предложением "
              "kind: skill с amends и base, а не правкой копии.")
        return 1
    print(f"копии навыков совпадают с каталогом: {len(имена)} — {', '.join(имена)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
