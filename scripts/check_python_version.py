#!/usr/bin/env python3
"""Версия исполнителя объявлена, и все три числа сходятся.

ЧИСЕЛ ТРИ, И РАСХОДЯТСЯ ОНИ ПОРОЗНЬ:

  • НИЖНЯЯ ПЛАНКА — `requires-python` в pyproject.toml. Это обещание
    потребителю: он поставит пакет и ждёт, что тот заработает;
  • ВЕРСИЯ КОНВЕЙЕРА — `python-version` в каждом прогоне. На ней снимается
    зелёное, которым закрывают изменение;
  • ВЕРСИЯ ОКНА — то, чем запущен прогон перед толчком. На ней автор видит
    «чисто» и на этом основании толкает.

ПОЧЕМУ ТРЕТЬЕ ВАЖНЕЕ ПЕРВЫХ ДВУХ. Прогон перед толчком печатает «чисто: N
шагов конвейера прошли локально» — утверждение о том, что конвейер согласится.
Если окно работает НИЖЕ объявленной планки, это утверждение снято не на той
поверхности (037): синтаксис, доступный конвейеру и недоступный окну, здесь
упадёт, и автор «починит» его вниз — молча привязав дерево к версии, которой
проект не объявлял. Обратная сторона тише и хуже: то, что здесь прошло, на
конвейере может вести себя иначе, и узнается это уже после толчка.

ЗАМЕР, РАДИ КОТОРОГО ЗАВЕДЕНО (4 сентября): pyproject объявлял >=3.12, все семь
прогонов гоняли 3.12, а окно работало на 3.11.15 — то есть НИЖЕ собственной
планки. Ни один механизм этого не спрашивал.

ПРЕДВАРИТЕЛЬНАЯ ВЕРСИЯ — НЕ ЧЕТВЁРТОЕ ЧИСЛО, А ВОПРОС. Прогон, объявивший
`allow-prereleases: true` в том же `with:`, спрашивает «заработает ли на
следующей версии», а не закрывает изменение. Требование «все прогоны на одной
версии» его не касается — иначе вопрос нельзя было бы задать вовсе. Зато он
обязан стоять ВЫШЕ версии прогонов: предварительный прогон на той же или более
старой версии ничего не спрашивает, а выглядит так, будто спрашивает (051).

ЧЕГО ГЕЙТ НЕ ДЕЛАЕТ. Не судит, хороша ли выбранная версия, и не требует
новейшей: «новее» и «лучше» здесь не синонимы — поднятие планки у проекта,
который отдаёт наружу заготовки и действие, есть подъём контракта с
потребителями (157), а это отдельная работа с их стороны. Предмет один:
объявленное совпадает с фактическим.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.

Реализует правила каталога:
  044 — премиса вердикта проверяется прежде, чем ему поверят: объявленная
        версия есть утверждение о текущем дереве, и оно сверяется с фактом;
  037 — зелёное, снятое не на той поверхности, — гипотеза;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  075 — ноль прогонов с версией это отказ, а не чистый прогон;
  158 — третий исход называет предмет отказа, а не только причину;
  217 — работа без числа версии исполняет код системным python раннера.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: `requires-python = ">=3.12"` — берём нижнюю планку. Верхних границ у нас нет
#: намеренно: потолок версии запрещает потребителю обновляться и стареет молча.
FLOOR_RE = re.compile(r'^\s*requires-python\s*=\s*"[^"0-9]*(\d+)\.(\d+)', re.M)

#: `python-version: "3.14"` в прогоне. Кавычки необязательны у площадки, но
#: без них YAML читает 3.10 как число 3.1 — поэтому в наших файлах они есть,
#: а разбор допускает все три формы — двойные, одинарные и без кавычек, —
#: чтобы находка была о версии, а не о кавычках: одинарные выпадали, и шаг
#: с верным числом считался шагом «без числа» (обзор #680).
CI_RE = re.compile(r"""^\s*python-version:\s*["']?(\d+)\.(\d+)["']?""", re.M)

#: Пометка предварительного прогона — ключ setup-python, без которого площадка
#: предрелизную версию не поставит вовсе. Поэтому пометка не договорённость, а
#: условие работы: снять её значит сломать прогон, а не обойти гейт.
PREVIEW_RE = re.compile(r'^\s*allow-prereleases:\s*"?true"?\s*$')

#: `python-version: ${{ matrix.<ось> }}` — версия из матрицы работы (#926).
#: Буквальным образцом `CI_RE` она не видна, и значок рисовал гоняемую ячейку
#: «проектом не проверяется», а гейт считал шаг «без числа».
MATRIX_RE = re.compile(
    r"""^\s*python-version:\s*["']?\$\{\{\s*matrix\.([\w-]+)\s*\}\}["']?\s*(?:#.*)?$""", re.M
)
#: Ячейка матрицы: «3.14», '3.14', 3.14 — тот же номер, что у `CI_RE`.
ЯЧЕЙКА_RE = re.compile(r"""^["']?(\d+)\.(\d+)["']?$""")


def floor(pyproject: str) -> tuple[int, int] | None:
    """Объявленная нижняя планка; None — не объявлена."""
    m = FLOOR_RE.search(pyproject)
    return (int(m.group(1)), int(m.group(2))) if m else None


def _в_том_же_with(text: str, конец: int) -> list[str]:
    """Все строки блока `with:`, в котором стоит `python-version:`.

    Блок целиком, а не хвост после версии: порядок ключей в `with:` значения не
    имеет, и пометка выше версии обязана читаться так же, как ниже."""
    строки = text.splitlines()
    номер = text.count("\n", 0, конец)
    отступ = len(строки[номер]) - len(строки[номер].lstrip())
    верх = номер
    while верх > 0:
        выше = строки[верх - 1]
        if выше.strip() and len(выше) - len(выше.lstrip()) < отступ:
            break
        верх -= 1
    низ = номер + 1
    while низ < len(строки):
        ниже = строки[низ]
        if ниже.strip() and len(ниже) - len(ниже.lstrip()) < отступ:
            break
        низ += 1
    return строки[верх:низ]


def _отступ(строка: str) -> int:
    return len(строка) - len(строка.lstrip())


def _блок(строки: list[str], i: int) -> list[str]:
    """Строки под ключом `строки[i]` — с отступом больше, до первой меньше или равной."""
    out = []
    for строка in строки[i + 1 :]:
        if строка.strip() and _отступ(строка) <= _отступ(строки[i]):
            break
        out.append(строка)
    return out


def _без_комментария(строка: str) -> str:
    """Строка без хвостового `# …` YAML: решётка после пробела — комментарий."""
    return строка.split(" #")[0].rstrip()


def _значения(строки: list[str], i: int) -> list[str] | None:
    """Значение ключа `строки[i]`: список в строку, столбцом или одно; None — выражение.

    Хвостовой комментарий снимается у КАЖДОЙ строки значения, а не только у
    строки ключа: `- "3.14"  # LTS` — верный YAML (обзор #928)."""
    после = _без_комментария(строки[i].split(":", 1)[1]).strip()
    if после.startswith("${{"):
        return None
    if после.startswith("["):
        текст, j = после, i
        while "]" not in текст and j + 1 < len(строки):  # список в скобках на нескольких строках
            j += 1
            текст += " " + _без_комментария(строки[j]).strip()
        return [х.strip() for х in текст.strip("[]").split(",") if х.strip()]
    if после:
        return [после]
    return [
        _без_комментария(с).strip()[1:].strip()
        for с in _блок(строки, i)
        if с.strip().startswith("- ")
    ]


def ось(тело: str, имя: str) -> tuple[list[tuple[int, int]], str | None]:
    """Номера оси `strategy.matrix.<имя>` работы и её ячеек `include:`; (номера, отказ).

    Формы (210, справка площадки «Using a matrix»): список в строку с любыми
    кавычками, список столбцом, одно значение, ячейки `include:` с этой осью.
    Отказ с адресом, а не молчание: оси нет, значение — выражение
    (`fromJSON(…)`), ячейка не формы X.Y. `exclude:` не разбирается — это
    граница: вычеркнуть версию целиком им можно, но так не пишут.
    """
    строки = тело.splitlines()
    матрица = next((i for i, с in enumerate(строки) if с.strip() == "matrix:"), None)
    if матрица is None:
        return [], f"python-version из matrix.{имя}, а матрицы у работы нет"
    под = _блок(строки, матрица)
    ключи = [с for с in под if с.strip()]
    if not ключи:
        return [], "матрица пуста"
    уровень = min(_отступ(с) for с in ключи)
    сырые: list[str] = []
    нашлась = False
    for j, с in enumerate(под):
        if _отступ(с) != уровень or ":" not in с:
            continue
        ключ = с.strip().split(":", 1)[0].lstrip("- ").strip()
        if ключ == имя:
            нашлась = True
            значения = _значения(под, j)
            if значения is None:
                return [], f"matrix.{имя} — выражение, а не список: версии не с чем сверить"
            сырые += значения
        elif ключ == "include":
            for к, ячейка in enumerate(блок := _блок(под, j)):
                строка = ячейка.strip().lstrip("- ").strip()
                if строка.split(":", 1)[0].strip() == имя:
                    нашлась = True
                    значения = _значения(блок, к)
                    if значения is None:  # выражение в ячейке — отказ, как у оси (обзор #928)
                        return [], f"ячейка include с matrix.{имя} — выражение, а не версия"
                    сырые += значения
    if not нашлась:
        return [], f"python-version из matrix.{имя}, а оси {имя} в матрице нет"
    номера = []
    for сырое in сырые:
        if (м := ЯЧЕЙКА_RE.match(сырое)) is None:
            return [], f"ячейка matrix.{имя} «{сырое}» не формы X.Y"
        номера.append((int(м.group(1)), int(м.group(2))))
    return номера, None


def _матричные(text: str) -> list[tuple[str, int, str, list[tuple[int, int]], str | None]]:
    """(работа, смещение в теле, тело, номера, отказ) для каждой матричной python-version."""
    # Работы разбирает check_runtime_deps — один разбор на территорию (214).
    from check_runtime_deps import работы

    out = []
    for имя, тело in работы(text).items():
        for m in MATRIX_RE.finditer(тело):
            номера, отказ = ось(тело, m.group(1))
            out.append((имя, m.end(), тело, номера, отказ))
    return out


def in_workflows(root: Path, *, preview: bool = False) -> list[tuple[str, tuple[int, int]]]:
    """Версия, объявленная каждым прогоном: (файл, версия).

    preview=False — прогоны, закрывающие изменение; True — только
    предварительные (`allow-prereleases: true` в том же `with:`). Версия из
    матрицы — каждой ячейкой оси (#926); неразобранная ось — в `отказы_матриц`."""
    out: list[tuple[str, tuple[int, int]]] = []
    for p in sorted((root / ".github" / "workflows").glob("*.yml")):
        text = p.read_text(encoding="utf-8")
        for m in CI_RE.finditer(text):
            помечен = any(PREVIEW_RE.match(l) for l in _в_том_же_with(text, m.end()))
            if помечен == preview:
                out.append((p.name, (int(m.group(1)), int(m.group(2)))))
        for _, конец, тело, номера, _ in _матричные(text):
            помечен = any(PREVIEW_RE.match(l) for l in _в_том_же_with(тело, конец))
            if помечен == preview:
                out += [(p.name, номер) for номер in номера]
    return out


def отказы_матриц(root: Path) -> list[str]:
    """Матричные python-version, ось которых не разобралась, — с адресом (#926)."""
    return [
        f".github/workflows/{p.name}: работа {работа}: {отказ}"
        for p in sorted((root / ".github" / "workflows").glob("*.yml"))
        for работа, _, _, _, отказ in _матричные(p.read_text(encoding="utf-8"))
        if отказ
    ]


#: Вызов интерпретатора в теле шага: `python3 scripts/x.py`, `python -m …`,
#: `python - <<…`. Комментарии и имена шагов — не вызов.
ВЫЗОВ_RE = re.compile(r"(?:^|[\s|;&(])python3?\s+(?:-m\s|-c\s|-\s|scripts/|\S+\.py)")


#: Шаг установки — строка `uses: actions/setup-python@…`, а не слово в тексте:
#: упоминание в комментарии выше вызова делало «установку» ранней и прятало
#: вызов python до неё (находка обзора #678).
SETUP_RE = re.compile(r"^([ \t]*)(?:-[ \t]+)?uses:[ \t]*actions/setup-python@", re.M)


def шаги_установки(text: str) -> list[tuple[int, list[str]]]:
    """Шаги `setup-python`: (смещение строки `uses:`, строки шага целиком).

    Шаг — от его строки с дефисом до следующей строки с отступом меньше
    ключей шага: `with:` выше или ниже `uses:` читается одинаково."""
    строки = text.splitlines()
    out: list[tuple[int, list[str]]] = []
    for m in SETUP_RE.finditer(text):
        номер = text.count("\n", 0, m.start())
        ключи = m.group(0).index("uses")
        верх = номер
        while верх > 0 and not строки[верх].lstrip().startswith("- "):
            выше = строки[верх - 1]
            if выше.strip() and len(выше) - len(выше.lstrip()) < ключи - 2:
                break
            верх -= 1
        низ = номер + 1
        while низ < len(строки):
            ниже = строки[низ]
            if ниже.strip() and len(ниже) - len(ниже.lstrip()) < ключи:
                break
            низ += 1
        out.append((m.start(), строки[верх:низ]))
    return out


def без_числа(шаги: list[tuple[int, list[str]]], тело: str = "") -> int:
    """Сколько шагов установки не называют версию числом: `${{ … }}`, файл
    `.python-version` или версия раннера — гейту не с чем сверять (#678).
    Ось матрицы работы, которая разобралась, — число (#926); не разобралась —
    шаг остаётся без числа, а адрес отказа называет `отказы_матриц`."""

    def с_числом(строки: list[str]) -> bool:
        if any(CI_RE.match(л) for л in строки):
            return True
        return any((м := MATRIX_RE.match(л)) and ось(тело, м.group(1))[0] for л in строки)

    return sum(1 for _, строки in шаги if not с_числом(строки))


def мимо_планки(root: Path) -> list[str]:
    """Работы, где код зовётся раньше `setup-python` — системным python раннера.

    ВЕРСИЯ ПРОГОНА ОБЪЯВЛЯЕТСЯ НЕ ТОЛЬКО ЧИСЛОМ. Работа без `setup-python`
    числа не объявляет вовсе — и потому `in_workflows` её не видит, а
    `python3` в ней есть: тот, что пришёл с образом раннера. Замер 2 октября,
    на следующий день после переезда планки на 3.14: так жили открытие
    изменения, автомерж и сверка задач — конвейер слияния гонял код каталога
    не на планке, и ни одна проверка этого не спрашивала."""
    out: list[str] = []
    # Работы разбирает check_runtime_deps — один разбор на территорию (214).
    from check_runtime_deps import работы

    for p in sorted((root / ".github" / "workflows").glob("*.yml")):
        for имя, тело in работы(p.read_text(encoding="utf-8")).items():
            шаги = шаги_установки(тело)
            if без_числа(шаги, тело):
                out.append(
                    f".github/workflows/{p.name}: работа {имя} ставит python "
                    "шагом setup-python без числа в python-version — версию не с "
                    "чем сверить с планкой, и ниже неё она пройдёт молча"
                )
            установка = шаги[0][0] if шаги else -1
            for строка_m in re.finditer(r"^.*$", тело, re.M):
                строка = строка_m.group(0).strip()
                if строка.startswith(("#", "- name:", "name:", "- uses:", "uses:")):
                    continue
                if ВЫЗОВ_RE.search(строка):
                    if установка < 0 or строка_m.start() < установка:
                        out.append(
                            f".github/workflows/{p.name}: работа {имя} зовёт "
                            "python раньше setup-python — код исполняется системным "
                            "python раннера, а не версией планки, и число этого не "
                            "выдаёт: его нет"
                        )
                    break
    return out


def действия(root: Path) -> list[Path]:
    """Составные действия каталога: корневое и те, что в `.github/actions/`.

    ДЕЙСТВИЕ — ТОЖЕ ПРОГОН, И ЧИСЛО У НЕГО СВОЁ. Оно ставит python своим
    `setup-python` и исполняет код каталога, но в `.github/workflows/` не
    лежит. Замер 2 октября: подъём планки (#647) перевёл действия в
    `.github/actions/` на 3.14, а корневое `action.yml` — действие для
    ПОТРЕБИТЕЛЕЙ — оставил на 3.12; после переезда стиля `sync_inbox.py` на
    3.12 падает SyntaxError'ом, а действие любой код, кроме 2, считает
    очередью, — сверка у потребителя выключилась бы молча (217)."""
    out = [root / "action.yml"] if (root / "action.yml").exists() else []
    return out + sorted((root / ".github" / "actions").glob("*/action.yml"))


def действия_мимо_планки(root: Path, планка: tuple[int, int]) -> list[str]:
    """Действие ставит версию ниже планки либо зовёт python раньше setup-python.

    Шаги действия — один список, а не работы: разбор `работы()` здесь не
    годится, и тело читается целиком."""
    out: list[str] = []
    for p in действия(root):
        имя = p.relative_to(root).as_posix()
        text = p.read_text(encoding="utf-8")
        for m in CI_RE.finditer(text):
            версия = (int(m.group(1)), int(m.group(2)))
            if версия < планка:
                out.append(
                    f"{имя}: ставит {версия[0]}.{версия[1]}, а pyproject.toml "
                    f"объявляет >={планка[0]}.{планка[1]} — код каталога "
                    "исполняется версией, на которой он не написан"
                )
        шаги = шаги_установки(text)
        if без_числа(шаги):
            out.append(
                f"{имя}: шаг setup-python без числа в python-version — версию "
                "не с чем сверить с планкой, и ниже неё она пройдёт молча"
            )
        установка = шаги[0][0] if шаги else -1
        for строка_m in re.finditer(r"^.*$", text, re.M):
            строка = строка_m.group(0).strip()
            if строка.startswith(("#", "- name:", "name:", "- uses:", "uses:")):
                continue
            if ВЫЗОВ_RE.search(строка):
                if установка < 0 or строка_m.start() < установка:
                    out.append(
                        f"{имя}: зовёт python раньше setup-python — код "
                        "исполняется системным python раннера, а не версией "
                        "планки"
                    )
                break
    return out


def findings(
    планка: tuple[int, int],
    прогоны: list[tuple[str, tuple[int, int]]],
    окно: tuple[int, int],
    предварительные: list[tuple[str, tuple[int, int]]] | None = None,
) -> list[str]:
    """Расхождения трёх чисел. Каждое — со своим сообщением, а не одним общим."""
    out: list[str] = []
    верх = max((в for _, в in прогоны), default=планка)
    for имя, версия in предварительные or []:
        if версия <= верх:
            out.append(
                f".github/workflows/{имя}: предварительный прогон на "
                f"{версия[0]}.{версия[1]}, а прогоны уже гоняют "
                f"{верх[0]}.{верх[1]} — он ничего не спрашивает о следующей "
                "версии, а выглядит так, будто спрашивает (051)"
            )
    for имя, версия in прогоны:
        if версия < планка:
            out.append(
                f".github/workflows/{имя}: гоняет {версия[0]}.{версия[1]}, а "
                f"pyproject.toml объявляет >={планка[0]}.{планка[1]} — конвейер "
                "проверяет версию, которую проект не поддерживает"
            )
    # НЕСКОЛЬКО ВЕРСИЙ ЗАКОННО, ЕСЛИ МЛАДШАЯ — ПЛАНКА (решение владельца
    # 14 октября: с выходом 3.15 планка осталась 3.14, а 3.15 стала
    # обязательной проверкой). Вопрос «какая закрывает изменение» отвечен:
    # закрывают все, а планка среди них проверена. Без планки среди версий
    # обещание потребителю не проверяет никто — это и осталось находкой.
    разные = {в for _, в in прогоны}
    if len(разные) > 1 and min(разные) != планка:
        какие = ", ".join(f"{a}.{b}" for a, b in sorted(разные))
        out.append(
            f"прогоны гоняют разные версии — {какие}, а планки "
            f"{планка[0]}.{планка[1]} среди них нет. Зелёное на одной не "
            "переносится на другую, и обещание потребителю не проверяет "
            "ни один прогон"
        )
    if окно < планка:
        out.append(
            f"прогон перед толчком запущен на {окно[0]}.{окно[1]}, а планка "
            f">={планка[0]}.{планка[1]}. «Чисто локально» снято НИЖЕ объявленной "
            "поверхности: доступное конвейеру здесь упадёт, и починят это вниз "
            f"(037). Запускайте: python{планка[0]}.{планка[1]} scripts/preflight.py"
        )
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)
    манифест = args.root / "pyproject.toml"

    # ── исход 2 ────────────────────────────────────────────────────────────
    if not манифест.exists():
        print(
            f"проверка не отработала: нет {манифест} — планку версии объявляет он", file=sys.stderr
        )
        return 2
    планка = floor(манифест.read_text(encoding="utf-8"))
    if планка is None:
        print(
            f"проверка не отработала: в {манифест} нет requires-python — сверять не с чем",
            file=sys.stderr,
        )
        return 2
    прогоны = in_workflows(args.root)
    if not прогоны:
        print(
            f"проверка не отработала: в {args.root}/.github/workflows ни один "
            "прогон не объявляет python-version — предмета нет, и зеленеть на "
            "этом нельзя (075)",
            file=sys.stderr,
        )
        return 2

    окно = sys.version_info[:2]
    предварительные = in_workflows(args.root, preview=True)
    найдено = (
        findings(планка, прогоны, окно, предварительные)
        + мимо_планки(args.root)
        + действия_мимо_планки(args.root, планка)
        + отказы_матриц(args.root)
    )

    # ── исход 1 ────────────────────────────────────────────────────────────
    if найдено:
        print("объявленная версия питона разошлась с фактической:", file=sys.stderr)
        for n in найдено:
            print(f"  • {n}", file=sys.stderr)
        return 1

    вопрос = "".join(f", предварительный {a}.{b} ({имя})" for имя, (a, b) in предварительные)
    print(
        f"версии сходятся: планка >={планка[0]}.{планка[1]}, прогонов "
        f"{len(прогоны)}, действий {len(действия(args.root))}, окно "
        f"{окно[0]}.{окно[1]}{вопрос}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
