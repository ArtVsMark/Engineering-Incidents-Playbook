#!/usr/bin/env python3
"""Версия исполнителя объявлена, и все три числа сходятся.

ЧИСЕЛ ТРИ, И РАСХОДЯТСЯ ОНИ ПОРОЗНЬ:

  • НИЖНЯЯ ПЛАНКА — `requires-python` в pyproject.toml. Это обещание
    потребителю: он поставит пакет и ждёт, что тот заработает;
  • ВЕРСИЯ КОНВЕЙЕРА — `python-version` в каждом прогоне. На ней снимается
    зелёное, которым закрывают изменение;
  • ВЕРСИЯ ОКНА — то, чем запущен прогон перед толчком. На ней автор видит
    «чисто» и на этом основании толкает.

ПОЧЕМУ ТРЕТЬЕ ВАЖНЕЕ ПЕРВЫХ ДВУХ. Прогон перед толчком печатает «чисто: N
шагов конвейера прошли локально» — утверждение о том, что конвейер согласится.
Если окно работает НИЖЕ объявленной планки, это утверждение снято не на той
поверхности (037): синтаксис, доступный конвейеру и недоступный окну, здесь
упадёт, и автор «починит» его вниз — молча привязав дерево к версии, которой
проект не объявлял. Обратная сторона тише и хуже: то, что здесь прошло, на
конвейере может вести себя иначе, и узнается это уже после толчка.

ЗАМЕР, РАДИ КОТОРОГО ЗАВЕДЕНО (4 сентября): pyproject объявлял >=3.12, все семь
прогонов гоняли 3.12, а окно работало на 3.11.15 — то есть НИЖЕ собственной
планки. Ни один механизм этого не спрашивал.

ЧЕГО ГЕЙТ НЕ ДЕЛАЕТ. Не судит, хороша ли выбранная версия, и не требует
новейшей: «новее» и «лучше» здесь не синонимы — поднятие планки у проекта,
который отдаёт наружу заготовки и действие, есть подъём контракта с
потребителями (157), а это отдельная работа с их стороны. Предмет один:
объявленное совпадает с фактическим.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.

Реализует правила каталога:
  044 — премиса вердикта проверяется прежде, чем ему поверят: объявленная
        версия есть утверждение о текущем дереве, и оно сверяется с фактом;
  037 — зелёное, снятое не на той поверхности, — гипотеза;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  075 — ноль прогонов с версией это отказ, а не чистый прогон;
  158 — третий исход называет предмет отказа, а не только причину.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: `requires-python = ">=3.12"` — берём нижнюю планку. Верхних границ у нас нет
#: намеренно: потолок версии запрещает потребителю обновляться и стареет молча.
FLOOR_RE = re.compile(r'^\s*requires-python\s*=\s*"[^"0-9]*(\d+)\.(\d+)', re.M)

#: `python-version: "3.12"` в прогоне. Кавычки необязательны у площадки, но
#: без них YAML читает 3.10 как число 3.1 — поэтому в наших файлах они есть,
#: а разбор допускает обе формы, чтобы находка была о версии, а не о кавычках.
CI_RE = re.compile(r'^\s*python-version:\s*"?(\d+)\.(\d+)"?', re.M)


def floor(pyproject: str) -> tuple[int, int] | None:
    """Объявленная нижняя планка; None — не объявлена."""
    m = FLOOR_RE.search(pyproject)
    return (int(m.group(1)), int(m.group(2))) if m else None


def in_workflows(root: Path) -> list[tuple[str, tuple[int, int]]]:
    """Версия, объявленная каждым прогоном: (файл, версия)."""
    out: list[tuple[str, tuple[int, int]]] = []
    for p in sorted((root / ".github" / "workflows").glob("*.yml")):
        for m in CI_RE.finditer(p.read_text(encoding="utf-8")):
            out.append((p.name, (int(m.group(1)), int(m.group(2)))))
    return out


def findings(планка: tuple[int, int], прогоны: list[tuple[str, tuple[int, int]]],
             окно: tuple[int, int]) -> list[str]:
    """Расхождения трёх чисел. Каждое — со своим сообщением, а не одним общим."""
    out: list[str] = []
    for имя, версия in прогоны:
        if версия < планка:
            out.append(
                f".github/workflows/{имя}: гоняет {версия[0]}.{версия[1]}, а "
                f"pyproject.toml объявляет >={планка[0]}.{планка[1]} — конвейер "
                "проверяет версию, которую проект не поддерживает")
    разные = {в for _, в in прогоны}
    if len(разные) > 1:
        какие = ", ".join(f"{a}.{b}" for a, b in sorted(разные))
        out.append(f"прогоны гоняют разные версии — {какие}. Зелёное на одной "
                   "не переносится на другую, и какая из них закрывает "
                   "изменение, не сказано нигде")
    if окно < планка:
        out.append(
            f"прогон перед толчком запущен на {окно[0]}.{окно[1]}, а планка "
            f">={планка[0]}.{планка[1]}. «Чисто локально» снято НИЖЕ объявленной "
            "поверхности: доступное конвейеру здесь упадёт, и починят это вниз "
            f"(037). Запускайте: python{планка[0]}.{планка[1]} scripts/preflight.py")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)
    манифест = args.root / "pyproject.toml"

    # ── исход 2 ────────────────────────────────────────────────────────────
    if not манифест.exists():
        print(f"проверка не отработала: нет {манифест} — планку версии "
              "объявляет он", file=sys.stderr)
        return 2
    планка = floor(манифест.read_text(encoding="utf-8"))
    if планка is None:
        print(f"проверка не отработала: в {манифест} нет requires-python — "
              "сверять не с чем", file=sys.stderr)
        return 2
    прогоны = in_workflows(args.root)
    if not прогоны:
        print(f"проверка не отработала: в {args.root}/.github/workflows ни один "
              "прогон не объявляет python-version — предмета нет, и зеленеть на "
              "этом нельзя (075)", file=sys.stderr)
        return 2

    окно = sys.version_info[:2]
    найдено = findings(планка, прогоны, окно)

    # ── исход 1 ────────────────────────────────────────────────────────────
    if найдено:
        print("объявленная версия питона разошлась с фактической:",
              file=sys.stderr)
        for n in найдено:
            print(f"  • {n}", file=sys.stderr)
        return 1

    print(f"версии сходятся: планка >={планка[0]}.{планка[1]}, прогонов "
          f"{len(прогоны)}, окно {окно[0]}.{окно[1]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
