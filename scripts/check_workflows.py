#: `${{ … }}` подставляет площадка ДО оболочки; для `bash -n` это не синтаксис.
ПОДСТАНОВКА = re.compile(r"\$\{\{[^}]*\}\}")
#: Начало блока команд. Скаляр может быть `|`, `|-`, `>` и с указателем отступа.
БЛОК_RUN = re.compile(r"^(\s*)-?\s*run:\s*[|>][-+0-9]*\s*$")
#: Язык шага и имя шага — читаются построчно, как и всё в этом файле.
ОБОЛОЧКА_ШАГА = re.compile(r"^\s*-?\s*shell:\s*(\S+)")
ИМЯ_ШАГА = re.compile(r"^\s*-?\s*name:\s*(.+)$")
#: `defaults: run: shell:` уровня файла — три строки подряд с ростом отступа.
DEFAULT_SHELL = re.compile(r"^defaults:\s*\n\s+run:\s*\n\s+shell:\s*(\S+)", re.M)


def sections(text: str) -> dict[str, list[str]]:
    """Строки файла, разложенные по ключам верхнего уровня.

    Разбор построчный, а не через YAML: конвейер каталога обходится
    стандартной библиотекой, и гейт, требующий установки, перестал бы
    запускаться там, где его запускают чаще всего — на рабочем столе.
    """
    out: dict[str, list[str]] = {}
    current = ""
    for line in text.splitlines():
        top = TOP_RE.match(line)
        if top:
            current = top.group(1)
            out.setdefault(current, [])
            continue
        if current:
            out[current].append(line)
    return out


def has_button(text: str) -> bool:
    """Ручная кнопка объявлена — в блочной форме или списком после `on:`."""
    blocks = sections(text)
    on = "\n".join(blocks.get("on", []))
    inline = re.search(r"^on:\s*\[(.*)\]", text, re.M)
    return "workflow_dispatch" in on or bool(
        inline and "workflow_dispatch" in inline.group(1))


def events(text: str) -> set[str]:
    """События, на которые просыпается прогон, — из блока `on:`."""
    blocks = sections(text)
    inline = re.search(r"^on:\s*\[(.*)\]", text, re.M)
    if inline:
        return {e.strip() for e in inline.group(1).split(",") if e.strip()}
    return {m.group(1) for m in (KEY_RE.match(line) for line in blocks.get("on", []))
            if m}


#: Шаг, который вносит в прогон код ИЗВНЕ файла прогона: выкачка дерева и
#: вызов чужого действия. Инлайновый `run:` сюда не входит — он записан в самом
#: файле, а файл на этих событиях берётся с общей ветки.
BRINGS_FOREIGN_CODE = re.compile(r"^\s+(?:-\s+)?uses:\s*\S", re.M)


def pins_checkout(text: str) -> bool:
    """Закреплено ли то, что прогон исполняет помимо собственного файла.

    Два ответа «да», и второй пришлось назвать отдельно. Первый: шаг выкачки
    берёт код с НАЗВАННОЙ ветки, а не из изменения. Второй: прогон не вносит
    чужого кода вовсе — ни выкачки, ни чужого действия, только собственные
    `run:`. Закреплять там нечего, и требование превращается в обряд: чтобы
    его исполнить, пришлось бы ДОБАВИТЬ выкачку, которая прогону не нужна, —
    то есть внести поверхность ради проверки, которая её же и сторожит.

    Замер: гейт отверг `thaw.yml`, у которого ни одного `uses:`. Отказ был
    верен по букве и ложен по существу, а ложный отказ приучает читать красное
    как фон (051).
    """
    if not BRINGS_FOREIGN_CODE.search(text):
        return True
    return bool(re.search(r"^\s+ref:\s*\S", text, re.M))


#: Ключ `env:` или присваивание в оболочке. Имя обязано быть ASCII — это
#: требование bash, а не наше соглашение (правило 167).
ENV_KEY_RE = re.compile(r"^\s+([^\s:#][^\s:]*):\s", re.M)
ASSIGN_RE = re.compile(r"^\s*([^\s=#$][^\s=]*)=", re.M)

#: ЗДЕСЬ ПРОВЕРЯЕТСЯ ЗНАЧЕНИЕ, А НЕ КЛЮЧ, И ЭТО НАЙДЕНО ЖИВЫМ ОТКАЗОМ. У `id:`
#: ключ всегда ASCII, а значение — ИДЕНТИФИКАТОР, по которому потом обращаются
#: из выражения. Прежняя редакция гейта смотрела только на ключи, докстрока прямо
#: разрешала «имена шагов на языке проекта» — и была права про `name:` (это
#: проза) и неправа про `id:` (это имя). Цена: `id: ключ` в review.yml сделал
#: файл НЕРАЗБИРАЕМЫМ — прогон падал за ноль секунд, работ ноль, шагов ноль, а
#: выглядело обычным красным; красный прогон на общей ветке заморозил очередь, и
#: два изменения простояли молча, пока причину искали в них самих.
#: `- id: x` и `  id: x` — обе формы законны, и вторую первая редакция
#: регулярки не видела: `\s+` не покрывает дефис элемента списка.
STEP_ID_RE = re.compile(r"^\s+(?:-\s+)?id:\s*(\S+)", re.M)

#: Обращение к выводу шага: и имя шага, и имя вывода — идентификаторы.
OUTPUT_REF_RE = re.compile(r"steps\.(\S+?)\.outputs\.([A-Za-z0-9_\-\u0080-\uffff]+)")


#: Блочный скаляр YAML: `ключ: |` или `ключ: >`. Всё, что глубже его отступа, —
#: ТЕКСТ, а не разметка.
БЛОЧНЫЙ_СКАЛЯР = re.compile(r"^(\s*)([\w.-]+):\s*[|>][-+0-9]*\s*$")


def без_чужого_текста(text: str) -> str:
    """Файл без содержимого блочных скаляров, кроме `run:`.

    ЗАЧЕМ. Ключи YAML ищутся образцом «отступ, слово, двоеточие» — и под него
    подходит ЛЮБАЯ строка текста с двоеточием. Замер 8 сентября: строка
    «ВЕРДИКТ: находок N» в промпте ревьюера — предписанная форма ответа для
    модели — была принята за имя ключа env и отвергнута как «не латиницей».
    Гейт краснел на верном файле, а ложный отказ дороже пропуска (051).

    ПОЧЕМУ `run:` ОСТАЁТСЯ. Там код, и присваивания в нём — настоящий предмет
    правила 167: `ИМЯ=значение` кириллицей падает кодом 127. Остальные блочные
    скаляры — проза для человека или для модели, и языка ей никто не диктует.
    """
    строки = text.split("\n")
    вышло: list[str] = []
    внутри: int | None = None
    for строка in строки:
        if внутри is not None:
            голая = строка.strip()
            отступ = len(строка) - len(строка.lstrip())
            if голая and отступ <= внутри:
                внутри = None
            else:
                вышло.append("")      # место сохраняется: номера строк не едут
                continue
        m = БЛОЧНЫЙ_СКАЛЯР.match(строка)
        if m and m.group(2) != "run":
            внутри = len(m.group(1))
        вышло.append(строка)
    return "\n".join(вышло)


def non_ascii_names(text: str) -> list[str]:
    """Имена переменных оболочки и ключей env, написанные не латиницей.

    Тихая половина ошибки опаснее громкой: переменная окружения с не-ASCII
    именем СОЗДАЁТСЯ, а `$ИМЯ` не раскрывается — условие на ней всегда даёт
    одну ветку, и гейт зеленеет, не проверив ничего (167, 075).

    Проверяются только ИМЕНА. Значения и любая проза остаются на языке проекта:
    требовать латиницу там значило бы переносить чужую границу и краснеть на
    верном файле (051). ГРАНИЦА МЕЖДУ `name:` И `id:` ПРОХОДИТ ИМЕННО ЗДЕСЬ:
    `name:` — проза для человека, и она на русском; `id:` — идентификатор для
    площадки, и он обязан быть латиницей, иначе файл не разбирается вовсе.
    """
    found: list[str] = []
    # Ключи ищутся в разметке, а не в прозе: содержимое блочных скаляров вне
    # `run:` — текст для человека или модели, и двоеточие в нём ключом не
    # является.
    разметка = без_чужого_текста(text)
    for regex in (ENV_KEY_RE, ASSIGN_RE):
        for m in regex.finditer(разметка):
            имя = m.group(1)
            if имя.isascii():
                continue
            # Ключи YAML верхнего уровня и имена работ тоже совпадут с образцом,
            # но они и обязаны быть ASCII: площадка читает их как ключи.
            found.append(имя)
    # Значения `id:` и обе половины обращения `steps.X.outputs.Y`.
    for m in STEP_ID_RE.finditer(разметка):
        if not m.group(1).isascii():
            found.append(f"id: {m.group(1)}")
    for m in OUTPUT_REF_RE.finditer(разметка):
        for часть in m.groups():
            if not часть.isascii():
                found.append(f"steps.{m.group(1)}.outputs.{m.group(2)}")
    return sorted(set(found))


#: Присвоение кода возврата. Слева от `=` — имя, а не выражение: `rc=$?`,
#: но не `[ $? -eq 0 ]` и не `exit $?`. Проброс кода наружу разбором не
#: является и под `-e` даёт тот же итог, поэтому предмета в нём нет.
RC_ASSIGN_RE = re.compile(r"^(?P<до>[^\n#]*?)(?P<имя>[A-Za-z_]\w*)=\$\?", re.M)

#: Единственная форма, доживающая до разбора. `||` снимает `-e` со всей
#: конструкции: оболочка не умирает, и присвоение выполняется. `&& rc=0 || rc=$?`
#: — та же форма с явной удачей, и она сюда попадает по тому же `||`.
ЖИВАЯ_ФОРМА = "||"


def dead_exit_codes(text: str) -> list[str]:
    """Присвоения `$?`, до которых под `bash -e` не доходит управление (145).

    ПОЧЕМУ РЕГУЛЯРКОЙ, А НЕ РАЗБОРОМ YAML. Предмет — текст оболочки внутри
    блока `run:`, и YAML отдаёт его той же строкой. Разбор добавил бы
    зависимость и не добавил бы точности: форма опознаётся по одной строке.
    """
    мёртвые = []
    for m in RC_ASSIGN_RE.finditer(text):
        if ЖИВАЯ_ФОРМА in m.group("до"):
            continue
        строка = text[:m.start()].count("\n") + 1
        мёртвые.append(f"строка {строка}: {m.group('имя')}=$?")
    return мёртвые


def unparsable_shell(text: str) -> list[str]:
    """Блоки `run:`, которые оболочка не разберёт. Пусто — все разбираются.

    ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ПРЕДМЕТ, А НЕ ЧАСТЬ РАЗБОРА YAML. Файл может быть
    безупречным YAML и при этом нести шаг, который оболочка отвергнет на
    первой строке. Тогда прогон падает МГНОВЕННО и выглядит обычным красным —
    ровно та картина, что стоила смены 4 сентября (`id: ключ`, 167).

    ЗАМЕР, НА КОТОРОМ ЭТО НАПИСАНО: 7 сентября я сам написал в оболочке
    функцию с именем `квота_кончилась`. bash её ПРИНИМАЕТ, dash отвергает —
    «Syntax error: Bad function name». Шаг идёт под `bash -e {0}`, то есть
    работало бы; но правильность держалась бы умолчанием площадки, а не
    кодом. Проверяет это `bash -n`: разбор без исполнения.

    БЕЗ YAML-ПАРСЕРА, И ЭТО НЕ ВКУС. Первая редакция звала `yaml.safe_load` —
    и прогон `catalogue` упал с `ModuleNotFoundError: No module named 'yaml'`:
    PyYAML стоит только в requirements-test.txt, а шаг гейта идёт без него.
    Локально пакет был, поэтому прогон перед толчком молчал — замер с той
    поверхности, на которой изменение не поедет (037), в тот самый день,
    когда об этом писали. Остальные функции этого файла работают по тексту, и
    зависимость выбивалась из его устройства; у потребителя, куда гейт едет
    шаблоном, PyYAML тем более не гарантирован.

    ГРАНИЦЫ. Подстановки площадки (`${{ … }}`) до оболочки не доживают — их
    подставляют раньше, — поэтому здесь они заменяются на безобидное слово.
    Шаг на другом языке (`shell: python`, `pwsh`) не предмет: мерить его
    оболочкой значит находить форму вместо предмета (051). Учитывается и
    `defaults.run.shell` уровня файла, а не только шага.
    """
    по_умолчанию = DEFAULT_SHELL.search(text)
    файловая = по_умолчанию.group(1).strip() if по_умолчанию else None

    плохо: list[str] = []
    строки = text.splitlines()
    n = 0
    имя = "шаг"
    оболочка: str | None = None
    while n < len(строки):
        строка = строки[n]
        голая = строка.strip()
        # Начало нового шага сбрасывает всё, что помнили о предыдущем.
        if голая.startswith("- "):
            имя, оболочка = "шаг", None
        м_имя = ИМЯ_ШАГА.match(строка)
        if м_имя:
            имя = м_имя.group(1).strip().strip("\"'")
        м_обол = ОБОЛОЧКА_ШАГА.match(строка)
        if м_обол:
            оболочка = м_обол.group(1).strip()
        м_run = БЛОК_RUN.match(строка)
        if not м_run:
            n += 1
            continue

        отступ = len(м_run.group(1))
        тело: list[str] = []
        n += 1
        while n < len(строки):
            сл = строки[n]
            if сл.strip() and (len(сл) - len(сл.lstrip())) <= отступ:
                break
            тело.append(сл[отступ + 2:] if len(сл) > отступ else "")
            n += 1

        язык = оболочка or файловая
        if язык and not язык.startswith(("bash", "sh")):
            continue                       # не оболочка — python, pwsh и прочее
        код = ПОДСТАНОВКА.sub("substituted", "\n".join(тело))
        if not код.strip():
            continue
        r = subprocess.run(["bash", "-n"], input=код, text=True,
                           capture_output=True, encoding="utf-8")
        if r.returncode != 0:
            причина = (r.stderr or "").strip().splitlines()
            плохо.append(f"{имя}: {причина[0] if причина else 'не разобран'}")
    return плохо


def jobs_without_timeout(text: str) -> list[str]:
    """Работы, у которых не задан предел времени.

    Считаются ключи второго уровня ВНУТРИ `jobs:` — события внутри `on:`
    выглядят так же, и спутать их значило бы требовать предел от `push`.
    """
    blocks = sections(text)
    lines = blocks.get("jobs")
    if lines is None:
        return []
    found: list[str] = []
    name = ""
    seen = False
    for line in lines:
        key = KEY_RE.match(line)
        if key:
            if name and not seen:
                found.append(name)
            name, seen = key.group(1), False
            continue
        if "timeout-minutes:" in line:
            seen = True
    # ПОСЛЕДНЯЯ РАБОТА ЗАКРЫВАЕТСЯ ЯВНО, а не строкой-стражем в конце списка.
    # Страж тут уже стоял и не работал: его имя было кириллицей, а ключом
    # считается только латинское — последняя работа в каждом файле не
    # проверялась вовсе, и гейт был зелёным, не держа ничего (146).
    if name and not seen:
        found.append(name)
    return found



def cancelling_groups(text: str) -> list[tuple[str, bool]]:
    """Группы `concurrency` файла: имя группы и признак «отменяет предыдущий».

    Разбор по отступу, а не через YAML, и не только по верхнему уровню:
    `concurrency` объявляют и внутри работы, и там дефект тот же. Опереться на
    sections() поэтому нельзя — она знает лишь ключи первой колонки.
    """
    lines = text.splitlines()
    out: list[tuple[str, bool]] = []
    i = 0
    while i < len(lines):
        m = re.match(r"^(\s*)concurrency:\s*$", lines[i])
        if not m:
            i += 1
            continue
        отступ = len(m.group(1))
        группа, отменяет = "", False
        i += 1
        while i < len(lines):
            строка = lines[i]
            есть = строка.strip()
            if есть and len(строка) - len(строка.lstrip()) <= отступ:
                break
            if есть.startswith("group:"):
                группа = есть.split("group:", 1)[1].strip()
            if re.match(r"cancel-in-progress:\s*true\b", есть):
                отменяет = True
            i += 1
        out.append((группа, отменяет))
    return out

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT,
                        help="корень каталога; по умолчанию сам этот репозиторий")
    args = parser.parse_args(argv)
    workflows = sorted((args.root / ".github" / "workflows").glob("*.yml"))
    # СОСТАВНОЕ ДЕЙСТВИЕ ПРОВЕРЯЕТСЯ ТОЙ ЖЕ МЕРКОЙ. Инцидент правила 145 — три
    # места одной формы, и одно из них корневой `action.yml`: там мёртвый
    # разбор красил прогоны ЧУЖИХ проектов, подключивших действие. Оболочка у
    # шага `composite` та же самая, значит и предмет тот же.
    действия = sorted(p for p in args.root.rglob("action.yml")
                      if ".git" not in p.parts)

    # ── исход 2 ────────────────────────────────────────────────────────────
    if not workflows:
        print("проверка не отработала: в .github/workflows не нашлось ни "
              "одного файла — проверять нечего, и зеленеть на этом нельзя",
              file=sys.stderr)
        return 2

    # ── исход 1 ────────────────────────────────────────────────────────────
    problems: list[str] = []
    for path in workflows:
        text = path.read_text(encoding="utf-8")
        name = path.name
        if not has_button(text) and name not in NO_BUTTON_NEEDED:
            problems.append(
                f"{name}: нет workflow_dispatch. Прогон, чьё событие не "
                "наступит, останется без выхода — а замереть он может "
                "именно тогда, когда нужен (126)")
        ev = events(text)
        if "pull_request" in ev and name not in MAY_BLOCK_MERGE:
            problems.append(
                f"{name}: просыпается на pull_request, а основной работой не "
                "объявлен. Необязательный канал, отказавший на изменении, "
                "задерживает слияние и роняет его — при том что его отсутствие "
                "штатный исход, а не ошибка (084)")
        # ЗАКРЕПЛЕНИЕ ЗНАЧИТ ЧТО-ТО ТОЛЬКО ТАМ, ГДЕ ВЫЗЫВАЮЩИЙ ТОЖЕ С ОБЩЕЙ
        # ВЕТКИ. На pull_request площадка берёт САМ файл прогона из изменения:
        # правящий изменение переписывает шаг и зовёт что угодно, а
        # закреплённый скрипт просто перестаёт вызываться — заперли дверь,
        # оставив стену (152).
        opasnye = ev & set(CALLER_FROM_BASE)
        if opasnye and not pins_checkout(text):
            problems.append(
                f"{name}: просыпается на {', '.join(sorted(opasnye))} — файл "
                "прогона берётся с общей ветки, — а вызываемое не закреплено. "
                "Здесь закреплять обязательно: код исполняется при правах "
                "общей ветки (152)")
        for имя in non_ascii_names(text):
            problems.append(
                f"{name}: имя «{имя}» не латиницей. У переменной оболочки "
                "присваивание падает кодом 127, а `$имя` не раскрывается — "
                "условие на ней всегда даёт одну ветку, и шаг зеленеет, не "
                "проверив ничего. У `id:` и `steps.X.outputs.Y` хуже: площадка "
                "НЕ РАЗБИРАЕТ такой файл вовсе — прогон падает за ноль секунд, "
                "работ в нём ноль, а выглядит это обычным красным (167)")
        # ГРУППА ОТМЕНЫ НАЗЫВАЕТ ПОКОЛЕНИЕ, А ПОКОЛЕНИЕ — ЭТО КОММИТ (179).
        # Без головы прогоны на РАЗНЫХ коммитах попадают в одну группу, и
        # вытеснить может более новый: события доставляются не в порядке
        # коммитов. Тогда на актуальной голове обязательной проверки нет вовсе,
        # а создать её нечем — новый прогон рождается только от нового события.
        for группа, отменяет in cancelling_groups(text):
            if not отменяет or name in CANCELS_BY_STATE:
                continue
            if any(mark in группа for mark in HEAD_MARKS):
                continue
            problems.append(
                f"{name}: группа отмены «{группа}» не называет голову. "
                "github.ref головой НЕ является: на pull_request это "
                "refs/pull/N/merge, один и тот же для всех событий изменения — "
                "прогон на устаревшем коммите вытеснит прогон на актуальном "
                "(179)")
        for job in jobs_without_timeout(text):
            problems.append(
                f"{name}: у работы «{job}» нет timeout-minutes. Зависшая "
                "работа держит очередь до умолчания площадки — шесть часов "
                "молчания вместо отказа (100)")

    # РАЗБИРАЕМОСТЬ ОБОЛОЧКИ — ТОЖЕ ПО ОБЕИМ ПОВЕРХНОСТЯМ. Первая редакция
    # звала это только в цикле по прогонам, и составные действия оставались
    # непроверенными: у `action.yml` шаги лежат в `runs:`, а не в `jobs:`.
    # Нашёл внешний взгляд на изменении #361 — с указанием на живой файл
    # .github/actions/attribution/action.yml, где `shell: bash` и `run:` уже
    # стоят. Ошибка ровно та, из-за которой сегодня чинили 145: знание не
    # доехало до второй поверхности, и я повторил её в том же файле.
    for path in [*workflows, *действия]:
        for место in unparsable_shell(path.read_text(encoding="utf-8")):
            problems.append(
                f"{path.relative_to(args.root)}: {место}. Оболочка не разберёт "
                "этот блок, и прогон упадёт МГНОВЕННО — работ ноль, шагов ноль, "
                "а выглядит это обычным красным. Ровно так 4 сентября `id: ключ` "
                "съел смену (167). У составного действия цена выше: красным "
                "станут прогоны ЧУЖИХ проектов, подключивших его")

    # ФОРМА РАЗБОРА КОДА ВОЗВРАТА — у прогонов и у составных действий сразу.
    for path in [*workflows, *действия]:
        for место in dead_exit_codes(path.read_text(encoding="utf-8")):
            problems.append(
                f"{path.relative_to(args.root)}: {место} — присвоение стоит за "
                "строкой, до которой не доходит управление. Площадка зовёт шаг "
                "как `bash -e {0}`, и `set -uo pipefail` этот `-e` НЕ снимает: "
                "на ненулевом коде оболочка умирает раньше присвоения, и весь "
                "разбор ниже — код, который не исполняется ни разу. Пишется "
                "`|| имя=$?` (145)")

    if problems:
        print("прогоны каталога разошлись с тем, что о них объявлено:",
              file=sys.stderr)
        for p in problems:
            print(f"  • {p}", file=sys.stderr)
        return 1

    print(f"прогоны в порядке: файлов {len(workflows)} — у каждого ручная "
          "кнопка, у каждой работы предел времени, необязательные каналы "
          f"слияние не держат, закрепление стоит там, где значит, "
          f"группа отмены называет голову, а код возврата разбирается формой, "
          f"доживающей до разбора — проверено вместе с {len(действия)} "
          f"составными действиями")
    return 0


if __name__ == "__main__":
    sys.exit(main())
