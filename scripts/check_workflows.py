#!/usr/bin/env python3
"""У каждого прогона есть ручная кнопка, у каждой работы — предел времени.

Оба требования каталог объявлял выполненными и не проверял ничем. Оба ответа
разошлись с фактом, и разошлись молча:

  • 126 — ответ говорил «кнопка есть у всех девяти работ», и это было правдой
    ровно потому, что кнопку доставили руками месяцем раньше. Сам `agent-pr.yml`
    прожил без неё до тех пор, пока разрешимость `where` не потребовала назвать
    адрес механизма, которого не существовало;
  • 100 — ответ говорил «у каждой работы стоит timeout-minutes». Замер 31
    августа: у `ci.yml` и `attribution-history.yml` его не было ни у одной
    работы, и зависшая проверка держала бы очередь до умолчания площадки.

ПОЧЕМУ ЭТО ОДИН ГЕЙТ, А НЕ ДВА. Предмет один — файл прогона, и оба вопроса к
нему задаются одним разбором. Два скрипта над одним предметом разошлись бы в
том, что считать работой (022), и разбор пришлось бы держать в двух местах.

ЧЕГО ЗДЕСЬ НЕТ. Дедлайна на СТАРТ, о котором говорит вторая половина 100:
площадка его не предоставляет — `timeout-minutes` начинает считаться после
того, как работа получила машину. Это граница правила на этой поверхности, а
не пропуск, и записана она в ответе каталога.

Реализует правила каталога:
  126 — у заморозки есть выход, не проходящий через замороженное действие:
        ручная кнопка запускает прогон, когда его событие не наступит;
  100 — у работы есть предел времени: зависшая держит очередь до умолчания;
  084 — необязательный канал не просыпается на изменении: его отказ не должен
        ни задерживать слияние, ни ронять его;
  152 — закрепление вызываемого требуется там и только там, где вызывающий
        тоже берётся с общей ветки;
  039 — три исхода: чисто · есть находки · проверка не отработала;
  075 — ноль файлов прогонов это отказ, а не чистый прогон;
  051 — запрещается достоверное: отсутствие ключа — факт, а не подозрение.

Исходы:
  0 — чисто;  1 — есть находки;  2 — проверка не отработала.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: Ключ верхнего уровня: начинается с буквы в первой колонке.
TOP_RE = re.compile(r"^([a-z_]+):")
#: Ключ второго уровня — работа внутри `jobs:` или событие внутри `on:`.
KEY_RE = re.compile(r"^  ([a-zA-Z_][\w-]*):")

#: Прогон, которому ручная кнопка не нужна: его событие наступает само и
#: заморозить его нечем. Список разрешительный и с причиной у каждой строки —
#: запретительный («всё, кроме…») завтра пропустит новый файл (правило 068).
NO_BUTTON_NEEDED: dict[str, str] = {}

#: Прогоны, которым ПОЛОЖЕНО просыпаться на изменении: они и есть основная
#: работа. Всё остальное — необязательные каналы, и их отказ не должен ни
#: задерживать слияние, ни ронять его (правило 084). Список разрешительный:
#: запретительный пропустил бы новый файл ровно в тот день, когда его завели.
MAY_BLOCK_MERGE = {
    # Обязательные проверки каталога: за тем и заведены.
    "ci.yml",
    # Сам конвейер слияния: он не проверка, он исполнитель очереди.
    "automerge.yml",
}

#: События, на которых файл прогона берётся С ОБЩЕЙ ВЕТКИ, а не из изменения.
#: Только там закрепление вызываемого что-то значит (правило 152).
CALLER_FROM_BASE = ("pull_request_target", "workflow_run")


def sections(text: str) -> dict[str, list[str]]:
    """Строки файла, разложенные по ключам верхнего уровня.

    Разбор построчный, а не через YAML: конвейер каталога обходится
    стандартной библиотекой, и гейт, требующий установки, перестал бы
    запускаться там, где его запускают чаще всего — на рабочем столе.
    """
    out: dict[str, list[str]] = {}
    current = ""
    for line in text.splitlines():
        top = TOP_RE.match(line)
        if top:
            current = top.group(1)
            out.setdefault(current, [])
            continue
        if current:
            out[current].append(line)
    return out


def has_button(text: str) -> bool:
    """Ручная кнопка объявлена — в блочной форме или списком после `on:`."""
    blocks = sections(text)
    on = "\n".join(blocks.get("on", []))
    inline = re.search(r"^on:\s*\[(.*)\]", text, re.M)
    return "workflow_dispatch" in on or bool(
        inline and "workflow_dispatch" in inline.group(1))


def events(text: str) -> set[str]:
    """События, на которые просыпается прогон, — из блока `on:`."""
    blocks = sections(text)
    inline = re.search(r"^on:\s*\[(.*)\]", text, re.M)
    if inline:
        return {e.strip() for e in inline.group(1).split(",") if e.strip()}
    return {m.group(1) for m in (KEY_RE.match(line) for line in blocks.get("on", []))
            if m}


def pins_checkout(text: str) -> bool:
    """Шаг `checkout` берёт код с названной ветки, а не из изменения."""
    return bool(re.search(r"^\s+ref:\s*\S", text, re.M))


def jobs_without_timeout(text: str) -> list[str]:
    """Работы, у которых не задан предел времени.

    Считаются ключи второго уровня ВНУТРИ `jobs:` — события внутри `on:`
    выглядят так же, и спутать их значило бы требовать предел от `push`.
    """
    blocks = sections(text)
    lines = blocks.get("jobs")
    if lines is None:
        return []
    found: list[str] = []
    name = ""
    seen = False
    for line in lines:
        key = KEY_RE.match(line)
        if key:
            if name and not seen:
                found.append(name)
            name, seen = key.group(1), False
            continue
        if "timeout-minutes:" in line:
            seen = True
    # ПОСЛЕДНЯЯ РАБОТА ЗАКРЫВАЕТСЯ ЯВНО, а не строкой-стражем в конце списка.
    # Страж тут уже стоял и не работал: его имя было кириллицей, а ключом
    # считается только латинское — последняя работа в каждом файле не
    # проверялась вовсе, и гейт был зелёным, не держа ничего (146).
    if name and not seen:
        found.append(name)
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT,
                        help="корень каталога; по умолчанию сам этот репозиторий")
    args = parser.parse_args(argv)
    workflows = sorted((args.root / ".github" / "workflows").glob("*.yml"))

    # ── исход 2 ────────────────────────────────────────────────────────────
    if not workflows:
        print("проверка не отработала: в .github/workflows не нашлось ни "
              "одного файла — проверять нечего, и зеленеть на этом нельзя",
              file=sys.stderr)
        return 2

    # ── исход 1 ────────────────────────────────────────────────────────────
    problems: list[str] = []
    for path in workflows:
        text = path.read_text(encoding="utf-8")
        name = path.name
        if not has_button(text) and name not in NO_BUTTON_NEEDED:
            problems.append(
                f"{name}: нет workflow_dispatch. Прогон, чьё событие не "
                "наступит, останется без выхода — а замереть он может "
                "именно тогда, когда нужен (126)")
        ev = events(text)
        if "pull_request" in ev and name not in MAY_BLOCK_MERGE:
            problems.append(
                f"{name}: просыпается на pull_request, а основной работой не "
                "объявлен. Необязательный канал, отказавший на изменении, "
                "задерживает слияние и роняет его — при том что его отсутствие "
                "штатный исход, а не ошибка (084)")
        # ЗАКРЕПЛЕНИЕ ЗНАЧИТ ЧТО-ТО ТОЛЬКО ТАМ, ГДЕ ВЫЗЫВАЮЩИЙ ТОЖЕ С ОБЩЕЙ
        # ВЕТКИ. На pull_request площадка берёт САМ файл прогона из изменения:
        # правящий изменение переписывает шаг и зовёт что угодно, а
        # закреплённый скрипт просто перестаёт вызываться — заперли дверь,
        # оставив стену (152).
        opasnye = ev & set(CALLER_FROM_BASE)
        if opasnye and not pins_checkout(text):
            problems.append(
                f"{name}: просыпается на {', '.join(sorted(opasnye))} — файл "
                "прогона берётся с общей ветки, — а вызываемое не закреплено. "
                "Здесь закреплять обязательно: код исполняется при правах "
                "общей ветки (152)")
        for job in jobs_without_timeout(text):
            problems.append(
                f"{name}: у работы «{job}» нет timeout-minutes. Зависшая "
                "работа держит очередь до умолчания площадки — шесть часов "
                "молчания вместо отказа (100)")

    if problems:
        print("прогоны каталога разошлись с тем, что о них объявлено:",
              file=sys.stderr)
        for p in problems:
            print(f"  • {p}", file=sys.stderr)
        return 1

    print(f"прогоны в порядке: файлов {len(workflows)} — у каждого ручная "
          "кнопка, у каждой работы предел времени, необязательные каналы "
          "слияние не держат, закрепление стоит там, где значит")
    return 0


if __name__ == "__main__":
    sys.exit(main())
